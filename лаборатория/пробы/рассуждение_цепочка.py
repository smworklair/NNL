# -*- coding: utf-8 -*-
"""Прототип рассуждения в процессоре: цепочка фактов, не заточенная под военкомат.

Мир:
  - симптом → болезнь (блок A)
  - болезнь → категория (таблица фактов)
  - категория + обстоятельство → тема (блок B)

Ядро не знает про симптомы/болезни/темы. Оно знает только операции:
  1. спросить_блок — получить факт.
  2. применить_правило — преобразовать факт по таблице.
  3. k2 — условный прогон читателя по мосту.
"""
import json
import math
import os
import random
import sys

sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ВЫХОД = os.path.join(КОРЕНЬ, "лаборатория", "результаты", "рассуждение_цепочка.json")


# --------------------------------------------------------------------------- абстрактный мир
СИМПТОМЫ = ["жар", "кашель", "слабость", "боль"]
БОЛЕЗНИ = ["b1", "b2", "b3", "b4"]
КАТЕГОРИИ = ["A", "B", "C", "D"]
ОБСТОЯТЕЛЬСТВА = ["o1", "o2", "o3", "o4"]
ТЕМЫ = ["t1", "t2", "t3", "t4"]

# таблица фактов: болезнь → категория
БОЛЕЗНЬ_КАТЕГОРИЯ = {"b1": "A", "b2": "B", "b3": "C", "b4": "D"}

# тема = XOR категории и обстоятельства (как в полигоне K2)
def тема(категория, обстоятельство):
    return ТЕМЫ[КАТЕГОРИИ.index(категория) ^ ОБСТОЯТЕЛЬСТВА.index(обстоятельство)]


# --------------------------------------------------------------------------- блоки
class Блок:
    """Универсальный блок: читает текст и входные факты, выдаёт распределение по выходным."""
    def __init__(self, имя, выходы, шум=0.1):
        self.имя = имя
        self.выходы = выходы
        self.шум = шум

    def распределение(self, текст, вход=None):
        """Если вход задан, считаем, что он помогает выбрать правильный выход.
        В противном случае — голый текст."""
        # базовый шум
        scores = {x: random.gauss(0, self.шум) for x in self.выходы}
        if вход is not None:
            # вход — правильный факт, мы его читаем и усиливаем соответствующий выход
            if вход in scores:
                scores[вход] += 2.0
        # softmax
        m = max(scores.values())
        e = {x: math.exp(scores[x] - m) for x in self.выходы}
        z = sum(e.values())
        return {x: e[x] / z for x in self.выходы}


class БлокA(Блок):
    """симптом + (опционально) категория → болезнь."""
    def __init__(self, шум=0.1):
        super().__init__("A", БОЛЕЗНИ, шум=шум)


class БлокB(Блок):
    """обстоятельство + (опционально) категория → тема."""
    def __init__(self, шум=0.1):
        super().__init__("B", ТЕМЫ, шум=шум)


# --------------------------------------------------------------------------- ядро-рассуждение
class Рассуждение:
    """Универсальное ядро: не знает домена, умеет цепочку фактов."""
    @staticmethod
    def спросить_блок(блок, текст, вход=None):
        return блок.распределение(текст, вход)

    @staticmethod
    def топ1(распределение):
        return max(распределение, key=распределение.get)

    @staticmethod
    def применить_правило(факт, правило):
        """правило: dict вход → выход."""
        return правило.get(факт)

    @staticmethod
    def k2(распределение_писателя, условные_распределения):
        """p(выход) = Σ_v p_A(v) · p_B(выход | v)."""
        итог = {}
        for v, p_v in распределение_писателя.items():
            for выход, p in условные_распределения[v].items():
                итог[выход] = итог.get(выход, 0.0) + p_v * p
        return итог


def генератор(n=200, seed=0):
    rng = random.Random(seed)
    данные = []
    for _ in range(n):
        симптом = rng.choice(СИМПТОМЫ)
        болезнь = rng.choice(БОЛЕЗНИ)
        обстоятельство = rng.choice(ОБСТОЯТЕЛЬСТВА)
        категория = БОЛЕЗНЬ_КАТЕГОРИЯ[болезнь]
        тема_ = тема(категория, обстоятельство)
        # текст содержит симптом и обстоятельство, но не болезнь/категорию явно
        текст = f"{симптом} и {обстоятельство}"
        данные.append({
            "текст": текст,
            "симптом": симптом,
            "болезнь": болезнь,
            "обстоятельство": обстоятельство,
            "категория": категория,
            "тема": тема_,
        })
    return данные


def main():
    random.seed(0)
    обучение = генератор(200, seed=0)
    тест = генератор(1000, seed=1)

    блокA = БлокA(шум=0.3)
    блокB = БлокB(шум=0.3)
    рассуждение = Рассуждение()

    # Цепочка:
    # 1. Текст → болезнь (блок A)
    # 2. Болезнь → категория (правило)
    # 3. Категория + обстоятельство → тема (K2 по категории)
    верно = 0
    примеры = []
    for r in тест:
        p_болезнь = рассуждение.спросить_блок(блокA, r["текст"])
        топ_болезнь = рассуждение.топ1(p_болезнь)

        # шаг 2: применяем правило к каждой возможной болезни
        # p(категория) = Σ_болезнь p_A(болезнь) · [категория(болезнь)]
        p_категория = {c: 0.0 for c in КАТЕГОРИИ}
        for болезнь, p in p_болезнь.items():
            категория = БОЛЕЗНЬ_КАТЕГОРИЯ[болезнь]
            p_категория[категория] += p

        # шаг 3: K2 по категории
        условные = {}
        for категория in КАТЕГОРИИ:
            условные[категория] = рассуждение.спросить_блок(блокB, r["текст"], вход=категория)
        p_тема = рассуждение.k2(p_категория, условные)
        топ_тема = рассуждение.топ1(p_тема)

        if топ_тема == r["тема"]:
            верно += 1

        примеры.append({
            "текст": r["текст"],
            "истинная_тема": r["тема"],
            "предсказанная_тема": топ_тема,
            "p_категория": {c: round(p, 3) for c, p in p_категория.items()},
            "p_тема": {t: round(p, 3) for t, p in p_тема.items()},
        })

    рез = {
        "n": len(тест),
        "accuracy": верно / len(тест),
        "описание": "цепочка: текст → болезнь → категория (правило) → тема (K2)",
        "примеры": примеры[:5],
    }

    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    json.dump(рез, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps(рез, ensure_ascii=False, indent=1))
    print("записано:", ВЫХОД)


if __name__ == "__main__":
    main()
