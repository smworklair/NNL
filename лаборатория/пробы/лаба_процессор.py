# -*- coding: utf-8 -*-
"""Лаба процессора (ядро-2) на 61 стыковом вопросе.
Сравнивает стратегию "набор" с v8 один ответ и с набором из соло-блоков.
Пишет v9/результаты/лаба_процессор.json."""
import json
import os
import sys

sys.dont_write_bytecode = True

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

from лаба_общее import О, Процессор  # noqa: E402

ВЫХОД = os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_процессор.json")


def метрики(зд, пр, зд_эт, пр_эт):
    зд_верно = bool(зд & зд_эт)
    пр_верно = bool(пр & пр_эт)
    return {
        "оба_верны": зд_верно and пр_верно,
        "хотя_бы_один": зд_верно or пр_верно,
        "только_зд": зд_верно and not пр_верно,
        "только_пр": not зд_верно and пр_верно,
        "оба_неверны": not зд_верно and not пр_верно,
        "зд_верно": зд_верно,
        "пр_верно": пр_верно,
    }


def main():
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    ядро, _ = О.система("основная_внешние", 1, язык=язык)
    проц = Процессор(ядро)

    стык = json.load(open(os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_стыки_полные.json"), encoding="utf-8"))["вопросы"]

    рез = {"вопросы": [], "метрики": {}}
    counts = {"набор_процессор": {"оба_верны": 0, "хотя_бы_один": 0, "только_зд": 0, "только_пр": 0,
                                   "оба_неверны": 0, "зд_верно": 0, "пр_верно": 0}}

    for r in стык:
        зд_эт, пр_эт = set(r["эталон_зд"]), set(r["эталон_пр"])
        ответ, запись = проц.спросить(r["текст"], "набор")
        набор = set(x["ключ"] for x in запись["набор"])
        зд_дано = set(x for x in набор if x.startswith("ответ:здоровье:"))
        пр_дано = set(x for x in набор if x.startswith("ответ:право:"))

        m = метрики(зд_дано, пр_дано, зд_эт, пр_эт)
        for k, v in m.items():
            counts["набор_процессор"][k] += bool(v)

        рез["вопросы"].append({
            "i": r["i"], "текст": r["текст"], "эталон_зд": sorted(зд_эт), "эталон_пр": sorted(пр_эт),
            "набор": sorted(набор), "зд_дано": sorted(зд_дано), "пр_дано": sorted(пр_дано),
            "оба_верны": m["оба_верны"],
        })

    n = len(стык)
    рез["метрики"] = {k: {m: "%.0f/%.0f" % (v, n) for m, v in c.items()} for k, c in counts.items()}
    рез["n"] = n

    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    json.dump(рез, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps(рез["метрики"], ensure_ascii=False, indent=1))
    print("записано:", ВЫХОД)


if __name__ == "__main__":
    main()
