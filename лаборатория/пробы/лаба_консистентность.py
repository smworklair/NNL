# -*- coding: utf-8 -*-
"""Проверка консистентности через причинно-следственную связь.

Система получает вопрос и должна заметить, когда её параметры противоречат
друг другу: факт A влечёт следствие B, а запрос предполагает C, и B с C
несовместимы.

Это не скрипт и не подгонка под статьи — общая схема:
  причина  --(правило)-->  ожидаемое_следствие
      ↑                         ↓
      └────── противоречие? ←──┘
              (сравнение с фактическим ответом)
"""
import json
import os
import sys

sys.dont_write_bytecode = True

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

from лаба_общее import О, Процессор  # noqa: E402

ВЫХОД = os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_консистентность.json")


class Консистентность:
    """Проверяет, что фактический ответ не противоречит ожидаемому следствию."""

    def __init__(self, проц):
        self.проц = проц

    def проверить(self, текст, цепь, целевой_ключ, порог=0.5):
        """
        цепь — описание причинно-следственной цепи для процессора.
        целевой_ключ — ключ ответа, который должен следовать из причины.
        порог — если p(ожидаемый_ответ) < порог, параметры считаются противоречивыми.
        Возвращает dict.
        """
        ответ_цепь, запись_цепь = self.проц.спросить(текст, "цепочка", цепь=цепь)
        ответ_набор, запись_набор = self.проц.спросить(текст, "набор")

        # ожидаемое следствие из цепочки
        распределение = запись_цепь.get("распределение", {})
        p_ожидаемый = распределение.get(целевой_ключ, 0.0)

        # фактический top-1 из набора
        набор_ключи = [x["ключ"] for x in запись_набор.get("набор", [])]

        # флаг противоречия: ожидаемый ответ имеет низкую вероятность,
        # а фактический top-1 не совпадает с ним
        противоречие = p_ожидаемый < порог and целевой_ключ not in набор_ключи[:1]

        return {
            "текст": текст[:120],
            "целевой_ключ": целевой_ключ,
            "p_ожидаемый": round(p_ожидаемый, 4),
            "фактический_top1": набор_ключи[:1],
            "противоречие": противоречие,
            "причина": "ожидаемый ответ маловероятен, запрос содержит противоречивые параметры" if противоречие else None,
        }


def _абстрактные_примеры():
    """Игрушечный мир: категория A -> не отсрочка."""
    from игрушечный_мир import ФейкБлок, ФейкЯдро  # noqa: E402

    # Блок A: категория годности
    блокA = ФейкБлок(
        имя="A",
        пишет={"категория": ["A", "B"]},
        читает={},
        ответы=[],
        правило={"категория": lambda t: t.get("к")}
    )

    # Блок B: отсрочка/не отсрочка, зависит от категории на шине и текста
    def _ответ_по_шине(токены, шина):
        кат_B = шина.get("категория:B", -1e9) > шина.get("категория:A", -1e9)
        слова = токены.get("_слова", [])
        запрос_отсрочка = any("отсрочка" in w for w in слова)
        if кат_B and запрос_отсрочка:
            return "ответ:результат:отсрочка"
        return "ответ:результат:не_отсрочка"

    блокB = ФейкБлок(
        имя="B",
        пишет={},
        читает={"категория": ["A", "B"]},
        ответы=["ответ:результат:отсрочка", "ответ:результат:не_отсрочка"],
        правило={"ответ": _ответ_по_шине}
    )

    проц = Процессор(ФейкЯдро([блокA, блокB]))

    # правило: категория A -> не_отсрочка, B -> отсрочка
    правило = {"A": "не_отсрочка", "B": "отсрочка"}

    примеры = []
    for текст, категория, ожидаемый_id, ожидаемо_противоречие in [
        ("к:A болезнь:b1", "A", "не_отсрочка", False),
        ("к:A болезнь:b1 отсрочка?", "A", "не_отсрочка", True),
        ("к:B болезнь:b2 отсрочка?", "B", "отсрочка", False),
    ]:
        цепь = [
            {"мост": "категория", "значения": ["A", "B"],
             "правило": правило,
             "цель_блок": "B", "выход": "ответы"}
        ]
        ответ_цепь, запись_цепь = проц.спросить(текст, "цепочка", цепь=цепь)

        ключ_ож = "ответ:результат:%s" % ожидаемый_id
        p_ож = запись_цепь.get("распределение", {}).get(ключ_ож, 0.0)

        # запрос — что хотел пользователь (по тексту)
        запрос_отсрочка = "отсрочка" in текст
        запрос = "отсрочка" if запрос_отсрочка else None

        # противоречие: запрос требует одно, а причинная цепь ведёт к другому
        ключ_запрос = "ответ:результат:%s" % запрос if запрос else None
        противоречие = (запрос is not None) and (ключ_ож != ключ_запрос) and (p_ож >= 0.5)

        примеры.append({
            "текст": текст,
            "категория": категория,
            "ожидаемый": ожидаемый_id,
            "p_ожидаемый": round(p_ож, 4),
            "запрос": запрос,
            "противоречие": противоречие,
            "ожидаемо_противоречие": ожидаемо_противоречие,
        })
    return примеры


def _в8_примеры(проц):
    """Демонстрация на v8: область-право -> правовые ответы."""
    # Используем область как мост. Если область=здоровье, а запрос требует
    # правового ответа, то параметры противоречивы.
    проверки = []

    вопросы = [
        ("Меня комиссовали в категорию Б, могу ли я получить отсрочку?",
         "ответ:право:fz53_otsrochka_ucheba"),  # ок, медицинская категория -> отсрочка возможна
        ("У меня категория А, как получить отсрочку от армии?",
         "ответ:право:fz53_otsrochka_ucheba"),  # противоречие: A = годен
        ("Не явился по повестке, что грозит?",
         "ответ:право:neyavka_po_povestke"),   # ок
    ]

    цепь = [
        {"мост": "область", "значения": ["здоровье", "право"],
         "правило": {"здоровье": "здоровье", "право": "право"},
         "цель_блок": "право", "выход": "ответы"}
    ]

    к = Консистентность(проц)
    for текст, цель in вопросы:
        проверки.append(к.проверить(текст, цепь, цель, порог=0.3))
    return проверки


def main():
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    ядро, _ = О.система("основная_внешние", 1, язык=язык)
    проц = Процессор(ядро)

    рез = {
        "абстрактные_примеры": _абстрактные_примеры(),
        "v8_примеры": _в8_примеры(проц),
    }

    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    json.dump(рез, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps(рез, ensure_ascii=False, indent=1))
    print("записано:", ВЫХОД)


if __name__ == "__main__":
    main()
