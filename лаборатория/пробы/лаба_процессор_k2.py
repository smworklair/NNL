# -*- coding: utf-8 -*-
"""K2 в процессоре (ядро-2) на 61 стыковом вопросе.

Используемые мосты:
  - "глава" (здоровье -> право): писатель здоровье, читатель право.
  - "акт"   (право -> здоровье): писатель право, читатель здоровье.

Метрики: для каждого направления — верно ли top-1 K2 против эталона своей области,
в сравнении с v8 один ответ и процессор "набор".
"""
import json
import os
import sys

sys.dont_write_bytecode = True
from лаба_общее import О, Процессор  # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

ВЫХОД = os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_процессор_k2.json")


def main():
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    ядро, _ = О.система("основная_внешние", 1, язык=язык)
    проц = Процессор(ядро)

    стык = json.load(open(os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_стыки_полные.json"), encoding="utf-8"))["вопросы"]

    # мосты: мост-значения из паспортов
    главы = [str(i) for i in range(1, 18)]
    акты = ["53фз", "пп565", "пп663", "пп719", "кас", "коап", "укрф", "127фз", "59фз"]

    направления = {
        "глава_зд_пр": ("глава", главы, "право"),
        "акт_пр_зд": ("акт", акты, "здоровье"),
    }

    рез = {"вопросы": [], "метрики": {}}
    for имя, (мост, значения, цель) in направления.items():
        к = 0
        вопросы_направ = []
        for r in стык:
            текст = r["текст"]
            эталон = set(r["эталон_пр"] if цель == "право" else r["эталон_зд"])

            # v8 один ответ
            ответ_v8, _ = ядро.спросить(текст)
            v8_верно = False
            if ответ_v8 != О.НЕ_ЗНАЮ and ответ_v8.get("вид") == "ответ":
                v8_верно = "ответ:%s:%s" % (ответ_v8["область"], ответ_v8["id"]) in эталон

            # процессор набор
            ответ_набор, запись_набор = проц.спросить(текст, "набор")
            набор_ключи = [x["ключ"] for x in запись_набор.get("набор", [])]
            набор_верно = bool(set(набор_ключи) & эталон)

            # K2
            try:
                ответ_k2, запись_k2 = проц.спросить(текст, "k2", мост=мост, значения=значения)
                k2_верно = "ответ:%s:%s" % (ответ_k2["область"], ответ_k2["id"]) in эталон if ответ_k2 != О.НЕ_ЗНАЮ else False
            except Exception as e:
                ответ_k2 = О.НЕ_ЗНАЮ
                k2_верно = False
                запись_k2 = {"ошибка": str(e)}

            if k2_верно:
                к += 1

            вопросы_направ.append({
                "i": r["i"],
                "текст": текст[:120],
                "цель": цель,
                "эталон": sorted(эталон),
                "v8_верно": v8_верно,
                "набор_верно": набор_верно,
                "k2_верно": k2_верно,
                "k2_ответ": ответ_k2,
            })

        рез["метрики"][имя] = {
            "n": len(стык),
            "v8_верно": sum(r["v8_верно"] for r in вопросы_направ),
            "набор_верно": sum(r["набор_верно"] for r in вопросы_направ),
            "k2_верно": sum(r["k2_верно"] for r in вопросы_направ),
        }
        рез["вопросы"].append({"направление": имя, "результаты": вопросы_направ})

    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    json.dump(рез, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps(рез["метрики"], ensure_ascii=False, indent=1))
    print("записано:", ВЫХОД)


if __name__ == "__main__":
    main()
