# --------------------------------------------------------------------------- абстрактный мир
class ФейкЯзык:
    """Язык для игрушечного мира. Текст вида 'симптом:X обст:Y б:Z к:C т:T'."""

    def перевести(self, текст):
        токены = {"симптом": "", "обст": "", "б": "", "к": "", "т": ""}
        for часть in текст.split():
            if ":" in часть:
                k, v = часть.split(":", 1)
                if k in токены:
                    токены[k] = v
        return {"токены": токены, "метки": {}, "отрицания": []}


class ФейкАрх:
    """Архитектура игрушечного блока: пишет понятия и/или даёт ответы."""

    def __init__(self, пишет, читает, ответы, правило):
        self._пишет = пишет  # {понятие: [значения]}
        self._читает = читает
        self._ответы = ответы  # ["ответ:<обл>:<id>"]
        self._правило = правило  # {понятие: lambda токены->значение}
        self.obj = self

    def _scores(self, значения, истина, шум=0.1):
        random.seed(hash(истина))
        с = {v: random.gauss(0, шум) for v in значения}
        if истина in значения:
            с[истина] += 2.0
        m = max(с.values())
        e = {v: math.exp(с[v] - m) for v in с}
        z = sum(e.values())
        return {v: math.log(e[v] / z) for v in с}

    def проход1(self, obj, токены):
        с = {}
        for понятие in self._пишет:
            истина = self._правило.get(понятие, lambda t: "")(токены)
            for v in self._пишет[понятие]:
                с["%s:%s" % (понятие, v)] = self._scores(self._пишет[понятие], истина)[v]
        return с

    def проход2(self, obj, токены, шина):
        # блок B: категория + обстоятельство -> тема
        кат = шина.get("категория:Z", None) or шина.get("категория:A", None)
        # для простоты берём максимум по категориям на шине
        категории = ["A", "B", "C", "D"]
        обст = токены.get("обст", "o1")
        best = max((шина.get("категория:%s" % c, -1e9), c) for c in категории)[1]
        тема_правильная = _тема(best, обст)
        return self._scores(self._ответы, "ответ:тема:%s" % тема_правильная, шум=0.2)


class ФейкБлок:
    def __init__(self, имя, пишет, читает, ответы, правило):
        self.имя = имя
        self.пишет = []
        for понятие, значения in пишет.items():
            for v in значения:
                self.пишет.append("%s:%s" % (понятие, v) if v else понятие)
        self.читает = []
        for понятие, значения in читает.items():
            for v in значения:
                self.читает.append("%s:%s" % (понятие, v) if v else понятие)
        self.ответы = ответы
        self.arch = ФейкАрх(пишет, читает, ответы, правило)
        self.obj = self.arch


def _тема(категория, обст):
    кат = ["A", "B", "C", "D"]
    обст_список = ["o1", "o2", "o3", "o4"]
    темы = ["t1", "t2", "t3", "t4"]
    return темы[кат.index(категория) ^ обст_список.index(обст)]


def _абстрактный_тест(процессор_класс, n=200):
    """Тест на абстрактном мире."""
    # Блок A: симптом → болезнь
    блокA = ФейкБлок(
        имя="A",
        пишет={"болезнь": ["b1", "b2", "b3", "b4"]},
        читает={},
        ответы=[],
        правило={"болезнь": lambda t: t["б"]}
    )
    # Блок B: категория + обстоятельство → тема
    блокB = ФейкБлок(
        имя="B",
        пишет={},
        читает={"категория": ["A", "B", "C", "D"]},
        ответы=["ответ:тема:%s" % t for t in ["t1", "t2", "t3", "t4"]],
        правило={}
    )
    # правило: болезнь -> категория
    БОЛЕЗНЬ_КАТЕГОРИЯ = {"b1": "A", "b2": "B", "b3": "C", "b4": "D"}

    class ФейкЯдро:
        def __init__(self):
            self.язык = ФейкЯзык()
            self.блоки = {"A": блокA, "B": блокB}
            self._схема = {"проходов": 2}
            self.схема = type("Схема", (), self._схема)()

    проц = процессор_класс(ФейкЯдро())

    # генерация теста
    rng = random.Random(1)
    верно = 0
    for _ in range(n):
        симптом = rng.choice(["жар", "кашель", "слабость", "боль"])
        обст = rng.choice(["o1", "o2", "o3", "o4"])
        # скрытые переменные
        болезнь = rng.choice(["b1", "b2", "b3", "b4"])
        категория = БОЛЕЗНЬ_КАТЕГОРИЯ[болезнь]
        тема_ист = _тема(категория, обст)
        текст = f"симптом:{симптом} обст:{обст} б:{болезнь} к:{категория} т:{тема_ист}"

        цепь = [
            {"мост": "болезнь", "значения": ["b1", "b2", "b3", "b4"],
             "правило": БОЛЕЗНЬ_КАТЕГОРИЯ, "цель_блок": None, "выход": "категория"},
            {"мост": "категория", "значения": ["A", "B", "C", "D"],
             "цель_блок": "B", "выход": "ответы"},
        ]
        ответ, _ = проц.спросить(текст, "цепочка", цепь=цепь)
        if ответ.get("id") == тема_ист:
            верно += 1
    return верно / n


# --------------------------------------------------------------------------- v8 демонстрация
def _v8_демо(проц):
    """Демонстрация на v8: область -> ответы через правило тождества."""
    стык = json.load(open(os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_стыки_полные.json"), encoding="utf-8"))["вопросы"]
    рез = []
    for цель in ["здоровье", "право"]:
        верно = 0
        for r in стык:
            текст = r["текст"]
            эталон = set(r["эталон_зд"] if цель == "здоровье" else r["эталон_пр"])
            цепь = [
                {"мост": "область", "значения": ["здоровье", "право"],
                 "правило": {"здоровье": "здоровье", "право": "право"},
                 "цель_блок": цель, "выход": "ответы"},
            ]
            ответ, _ = проц.спросить(текст, "цепочка", цепь=цепь)
            if ответ != О.НЕ_ЗНАЮ and "ответ:%s:%s" % (ответ["область"], ответ["id"]) in эталон:
                верно += 1
        рез.append({"цель": цель, "верно": верно, "n": len(стык)})
    return рез


