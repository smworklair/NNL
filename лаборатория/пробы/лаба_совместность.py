# -*- coding: utf-8 -*-
"""Лаба «Совместность»: отвечает один блок или вместе?
Стыковые вопросы = cowork_пул3, где в эталоне есть И статья (здоровье) И тема (право).
Опыт 1: на полной системе — чей ответ побеждает, каков вклад чужого блока.
Опыт 2: снять соседа (ядро с одним блоком) — меняется ли ответ.
Пишет v9/результаты/лаба_совместность.json"""
import json
import os
import sys

sys.dont_write_bytecode = True
from лаба_общее import О  # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

sys.path.insert(0, О.V8)
from обучение import данные as D  # noqa: E402
from ядро import Ядро, Язык  # noqa: E402


def соло(кого, язык):
    k = Ядро(язык, О.ARCH, схема=os.path.join(О.V8, "схемы", "основная_внешние.json"))
    p = os.path.join(О.V8, "блоки", "основная_внешние.з1", кого)
    ok, msg, _ = k.подключить(p)
    assert ok, (кого, msg)
    return k


def main():
    ВН = os.path.join(О.БАЗА, "внешние")
    txt = {r["i"]: r["текст"] for r in json.load(open(os.path.join(ВН, "пул3_вопросы.json"), encoding="utf-8"))}
    зд = set(D.ответы_здоровья())
    пр = set(D.ответы_права())
    стык = []
    for r in О.jl(os.path.join(ВН, "cowork_пул3.jsonl")):
        s = {"ответ:здоровье:%s" % a for a in r["ответы"]} | {"ответ:право:%s" % a for a in r["ответы"]}
        hs = s & зд
        ps = s & пр
        if hs and ps:
            стык.append((txt[r["i"]], sorted(hs), sorted(ps)))
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    полная, _ = О.система("основная_внешние", 1, язык=язык)
    сз = соло("здоровье", язык)
    сп = соло("право", язык)

    итог = {"стыковых": len(стык), "вопросы": []}
    смена_без_з = смена_без_п = 0
    чуж_сумм = чуж_макс = чуж_доля20 = 0
    n_отв = 0
    for t, hs, ps in стык:
        a, rec = полная.спросить(t)
        канд = (rec.get("кандидаты") or [{}])[0]
        топ = канд.get("ответ", "")
        хоз = канд.get("хозяин", "")
        прям = канд.get("прямой", 0) or 0
        чз = канд.get("через_шину", {}) or {}
        чуж = sum(v for n, v in чз.items() if n != хоз)
        if топ:
            n_отв += 1
            чуж_сумм += abs(чуж)
            чуж_макс = max(чуж_макс, abs(чуж))
            if прям and abs(чуж) >= 0.2 * abs(прям):
                чуж_доля20 += 1
        # снятие: ответ solo-систем
        az, _ = сз.спросить(t)
        ap, _ = сп.спросить(t)
        кз = "" if az == О.НЕ_ЗНАЮ else "ответ:%s:%s" % (az["область"], az.get("id") or "")
        кп = "" if ap == О.НЕ_ЗНАЮ else "ответ:%s:%s" % (ap["область"], ap.get("id") or "")
        if кз != топ:
            смена_без_з += 1
        if кп != топ:
            смена_без_п += 1
        итог["вопросы"].append({"текст": t[:120], "эталон_зд": hs, "эталон_пр": ps, "топ": топ,
                                "хозяин": хоз, "p": канд.get("p"), "прямой": прям,
                                "через_шину": чз, "соло_зд": кз, "соло_пр": кп})
    итог["опыт1_вклады"] = {"ответов": n_отв, "средний_модуль_чужого": round(чуж_сумм / max(1, n_отв), 3),
                            "макс_модуль_чужого": round(чуж_макс, 3),
                            "доля_где_чужой_20проц_прямого": "%d/%d" % (чуж_доля20, n_отв)}
    итог["опыт2_снятие"] = {"ответ_изменился_без_здоровья": "%d/%d" % (смена_без_з, len(стык)),
                            "ответ_изменился_без_права": "%d/%d" % (смена_без_п, len(стык))}
    out = os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_совместность.json")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    json.dump(итог, open(out, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps({"стыковых": итог["стыковых"], "опыт1": итог["опыт1_вклады"],
                      "опыт2": итог["опыт2_снятие"]}, ensure_ascii=False))


if __name__ == "__main__":
    main()
