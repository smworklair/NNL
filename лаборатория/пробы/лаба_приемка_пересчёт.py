# -*- coding: utf-8 -*-
"""Независимый пересчёт приёмки v9/ядро_процессор по v9/результатам.

Лаба приёмки сохранила только финальный результат по вопросам — базовой линии
повопросно там нет, поэтому «выигрыш +3» в ней непроверяем. Здесь базовая
линия восстанавливается из v9/результаты/лаба_процессор.json (стратегия
«набор» v9-процессора) и считаются:

  1. Точный тест Макнемара на discordant-парах для «оба верны» и для каждой
     области отдельно (n=61, аргументировать «+3» без значности нельзя).
  2. Согласуется ли сводка приёмки с повопросными данными.
  3. Держится ли структурный факт «оба_неверны = 0» и каков независимый потолок.
  4. Есть ли у маржи решателя réel сигнал: AUC(маржа vs верность). Если AUC~0.5,
     кривая воздержаний — перебор порога на шумe, а не калибровка.
  5. Сколько ошибок решатель ловит при воздержании <= 20 % и сколько верных
     при этом теряется.

Пишет v9/результаты/лаба_приемка_пересчёт.json.
"""
import json
import math
import os
import sys

sys.dont_write_bytecode = True

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

from лаба_общее import О  # noqa: E402

Ф_ПРИЕМКА = os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_приемка.json")
Ф_БАЗА = os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_процессор.json")
ВЫХОД = os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_приемка_пересчёт.json")


def макнемар(b, c):
    """Точный двусторонний тест Макнемара. b = стало верно, c = стало неверно."""
    n = b + c
    if n == 0:
        return 1.0, n
    d = abs(b - c)
    p = sum(math.comb(n, k) * 0.5 ** n for k in range(n + 1) if abs(2 * k - n) >= d)
    return min(1.0, p), n


def auc(оценки, метки):
    """AUC по Манан-Уитни с обработкой ничьих (0.5 веса)."""
    пары = list(zip(оценки, метки))
    pos = [x for x, y in пары if y]
    neg = [x for x, y in пары if not y]
    if not pos or not neg:
        return None
    с = 0.0
    for p in pos:
        for q in neg:
            с += 1.0 if p > q else (0.5 if p == q else 0.0)
    return с / (len(pos) * len(neg))


def долька(x, n):
    return "%.1f%%" % (100.0 * x / n) if n else "н/д"


def main():
    приемка = json.load(open(Ф_ПРИЕМКА, encoding="utf-8"))
    база = json.load(open(Ф_БАЗА, encoding="utf-8"))

    баз_вопр = {q["i"]: q for q in база["вопросы"]}
    при_вопр = {q["i"]: q for q in приемка["вопросы"]}
    общие = sorted(set(баз_вопр) & set(при_вопр))
    n = len(общие)

    свод = приемка["стыки_61"]

    # --- 1/2: повопросное сравнение и сверка со сводкой --------------------
    сч = {"оба": [0, 0], "зд": [0, 0], "пр": [0, 0]}  # [стало_верно, стало_неверно]
    агрег = {"база_оба": 0, "прием_оба": 0, "база_зд": 0, "прием_зд": 0,
             "база_пр": 0, "прием_пр": 0, "прием_оба_неверны": 0, "база_оба_неверны": 0}
    размаркованы = []
    for i in общие:
        b, a = баз_вопр[i], при_вопр[i]
        bz = bool(set(b["зд_дано"]) & set(b["эталон_зд"]))
        bp = bool(set(b["пр_дано"]) & set(b["эталон_пр"]))
        az, ap = bool(a["верно_здоровье"]), bool(a["верно_право"])

        # сверка: поле верно_* в приёмке должно совпадать с ответ vs эталон
        if az != (a["ответ_здоровье"] in set(a["эталон_зд"])):
            размаркованы.append((i, "здоровье"))
        if ap != (a["ответ_право"] in set(a["эталон_пр"])):
            размаркованы.append((i, "право"))

        for ключ, было, стало in (("оба", bz and bp, az and ap),
                                 ("зд", bz, az), ("пр", bp, ap)):
            if стало and not было:
                сч[ключ][0] += 1
            if было and not стало:
                сч[ключ][1] += 1
        агрег["база_оба"] += bool(bz and bp)
        агрег["прием_оба"] += bool(az and ap)
        агрег["база_зд"] += bz
        агрег["прием_зд"] += az
        агрег["база_пр"] += bp
        агрег["прием_пр"] += ap
        агрег["база_оба_неверны"] += not bz and not bp
        агрег["прием_оба_неверны"] += not az and not ap

    знач = {}
    for ключ, (b, c) in сч.items():
        p, nn = макнемар(b, c)
        знач[ключ] = {"стало_верно": b, "стало_неверно": c, "discordant": nn, "p_точное": round(p, 4)}

    независ_потолок = агрег["прием_зд"] * агрег["прием_пр"] / float(n) if n else None

    # --- 4/5: сигнал маржи --------------------------------------------------
    реш = {}
    for обл, поле in (("здоровье", "margin_здоровье"), ("право", "margin_право")):
        метки = [bool(при_вопр[i]["верно_" + обл]) for i in общие]
        аук = auc([при_вопр[i][поле] for i in общие], метки)
        пары = sorted(zip([при_вопр[i][поле] for i in общие], метки), key=lambda x: -x[0])
        точка = None
        for k in range(1, n + 1):
            подмножество = пары[:k]
            доля_воздерж = (n - k) / float(n)
            if доля_воздерж <= 0.20:
                верно = sum(1 for _, y in подмножество if y)
                точка = {"отвечено": k, "воздержание": round(доля_воздерж, 4),
                         "точность": round(верно / float(k), 4),
                         "верно": верно, "ошибок_осталось": k - верно}
                break
        крив = приемка.get("кривая_решателя_" + обл) or []
        реш[обл] = {
            "AUC_маржа_против_верности": round(аук, 4) if аук is not None else None,
            "верно_всего": sum(метки),
            "точка_воздержание_до_20proc": точка,
            "кривая_из_отчёта": крив,
        }

    # --- 3: Lego ------------------------------------------------------------
    lego = приемка.get("lego_индекс", {})

    вывод = {
        "n_общих_вопросов": n,
        "сверка_с_отчётом": {
            "отчёт_стыки_61": свод,
            "пересчёт_из_повопросных": {
                "база_оба": "%d/%d" % (агрег["база_оба"], n),
                "приемка_оба": "%d/%d" % (агрег["прием_оба"], n),
                "база_зд": "%d/%d" % (агрег["база_зд"], n),
                "приемка_зд": "%d/%d" % (агрег["прием_зд"], n),
                "база_пр": "%d/%d" % (агрег["база_пр"], n),
                "приемка_пр": "%d/%d" % (агрег["прием_пр"], n),
                "база_оба_неверны": агрег["база_оба_неверны"],
                "приемка_оба_неверны": агрег["прием_оба_неверны"],
            },
            "несогласованных_меток": размаркованы,
        },
        "значимость_макнемар": знач,
        "структура_ошибок": {
            "оба_неверны_в_приемке": агрег["прием_оба_неверны"],
            "ожидаемо_при_независимости": round(
                (n - агрег["прием_зд"]) * (n - агрег["прием_пр"]) / float(n), 2),
            "независимый_потолок_оба_верны": round(независ_потолок, 2) if независ_потолок else None,
        },
        "решатель": реш,
        "lego_индекс_из_отчёта": lego,
    }

    json.dump(вывод, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    print("=== сверка отчёта с повопросными данными (n=%d) ===" % n)
    print(" отчёт:", json.dumps(свод, ensure_ascii=False))
    print(" пересчёт:", json.dumps(вывод["сверка_с_отчётом"]["пересчёт_из_повопросных"], ensure_ascii=False))
    if размаркованы:
        print(" !! метки верно_* не совпадают с ответ vs эталон:", размаркованы)
    print("\n=== значимость (точныи Макнемар) ===")
    for ключ, v in знач.items():
        print(" %-4s +%d/-%d  discordant=%d  p=%.4f" %
              (ключ, v["стало_верно"], v["стало_неверно"], v["discordant"], v["p_точное"]))
    print("\n=== структура ошибок ===")
    print(" ", json.dumps(вывод["структура_ошибок"], ensure_ascii=False))
    print("\n=== решатель ===")
    for обл, v in реш.items():
        print(" %-9s AUC=%.3f  верно %d/%d  точка<=20%%: %s" %
              (обл, v["AUC_маржа_против_верности"] or -1, v["верно_всего"], n,
               json.dumps(v["точка_воздержание_до_20proc"], ensure_ascii=False)))
    print("\n=== lego ===")
    print(" ", json.dumps(lego, ensure_ascii=False))
    print("\nзаписано:", ВЫХОД)


if __name__ == "__main__":
    main()
