# -*- coding: utf-8 -*-
"""Bidirectional K2 в процессоре.

Запускаем K2 в обе стороны:
  - глава: здоровье -> право (мост "глава")
  - акт:   право   -> здоровье (мост "акт")

Собираем пару: top-1 K2 для право + top-1 K2 для здоровье.
Сравниваем с v8, набор, k2+набор.
"""
import json
import os
import sys

sys.dont_write_bytecode = True
from лаба_общее import О, Процессор  # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

ВЫХОД = os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_процессор_k2_bidirectional.json")


def main():
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    ядро, _ = О.система("основная_внешние", 1, язык=язык)
    проц = Процессор(ядро)

    стык = json.load(open(os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_стыки_полные.json"), encoding="utf-8"))["вопросы"]

    главы = [str(i) for i in range(1, 18)]
    акты = ["53фз", "пп565", "пп663", "пп719", "кас", "коап", "укрф", "127фз", "59фз"]

    counts = {
        "v8": {"оба": 0, "хотя_бы_один": 0, "зд": 0, "пр": 0},
        "набор": {"оба": 0, "хотя_бы_один": 0, "зд": 0, "пр": 0},
        "k2_bidirectional": {"оба": 0, "хотя_бы_один": 0, "зд": 0, "пр": 0},
    }

    вопросы = []

    for r in стык:
        текст = r["текст"]
        зд_эт = set(r["эталон_зд"])
        пр_эт = set(r["эталон_пр"])

        # v8
        ответ_v8, _ = ядро.спросить(текст)
        v8_зд = set()
        v8_пр = set()
        if ответ_v8 != О.НЕ_ЗНАЮ and ответ_v8.get("вид") == "ответ":
            key = "ответ:%s:%s" % (ответ_v8["область"], ответ_v8["id"])
            if key.startswith("ответ:здоровье:"):
                v8_зд.add(key)
            elif key.startswith("ответ:право:"):
                v8_пр.add(key)

        # набор
        ответ_набор, запись_набор = проц.спросить(текст, "набор")
        набор_зд = set(x["ключ"] for x in запись_набор.get("набор", []) if x["ключ"].startswith("ответ:здоровье:"))
        набор_пр = set(x["ключ"] for x in запись_набор.get("набор", []) if x["ключ"].startswith("ответ:право:"))

        # bidirectional K2
        try:
            ответ_k2_глава, _ = проц.спросить(текст, "k2", мост="глава", значения=главы)
            k2_пр = set() if ответ_k2_глава == О.НЕ_ЗНАЮ else {"ответ:%s:%s" % (ответ_k2_глава["область"], ответ_k2_глава["id"])}
        except Exception:
            k2_пр = set()
        try:
            ответ_k2_акт, _ = проц.спросить(текст, "k2", мост="акт", значения=акты)
            k2_зд = set() if ответ_k2_акт == О.НЕ_ЗНАЮ else {"ответ:%s:%s" % (ответ_k2_акт["область"], ответ_k2_акт["id"])}
        except Exception:
            k2_зд = set()

        def метрики(зд, пр):
            return {
                "оба": bool((зд & зд_эт) and (пр & пр_эт)),
                "хотя_бы_один": bool((зд & зд_эт) or (пр & пр_эт)),
                "зд": bool(зд & зд_эт),
                "пр": bool(пр & пр_эт),
            }

        for имя, (зд, пр) in [
            ("v8", (v8_зд, v8_пр)),
            ("набор", (набор_зд, набор_пр)),
            ("k2_bidirectional", (k2_зд, k2_пр)),
        ]:
            m = метрики(зд, пр)
            for k in counts[имя]:
                counts[имя][k] += m[k]

        вопросы.append({
            "i": r["i"],
            "текст": текст[:120],
            "эталон_зд": sorted(зд_эт),
            "эталон_пр": sorted(пр_эт),
            "v8": sorted(v8_зд | v8_пр),
            "набор": sorted(набор_зд | набор_пр),
            "k2_bidirectional": sorted(k2_зд | k2_пр),
        })

    n = len(стык)
    рез = {
        "n": n,
        "метрики": {
            k: {m: "%d/%d" % (v, n) for m, v in c.items()}
            for k, c in counts.items()
        },
        "вопросы": вопросы,
    }

    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    json.dump(рез, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps(рез["метрики"], ensure_ascii=False, indent=1))
    print("записано:", ВЫХОД)


if __name__ == "__main__":
    main()
