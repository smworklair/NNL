# -*- coding: utf-8 -*-
"""Лаба «Стыки на полных текстах»: те же 61 стыковой вопрос и те же системы, что в `лаба_совместность.py`,
но полный текст сохраняется и измеряется то, чего прежний прогон не мерил:
  1. попадает ли единственный ответ v8 в эталон здоровья / права / в оба сразу;
  2. есть ли пара (статья + тема) в топ-3 кандидатах полной системы;
  3. где пара теряется — в блоках или в сборке: сравнение с соло-системами (по одному блоку);
  4. воспроизведение: сходится ли топ-1 с прежним прогоном (`лаба_совместность.json`).
Пишет v9/результаты/лаба_стыки_полные.json. Прежние результаты не трогает, веса блоков не меняет."""
import collections
import json
import os
import sys

sys.dont_write_bytecode = True
from лаба_общее import О  # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

sys.path.insert(0, О.V8)
from обучение import данные as D  # noqa: E402
from ядро import Ядро, Язык  # noqa: E402

СТАРОЕ = os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_совместность.json")
ВЫХОД = os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_стыки_полные.json")

ФЛАГИ = ("топ1_в_зд", "топ1_в_пр", "топ1_оба", "ответ_ядра_в_зд", "ответ_ядра_в_пр", "ответ_ядра_оба",
         "зд_в_топ3", "пр_в_топ3", "пара_в_топ3", "соло_зд_верно", "соло_пр_верно", "соло_оба_верны",
         "потеря_на_сборке", "совпало_с_прежним")


def соло(кого, язык):
    k = Ядро(язык, О.ARCH, схема=os.path.join(О.V8, "схемы", "основная_внешние.json"))
    p = os.path.join(О.V8, "блоки", "основная_внешние.з1", кого)
    ok, msg, _ = k.подключить(p)
    assert ok, (кого, msg)
    return k


def ключ(a):
    """Ответ ядра -> «ответ:область:id»; пусто, если ответа нет (порог не набран, «уточнить», «не знаю»)."""
    if a == О.НЕ_ЗНАЮ or a.get("вид") != "ответ":
        return ""
    return "ответ:%s:%s" % (a["область"], a.get("id") or "")


def вид_ответа(a):
    return "не знаю" if a == О.НЕ_ЗНАЮ else a.get("вид", "?")


def стыковые():
    """Те же стыковые вопросы, что в лаба_совместность.py: cowork_пул3, где в эталоне И статья И тема."""
    ВН = os.path.join(О.БАЗА, "внешние")
    txt = {r["i"]: r["текст"] for r in json.load(open(os.path.join(ВН, "пул3_вопросы.json"), encoding="utf-8"))}
    зд = set(D.ответы_здоровья())
    пр = set(D.ответы_права())
    out = []
    for r in О.jl(os.path.join(ВН, "cowork_пул3.jsonl")):
        s = {"ответ:здоровье:%s" % a for a in r["ответы"]} | {"ответ:право:%s" % a for a in r["ответы"]}
        hs, ps = s & зд, s & пр
        if hs and ps:
            out.append({"i": r["i"], "текст": txt[r["i"]], "эталон_зд": sorted(hs), "эталон_пр": sorted(ps)})
    return out


def main():
    стык = стыковые()
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    полная, _ = О.система("основная_внешние", 1, язык=язык)
    сз = соло("здоровье", язык)
    сп = соло("право", язык)

    прежнее = {}
    if os.path.exists(СТАРОЕ):
        for r in json.load(open(СТАРОЕ, encoding="utf-8"))["вопросы"]:
            прежнее[r["текст"]] = r          # ключ — обрезанный до 120 знаков текст прежнего отчёта

    c = collections.Counter()
    вопросы = []
    for q in стык:
        t = q["текст"]
        зд = set(q["эталон_зд"])
        пр = set(q["эталон_пр"])
        a, rec = полная.спросить(t)
        канд = rec.get("кандидаты") or []
        первый = канд[0] if канд else {}
        топ = первый.get("ответ", "")                    # лучший по счёту, как в прежней лабе
        хоз = первый.get("хозяин", "")
        прям = первый.get("прямой", 0) or 0
        чз = первый.get("через_шину", {}) or {}
        чуж = sum(v for n, v in чз.items() if n != хоз)
        ядро_дал = ключ(a)                               # то же, но с порогом 0,5
        топ3 = [x["ответ"] for x in канд]

        az, _ = сз.спросить(t)
        ap, _ = сп.спросить(t)
        кз = ключ(az)
        кп = ключ(ap)

        пара_в_топ3 = bool(set(топ3) & зд) and bool(set(топ3) & пр)
        соло_оба = (кз in зд) and (кп in пр)
        st = прежнее.get(t[:120])
        r = {
            "i": q["i"], "текст": t, "эталон_зд": sorted(зд), "эталон_пр": sorted(пр),
            "вид": вид_ответа(a), "топ1": топ, "ответ_ядра": ядро_дал, "p": первый.get("p"),
            "хозяин": хоз, "прямой": прям, "через_шину": чз,
            "топ3": [{"ответ": x["ответ"], "p": x.get("p"), "хозяин": x.get("хозяин")} for x in канд],
            "соло_зд": кз, "соло_пр": кп,
            "топ1_в_зд": топ in зд, "топ1_в_пр": топ in пр, "топ1_оба": (топ in зд) and (топ in пр),
            "ответ_ядра_в_зд": ядро_дал in зд, "ответ_ядра_в_пр": ядро_дал in пр,
            "ответ_ядра_оба": (ядро_дал in зд) and (ядро_дал in пр),
            "зд_в_топ3": bool(set(топ3) & зд), "пр_в_топ3": bool(set(топ3) & пр), "пара_в_топ3": пара_в_топ3,
            "соло_зд_верно": кз in зд, "соло_пр_верно": кп in пр, "соло_оба_верны": соло_оба,
            "потеря_на_сборке": соло_оба and not пара_в_топ3,
            "прежний_топ1": st["топ"] if st else None,
            "совпало_с_прежним": (st is not None) and st["топ"] == топ,
        }

        c["n"] += 1
        c["вид:" + r["вид"]] += 1
        for k in ФЛАГИ:
            c[k] += bool(r[k])
        if r["совпало_с_прежним"] is False:
            c["расхождений"] += 1
        if топ:
            c["ответов"] += 1
            c["чуж_сумма"] += abs(чуж)
            c["чуж_макс"] = max(c["чуж_макс"], abs(чуж))
            if прям and abs(чуж) >= 0.2 * abs(прям):
                c["чуж_20проц"] += 1
        вопросы.append(r)

    n = c["n"]
    итог = {
        "описание": "61 стыковой вопрос cowork_пул3, полные тексты; системы те же, что в лаба_совместность.py",
        "система": "основная_внешние.з1, схема основная_внешние.json, 2 прохода, порог ответа 0,5",
        "стыковых": n,
        "виды_ответа": {k.split(":", 1)[1]: c[k] for k in c if k.startswith("вид:")},
        "единственный_ответ": {
            "топ1_по_счёту_в_эталон_зд": "%d/%d" % (c["топ1_в_зд"], n),
            "топ1_по_счёту_в_эталон_пр": "%d/%d" % (c["топ1_в_пр"], n),
            "топ1_по_счёту_в_оба_сразу": "%d/%d" % (c["топ1_оба"], n),
            "ответ_ядра_с_порогом_в_зд": "%d/%d" % (c["ответ_ядра_в_зд"], n),
            "ответ_ядра_с_порогом_в_пр": "%d/%d" % (c["ответ_ядра_в_пр"], n),
            "ответ_ядра_с_порогом_в_оба": "%d/%d" % (c["ответ_ядра_оба"], n),
        },
        "пара_в_топ3": {
            "здоровье_в_топ3": "%d/%d" % (c["зд_в_топ3"], n),
            "право_в_топ3": "%d/%d" % (c["пр_в_топ3"], n),
            "оба_в_топ3": "%d/%d" % (c["пара_в_топ3"], n),
        },
        "соло_по_одному_блоку": {
            "здоровье_верно": "%d/%d" % (c["соло_зд_верно"], n),
            "право_верно": "%d/%d" % (c["соло_пр_верно"], n),
            "оба_верны": "%d/%d" % (c["соло_оба_верны"], n),
        },
        "где_теряется_пара": {
            "соло_оба_верны_но_в_полной_системе_пары_нет_в_топ3": "%d/%d" % (c["потеря_на_сборке"], n),
        },
        "вклады_соседей_как_в_прежней_лабе": {
            "ответов": c["ответов"],
            "средний_модуль_чужого": round(c["чуж_сумма"] / max(1, c["ответов"]), 3),
            "макс_модуль_чужого": round(c["чуж_макс"], 3),
            "доля_где_чужой_20проц_прямого": "%d/%d" % (c["чуж_20проц"], c["ответов"]),
        },
        "воспроизведение_прежней_лабы": {
            "топ1_совпал": "%d/%d" % (c["совпало_с_прежним"], n),
            "расхождений": c["расхождений"],
        },
        "вопросы": вопросы,
    }
    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    json.dump(итог, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps({k: v for k, v in итог.items() if k != "вопросы"}, ensure_ascii=False, indent=1))
    print("записано:", ВЫХОД)


if __name__ == "__main__":
    main()
