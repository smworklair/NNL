# -*- coding: utf-8 -*-
"""Поиск кандидатов в настоящие мост-переменные между v8-блоками.

Для 61 стыкового вопроса смотрим, какие понятия на шине
(область, глава, акт) коррелируют с правильным ответом другой области.

Метод:
  * Для каждого понятия k и значения v:
    - смотрим вопросы, где эталон в области A верен;
    - сравниваем средний счёт понятия k в этих вопросах
      со средним счётом, когда эталон в области A неверен.
  * Также считаем, сколько раз top-1 значение понятия k
    совпадает с "правильным" значением для группы вопросов.

Цель: найти понятие, которое один блок пишет, а другой блок
потенциально мог бы читать, чтобы улучшить ответы.
"""
import json
import math
import os
import sys
from collections import defaultdict

sys.dont_write_bytecode = True
from лаба_общее import О, Процессор  # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")



ВЫХОД = os.path.join(О.БАЗА, "лаборатория", "результаты", "поиск_мост.json")


def main():
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    ядро, _ = О.система("основная_внешние", 1, язык=язык)
    проц = Процессор(ядро)

    стык = json.load(open(os.path.join(О.БАЗА, "лаборатория", "результаты", "лаба_стыки_полные.json"), encoding="utf-8"))["вопросы"]

    # понятия, которые пишет каждый блок
    понятия_зд = set(ядро.блоки["здоровье"].пишет)
    понятия_пр = set(ядро.блоки["право"].пишет)

    # группировка по домену
    понятия = {
        "здоровье": понятия_зд,
        "право": понятия_пр,
    }

    статистика = []

    for понятие_общее in sorted(понятия_зд | понятия_пр):
        # определяем, кто пишет
        писатель = "здоровье" if понятие_общее in понятия_зд else "право"
        # исследуем влияние на другую область
        цель = "право" if писатель == "здоровье" else "здоровье"

        значения = defaultdict(lambda: {"верно": [], "неверно": []})

        for r in стык:
            токены, вклады, шина, писатели, счёты, видел = проц._прогоны(r["текст"])
            эталон = set(r["эталон_пр"] if цель == "право" else r["эталон_зд"])

            # значение понятия на шине
            v_шины = шина.get(понятие_общее, 0.0)

            # top-1 ответ целевого блока из счётов
            целевые_ответы = {a: x for a, x in счёты.items() if a.startswith("ответ:%s:" % цель)}
            if целевые_ответы:
                топ = max(целевые_ответы, key=целевые_ответы.get)
                верно = топ in эталон
            else:
                верно = False

            if верно:
                значения[понятие_общее]["верно"].append(v_шины)
            else:
                значения[понятие_общее]["неверно"].append(v_шины)

        # средние
        верно = значения[понятие_общее]["верно"]
        неверно = значения[понятие_общее]["неверно"]
        if верно and неверно:
            статистика.append({
                "понятие": понятие_общее,
                "писатель": писатель,
                "цель": цель,
                "средний_верно": round(sum(верно) / len(верно), 4),
                "средний_неверно": round(sum(неверно) / len(неверно), 4),
                "n_верно": len(верно),
                "n_неверно": len(неверно),
            })

    # сортируем по разницу средних
    for s in статистика:
        s["разница"] = round(abs(s["средний_верно"] - s["средний_неверно"]), 4)

    статистика.sort(key=lambda x: -x["разница"])

    рез = {"статистика": статистика}
    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    json.dump(рез, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("топ-10 по разнице среднего счёта:")
    for s in статистика[:10]:
        print(s)
    print("записано:", ВЫХОД)


if __name__ == "__main__":
    main()
