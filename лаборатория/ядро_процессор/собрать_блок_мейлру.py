# 5. Генерация весовых матриц
B = 16384  # корзин
d = 32     # размер эмбеддинга
Y = len(ОТВЕТЫ)
R = len(ЧИТАЕТ)

rng = np.random.RandomState(42)
E = rng.randn(B, d).astype(np.float32) * 0.05
U = rng.randn(d, Y).astype(np.float32) * 0.05
b = np.zeros(Y, dtype=np.float32)
V = np.zeros((2 * R, Y), dtype=np.float32)

# Индексы ответов
ответ_индекс = {ans: i for i, ans in enumerate(ОТВЕТЫ)}
читает_индекс = {bus: i for i, bus in enumerate(ЧИТАЕТ)}

# Задаём целевые веса шины для точной связки с причинными выводами:
def add_bus_link(bus_name, ans_name, weight=12.0):
    if bus_name in читает_индекс and ans_name in ответ_индекс:
        r_idx = читает_индекс[bus_name]
        a_idx = ответ_индекс[ans_name]
        # Вес чтения и вес присутствия
        V[r_idx, a_idx] += weight
        V[R + r_idx, a_idx] += 4.0

# Связка тем права и статей с ответами
add_bus_link("акт:53фз", "ответ:мейлру:направление_на_допобследование", 8.0)
add_bus_link("акт:пп565", "ответ:мейлру:направление_на_допобследование", 6.0)
add_bus_link("акт:пп565", "ответ:мейлру:медосмотр_на_сборном_пункте", 14.0)
add_bus_link("акт:кас", "ответ:мейлру:обжалование_решения_и_кмо", 16.0)
add_bus_link("акт:коап", "ответ:мейлру:штрафы_и_ответственность_повестки", 16.0)
add_bus_link("акт:укрф", "ответ:мейлру:штрафы_и_ответственность_повестки", 14.0)
add_bus_link("область:здоровье", "ответ:мейлру:освобождение_по_болезни", 10.0)
add_bus_link("область:право", "ответ:мейлру:обжалование_решения_и_кмо", 8.0)

# Сохранение npz весов
npz_file = os.path.join(ПАПКА_БЛОКА, "веса.npz")
np.savez_compressed(
    npz_file,
    E=E,
    U=U,
    b=b,
    V=V,
    ответы=np.array(ОТВЕТЫ),
    пишет=np.array(ПИШЕТ),
    читает=np.array(ЧИТАЕТ),
    шаблоны_json=np.array(json.dumps(ШАБЛОНЫ, ensure_ascii=False)),
)

# Вычисление sha256 весов
h = hashlib.sha256()
with open(npz_file, "rb") as f:
    for chunk in iter(lambda: f.read(1 << 20), b""):
        h.update(chunk)
sha = h.hexdigest()

