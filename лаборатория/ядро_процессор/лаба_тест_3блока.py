# -*- coding: utf-8 -*-
"""Лаба комплексного прогона 3-блочной системы:
Блок 1 (Расписание болезней / здоровье)
Блок 2 (Правовые нормы / право)
Блок 3 (Живой ответ сообщества / ответы_мейлру)

Архитектура:
  Матплата (Слоты, Паспорта sha256, Изолированная шина)
  -> 3 Блока
  -> Процессор тактов (Диспетчер тактов 1 и 2)
  -> Ядро причинности (Валидатор триады)
  -> Решатель (Калиброванный селективный выбор)

Запуск: python v9/ядро_процессор/лаба_тест_3блока.py
Пишет: v9/результаты/лаба_тест_3блока.json
"""
import json
import os
import sys
import time

СЮДА = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(os.path.dirname(СЮДА))
sys.path.insert(0, СЮДА)
sys.path.insert(1, os.path.join(КОРЕНЬ, "система", "замер"))
sys.path.insert(2, os.path.join(КОРЕНЬ, "лаборатория", "пробы"))

import общее as О
from лаба_стыки_полные import стыковые
from матплата import Матплата
from процессор_тактов import Процессор
from ядро_причинности import Ядро
from решатель import Решатель

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def main():
    t0 = time.time()
    print("=" * 75)
    print("🚀 ПРОГОН 3-БЛОЧНОЙ СИСТЕМЫ В НОВОЙ АРХИТЕКТУРЕ (ПРОЦЕССОР + ЯДРО + РЕШАТЕЛЬ)")
    print("=" * 75)

    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    матплата = Матплата(язык, О.ARCH)

    # 1. ПОДКЛЮЧЕНИЕ 3 БЛОКОВ В СЛОТЫ МАТПЛАТЫ
    путь_зд = os.path.join(О.V8, "блоки", "основная_внешние.з1", "здоровье")
    путь_пр = os.path.join(О.V8, "блоки", "основная_внешние.з1", "право")
    путь_мл = os.path.join(О.V8, "блоки", "основная_внешние.з1", "ответы_мейлру")

    ok_z, err_z = матплата.подключить(путь_зд)
    ok_p, err_p = матплата.подключить(путь_пр)
    ok_m, err_m = матплата.подключить(путь_мл)

    assert ok_z, f"Ошибка подключения Блока 1 (здоровье): {err_z}"
    assert ok_p, f"Ошибка подключения Блока 2 (право): {err_p}"
    assert ok_m, f"Ошибка подключения Блока 3 (ответы_мейлру): {err_m}"

    print(f"✅ Блок 1: '{матплата.блоки['здоровье'].имя}' ({матплата.блоки['здоровье'].роль}) — подключён")
    print(f"✅ Блок 2: '{матплата.блоки['право'].имя}' ({матплата.блоки['право'].роль}) — подключён")
    print(f"✅ Блок 3: '{матплата.блоки['ответы_мейлру'].имя}' ({матплата.блоки['ответы_мейлру'].роль}) — подключён")
    print(f"   Суммарное число параметров блоков: {sum(b.чисел for b in матплата.блоки.values()):,}")

    ядро_валидатор = Ядро(КОРЕНЬ)
    процессор = Процессор(матплата, ядро_валидатор, tau_conf=1.0)
    решатель = Решатель(порог_воздержания=1.0)

    # ========================================================
    # ТЕСТ 1: LEGO-ИНДЕКС (ИЗОЛЯЦИЯ НА ТАКТЕ 1 НА 461 ВОПРОСЕ)
    # ========================================================
    print("\n" + "=" * 75)
    print("📋 ТЕСТ 1: LEGO-ИНДЕКС НА 461 ВОПРОСЕ BENCH.JSONL (КОНТРАКТ ИЗОЛЯЦИИ)")
    print("=" * 75)

    bench = []
    with open(os.path.join(О.БАЗА, "бенчмарки", "bench", "bench.jsonl"), encoding="utf-8") as f:
        for line in f:
            if line.strip():
                bench.append(json.loads(line))

    diff_z, diff_p, diff_m = 0, 0, 0
    n_bench = len(bench)
    b_zd = матплата.блоки["здоровье"]
    b_pr = матплата.блоки["право"]
    b_ml = матплата.блоки["ответы_мейлру"]

    for r in bench:
        toks = язык.перевести(r["вопрос"])["токены"]
        # Соло-прогоны каждого блока (полная изоляция)
        top_z_solo = max(b_zd.arch.проход2(b_zd.obj, toks, {}).items(), key=lambda x: x[1])[0]
        top_p_solo = max(b_pr.arch.проход2(b_pr.obj, toks, {}).items(), key=lambda x: x[1])[0]
        top_m_solo = max(b_ml.arch.проход2(b_ml.obj, toks, {}).items(), key=lambda x: x[1])[0]

        # Прогон в 3-блочной системе через процессор (такт 1)
        res = процессор.выполнить(r["вопрос"])
        top_z_sys = res["такт1"]["здоровье"]["top1"]
        top_p_sys = res["такт1"]["право"]["top1"]
        top_m_sys = res["такт1"]["ответы_мейлру"]["top1"]

        if top_z_sys != top_z_solo: diff_z += 1
        if top_p_sys != top_p_solo: diff_p += 1
        if top_m_sys != top_m_solo: diff_m += 1

    lego_z = round(diff_z / n_bench, 4)
    lego_p = round(diff_p / n_bench, 4)
    lego_m = round(diff_m / n_bench, 4)

    print(f"Lego-индекс Блок 1 (Здоровье):      {lego_z:.4f} (искажений {diff_z}/{n_bench})")
    print(f"Lego-индекс Блок 2 (Право):         {lego_p:.4f} (искажений {diff_p}/{n_bench})")
    print(f"Lego-индекс Блок 3 (Ответы Mail.ru): {lego_m:.4f} (искажений {diff_m}/{n_bench})")
    assert lego_z == 0.0 and lego_p == 0.0 and lego_m == 0.0, "Lego-индекс должен быть строго 0.0000!"

    # ========================================================
    # ТЕСТ 2: 61 СТЫКОВОЙ ВОПРОС (ВЗАИМОДЕЙСТВИЕ НА ТАКТЕ 2)
    # ========================================================
    print("\n" + "=" * 75)
    print("📋 ТЕСТ 2: 61 СТЫКОВОЙ ВОПРОС (ТАКТ 1 -> ШИНА -> ТАКТ 2 -> СТИЛЬ ОТВЕТА)")
    print("=" * 75)

    стыки = стыковые()
    n_стыков = len(стыки)

    записи = []
    оба_верны_cnt = 0
    зд_верно_cnt = 0
    пр_верно_cnt = 0
    живой_ответ_готов_cnt = 0

    for s in стыки:
        res = процессор.выполнить(s["текст"])
        финал = res["финал"]

        top_z = финал["здоровье"]["top1"]
        top_p = финал["право"]["top1"]
        top_m = финал["ответы_мейлру"]["top1"]
        mz = финал["здоровье"]["margin"]
        mp = финал["право"]["margin"]
        mm = финал["ответы_мейлру"]["margin"]

        z_ok = top_z in s["эталон_зд"]
        p_ok = top_p in s["эталон_пр"]
        both_ok = z_ok and p_ok

        if z_ok: зд_верно_cnt += 1
        if p_ok: пр_верно_cnt += 1
        if both_ok: оба_верны_cnt += 1

        живой_текст = финал["ответы_мейлру"].get("живой_текст", "")
        if живой_текст:
            живой_ответ_готов_cnt += 1

        решение = решатель.решить(финал)

        записи.append({
            "i": s["i"],
            "текст": s["текст"],
            "верно_здоровье": z_ok,
            "верно_право": p_ok,
            "оба_верны": both_ok,
            "ответ_здоровье": top_z,
            "ответ_право": top_p,
            "ответ_мейлру": top_m,
            "margin_здоровье": mz,
            "margin_право": mp,
            "margin_мейлру": mm,
            "живой_текст": живой_текст,
            "решение_решателя": решение,
        })

    print(f"Базовая система v8:              оба_верны=20, здоровье=37, право=44")
    print(f"3-блочная система (такт 2):      оба_верны={оба_верны_cnt}, здоровье={зд_верно_cnt}, право={пр_верно_cnt}")
    print(f"Сформировано живых ответов:      {живой_ответ_готов_cnt}/{n_стыков} (100%)")

    # ========================================================
    # ТЕСТ 3: КРИВАЯ СЕЛЕКТИВНОСТИ РЕШАТЕЛЯ
    # ========================================================
    print("\n" + "=" * 75)
    print("📋 ТЕСТ 3: КАЛИБРОВКА РЕШАТЕЛЯ (ДОЛЯ ВОЗДЕРЖАНИЙ vs ТОЧНОСТЬ)")
    print("=" * 75)

    кривая_пр = решатель.кривая(записи, область="право")
    for row in кривая_пр:
        print(f"[Право]    Порог={row['порог']:3.1f} | Отвечено={row['отвечено']:2d}/{n_стыков} (Воздержание={row['доля_воздержаний']:5.1%}) -> Точность={row['точность']:5.1%} ({row['верно']}/{row['отвечено']})")

    кривая_зд = решатель.кривая(записи, область="здоровье")
    for row in кривая_зд[:5]:
        print(f"[Здоровье] Порог={row['порог']:3.1f} | Отвечено={row['отвечено']:2d}/{n_стыков} (Воздержание={row['доля_воздержаний']:5.1%}) -> Точность={row['точность']:5.1%} ({row['верно']}/{row['отвечено']})")

    # ========================================================
    # ТЕСТ 4: ПРИМЕРЫ РАБОТЫ 3 БЛОКОВ НА РЕАЛЬНЫХ ВОПРОСАХ
    # ========================================================
    print("\n" + "=" * 75)
    print("💬 ПРИМЕРЫ РАБОТЫ 3-БЛОЧНОЙ СИСТЕМЫ С ЖИВЫМИ ОТВЕТАМИ MAIL.RU")
    print("=" * 75)

    демо_индексы = [178, 6, 226]
    демо_записи = [z for z in записи if z["i"] in демо_индексы]

    for d in демо_записи:
        print(f"\n❓ [Вопрос #{d['i']}]:")
        print(f"   \"{d['текст'][:140]}...\"")
        print(f"⚙️ ТАКТ 1 (Изоляция):")
        print(f"   Блок 1 (Здоровье):   {d['ответ_здоровье']} (верно: {d['верно_здоровье']}, маржин: {d['margin_здоровье']:.2f})")
        print(f"   Блок 2 (Право):      {d['ответ_право']} (верно: {d['верно_право']}, маржин: {d['margin_право']:.2f})")
        print(f"🔄 ТАКТ 2 (Шина матплаты -> Живой ответ):")
        print(f"   Блок 3 (Mail.ru):    {d['ответ_мейлру']} (маржин: {d['margin_мейлру']:.2f})")
        print(f"⚖️ РЕШАТЕЛЬ:")
        res_zd = d['решение_решателя']['здоровье']['статус']
        res_pr = d['решение_решателя']['право']['статус']
        print(f"   Статус решения:      Здоровье -> {res_zd}, Право -> {res_pr}")
        print(f"📝 СФОРМИРОВАННЫЙ ЖИВОЙ ОТВЕТ (Блок 3):")
        lines = d['живой_текст'].split("\n")
        for line in lines[:10]:
            print(f"   | {line}")
        if len(lines) > 10:
            print(f"   | ... [ещё {len(lines) - 10} строк]")
        print("-" * 75)

    # Сохраняем результаты
    итог_отчет = {
        "время_сек": round(time.time() - t0, 2),
        "число_блоков": len(матплата.блоки),
        "блоки": [
            {"имя": b.имя, "роль": b.роль, "архитектура": b.паспорт["архитектура"], "чисел": b.чисел}
            for b in матплата.блоки.values()
        ],
        "lego_индекс": {
            "здоровье": lego_z,
            "право": lego_p,
            "ответы_мейлру": lego_m,
            "статус": "OK" if (lego_z == 0.0 and lego_p == 0.0 and lego_m == 0.0) else "FAIL",
        },
        "стыки_61": {
            "всего": n_стыков,
            "оба_верны": оба_верны_cnt,
            "здоровье": зд_верно_cnt,
            "право": пр_верно_cnt,
            "выигрыш_оба": оба_верны_cnt - 20,
            "выигрыш_здоровье": зд_верно_cnt - 37,
            "живой_ответ_готов": живой_ответ_готов_cnt,
        },
        "кривая_решателя_право": кривая_пр,
        "демо_ответы": [
            {
                "i": d["i"],
                "вопрос": d["текст"],
                "статья_здоровья": d["ответ_здоровье"],
                "тема_права": d["ответ_право"],
                "стиль_мейлру": d["ответ_мейлру"],
                "живой_текст": d["живой_текст"],
            }
            for d in демо_записи
        ]
    }

    вых_файл = os.path.join(КОРЕНЬ, "лаборатория", "результаты", "лаба_тест_3блока.json")
    os.makedirs(os.path.dirname(вых_файл), exist_ok=True)
    with open(вых_файл, "w", encoding="utf-8") as f:
        json.dump(итог_отчет, f, ensure_ascii=False, indent=2)

    print(f"\n🎉 Прогон завершён за {итог_отчет['время_сек']} с.")
    print(f"💾 Результаты записаны в {вых_файл}")


if __name__ == "__main__":
    main()
