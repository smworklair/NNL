# -*- coding: utf-8 -*-
"""v9.1 ядро-держатель. Три функции, мнения нет:
воткнуть/вынуть (реестр) → запустить (ВСЕ воткнутые работают каждый запрос,
отдыхающих нет) → собрать (ОДИН ответ модели, хозяина у ответа нет) + след."""
import numpy as np

import среда as С


class Модель:
    def __init__(s, круги=3, tau=2.0, преломление=True, только_через_поле=False):
        s.воткнуты = {}       # имя -> блок-коннектор
        s.K, s.Ki = [], {}    # общее поле: понятия всех воткнутых
        s.круги, s.tau, s.преломление = круги, tau, преломление
        s.только_через_поле = только_через_поле  # проба 2: прямой путь запрещён,
        # ответ читается только через поле — в одиночку не может никто по построению
        s.запуски = []        # кто реально работал (доказательство: все всегда)

    # ---- держать ----
    def воткнуть(s, б):
        s.воткнуты[б["имя"]] = б
        for k in б["пишет"]:
            if k not in s.Ki:
                s.Ki[k] = len(s.K)
                s.K.append(k)

    def вынуть(s, имя):
        del s.воткнуты[имя]

    # ---- запустить: работают ВСЕ, каждый круг ----
    def спросить(s, подготовленные):
        """подготовленные: {имя: (h, токены)}. Возвращает (ответ_модели, след)."""
        имена = sorted(s.воткнуты)
        assert set(подготовленные) == set(имена), "работают все воткнутые, без исключений"
        s.запуски.append(имена)
        h = {n: подготовленные[n][0] for n in имена}
        # круг 1: пишут из вопроса; дальше круги отражений: сверка с полем + перепись
        затвор = {n: np.ones(len(s.воткнуты[n]["пишет"]), np.float32) for n in имена}
        for t in range(s.круги):
            записи = {}
            for n in имена:
                б = s.воткнуты[n]
                z = h[n] @ б["P"]["A"] + б["P"]["a"]
                c = (б["L"] * np.tanh(z / б["L"]) * затвор[n]).astype(np.float32)
                записи[n] = (c, б["пишет"])
            m, pi, писатели = С.смешать(записи, s.Ki, s.K, set(имена))
            mt = С.преломить(m, включить=s.преломление)
            if t < s.круги - 1:
                for n in имена:
                    cols = np.array([s.Ki[k] for k in s.воткнуты[n]["пишет"]], np.int64)
                    затвор[n] = С.стробировать(mt, cols, s.tau)
        # собрать: ОДИН softmax по ответам всех сразу; у ответа нет хозяина
        всё, cols, start = [], {}, 1
        for n in имена:
            cols[n] = np.arange(start, start + len(s.воткнуты[n]["ответы"]))
            start += len(s.воткнуты[n]["ответы"])
            всё += s.воткнуты[n]["ответы"]
        счёты, разбор = {}, {}
        for n in имена:
            б = s.воткнуты[n]
            прямой_вектор = h[n] @ б["P"]["U"] + б["P"]["b"]
            X = np.zeros((2 * len(б["читает"])), np.float32)
            for j, k in enumerate(б["читает"]):
                if k in s.Ki:
                    X[j] = mt[s.Ki[k]] / б["масштаб"]
                    X[len(б["читает"]) + j] = pi[s.Ki[k]]
            шина = X @ б["P"]["V"]
            sc = шина if s.только_через_поле else прямой_вектор + шина
            счёты[n] = sc
            разбор[n] = (sc, X, шина)
        logits = np.full((start,), -1e30, np.float32)
        logits[0] = 0.0
        for n in имена:
            logits[cols[n]] = счёты[n]
        mx = logits.max()
        e = np.exp(logits - mx)
        p = e / e.sum()
        top = int(p.argmax())
        if top == 0:
            return ({"модель": "v9.1-целая", "ответ": "", "p": round(float(p[0]), 4)},
                    {"топ": "", "p": round(float(p[0]), 4), "работали": имена, "кругов": s.круги,
                     "поле": [round(float(x), 4) for x in mt]})
        ans = всё[top - 1]
        # чей вклад: прямой своего + шина по писателям (каждое понятие писал ровно один)
        влад = next(n for n in имена if top in cols[n])
        б = s.воткнуты[влад]
        la = top - cols[влад][0]
        sc, X, шина = разбор[влад]
        прямой = 0.0 if s.только_через_поле else float((h[влад] @ б["P"]["U"] + б["P"]["b"])[la])
        по_писателям = {}
        R = len(б["читает"])
        for j, k in enumerate(б["читает"]):
            if k not in s.Ki:
                continue
            v = float(X[j] * б["P"]["V"][j, la] + X[R + j] * б["P"]["V"][R + j, la])
            w = next(iter(писатели.get(k, ["?"])))
            по_писателям[w] = по_писателям.get(w, 0.0) + v
        обл, ид = ans.split(":")[1], ans.split(":", 2)[2]
        return {"модель": "v9.1-целая", "ответ": ans, "область": обл, "id": ид, "p": round(float(p[top]), 4)}, \
               {"топ": ans, "p": round(float(p[top]), 4), "прямой": round(прямой, 3),
                "шина_по_писателям": {n: round(v, 3) for n, v in по_писателям.items()},
                "работали": имена, "кругов": s.круги,
                "поле": [round(float(x), 4) for x in mt]}
