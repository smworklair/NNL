/* Бланки: заявления и жалобы с пустыми местами «____». Данные собраны из старого сайта (макет.js: БУМАГИ), заполнение хранится на устройстве. */
export type Бумага = {
  н: number; вид: string; куда: string; титул: string; подтитул: string | null; имя: string; лид: string;
  кому: string[]; тело: string[]; подсказка: string;
};
export type Поле = { и: number; дата: boolean; исх: string; подпись: string; длинное: boolean };
export type Сегмент = { т: string } | { п: Поле };
export type Разбор = { абзацы: Сегмент[][]; поля: Поле[] };

export const ЗАЯВИТЕЛЬ_ПУСТО = [
  "от ___________________________________", "дата рождения: _______________________",
  "адрес регистрации: ___________________", "телефон: _____________________________",
];

const РЕГ = /(«_{2,}»\s*_{3,}\s*20_{2,}\s*г\.)|(_{4,})(\s*\(([^)]{2,}?)\))?/g;
const заглавная = (с: string) => (с ? с.charAt(0).toUpperCase() + с.slice(1) : с);

/* Подпись поля: подсказка в скобках после пропуска или несколько слов перед ним. */
function подписьПоля(до: string, дата: boolean) {
  if (дата) return "Дата";
  const слова = до.replace(/[«»_.,;:()\d]+/g, " ").trim().split(/\s+/).filter(Boolean);
  return слова.length ? заглавная(слова.slice(-4).join(" ")) : "Заполните";
}

export function разобрать(б: Бумага): Разбор {
  const поля: Поле[] = [];
  const абзацы = б.тело.map((т) => {
    const сег: Сегмент[] = [];
    let поз = 0;
    for (const м of т.matchAll(РЕГ)) {
      const инд = m_index(м);
      if (инд > поз) сег.push({ т: т.slice(поз, инд) });
      const дата = !!м[1];
      const хинт = м[4] || "";
      const подп = заглавная(хинт ? хинт.replace(/^укажите[,:]?\s*/i, "") : подписьПоля(т.slice(0, инд), дата));
      const поле: Поле = { и: поля.length, дата, исх: м[0], подпись: подп, длинное: !дата && (хинт.length > 28 || /опишите|перечислите|обстоятельства|факт|довод/i.test(хинт)) };
      поля.push(поле);
      сег.push({ п: поле });
      поз = инд + м[0].length;
    }
    if (поз < т.length) сег.push({ т: т.slice(поз) });
    return сег;
  });
  return { абзацы, поля };
}
const m_index = (м: RegExpMatchArray) => м.index ?? 0;

/* Хранилище на устройстве: свои данные заявителя и значения пропусков каждой бумаги (ключи как у старого сайта). */
export type Заявитель = { фио?: string; дата?: string; адрес?: string; тел?: string };
const КЛЮЧ_МОИ = "справка_годность_мои";
const ключБумаги = (н: number) => `справка_годность_бумага_${н}`;

export function читатьЗаявителя(): Заявитель {
  try { const м = JSON.parse(localStorage.getItem(КЛЮЧ_МОИ) || "{}"); return м && typeof м === "object" ? м : {}; } catch { return {}; }
}
export function записатьЗаявителя(м: Заявитель) {
  try { localStorage.setItem(КЛЮЧ_МОИ, JSON.stringify(м)); } catch { /* не сохранится */ }
}
export function читатьЗначения(н: number): Record<number, string> {
  try { const х = JSON.parse(localStorage.getItem(ключБумаги(н)) || "{}"); return (х && х.в) || {}; } catch { return {}; }
}
export function записатьЗначения(н: number, в: Record<number, string>) {
  try { localStorage.setItem(ключБумаги(н), JSON.stringify({ в, а: {} })); } catch { /* не сохранится */ }
}

export const строкиЗаявителя = (м: Заявитель) =>
  !м.фио && !м.дата && !м.адрес && !м.тел
    ? ЗАЯВИТЕЛЬ_ПУСТО
    : [
        "от " + (м.фио || "______________________________________"),
        "дата рождения: " + (м.дата || "____________________"),
        "адрес регистрации: " + (м.адрес || "____________________"),
        "телефон: " + (м.тел || "____________________"),
      ];

export const значениеПоля = (п: Поле, в: string | undefined) => {
  const з = (в ?? "").trim();
  if (!з) return "";
  if (п.дата && /^\d{4}-\d{2}-\d{2}$/.test(з)) { const [г, м, д] = з.split("-"); return `«${д}» ${м}.${г} г.`; }
  return з;
};

export function плоскийТекст(б: Бумага, р: Разбор, в: Record<number, string>, м: Заявитель): string {
  const тело = р.абзацы.map((сег) => сег.map((с) => ("т" in с ? с.т : значениеПоля(с.п, в[с.п.и]) || с.п.исх)).join(""));
  return [...б.кому, "", ...строкиЗаявителя(м), "", б.титул, ...(б.подтитул ? [б.подтитул] : []), "", ...тело, "",
    "«___» ______________ 20___ г.    ______________ / __________________", "(подпись)          (фамилия, инициалы)"].join("\n");
}
