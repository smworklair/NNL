export const БУКВЫ = ["А", "Б", "В", "Г", "Д"] as const;

/* Буква категории из записи вроде «Б-3» или «Д»; пусто, если категории нет. */
export const буква = (к: string | undefined | null) => {
  const б = (к ?? "").trim().charAt(0).toUpperCase();
  return (БУКВЫ as readonly string[]).includes(б) ? б : "";
};
