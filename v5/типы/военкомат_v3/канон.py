# -*- coding: utf-8 -*-
"""Эталонное правило «текст → основы». Это часть ОПРЕДЕЛЕНИЯ типа «Разбор», а не блок: обученных чисел здесь нет.

Правило:
  1) нижний регистр, «ё» → «е»;
  2) слова — непрерывные куски из русских/латинских букв и цифр;
  3) служебные слова из списка STOP выбрасываются («не», «нет», «без» — оставляются: они меняют смысл);
  4) основа слова — стеммер Snowball для русского (пакет snowballstemmer, версия записана в типы.json).

Эталонный разбор = основы, которые есть в СЛОВАРЕ типа, в порядке текста (повторы сохраняются).
Им пользуются: блок разбора (как первым шагом) и обучение блоков областей (чтобы учиться без блока разбора).
Ядро это правило не вызывает: ядро только проверяет, что пришедшие основы лежат в словаре.
"""
import re

import snowballstemmer

STOP = frozenset("""
и в во на с со к ко о об обо от до по за из изо у а но да или либо ли же бы б ведь вот ну то это этот эта эти этого этой
этим этих тот та те того той тем тех так как что чтобы когда где куда откуда если чем при для под над про через между
я мы ты вы он она оно они меня мне мной нас нам нами тебя тебе тобой вас вам вами его ему им её ее ей ею их ими него нему
нем нём ней нее неё них ним ними мой моя мое моё мои моего моей моему моим моих свой своя свое своё свои своего своей
своему своим своих себя себе собой твой твоя твое твоё твои ваш ваша ваше ваши наш наша наше наши уже ещё еще тоже также
даже лишь вообще просто типа нибудь
""".split())

_WORD = re.compile(r"[а-яa-z0-9]+")
_stemmer = snowballstemmer.stemmer("russian")


def words(text):
    """Слова текста по правилу 1–2 (без выбрасывания служебных)."""
    return _WORD.findall(text.lower().replace("ё", "е"))


def stem(word):
    return _stemmer.stemWord(word)


def content_words(text):
    """Значимые слова (правила 1–3) в порядке текста."""
    return [w for w in words(text) if w not in STOP]


def stems(text):
    """Основы значимых слов (правила 1–4), без сверки со словарём."""
    return [stem(w) for w in content_words(text)]


def reference_parse(text, vocab):
    """Эталонные основы: только те, что есть в словаре типа (vocab — множество строк)."""
    return [s for s in stems(text) if s in vocab]
