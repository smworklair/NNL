# -*- coding: utf-8 -*-
"""Создать блок NNL из размеченных примеров за один вызов: папка блока (паспорт.json + веса.npz) под архитектуру «мешок_шина».

    from nnl.создать_блок import создать_блок
    отчёт = создать_блок("блоки/погода", "погода", примеры=[("дождь и ветер", "плохая"), ("солнце жара", "хорошая"), ...],
                         проекции={"плохая": {"погода:плохая": 16.0}})

Что делает: хэшированные признаки слов (как в архитектуре «мешок_шина»), softmax-регрессия, Адам, деление на обучающую и отложенную часть по зерну.
Возвращает отчёт: сколько примеров, точность на отложенных, уверенность. Читать шину блок учится отдельно (здесь матрица чтения нулевая):
блок, сделанный этим вызовом, на такте 1 полноценен, на такте 2 пока не использует чужие выводы. Вес-файл подписывается sha256 для паспорта.
Нужны только numpy и стандартная библиотека; нейросетевых фреймворков и сети нет."""
import hashlib
import json
import os
import zlib

import numpy as np

from .язык import Язык


def _индексы(соль, токены, корзины):
    return np.fromiter((zlib.crc32((соль + "\x1f" + t).encode("utf-8")) % корзины for t in токены), dtype=np.int64, count=len(токены))


def _свёртка(E, idx):
    if len(idx) == 0:
        return np.zeros(E.shape[1])
    return E[idx].sum(0) / np.sqrt(len(idx))


def создать_блок(папка, имя, примеры, язык=None, проекции=None, читает=(), корзины=4096, размер=16, эпохи=30, шаг=0.05, доля_отложенных=0.15, зерно=0,
                 роль=None):
    """примеры: [(текст, id_ответа)]. проекции: {id_ответа: {понятие_шины: значение}} — что блок пишет на шину при уверенном ответе.
    читает: понятия шины, которые блок будет читать на такте 2 (матрица чтения нулевая, обучить её можно отдельно)."""
    язык = язык or Язык()
    соль = имя
    ответы = sorted({a for _, a in примеры})
    Y = len(ответы)
    if Y < 2:
        raise ValueError("нужно не меньше двух разных ответов, получено %d" % Y)
    рнд = np.random.RandomState(зерно)
    порядок = рнд.permutation(len(примеры))
    n_отл = max(1, int(доля_отложенных * len(примеры)))
    отл_idx, обуч_idx = порядок[:n_отл], порядок[n_отл:]
    номер = {a: i for i, a in enumerate(ответы)}
    X = [_индексы(соль, язык.перевести(t)["токены"], корзины) for t, _ in примеры]
    y = np.array([номер[a] for _, a in примеры])
    E = (рнд.randn(корзины, размер) * 0.05)
    U = (рнд.randn(размер, Y) * 0.05)
    b = np.zeros(Y)
    mE, vE, mU, vU, mb, vb = (np.zeros_like(E), np.zeros_like(E), np.zeros_like(U), np.zeros_like(U), np.zeros_like(b), np.zeros_like(b))
    t_ = 0
    for эпоха in range(эпохи):
        for i in рнд.permutation(обуч_idx):
            idx = X[i]
            h = _свёртка(E, idx)
            z = h @ U + b
            z -= z.max()
            p = np.exp(z)
            p /= p.sum()
            p[y[i]] -= 1.0
            gU, gb = np.outer(h, p), p
            gh = U @ p
            gE = np.zeros_like(E)
            if len(idx):
                np.add.at(gE, idx, gh / np.sqrt(len(idx)))
            t_ += 1
            for (par, g, m, v) in ((E, gE, mE, vE), (U, gU, mU, vU), (b, gb, mb, vb)):
                m *= 0.9
                m += 0.1 * g
                v *= 0.999
                v += 0.001 * g * g
                par -= шаг * (m / (1 - 0.9 ** t_)) / (np.sqrt(v / (1 - 0.999 ** t_)) + 1e-8)

    def предсказать(i):
        z = _свёртка(E, X[i]) @ U + b
        o = np.sort(z)
        return int(z.argmax()), float(o[-1] - o[-2])
    верно = [предсказать(i)[0] == y[i] for i in отл_idx]
    верно_обуч = [предсказать(i)[0] == y[i] for i in обуч_idx[: max(1, len(отл_idx))]]
    отрывы = [предсказать(i)[1] for i in отл_idx]

    пишет = sorted({k for п in (проекции or {}).values() for k in п})
    читает = list(читает)
    W, R = len(пишет), len(читает)
    os.makedirs(папка, exist_ok=True)
    файл = os.path.join(папка, "веса.npz")
    np.savez(файл, E=E.astype(np.float32), A=np.zeros((размер, W), dtype=np.float32), a=np.zeros(W, dtype=np.float32), U=U.astype(np.float32),
             V=np.zeros((2 * R, Y), dtype=np.float32), b=b.astype(np.float32), пишет=np.array(пишет, dtype=str), читает=np.array(читает, dtype=str),
             ответы=np.array(ответы, dtype=str))
    sha = hashlib.sha256(open(файл, "rb").read()).hexdigest()
    паспорт = {"имя": имя, "версия": 1, "роль": роль or имя, "архитектура": "мешок_шина",
               "настройки": {"корзины": корзины, "размер": размер, "граница": 8.0, "соль": соль, "свёртка": "корень", "масштаб_чтения": 8.0},
               "веса": {"файл": "веса.npz", "sha256": sha, "чисел": int(E.size + U.size + b.size + размер * W + W + 2 * R * Y)},
               "пишет": пишет, "читает": читает, "ответы": ответы, "проекции": проекции or {},
               "обучение": {"примеров": len(примеры), "обучающих": int(len(обуч_idx)), "отложенных": int(len(отл_idx)), "эпох": эпохи, "зерно": зерно}}
    with open(os.path.join(папка, "паспорт.json"), "w", encoding="utf-8") as f:
        json.dump(паспорт, f, ensure_ascii=False, indent=1)
    return {"папка": папка, "ответов": Y, "примеров": len(примеры), "точность_отложенных": round(float(np.mean(верно)), 3),
            "точность_обучающих": round(float(np.mean(верно_обуч)), 3), "средний_отрыв_отложенных": round(float(np.mean(отрывы)), 2)}
