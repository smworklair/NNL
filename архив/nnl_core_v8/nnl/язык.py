# -*- coding: utf-8 -*-
"""Простейший язык NNL: текст → токены (слова и пары соседних слов), без словарей предметной области и без обученных чисел.
Матплата требует от языка один метод: перевести(текст) → {"токены": [...]}. Для своего языка (стемминг, отрицание, другая письменность)
напишите класс с таким же методом и передайте его матплате."""
import re

_СЛОВО = re.compile(r"[\w\-]+", re.U)


class Язык:
    def __init__(self, пары=True, мин_длина=1):
        self.пары = пары
        self.мин_длина = мин_длина

    def перевести(self, текст):
        слова = [w for w in _СЛОВО.findall((текст or "").lower().replace("ё", "е")) if len(w) >= self.мин_длина]
        токены = list(слова)
        if self.пары:
            токены += ["%s_%s" % (a, b) for a, b in zip(слова, слова[1:])]
        return {"токены": токены}
