# -*- coding: utf-8 -*-
"""NNL (Neural Network Lego) — Утилита валидации блока (NNL Linter / Checker).

Проверяет соответствие папки блока стандарту NNL v1.0:
  1. Наличие и валидность паспорт.json.
  2. Соответствие контрольной суммы sha256 файла весов.
  3. Совместимость с кодом объявленной архитектуры.
  4. Тест контракта изоляции (проход при пустом срезе шины).

Проверка вставки (проверить_вставку): новый блок, подключённый при замороженных старых, не должен менять ответы соседей больше чем на ε.
Через шину новый блок может влиять на соседей (они читают его понятия на такте 2), и каждый независимо обученный блок увеличивает такой риск.
Проверяется на вопросах: (1) доля изменённых итоговых ответов соседей ≤ ε; (2) такт 1 соседей не изменился ни на одном вопросе (Lego-индекс 0);
(3) собственный ответ нового блока на такте 1 равен его соло-ответу; (4) после снятия блока всё как до вставки.

Запуск:
  python -m nnl.линтер <путь_к_папке_блока> [путь_к_папке_архитектур]
  python -m nnl.линтер <папка_нового_блока> --вставка <папка_соседа> [<папка_соседа> ...] [--вопросы файл.jsonl] [--эпсилон 0.01]
"""
import hashlib
import importlib.util
import json
import os
import sys

ОБЯЗАТЕЛЬНО = ("имя", "версия", "архитектура", "веса", "пишет", "читает", "ответы")


def _sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _load_module(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def проверить_блок(папка_блока, папка_архитектур=None):
    ошибки = []
    предупреждения = []
    папка_блока = os.path.abspath(папка_блока)

    # 1. Проверка паспорт.json
    пасп_файл = os.path.join(папка_блока, "паспорт.json")
    if not os.path.isfile(пасп_файл):
        return {"статус": "ОШИБКА", "ошибки": [f"Файл {пасп_файл} не найден"]}

    try:
        with open(пасп_файл, encoding="utf-8") as f:
            пасп = json.load(f)
    except Exception as e:
        return {"статус": "ОШИБКА", "ошибки": [f"Ошибка парсинга JSON: {e}"]}

    for поле in ОБЯЗАТЕЛЬНО:
        if поле not in пасп:
            ошибки.append(f"Отсутствует обязательное поле {поле!r} в паспорте")

    if ошибки:
        return {"статус": "ОШИБКА", "ошибки": ошибки}

    # 2. Проверка файла весов
    веса_cfg = пасп.get("веса", {})
    вес_файл = os.path.join(папка_блока, веса_cfg.get("файл", ""))
    if not os.path.isfile(вес_файл):
        ошибки.append(f"Файл весов {вес_файл!r} не существует")
    else:
        sha_факт = _sha256_file(вес_файл)
        sha_паспорт = веса_cfg.get("sha256")
        if sha_факт != sha_паспорт:
            ошибки.append(f"Несовпадение sha256 весов: в паспорте {sha_паспорт}, на диске {sha_факт}")

    # 3. Проверка архитектуры
    arch_имя = пасп.get("архитектура")
    if папка_архитектур:
        arch_путь = os.path.join(папка_архитектур, arch_имя + ".py")
    else:
        # без явной папки: поднимаемся от папки блока вверх и берём первую «архитектуры/<имя>.py»
        arch_путь = None
        д = os.path.abspath(папка_блока)
        for _ in range(6):
            кандидат = os.path.join(д, "архитектуры", arch_имя + ".py")
            if os.path.isfile(кандидат):
                arch_путь = кандидат
                break
            д = os.path.dirname(д)
        if arch_путь is None:
            arch_путь = os.path.join(os.path.abspath(папка_блока), "архитектуры", arch_имя + ".py")

    if not os.path.isfile(arch_путь):
        ошибки.append(f"Код архитектуры {arch_имя!r} не найден по пути {arch_путь}")
        obj = None
        arch_mod = None
    else:
        try:
            arch_mod = _load_module(arch_путь, f"lint_arch_{arch_имя}")
            for метод in ("загрузить", "чисел", "проход2"):
                if not hasattr(arch_mod, метод):
                    ошибки.append(f"В модуле архитектуры {arch_имя} отсутствует обязательный метод {метод}")
            if not ошибки:
                obj = arch_mod.загрузить(вес_файл, пасп)
            else:
                obj = None
        except Exception as e:
            ошибки.append(f"Ошибка загрузки блока архитектурой {arch_имя}: {e}")
            obj = None
            arch_mod = None

    # 4. Проверка контракта изоляции
    if obj is not None and arch_mod is not None:
        try:
            тест_токены = ["тест", "проверка", "блок"]
            счёт_изоляция = arch_mod.проход2(obj, тест_токены, {})
            if not isinstance(счёт_изоляция, dict) or len(счёт_изоляция) == 0:
                ошибки.append("Метод проход2 вернул пустой или некорректный словарь счетов при изолированном срезе {}")
        except Exception as e:
            ошибки.append(f"Сбой выполнения проход2 в изолированном режиме: {e}")

    # 5. Проверка объявленных проекций
    if "проекции" not in пасп:
        предупреждения.append("В паспорте нет поля 'проекции'. Блок будет использовать внешнюю онтологию.")

    статус = "УСПЕХ" if not ошибки else "ОШИБКА"
    return {
        "статус": статус,
        "имя_блока": пасп.get("имя"),
        "архитектура": arch_имя,
        "чисел": arch_mod.чисел(obj) if obj and arch_mod else 0,
        "число_ответов": len(пасп.get("ответы", [])),
        "читает": пасп.get("читает", []),
        "пишет": пасп.get("пишет", []),
        "ошибки": ошибки,
        "предупреждения": предупреждения,
    }


ЭПСИЛОН_ПО_УМОЛЧАНИЮ = 0.01       # вставка настоящего блока в первой системе проекта меняла 0,22 % ответов соседей; 1 % — запас на порядок больше


def _ответы(процессор, вопросы, имена):
    """Итоговые (после такта 2) и тактовые top-1 ответы названных блоков на каждый вопрос."""
    итог, такт1 = [], []
    for q in вопросы:
        res = процессор.выполнить(q)
        итог.append({n: res["такт2"][n]["top1"] for n in имена if n in res["такт2"]})
        такт1.append({n: res["такт1"][n]["top1"] for n in имена if n in res["такт1"]})
    return итог, такт1


def проверить_вставку(процессор, папка_блока, вопросы, эпсилон=ЭПСИЛОН_ПО_УМОЛЧАНИЮ):
    """Вставка блока в работающую систему. процессор: Процессор над матплатой с уже подключёнными соседями (ядро — на усмотрение вызывающего).
    Блок подключается, система прогоняется на вопросах, блок снимается. Возвращает отчёт; статус «УСПЕХ», если все четыре условия выполнены."""
    матплата = процессор.матплата
    соседи = list(матплата.блоки)
    ошибки = []
    итог_до, такт1_до = _ответы(процессор, вопросы, соседи)
    ok, msg = матплата.подключить(папка_блока)
    if not ok:
        return {"статус": "ОШИБКА", "ошибки": list(msg), "соседи": соседи}
    имя = msg
    try:
        итог_после, такт1_после = _ответы(процессор, вопросы, соседи)
        блок = матплата.блоки[имя]
        изменилось, всего = 0, 0
        по_соседям = {n: 0 for n in соседи}
        for до, после in zip(итог_до, итог_после):
            for n in соседи:
                всего += 1
                if до.get(n) != после.get(n):
                    изменилось += 1
                    по_соседям[n] += 1
        доля = изменилось / всего if всего else 0.0
        if доля > эпсилон:
            ошибки.append("вставка меняет ответы соседей: %d из %d (%.2f %%) при допустимых %.2f %%" % (изменилось, всего, 100 * доля, 100 * эпсилон))
        такт1_изменилось = sum(1 for до, после in zip(такт1_до, такт1_после) for n in соседи if до.get(n) != после.get(n))
        if такт1_изменилось:
            ошибки.append("нарушена изоляция такта 1: ответы соседей на такте 1 изменились %d раз" % такт1_изменилось)
        расхождений_соло = 0
        for q in вопросы:
            токены = матплата.язык.перевести(q)["токены"]
            соло = блок.arch.проход2(блок.obj, токены, {})
            расхождений_соло += max(соло, key=соло.get) != процессор.выполнить(q)["такт1"][имя]["top1"]
        if расхождений_соло:
            ошибки.append("ответ нового блока на такте 1 не равен его соло-ответу (%d вопросов)" % расхождений_соло)
    finally:
        матплата.снять(имя)
    итог_снятие, _ = _ответы(процессор, вопросы, соседи)
    вернулось = итог_снятие == итог_до
    if not вернулось:
        ошибки.append("после снятия блока ответы соседей не вернулись к прежним")
    return {"статус": "УСПЕХ" if not ошибки else "ОШИБКА", "блок": имя, "соседи": соседи, "вопросов": len(вопросы), "эпсилон": эпсилон,
            "изменилось_ответов_соседей": изменилось, "всего_ответов_соседей": всего, "доля_изменений": round(доля, 5), "по_соседям": по_соседям,
            "такт1_соседей_изменилось": такт1_изменилось, "расхождений_с_соло": расхождений_соло, "снятие_возвращает_как_было": вернулось, "ошибки": ошибки}


def _вставка_из_командной_строки(аргументы):
    """--вставка: подключить соседей из папок и прогнать новый блок на вопросах из файла (jsonl с полем «текст» или «вопрос»).
    Язык по умолчанию — nnl.язык.Язык (слова и пары слов); архитектуры берутся из --архитектуры (по умолчанию ./архитектуры)."""
    from nnl.матплата import Матплата
    from nnl.процессор import Процессор
    from nnl.ядро import ЯдроПричинности
    from nnl.язык import Язык
    папка_блока = аргументы[0]
    соседи = аргументы[аргументы.index("--вставка") + 1:]
    соседи = [x for x in соседи[:next((i for i, x in enumerate(соседи) if x.startswith("--")), len(соседи))]]
    if "--вопросы" not in аргументы:
        raise SystemExit("нужен --вопросы файл.jsonl (по одному вопросу на строку, поле «текст» или «вопрос»)")
    файл = аргументы[аргументы.index("--вопросы") + 1]
    эпсилон = float(аргументы[аргументы.index("--эпсилон") + 1]) if "--эпсилон" in аргументы else ЭПСИЛОН_ПО_УМОЛЧАНИЮ
    архитектуры = аргументы[аргументы.index("--архитектуры") + 1] if "--архитектуры" in аргументы else os.path.join(os.getcwd(), "архитектуры")
    с_вопросами = [json.loads(l) for l in open(файл, encoding="utf-8") if l.strip()]
    вопросы = [r.get("текст") or r.get("вопрос") for r in с_вопросами][:300]
    м = Матплата(Язык(), архитектуры)
    for п in соседи:
        ok, msg = м.подключить(п)
        assert ok, (п, msg)
    return проверить_вставку(Процессор(м, ядро=ЯдроПричинности(), tau_conf=1.0), папка_блока, вопросы, эпсилон)


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Использование: python -m nnl.линтер <папка_блока> [папка_архитектур]  |  ... --вставка <папка_соседа>... --вопросы файл.jsonl")
        sys.exit(1)

    if "--вставка" in sys.argv:
        res = _вставка_из_командной_строки(sys.argv[1:])
        print(json.dumps(res, ensure_ascii=False, indent=2))
        sys.exit(0 if res["статус"] == "УСПЕХ" else 1)
    папка = sys.argv[1]
    arch_dir = sys.argv[2] if len(sys.argv) > 2 and not sys.argv[2].startswith("--") else None
    res = проверить_блок(папка, arch_dir)
    print(json.dumps(res, ensure_ascii=False, indent=2))
    sys.exit(0 if res["статус"] == "УСПЕХ" else 1)
