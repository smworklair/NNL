# -*- coding: utf-8 -*-
"""Игрушечный мир из N независимых блоков для стенда шины. Предметной области нет: у каждого блока три класса ответа, скрытое состояние
мира g общее и связывает блоки (блок b видит его как класс (g + сдвиг_b) mod 3 с вероятностью ρ, иначе случайный класс).

Каждый блок видит на входе только свои подсказки: «сильную» (верна в 95 %) или «слабую» (верна в 55 %), поэтому его собственная точность ≈ 75 % и
отрыв уверенности что-то говорит о правоте. Свои выводы блок пишет на шину (понятие «имя:класс» = 16,0); читает выводы нескольких других.
Матрицу чтения шины V блок ОБУЧАЕТ (логистическая регрессия на шумных выводах писателей, как обучены настоящие блоки на шине), то есть
чтение откалибровано на обычную долю чужих ошибок. Что не откалибровано — поведение при ошибке, которой обучение не видело
(системный сбой писателя, десятки согласных писателей): именно это и измеряет стенд.
Мир нужен для измерения того, как растёт каскад с числом и плотностью блоков; на точность настоящей системы он не претендует."""
import hashlib
import json
import os
import tempfile

import numpy as np

K = 3                       # классов ответа у каждого блока
ЗНАЧЕНИЕ_ПРОЕКЦИИ = 16.0    # как в настоящих блоках: понятие, подтверждённое выводом, пишется числом 16,0
МАСШТАБ_ЧТЕНИЯ = 8.0
СИЛА = {"с": 3.0, "с0": 0.8}   # отрыв сильной и слабой подсказки (на такте 1 блок «уверен» при отрыве ≥ 1,0 — то есть при сильной)
ВЕРНА = {"с": 0.95, "с0": 0.55}
ТАУ = 1.0


class Язык:
    def перевести(self, текст):
        return {"токены": текст.split()}


class Мир:
    def __init__(self, N, степень, зерно=0, rho=0.85):
        self.N, self.rho = N, rho
        self.rng = np.random.default_rng(зерно)
        self.имена = ["б%02d" % i for i in range(N)]
        self.сдвиг = self.rng.integers(0, K, size=N)
        # у каждого блока степень писателей: кого он читает
        self.писатели = {}
        for i in range(N):
            другие = [j for j in range(N) if j != i]
            self.писатели[i] = sorted(self.rng.choice(другие, size=min(степень, len(другие)), replace=False).tolist())
        self.V = {}

    # --- генерация вопросов
    def вопрос(self, rng):
        g = int(rng.integers(0, K))
        истина = [(g + int(self.сдвиг[b])) % K if rng.random() < self.rho else int(rng.integers(0, K)) for b in range(self.N)]
        токены = []
        for b in range(self.N):
            сила = "с" if rng.random() < 0.5 else "с0"
            if rng.random() < ВЕРНА[сила]:
                y = истина[b]
            else:
                y = int(rng.choice([c for c in range(K) if c != истина[b]]))
            токены.append("%s:%d:%s" % (self.имена[b], y, сила))
        return токены, истина

    # --- обучение чтения шины: что блок b должен делать с выводами своих писателей
    def обучить(self, вопросов=3000, шагов=300, lr=0.2, зерно=1):
        rng = np.random.default_rng(зерно)
        данные = [self.вопрос(rng) for _ in range(вопросов)]
        # вывод каждого блока на такте 1: класс и «уверен ли» (отрыв ≥ ТАУ)
        вывод = []
        for токены, _ in данные:
            строка = []
            for b in range(self.N):
                s = np.zeros(K)
                for t in токены:
                    ч = t.split(":")
                    if ч[0] == self.имена[b]:
                        s[int(ч[1])] += СИЛА[ч[2]]
                o = np.sort(s)
                строка.append((int(s.argmax()), (o[-1] - o[-2]) >= ТАУ, s))
            вывод.append(строка)
        for b in range(self.N):
            W = self.писатели[b]
            R = len(W) * K
            X = np.zeros((вопросов, R))
            S = np.zeros((вопросов, K))
            Y = np.zeros(вопросов, dtype=int)
            for q, (токены, истина) in enumerate(данные):
                for wi, w in enumerate(W):
                    y, уверен, _ = вывод[q][w]
                    if уверен:
                        X[q, wi * K + y] = ЗНАЧЕНИЕ_ПРОЕКЦИИ / МАСШТАБ_ЧТЕНИЯ
                S[q] = вывод[q][b][2]
                Y[q] = истина[b]
            V = np.zeros((R, K))
            for _ in range(шагов):
                z = S + X @ V
                z -= z.max(1, keepdims=True)
                p = np.exp(z)
                p /= p.sum(1, keepdims=True)
                p[np.arange(вопросов), Y] -= 1
                V -= lr * (X.T @ p) / вопросов
            self.V[b] = V


def записать_блок(м, каталог, имя, ответы, читает, проекции, V, сила=None):
    """Папка блока (паспорт + веса) и подключение к матплате. Общая часть для всех игрушечных миров стенда."""
    папка = os.path.join(каталог, имя)
    os.makedirs(папка, exist_ok=True)
    np.savez(os.path.join(папка, "веса.npz"), V=V)
    sha = hashlib.sha256(open(os.path.join(папка, "веса.npz"), "rb").read()).hexdigest()
    паспорт = {"имя": имя, "версия": 1, "роль": "игрушечный блок", "архитектура": "игрушка_арх",
               "настройки": {"масштаб_чтения": МАСШТАБ_ЧТЕНИЯ, "сила": сила or СИЛА},
               "веса": {"файл": "веса.npz", "sha256": sha, "чисел": int(V.size)},
               "пишет": sorted({k for п in проекции.values() for k in п}), "читает": читает, "ответы": ответы, "проекции": проекции}
    with open(os.path.join(папка, "паспорт.json"), "w", encoding="utf-8") as f:
        json.dump(паспорт, f, ensure_ascii=False)
    ok, msg = м.подключить(папка)
    assert ok, msg


def новая_матплата(Матплата):
    return Матплата(Язык(), os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "архитектуры")), tempfile.mkdtemp(prefix="игрушка_")


def собрать_матплату(мир, Матплата):
    """Мир → подключённая Матплата: у каждого блока три ответа, он пишет «имя:класс» и читает выводы своих писателей."""
    м, каталог = новая_матплата(Матплата)
    for b, имя in enumerate(мир.имена):
        читает = ["%s:%d" % (мир.имена[w], y) for w in мир.писатели[b] for y in range(K)]
        записать_блок(м, каталог, имя, [str(y) for y in range(K)], читает,
                      {str(y): {"%s:%d" % (имя, y): ЗНАЧЕНИЕ_ПРОЕКЦИИ} for y in range(K)}, мир.V[b])
    return м
