# -*- coding: utf-8 -*-
"""Своя система NNL за 30 строк: два блока из размеченных фраз, шина, два такта, решатель. Запуск (из папки nnl-core): python -X utf8 примеры/своя_система.py"""
import os
import sys
import tempfile

import numpy as np

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, КОРЕНЬ)
sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

from nnl import Матплата, Процессор, ЯдроПричинности, Решатель, Язык  # noqa: E402
from nnl.создать_блок import создать_блок  # noqa: E402

слова = {"хорошая": "солнце тепло ясно лето жара пляж".split(), "плохая": "дождь холод ветер гроза слякоть мороз".split()}
рнд = np.random.RandomState(0)
фразы = [(" ".join(рнд.choice(сл, size=3)), кл) for кл, сл in слова.items() for _ in range(100)]

папка = tempfile.mkdtemp(prefix="своя_система_")
# блок 1 понимает погоду и объявляет, что при уверенном ответе пишет на шину; блок 2 читает это понятие (на такте 2)
print(создать_блок(os.path.join(папка, "погода"), "погода", фразы, проекции={"плохая": {"погода:плохая": 16.0}, "хорошая": {}}))
print(создать_блок(os.path.join(папка, "одежда"), "одежда", [("надень куртку", "куртка"), ("надень футболку", "футболка")] * 20, читает=["погода:плохая"]))

м = Матплата(Язык(), os.path.join(КОРЕНЬ, "архитектуры"))
for блок in ("погода", "одежда"):
    ok, msg = м.подключить(os.path.join(папка, блок))
    assert ok, msg
результат = Процессор(м, ядро=ЯдроПричинности(), tau_conf=1.0).выполнить("дождь холод ветер")
print("шина:", результат["шина"])
print("решение:", Решатель(порог_воздержания=1.0).решить(результат["финал"])["погода"])
