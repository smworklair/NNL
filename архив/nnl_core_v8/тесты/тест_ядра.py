# -*- coding: utf-8 -*-
"""Тесты чистого ядра NNL без предметной области и без внешних данных. Каждая проверка может покраснеть.
Запуск (из папки nnl-core): python -X utf8 тесты/тест_ядра.py   (код возврата 1, если хоть одна проверка не совпала)."""
import itertools
import json
import os
import re
import sys
import tempfile

import numpy as np

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
for п in (КОРЕНЬ, os.path.join(КОРЕНЬ, "примеры")):
    if п not in sys.path:
        sys.path.insert(0, п)
sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

import игрушка as И  # noqa: E402
from nnl import Матплата, Процессор, ЯдроПричинности  # noqa: E402
from nnl import линтер as Л  # noqa: E402
from nnl.создать_блок import создать_блок  # noqa: E402
from nnl.язык import Язык  # noqa: E402

АРХ = os.path.join(КОРЕНЬ, "архитектуры")
проверок = прошло = 0


def отметить(условие, название):
    global проверок, прошло
    проверок += 1
    прошло += 1 if условие else 0
    print("проверка %d: %s — %s" % (проверок, название, "совпало" if условие else "НЕ СОВПАЛО"), flush=True)
    return условие


def новая():
    return Матплата(И.Язык(), АРХ)


def main():
    # --- шина: конфликты, порядок, согласие, слабые значения
    м = новая()
    м.записать_на_шину("x", 16.0, источник="а")
    м.записать_на_шину("x", -16.0, источник="б")
    отметить("x" not in м.шина and set(м.конфликты["x"]) == {"а", "б"}, "шина: «да» и «нет» к одному понятию — конфликт, понятия нет на шине")
    итоги = set()
    for порядок in itertools.permutations([("а", 16.0), ("б", -16.0), ("в", 16.0)]):
        м = новая()
        for источник, v in порядок:
            м.записать_на_шину("x", v, источник=источник)
        итоги.add((tuple(sorted(м.шина.items())), tuple(sorted(м.конфликты))))
    отметить(len(итоги) == 1, "шина: результат не зависит от порядка записи (6 перестановок)")
    м = новая()
    for источник, v in (("а", 16.0), ("б", 12.0), ("в", 12.0)):
        м.записать_на_шину("y", v, источник=источник)
    отметить(м.шина["y"] == 16.0, "шина: согласные источники не складываются")
    м.записать_на_шину("слабое", 0.5, источник="а")
    м.записать_на_шину("слабое", -0.5, источник="б")
    отметить("слабое" in м.шина and "слабое" not in м.конфликты, "шина: слабые значения не конфликт")

    # --- процессор + ядро на трёх блоках: спор датчиков
    м, каталог = И.новая_матплата(Матплата)
    for имя in ("д1", "д2"):
        И.записать_блок(м, каталог, имя, ["0", "1"], [], {"0": {"факт": -16.0}, "1": {"факт": 16.0}}, np.zeros((0, 2)))
    И.записать_блок(м, каталог, "чт", ["0", "1"], ["факт"], {"0": {"чт:0": 16.0}, "1": {"чт:1": 16.0}}, np.array([[-3.0, 3.0]]))
    пр = Процессор(м, ядро=ЯдроПричинности(), tau_conf=1.0)
    согласны, спор, обмен = (пр.выполнить(s) for s in ("д1:1:с д2:1:с чт:0:с0", "д1:1:с д2:0:с чт:0:с0", "д1:0:с д2:1:с чт:0:с0"))
    отметить(согласны["такт2"]["чт"]["top1"] == "1" and not согласны["конфликты"], "процессор: согласные датчики — читатель использует понятие")
    отметить("факт" in спор["конфликты"] and спор["такт2"]["чт"]["top1"] == "0", "процессор: датчики спорят — понятие не записано, читатель при своём")
    отметить(спор["такт2"]["чт"]["top1"] == обмен["такт2"]["чт"]["top1"], "процессор: обмен датчиков местами не меняет ответ")
    отметить(спор["финал"]["_причинная_цепочка"]["статус"] == "есть конфликты", "ядро: конфликт виден в причинной цепочке")

    # --- мир из 10 блоков: изоляция такта 1 и предел влияния
    мир = И.Мир(10, 9, зерно=2)
    мир.обучить(вопросов=1500, шагов=150)
    игр = И.собрать_матплату(мир, Матплата)
    rng = np.random.default_rng(5)
    тесты = [" ".join(мир.вопрос(rng)[0]) for _ in range(80)]
    без = Процессор(игр, ядро=ЯдроПричинности(), tau_conf=1.0)
    с_пределом = Процессор(игр, ядро=ЯдроПричинности(), tau_conf=1.0, предел_влияния=0.5)
    искажений = нарушений = 0
    for q in тесты:
        r = без.выполнить(q)
        токены = игр.язык.перевести(q)["токены"]
        for имя, б in игр.блоки.items():
            соло = б.arch.проход2(б.obj, токены, {})
            искажений += max(соло, key=соло.get) != r["такт1"][имя]["top1"]
        rr = с_пределом.выполнить(q)
        for имя, о2 in rr["такт2"].items():
            о1 = rr["такт1"][имя]
            L = 0.5 * max(о1["margin"], 1.0)
            нарушений += max(abs(о2["счёты"][a] - о1["счёты"][a]) for a in о2["счёты"]) > L + 1e-9
    отметить(искажений == 0, "изоляция: Lego-индекс мира из 10 блоков равен 0")
    отметить(нарушений == 0, "предел влияния: сдвиг такта 2 не выходит за предел × max(отрыв такта 1, tau)")

    # --- блок из размеченных примеров: обучение, паспорт, линтер, вставка
    слова = {"хор": "солнце тепло ясно лето жара пляж отпуск".split(), "плох": "дождь холод ветер гроза слякоть мороз буря".split(), "нейтр": "облачно пасмурно туман сухо тихо".split()}
    rnd = np.random.RandomState(1)
    примеры = []
    for кл, сл in слова.items():
        for _ in range(120):
            примеры.append((" ".join(rnd.choice(сл, size=3)), кл))
    временный = tempfile.mkdtemp(prefix="блок_")
    отчёт = создать_блок(os.path.join(временный, "погода"), "погода", примеры, проекции={"хор": {"погода:хор": 16.0}, "плох": {"погода:плох": 16.0}, "нейтр": {}})
    отметить(отчёт["точность_отложенных"] >= 0.95, "создать_блок: блок из 360 размеченных фраз даёт точность %.2f на отложенных" % отчёт["точность_отложенных"])
    результат = Л.проверить_блок(os.path.join(временный, "погода"), АРХ)
    отметить(результат["статус"] == "УСПЕХ", "линтер: созданный блок проходит проверку паспорта, весов и архитектуры %s" % результат["ошибки"])
    создать_блок(os.path.join(временный, "зонт"), "зонт", [("нужен зонт дождь", "да"), ("зонт не нужен", "нет")] * 20, читает=["погода:плох"])
    м = Матплата(Язык(), АРХ)
    ok, имя = м.подключить(os.path.join(временный, "погода"))
    ok2, _ = м.подключить(os.path.join(временный, "зонт"))
    пр2 = Процессор(м, ядро=ЯдроПричинности(), tau_conf=1.0)
    r = пр2.выполнить("дождь ветер гроза")
    отметить(ok and ok2 and r["такт1"]["погода"]["top1"] == "плох" and "погода:плох" in r["шина"], "созданные блоки подключаются, первый отвечает и пишет понятие на шину, второй его читает")
    отметить(ok and пр2.выполнить("солнце жара")["такт1"]["погода"]["top1"] == "хор", "и отвечает на другой класс")

    # --- вставка блока в систему из нескольких блоков, подделка не проходит
    мир2 = И.Мир(6, 5, зерно=4)
    мир2.обучить(вопросов=1500, шагов=150)
    м2 = И.собрать_матплату(мир2, Матплата)
    пр3 = Процессор(м2, ядро=ЯдроПричинности(), tau_conf=1.0)
    rng2 = np.random.default_rng(8)
    вопросы2 = [" ".join(мир2.вопрос(rng2)[0]) + " подделка:0:с безобидный:0:с" for _ in range(200)]

    def блок(имя, проекции):
        мм, _ = И.новая_матплата(Матплата)
        И.записать_блок(мм, временный, имя, ["0", "1"], [], проекции, np.zeros((0, 2)))
        return os.path.join(временный, имя)
    подделка = блок("подделка", {"0": {"%s:%d" % (мир2.имена[0], y): 16.0 for y in range(3)}, "1": {}})
    безобидный = блок("безобидный", {"0": {"никто_не_читает": 16.0}, "1": {}})
    р1 = Л.проверить_вставку(пр3, подделка, вопросы2, эпсилон=0.01)
    р2 = Л.проверить_вставку(пр3, безобидный, вопросы2, эпсилон=0.01)
    р3 = Л.проверить_вставку(пр3, подделка, вопросы2, эпсилон=0.5)
    отметить(р1["статус"] == "ОШИБКА" and р1["доля_изменений"] > 0.01, "вставка: блок, подделывающий чужие понятия, не проходит (%.1f %% ответов соседей изменено)" % (100 * р1["доля_изменений"]))
    отметить(р2["статус"] == "УСПЕХ" and р2["доля_изменений"] == 0.0, "вставка: безобидный блок проходит")
    отметить(р3["статус"] == "УСПЕХ", "вставка: порог ε работает в обе стороны")
    отметить(р1["снятие_возвращает_как_было"] and р1["такт1_соседей_изменилось"] == 0, "вставка: после снятия всё как было, такт 1 соседей не менялся")

    # --- в пакете нет предметной области и имён блоков
    запрещено = re.compile(r"if\s+(?:имя|block|блок\w*)\s*==|здоровье|военкомат|призыв|статья|болезн|закон|повестк", re.I)
    нашли = {}
    for f in os.listdir(os.path.join(КОРЕНЬ, "nnl")):
        if f.endswith(".py"):
            текст = open(os.path.join(КОРЕНЬ, "nnl", f), encoding="utf-8").read()
            код = "\n".join(l for l in текст.splitlines() if "if имя ==" not in l)
            найдено = sorted(set(m.group(0) for m in запрещено.finditer(код)))
            if найдено:
                нашли[f] = найдено
    отметить(not нашли, "пакет nnl не содержит имён блоков и слов предметной области %s" % нашли)

    print("\nпройдено %d из %d" % (прошло, проверок))
    sys.exit(0 if прошло == проверок else 1)


if __name__ == "__main__":
    main()
