"""Контрольный тест падения (Red Test).
Проверяет измерительный стенд на заведомо плохой (наивной) реализации разборщика.
Тест ОБЯЗАН падать и показывать катастрофическую долю ошибок (>80%),
доказывая, что метрики валидны и способны выявлять нарушения инвариантов.
"""
import sys
import os

sys.path.insert(0, r"C:\ЯДРО-ОПЫТ\NNL\диалог")
import диалог as Д
from данные import получить_выборку
from оценка import оценить_кейс, агрегировать_результаты


def заведомо_плохой_разборщик(текст):
    """Наивный разборщик с критическими дефектами архитектуры:
    1. Игнорирует модальности и отрицания: всегда ставит статус 'есть'.
    2. Игнорирует источник: всегда приписывает 'врач'.
    3. Не умеет распознавать числа словами (оставляет уточнение пустым).
    4. Зависим от порядка слов: извлекает только первое попавшееся слово диагноза.
    """
    упоминания = []
    текст_н = текст.lower()
    словарь = [
        "близорукость", "миопия", "астигматизм", "язва", "гипертон", "гипертензи",
        "плоскостопи", "астм", "сколиоз", "кифоз", "дерматит", "экзем", "псориаз",
        "клапан", "артроз", "перелом", "металлоконструкци", "пластин", "штифт", "спиц",
        "грыж", "панкреатит", "питания", "дефицит массы", "варикоз", "туберкулез",
        "пиелонефрит", "эпилепси", "склероз", "порок"
    ]
    
    # Находим все совпадения по позиции в тексте
    позиции = []
    for w in словарь:
        pos = текст_н.find(w)
        if pos != -1:
            позиции.append((pos, w))
    позиции.sort()

    for _, w in позиции:
        упоминания.append({
            "термин": w,
            "статус": "есть",        # ДЕФЕКТ: всегда "есть", игнорирует "нет", "было", "у брата"
            "уточнение": "",          # ДЕФЕКТ: теряет числа и единицы
            "кто_подтвердил": "врач"  # ДЕФЕКТ: всегда "врач", игнорирует "сам"
        })

    
    return {
        "упоминания": упоминания,
        "ответ_на_вопрос": "нет_вопроса",
        "значение": "",
        "хочет_завершить": False
    }


def main():
    print("=" * 70)
    print("ЗАПУСК КОНТРОЛЬНОГО ТЕСТА ПАДЕНИЯ (RED TEST)")
    print("Тестирование заведомо дефектного разборщика на контрольной выборке TEST")
    print("=" * 70)

    система = Д.Система()
    тест_кейсы = получить_выборку("test")
    print(f"Размер контрольной выборки: {len(тест_кейсы)} кейсов.")

    результаты = []
    for c in тест_кейсы:
        res = оценить_кейс(система, c, заведомо_плохой_разборщик)
        результаты.append(res)

    сводка = агрегировать_результаты(результаты)

    print("\n--- РЕЗУЛЬТАТЫ КОНТРОЛЯ ПАДЕНИЯ ---")
    print(f"{'Трансформация':<12} | {'Ошибки фактов':<15} | {'95% ДИ фактов':<18} | {'Ошибки ядра':<15} | {'95% ДИ ядра':<18}")
    print("-" * 85)
    for t, m in сводка.items():
        print(f"{t:<12} | {m['fact_errs']}/{m['n']} ({m['fact_err_rate']*100:5.1f}%) | "
              f"[{m['fact_ci'][0]*100:.1f}%, {m['fact_ci'][1]*100:.1f}%]   | "
              f"{m['core_errs']}/{m['n']} ({m['core_err_rate']*100:5.1f}%) | "
              f"[{m['core_ci'][0]*100:.1f}%, {m['core_ci'][1]*100:.1f}%]")

    # Проверка падения стенда:
    # На наивной реализации T4 (самодиагностика) и T5 (отрицание/чужое) ДОЛЖНЫ дать > 80% ошибок.
    критические_ошибки = [
        сводка["T4_self"]["core_err_rate"],
        сводка["T5a_neg"]["core_err_rate"],
        сводка["T5c_other"]["core_err_rate"]
    ]
    средняя_ошибка = sum(критические_ошибки) / len(критические_ошибки)
    print("\nСредний уровень критических ошибок:", round(средняя_ошибка * 100, 1), "%")

    if средняя_ошибка >= 0.80:
        print("\n[КРАСНЫЙ ТЕСТ УСПЕШНО СРАБОТАЛ (RED TEST PASSED)]")
        print("Тестовый стенд зафиксировал катастрофический провал наивной реализации.")
        print("Вывод: метрики чувствительны к нарушениям инвариантов и способны фальсифицировать гипотезу.")
        return 0
    else:
        print("\n[ОШИБКА МЕТОДОЛОГИИ]: Стенд не покраснел на плохой реализации!")
        return 1


if __name__ == "__main__":
    code = main()
    sys.exit(code)
