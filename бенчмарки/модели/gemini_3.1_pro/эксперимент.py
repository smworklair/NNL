def надежный_спрос(провайдер, модель, система, история, схема=None, температура=0.0):
    """Вызов К.спросить с автоматическим ожиданием при лимитах и сетевых сбоях."""
    for попытка in range(8):
        try:
            return К.спросить(провайдер, модель, система, история, схема=схема, температура=температура)
        except К.Ошибка as e:
            msg = str(e)
            if "Rate limit" in msg or "HTTP 429" in msg or "429" in msg:
                ждать = 15.0
                m = re.search(r"(?:try again in|retry in)\s+(?:(\d+)m)?([\d.]+)s", msg)
                if m:
                    мин = float(m.group(1)) if m.group(1) else 0.0
                    сек = float(m.group(2)) if m.group(2) else 0.0
                    ждать = мин * 60.0 + сек + 2.0
                print(f"\n[Лимит Groq 429]: пауза {ждать:.1f} с перед повтором (попытка {попытка + 1}/8)...", flush=True)
                time.sleep(ждать)
            elif "URLError" in msg or "Timeout" in msg or "RemoteDisconnected" in msg or "Connection" in msg:
                ждать = 10.0
                print(f"\n[Сетевой сбой]: {msg}, пауза {ждать:.1f} с (попытка {попытка + 1}/8)...", flush=True)
                time.sleep(ждать)
            else:
                raise
    raise RuntimeError("Превышено число попыток вызова модели")



def создать_разборщик(провайдер, модель, пауза=0.5):
    """Обертка над клиентом NNL для вызова структурированного разбора реплики."""
    def разборщик(текст):
        res = надежный_спрос(
            провайдер,
            модель,
            Д.СИСТЕМА_РАЗБОРА,
            [("user", "Реплика человека: " + текст)],
            схема=Д.СХЕМА_РАЗБОРА,
            температура=0.0
        )
        if not res.get("из_кэша"):
            time.sleep(пауза)
        данные = res.get("данные")
        if not данные or not isinstance(данные, dict):
            return {
                "упоминания": [],
                "ответ_на_вопрос": "нет_вопроса",
                "значение": "",
                "хочет_завершить": False
            }
        return данные
    return разборщик



def запустить_оценку_модели(система, провайдер, модель, выборка="test"):
    print("=" * 80)
    print(f"ЗАПУСК ТЕСТИРОВАНИЯ МОДЕЛИ: {провайдер}/{модель} (выборка: {выборка.upper()})")
    print("=" * 80)
    
    кейсы = получить_выборку(выборка)
    print(f"Загружено {len(кейсы)} тестовых кейсов.")
    разборщик = создать_разборщик(провайдер, модель)

    результаты = []
    всего = len(кейсы)
    for i, c in enumerate(кейсы, 1):
        print(f"[{i:02d}/{всего:02d}] Обработка {c['id']}...", end=" ", flush=True)
        t0 = time.time()
        res = оценить_кейс(система, c, разборщик)
        dt = time.time() - t0
        результаты.append(res)
        print(f"готово за {dt:.1f} с.")

    сводка = агрегировать_результаты(результаты)
    
    # Сохранение детальных результатов
    имя_файла = f"результаты_{модель.replace('/', '_')}_{выборка}.json"
    путь_файла = os.path.join(ПАПКА, имя_файла)
    with open(путь_файла, "w", encoding="utf-8") as f:
        json.dump({"модель": модель, "выборка": выборка, "сводка": сводка, "кейсы": результаты}, f, ensure_ascii=False, indent=2)
    print(f"\nДетальные результаты сохранены в: {имя_файла}")
    return сводка, результаты


def напечатать_таблицу(сводка, заголовок="СВОДКА РЕЗУЛЬТАТОВ"):
    print("\n" + "=" * 90)
    print(zaголовок := zaголовок if 'zaголовок' in locals() else заголовок)
