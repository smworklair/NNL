# -*- coding: utf-8 -*-
"""Генерация выдуманных кейсов по статье 34. Только выдуманные числа, никаких реальных людей."""
import json
import os

# 22 значения худшего глаза, покрывающие границы 3.0 / 6.0 / 8.0 / 12.0 и середины интервалов
МАКС_ГЛАЗ = [1.0, 2.0, 2.75, 3.0, 3.25, 3.5, 4.5, 5.0, 5.75, 6.0, 6.25, 6.5, 7.0, 7.75, 8.0, 8.25, 9.5, 10.5, 11.75, 12.0, 12.5, 14.0]

def истина(пара):
    x = max(пара)
    if x > 12:
        return ("а", "Д")
    if x > 8:
        return ("б", "В")
    if x > 6:
        return ("в", "В")
    if x > 3:
        return ("г", "Б-3")
    return ("не_применяется", "нет_категории")

def main():
    кейсы = []
    номер = 1
    for худший in МАКС_ГЛАЗ:
        # вариант А: второй глаз чуть лучше худшего
        второй_а = round(max(0.5, худший - 0.5), 2)
        # вариант Б: второй глаз заведомо здоровый 1.0 (если худший и есть 1.0, берем 0.5)
        второй_б = 0.5 if худший <= 1.0 else 1.0
        for второй in (второй_а, второй_б):
            од = худший
            ос = второй
            # чередуем порядок глаз, чтобы не было привязки к правому
            if номер % 2 == 0:
                од, ос = ос, од
            пункт, кат = истина((од, ос))
            кейсы.append({
                "id": "musi-%02d" % номер,
                "од": од,
                "ос": ос,
                "худший": max(од, ос),
                "истина_пункт": пункт,
                "истина_категория": кат,
            })
            номер += 1
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "кейсы.json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(кейсы, f, ensure_ascii=False, indent=1)
    print("кейсов: %d -> %s" % (len(кейсы), out))

if __name__ == "__main__":
    main()
