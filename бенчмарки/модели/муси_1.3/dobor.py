# -*- coding: utf-8 -*-
"""Добор: по одному повтору для групп тест-половины, где нет ни одного usable ответа.
Не превышает бюджет 600. Медленные паузы против 429."""
import json
import os
import sys
import time

ПАПКА = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, r"C:\ЯДРО-ОПЫТ\NNL\диалог")
sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
import run_exp as R
import клиент as К
import знания as З

def main():
    with open(os.path.join(ПАПКА, "кейсы.json"), encoding="utf-8") as f:
        кейсы = {к["id"]: к for к in json.load(f)}
    путь = os.path.join(ПАПКА, "сырые_ответы.jsonl")
    rec = [json.loads(l) for l in open(путь, encoding="utf-8") if l.strip()]
    usable = set()
    for r in rec:
        if r["половина"] == "тест" and not r.get("ошибка") and r.get("ответ"):
            usable.add((r["id"], r["модель"], r["вариант"]))
    # все нужные группы
    нужные = []
    for ид, к in sorted(кейсы.items()):
        if R.половина(ид) != "тест":
            continue
        for модель in R.МОДЕЛИ:
            for вариант in ("база", "без_основания", "шум"):
                if (ид, модель, вариант) not in usable:
                    нужные.append((ид, модель, вариант))
    print("групп без usable: %d" % len(нужные))
    # бюджет: уже потрачено = число строк + 4 пилота; осталось до 600
    потрачено = len(rec) + 4
    осталось = 600 - потрачено
    print("потрачено ~%d, осталось %d" % (потрачено, осталось))
    взять = нужные[:max(0, осталось)]
    print("доберу: %d" % len(взять))
    if not взять:
        return
    система = R.СИСТЕМА_БАЗА + З.ЛЕГЕНДА_КАТЕГОРИЙ
    статья = R.статья34_текст()
    fw = open(путь, "a", encoding="utf-8")
    for (ид, модель, вариант) in взять:
        к = кейсы[ид]
        д = R.досье(к, "база" if вариант in ("база", "шум") else "без_основания", статья)
        if вариант == "шум":
            д = R.досье(к, "шум", статья)
        try:
            r = К.спросить("groq", модель, система, [("user", д)], температура=R.ТЕМПЕРАТУРА, макс_токенов=R.МАКС_ТОКЕНОВ, кэш=False, таймаут=120)
            запись = {"id": ид, "од": к["од"], "ос": к["ос"], "истина_пункт": к["истина_пункт"],
                      "истина_категория": к["истина_категория"], "половина": "тест", "модель": модель,
                      "вариант": вариант, "повтор": 99, "досье": д, "ответ": r.get("текст", ""),
                      "токены_вход": r.get("токены_вход"), "токены_выход": r.get("токены_выход"), "мс": r.get("мс"), "добор": True}
        except Exception as e:
            запись = {"id": ид, "од": к["од"], "ос": к["ос"], "истина_пункт": к["истина_пункт"],
                      "истина_категория": к["истина_категория"], "половина": "тест", "модель": модель,
                      "вариант": вариант, "повтор": 99, "досье": д, "ответ": "", "ошибка": str(e)[:200], "добор": True}
        fw.write(json.dumps(запись, ensure_ascii=False) + "\n")
        fw.flush()
        time.sleep(20.0)
    fw.close()
    print("добор готов")

if __name__ == "__main__":
    main()
