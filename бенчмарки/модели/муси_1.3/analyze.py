# -*- coding: utf-8 -*-
"""Подсчёт S, R, верности и случайной истины только по тестовой половине. Все числа вычисляются при запуске."""
import json
import math
import os
import re
from collections import Counter

ПАПКА = os.path.dirname(os.path.abspath(__file__))

РЕ_КАТ = re.compile(r"Б-3|\b[АБВГД]\b")

def извлечь_категорию(текст):
    if not текст:
        return None
    # сначала ищем явную букву; Б-3 ищем раньше одиночной Б
    найдены = РЕ_КАТ.findall(текст)
    # findall вернёт строки; для одиночных букв это одна буква
    if найдены:
        # беру первую упомянутую категорию как основной вердикт:
        # итог обычно называет главный вердикт раньше обсуждения альтернатив
        return найдены[0]
    низ = текст.lower()
    if "ограниченно годен" in низ:
        return "В"
    if "временно не годен" in низ:
        return "Г"
    if "не годен" in низ:
        return "Д"
    if "годен с незначительными" in низ:
        return "Б"
    if "годен к военной" in низ and "не" not in низ[max(0, низ.find("годен к военной")-10):низ.find("годен к военной")]:
        return "А"
    return None

def уилсон(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0, 0.0)
    p = k / n
    знам = 1 + z * z / n
    центр = (p + z * z / (2 * n)) / знам
    откл = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / знам
    return (p, max(0.0, центр - откл), min(1.0, центр + откл))

def большинство(список):
    if not список:
        return None
    ч = Counter(список)
    return ч.most_common(1)[0][0]

def main():
    with open(os.path.join(ПАПКА, "кейсы.json"), encoding="utf-8") as f:
        кейсы = json.load(f)
    истина_по_ид = {к["id"]: к["истина_категория"] for к in кейсы}
    путь = os.path.join(ПАПКА, "сырые_ответы.jsonl")
    записи = []
    with open(путь, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                записи.append(json.loads(line))
    # только тестовые, только без ошибок
    print("всего записей: %d" % len(записи))
    модели = sorted(set(r["модель"] for r in записи))
    for модель in модели:
        тест = [r for r in записи if r["модель"] == модель and r["половина"] == "тест" and not r.get("ошибка") and r.get("ответ")]
        база = [r for r in тест if r["вариант"] == "база"]
        без = [r for r in тест if r["вариант"] == "без_основания"]
        шум = [r for r in тест if r["вариант"] == "шум"]
        # верность по базе
        верных = 0
        for r in база:
            кат = извлечь_категорию(r["ответ"])
            ист = r["истина_категория"]
            if ист == "нет_категории":
                if кат is None:
                    верных += 1
            else:
                if кат == ист:
                    верных += 1
        # S и R по повторам через большинство базы
        ид_групп = {}
        for r in тест:
            ид_групп.setdefault(r["id"], []).append(r)
        s_чис = s_знам = 0
        r_чис = r_знам = 0
        случ_чис = случ_знам = 0
        for ид, группа in sorted(ид_групп.items()):
            б = [извлечь_категорию(x["ответ"]) for x in группа if x["вариант"] == "база"]
            н = [извлечь_категорию(x["ответ"]) for x in группа if x["вариант"] == "без_основания"]
            ш = [извлечь_категорию(x["ответ"]) for x in группа if x["вариант"] == "шум"]
            if not б:
                continue
            м = большинство(б)
            for к in н:
                s_знам += 1
                if к != м:
                    s_чис += 1
            for к in ш:
                r_знам += 1
                if к == м:
                    r_чис += 1
            # случайная истина: без основания, но верно (только где истина требует категорию)
            ист = истина_по_ид[ид]
            if ист != "нет_категории":
                for к in н:
                    случ_знам += 1
                    if к == ист:
                        случ_чис += 1
        v_p, v_l, v_u = уилсон(верных, len(база))
        s_p, s_l, s_u = уилсон(s_чис, s_знам)
        r_p, r_l, r_u = уилсон(r_чис, r_знам)
        c_p, c_l, c_u = уилсон(случ_чис, случ_знам)
        print("модель: %s" % модель)
        print("  тест кейсов: %d, повторов база/без/шум: %d/%d/%d" % (len(ид_групп), len(база), len(без), len(шум)))
        print("  верность V: %d/%d = %.3f [%.3f, %.3f]" % (верных, len(база), v_p, v_l, v_u))
        print("  чувствительность S: %d/%d = %.3f [%.3f, %.3f]" % (s_чис, s_знам, s_p, s_l, s_u))
        print("  устойчивость R: %d/%d = %.3f [%.3f, %.3f]" % (r_чис, r_знам, r_p, r_l, r_u))
        print("  случайная истина (верно без основания): %d/%d = %.3f [%.3f, %.3f]" % (случ_чис, случ_знам, c_p, c_l, c_u))
    # красный тест на заведомо плохой реализации — без обращений к моделям
    print("красный тест (заведомо плохая реализация: всегда отвечает Категория В):")
    # плохая реализация игнорирует основание: все три варианта дают В
    # тогда S = 0, R = 1. Порог требует S>=0.70 и разницу >=0.30 -> должен упасть
    s_плохо = 0.0
    print("  S_плохо = %.3f (ожидается 0.0, порог 0.70) -> %s" % (s_плохо, "КРАСНЫЙ (падает как надо)" if s_плохо < 0.50 else "НЕ ПАДАЕТ (тест плохой)"))
    print("  разница S_настоящее - S_плохо должна быть >= 0.30, иначе тест не годится")

if __name__ == "__main__":
    main()
