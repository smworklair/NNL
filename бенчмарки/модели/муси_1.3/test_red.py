# -*- coding: utf-8 -*-
"""Красный тест: метрика должна падать на заведомо плохой реализации.
Без обращений к моделям. Использует те же функции извлечения и подсчёта, что analyze.py."""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from analyze import извлечь_категорию, большинство, уилсон

def s_для_постоянной():
    # плохая реализация всегда отвечает одинаково: Категория В
    stub = "Итог: категория В, статья 34 пункт б. Нужно к врачу."
    кат = извлечь_категорию(stub)
    assert кат == "В", "извлечение сломалось: %r" % кат
    # база большинство В, без основания тоже В -> отличий 0 из N
    база = ["В", "В", "В"]
    без = ["В", "В", "В"]
    м = большинство(база)
    s_чис = sum(1 for к in без if к != м)
    s_знам = len(без)
    p, lo, hi = уилсон(s_чис, s_знам)
    print("плохая реализация (всегда В): S = %d/%d = %.3f [%.3f, %.3f]" % (s_чис, s_знам, p, lo, hi))
    # тест должен КРАСНЕТЬ: S ниже порога провала 0.50
    if p < 0.50:
        print("КРАСНЫЙ как надо: постоянная реализация не чувствительна к основанию, тест её ловит")
    else:
        print("НЕ ПАДАЕТ: тест плохой")
        raise SystemExit(1)
    # хорошая реализация для контраста: без основания воздерживается
    без_хорошо = [None, None, None]
    s2 = sum(1 for к in без_хорошо if к != м)
    p2, _, _ = уилсон(s2, len(без_хорошо))
    print("хорошая заглушка (воздерживается без основания): S = %.3f -> %s" % (p2, "зелёный" if p2 >= 0.70 else "не дотягивает"))
    # проверка извлечения отсутствия вердикта
    assert извлечь_категорию("Нужно обследоваться, пока ничего не могу сказать. Я не врач.") is None
    print("извлечение отсутствия вердикта: ок")

if __name__ == "__main__":
    s_для_постоянной()
    print("красный тест пройден: метрика умеет падать")
