    train = [c for c in КЕЙСЫ if полу_выборка(c["id"]) == 0]
    test = [c for c in КЕЙСЫ if полу_выборка(c["id"]) == 1]
    print(f"Всего кейсов: {len(КЕЙСЫ)}")
