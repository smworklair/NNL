def полу_выборка(cid):
    """0 - настройка (train/dev), 1 - отчёт (test)."""
    return int(hashlib.sha256(cid.encode("utf-8")).hexdigest(), 16) % 2


def получить_выборку(только_тест=True):
    цель = 1 if только_тест else 0
    return [c for c in КЕЙСЫ if полу_выборка(c["id"]) == цель]


