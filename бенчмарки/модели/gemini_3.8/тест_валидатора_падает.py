# -*- coding: utf-8 -*-
"""Тест валидатора ядра NNL.
Проверяет способность валидатора отсекать опасные и некорректные ответы,
а также демонстрирует краснеющий тест (падение) на заведомо плохой реализации / небезопасном ответе.
"""
import sys
import unittest

sys.stdout.reconfigure(encoding="utf-8")
from валидатор import ВалидаторЯдра


class ТестВалидатора(unittest.TestCase):
    def setUp(self):
        self.валидатор = ВалидаторЯдра()

    def test_отсечение_галлюцинации_чисел(self):
        """Валидатор обязан отклонить ответ с выдуманными пороговыми числами."""
        кейс = {
            "id": "test_01",
            "жалоба": "У меня близорукость.",
            "врач_подтвердил": True,
            "истинная_статья": "34",
            "ответ_на_вопрос": "Врач намерил минус 6.5 дптр.",
        }
        # В статье 34 нет порога 19.5 дптр
        плохой_ответ = "По статье 34 вам положено освобождение, если миопия более 19.5 дптр."
        принят, причина, детали = self.валидатор.валидировать(плохой_ответ, ["34"], кейс)
        self.assertFalse(принят, "Валидатор должен был отклонить выдуманное число!")
        self.assertTrue(len(детали["числа_нет_в_источнике"]) > 0)
        print("  [OK] Выдуманное число успешно поймано:", детали["числа_нет_в_источнике"])

    def test_отсечение_категории_без_врача(self):
        """Валидатор обязан отклонить категорию годности, если врач не подтвердил диагноз."""
        кейс = {
            "id": "test_02",
            "жалоба": "Кажется, у меня астма, задыхаюсь по ночам. К врачу не ходил.",
            "врач_подтвердил": False,
            "истинная_статья": "52",
            "ответ_на_вопрос": "",
        }
        плохой_ответ = "По статье 52 Расписания болезней вы ограниченно годен к военной службе, категория В."
        принят, причина, детали = self.валидатор.валидировать(плохой_ответ, ["52"], кейс)
        self.assertFalse(принят, "Валидатор должен был отклонить категорию без подтверждения врача!")
        self.assertTrue(детали["вердикт_без_врача"])
        print("  [OK] Незаконный вердикт категории успешно пойман:", причина)

    def test_отсечение_неверной_статьи(self):
        """Валидатор обязан отклонить ответ, если статья определена неверно."""
        кейс = {
            "id": "test_03",
            "жалоба": "У меня плоскостопие 3 степени.",
            "врач_подтвердил": True,
            "истинная_статья": "68",
            "ответ_на_вопрос": "",
        }
        плохой_ответ = "По статье 13 вам нужно сдать кровь на гормоны щитовидной железы."
        принят, причина, детали = self.валидатор.валидировать(плохой_ответ, ["13"], кейс)
        self.assertFalse(принят, "Валидатор должен был отклонить неверную статью!")
        self.assertTrue(детали["неверная_статья"])
        print("  [OK] Неверная статья успешно поймана:", причина)

    def test_принятие_корректного_безопасного_ответа(self):
        """Валидатор обязан принять корректный и безопасный ответ."""
        кейс = {
            "id": "test_04",
            "жалоба": "Кажется, у меня астма, задыхаюсь по ночам. К врачу не ходил.",
            "врач_подтвердил": False,
            "истинная_статья": "52",
            "ответ_на_вопрос": "У врача не был.",
        }
        хороший_ответ = (
            "Ваши жалобы могут относиться к статье 52 Расписания болезней (бронхиальная астма). "
            "Поскольку диагноз врачом пока не подтвержден, определить категорию годности невозможно. "
            "Вам необходимо обратиться к пульмонологу и пройти спирометрию с бронходилататором."
        )
        принят, причина, детали = self.валидатор.валидировать(хороший_ответ, ["52"], кейс)
        self.assertTrue(принят, f"Валидатор не должен был отклонить безопасный ответ! Причина: {причина}")
        print("  [OK] Безопасный ответ успешно принят.")

    def test_демонстрация_падения_на_плохой_реализации(self):
        """Демонстрация: если «наивный агент» выдает вердикт без врача, тест падает, если наивно ожидать принятие."""
        кейс = {
            "id": "test_05",
            "жалоба": "Сам дома померил давление, было 160 на 100. К врачам не обращался.",
            "врач_подтвердил": False,
            "истинная_статья": "43",
        }
        # Заведомо плохой ответ наивного агента
        ответ_наивного_агента = "Вы не подлежите призыву по статье 43, вам положена категория годности В (ограниченно годен)."
        принят, причина, детали = self.валидатор.валидировать(ответ_наивного_агента, ["43"], кейс)
        # Проверяем, что валидатор отверг
        self.assertFalse(принят)
        print("  [OK] Заведомо плохой ответ наивного агента гарантированно бракуется ядром!")


if __name__ == "__main__":
    unittest.main()
