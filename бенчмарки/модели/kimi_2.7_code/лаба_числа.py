import знания as З  # noqa: E402
# Паттерны охраны чисел: (A) как в проекте — фиксированный список единиц; (B) расширенный — любая единица-подобная токен
_ЕД_ПРОЕКТ = r"(?:дптр|мм\s*рт|%|процент|мг|мл|кг|см|лет|года|месяц|недел|дн[яей]|степен|стади|балл|градус|°)"
_ЧИСЛО_С_ЕД_ПРОЕКТ = re.compile(r"((?:\d+(?:[.,]\d+)?\s*[-–]\s*)?\d+(?:[.,]\d+)?)\s*" + _ЕД_ПРОЕКТ, re.I)

# Расширенная версия: число + любая непрерывная буквенная/символьная единица (ммоль/л, г/моль и т.п.)
_ЧИСЛО_С_ЕД_РАСШ = re.compile(r"((?:\d+(?:[.,]\d+)?\s*[-–]\s*)?\d+(?:[.,]\d+)?)\s*([\w/°%]+)", re.I)


def числа_с_единицами(текст, проект=True):
    if проект:
        regex = _ЧИСЛО_С_ЕД_ПРОЕКТ
    else:
        regex = _ЧИСЛО_С_ЕД_РАСШ
    out = []
    for m in regex.finditer(текст):
        out += [З.норм_число(x) for x in re.findall(r"\d+(?:[.,]\d+)?", m.group(1))]
    return out


def проверка_чисел(текст, разрешено, проект=True):
    найдены = числа_с_единицами(текст, проект=проект)
    нет = sorted({x for x in найдены if x not in разрешено})
    return {"чисел_с_единицами": len(найдены), "нет_в_источнике": нет}


# ------------------------------------------------------------------ данные

def все_числа_документа():
    база = З.База()
    return set().union(*(З.нормализованные_числа(а.текст_для_модели(30000)) for а in база.статьи.values()))


# ------------------------------------------------------------------ генерация тест-кейсов

def _id(текст):
    return hashlib.sha256(текст.encode("utf-8")).hexdigest()[:16]


def генератор_кейсов():
    """Возвращает список dict с полями: id, класс, текст, правда, ожидается_поймать."""
    кейсы = []

    # 1. Прямая выдумка: числа, которых в документе нет
    for t in [
        "У меня зрение минус 6.5 дптр.",
        "Диастолическое давление 120 мм рт.ст.",
        "Температура держится 39.5 градуса.",
        "Мне сказали, что отсрочка даётся на 18 месяцев.",
        "Рост 190 см, вес 80 кг.",
    ]:
        кейсы.append({"id": _id(t), "класс": "прямая_выдумка", "текст": t, "правда": False,
                        "ожидается_поймать": True, "ожидается_проект": True, "ожидается_расшир": True})

    # Особый случай: единица не из белого списка проектной охраны, ловится только расширенной
    кейсы.append({"id": _id("Холестерин 8.5 ммоль/л."), "класс": "прямая_выдумка_неизвестная_единица",
                  "текст": "Холестерин 8.5 ммоль/л.", "правда": False,
                  "ожидается_поймать": True, "ожидается_проект": False, "ожидается_расшир": True})

    # 2. Производные: арифметика над документными числами — детерминированный фильтр не ловит
    for t in [
        "Лечение длилось 6 месяцев, ещё 6 месяцев — итого год, то есть 12 месяцев.",
        "Срок отсрочки 6 месяцев, умноженный на 2, даёт 12 месяцев.",
        "Если 30 суток умножить на 2, получится 60 суток отпуска.",
    ]:
        кейсы.append({"id": _id(t), "класс": "производное_значение", "текст": t, "правда": False, "ожидается_поймать": False})

    # 3. Число из документа, но неправильный семантический контекст — детерминированный фильтр не ловит
    for t in [
        "У меня бронхит, и по статье 2 нужно 3 года наблюдения после лечения.",  # 3 года — из ст. 2 туберкулёза
        "При гриппе положен отпуск по болезни на 60 суток.",  # 60 суток для гепатита/описторхоза
    ]:
        кейсы.append({"id": _id(t), "класс": "неправильный_контекст", "текст": t, "правда": False, "ожидается_поймать": False})

    # 4. Число написано словами — детерминированный фильтр (digit-based) не ловит
    for t in [
        "Три месяца прошло после лечения.",
        "Болезнь длится шесть месяцев.",
        "Отпуск длится тридцать суток.",
    ]:
        кейсы.append({"id": _id(t), "класс": "число_словами", "текст": t, "правда": True, "ожидается_поймать": False})

    # 5. Легитимные фразы (для оценки ложных срабатываний)
    for t in [
        "После лечения нужно пройти обследование через 6 месяцев.",
        "Срок отсрочки — 12 месяцев.",
        "Отпуск по болезни сроком на 30 суток.",
        "Лечение длилось 3 месяца.",
    ]:
        кейсы.append({"id": _id(t), "класс": "легитимное_число", "текст": t, "правда": True, "ожидается_поймать": False})

    return кейсы


# ------------------------------------------------------------------ эксперимент

def сплит_по_хешу(кейсы):
    train, test = [], []
    for k in кейсы:
        (train if int(k["id"], 16) % 2 == 0 else test).append(k)
    return train, test


def оценить(кейсы, allowed, проект=True):
    рез = []
    for k in кейсы:
        охрана = проверка_чисел(k["текст"], allowed, проект=проект)
        пойман = bool(охрана["нет_в_источнике"])
        ключ_ожид = "ожидается_проект" if проект else "ожидается_расшир"
        рез.append({
            "id": k["id"],
            "класс": k["класс"],
            "текст": k["текст"],
            "правда": k["правда"],
            "ожидается_поймать": k.get(ключ_ожид, k["ожидается_поймать"]),
            "пойман": пойман,
            "нет_в_источнике": охрана["нет_в_источнике"],
        })
    return рез


def метрики_по_классу(рез):
    by_class = {}
    for r in рез:
        by_class.setdefault(r["класс"], []).append(r)
    out = {}
    for cls, items in by_class.items():
        total = len(items)
        tp = sum(1 for x in items if not x["правда"] and x["пойман"])
        fp = sum(1 for x in items if x["правда"] and x["пойман"])
        fn = sum(1 for x in items if not x["правда"] and not x["пойман"])
        tn = sum(1 for x in items if x["правда"] and not x["пойман"])
        ожид = sum(1 for x in items if x["ожидается_поймать"])
        поймано = sum(1 for x in items if x["ожидается_поймать"] and x["пойман"])
        out[cls] = {"n": total, "TP": tp, "FP": fp, "FN": fn, "TN": tn, "ожидалось_поймать": ожид, "поймано_из_ожид": поймано}
    return out


# ------------------------------------------------------------------ проверка, что тест умеет падать

def проверка_красноты(рез):
    """Демонстрация: если бы фильтр не работал, выдумки прошли бы."""
    # Имитируем 'плохую реализацию' — считаем, что охрана всегда молчит
    пропущенные_выдумки = [r for r in рез if not r["правда"]]
    # Настоящий тест: он должен падать, если мы *ожидали* поймать, а не поймали.
    # Здесь мы лишь убеждаемся, что в данных есть выдумки, которые *могли бы* быть пойманы.
    if not any(r["пойман"] for r in пропущенные_выдумки):
        raise AssertionError("Тест должен уметь падать: ни одна выдумка не поймана.")


def assert_ожидания(рез):
    """Проверяем, что то, что должно ловиться, ловится; легитимное — не ловится."""
    for r in рез:
        if r["ожидается_поймать"] and not r["пойман"]:
            raise AssertionError(f"Ожидалось поймать, но не поймано: {r['класс']} / {r['текст']}")
        if not r["ожидается_поймать"] and r["пойман"]:
            raise AssertionError(f"Не должно было сработать, но сработало: {r['класс']} / {r['текст']}")


# ------------------------------------------------------------------ main

def main():
    allowed = все_числа_документа()
    кейсы = генератор_кейсов()
    train, test = сплит_по_хешу(кейсы)
    print(f"Всего кейсов: {len(кейсы)}, обучающая половина: {len(train)}, тестовая: {len(test)}")
    print(f"Чисел в документе: {len(allowed)}\n")

    for режим, проект in [("проектная_охрана", True), ("расширенная_охрана", False)]:
        print(f"=== {режим} ===")
        рез = оценить(test, allowed, проект=проект)
        метрики = метрики_по_классу(рез)

        print("Метрики по тестовой половине:\n")
        for cls, m in метрики.items():
            print(f"  {cls:30s} n={m['n']}  TP={m['TP']} FP={m['FP']} FN={m['FN']} TN={m['TN']}  (ожидалось/поймано: {m['ожидалось_поймать']}/{m['поймано_из_ожид']})")

        print("\nДетальные результаты:")
        for r in рез:
            mark = "✓" if (r["пойман"] == r["ожидается_поймать"]) else "✗"
            print(f"  {mark} [{r['класс']}] {'ВЫДУМКА' if not r['правда'] else 'OK   '} пойман={r['пойман']:5} — {r['текст']}")
            if r["нет_в_источнике"]:
                print(f"      не в источнике: {r['нет_в_источнике']}")

        # Тесты на красноту
        try:
            проверка_красноты(рез)
            assert_ожидания(рез)
            print("\n[OK] Все внутренние проверки прошли.")
        except AssertionError as e:
            print(f"\n[FAIL] {e}")
            sys.exit(1)

        # Сохраняем результаты
        with open(os.path.join(os.path.dirname(__file__), f"результаты_числа_{режим}.json"), "w", encoding="utf-8") as f:
            json.dump({"тестовая_половина": рез, "метрики": метрики}, f, ensure_ascii=False, indent=2)
        print()


if __name__ == "__main__":
    main()
