# -*- coding: utf-8 -*-
"""Архитектура игрушечного блока для стенда шины (без предметной области): подсказки в токенах вида «имя:класс:сила» плюс чтение шины.
Контракт тот же, что у настоящих блоков (СТАНДАРТ_БЛОКА.md): загрузить / чисел / проход2. Веса — матрица чтения шины V."""
import numpy as np


def загрузить(путь, паспорт):
    with np.load(путь, allow_pickle=False) as z:
        V = np.array(z["V"], dtype=np.float64)
    cfg = паспорт["настройки"]
    return {"V": V, "имя": паспорт["имя"], "читает": list(паспорт["читает"]), "ответы": list(паспорт["ответы"]),
            "масштаб": float(cfg["масштаб_чтения"]), "сила": dict(cfg["сила"])}


def чисел(obj):
    return int(obj["V"].size)


def проход2(obj, токены, шина):
    s = np.zeros(len(obj["ответы"]))
    for t in токены:
        часть = t.split(":")
        if len(часть) == 3 and часть[0] == obj["имя"]:
            s[int(часть[1])] += obj["сила"][часть[2]]
    if шина and obj["читает"]:
        x = np.zeros(len(obj["читает"]))
        for i, k in enumerate(obj["читает"]):
            if k in шина:
                x[i] = шина[k] / obj["масштаб"]
        s = s + x @ obj["V"]
    return {a: float(v) for a, v in zip(obj["ответы"], s)}
