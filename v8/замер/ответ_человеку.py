# -*- coding: utf-8 -*-
"""Человеческие ответы поверх блоков: id -> текст из документов.
Блоки выдают только код (статья 43 / тема fz53_...). Этот слой ничего не обучает:
подтягивает название + критерий/подсказку из тех же данных, на которых учили блоки,
плюс клинические рекомендации и расхождения из внешние/документы (когда есть).
Запуск: python замер/ответ_человеку.py "вопрос" [вариант]"""
import json
import os
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import общее as О  # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

НД = {}


def база():
    global НД
    if НД:
        return НД
    sys.path.insert(0, О.V8)
    from обучение import данные as D  # noqa: E402
    НД = {"статьи": {a["article_no"]: a for a in D.статьи()},
          "темы": {t["topic_id"]: t for t in D.темы()},
          "справ": json.load(open(os.path.join(О.БАЗА, "внешние", "справочник.json"), encoding="utf-8"))}
    # расхождения расписание<->КР
    рас = {}
    p = os.path.join(О.БАЗА, "внешние", "документы", "расхождения.jsonl")
    if os.path.exists(p):
        for l in open(p, encoding="utf-8"):
            if l.strip():
                r = json.loads(l)
                ст = str(r.get("расписание", {}).get("статья", ""))
                if ст:
                    рас[ст] = r
    НД["рас"] = рас
    return НД


def ответить(текст, вариант="основная_внешние", зерно=1):
    бд = база()
    k, _ = О.система(вариант, зерно)
    a, rec = k.спросить(текст)
    if a == "не знаю" or (isinstance(a, dict) is False and a == О.НЕ_ЗНАЮ):
        return {"вопрос": текст, "ответ_вид": "не_знаю",
                "текст_человеку": "Не могу уверенно ответить — вопрос вне тем призыва или данных мало. Уточните: про здоровье (диагноз/симптомы) или про право (отсрочка, повестка, обжалование)?",
                "след": rec.get("причина")}
    if a.get("вид") == "уточнить":
        return {"вопрос": текст, "ответ_вид": "уточнить",
                "текст_человеку": "Похоже, вопрос про область «%s», но точную статью/тему назвать не могу — добавьте подробностей (диагноз из выписки, какая повестка, какой этап)." % a.get("область"),
                "след": rec.get("причина")}
    обл, ид = a["область"], a.get("id") or ""
    if обл == "здоровье":
        ст = бд["статьи"].get(str(ид), {})
        назв = next((s["название"] for s in бд["справ"]["статьи_болезней"] if str(s["id"]) == str(ид)), ст.get("title", ""))
        ч = {"вопрос": текст, "ответ_вид": "ответ", "область": обл, "id": ид, "уверенность": round(a.get("p", 0), 3),
             "заголовок": "Статья %s Расписания болезней — %s" % (ид, назв),
             "что_это": (ст.get("criteria") or "")[:600],
             "что_нести": "На медкомиссию: выписки, анализы и заключения по этой статье; комиссия смотрит нарушение функции, а не только диагноз в справке."}
        if str(ид) in бд["рас"]:
            рх = бд["рас"][str(ид)]
            ч["важно_про_диагноз"] = рх["в_чём_расхождение"]
            ч["что_говорить"] = рх["что_говорить_человеку"]
        ч["текст_человеку"] = "%s. %s %s" % (ч["заголовок"], ч["что_это"], ч["что_нести"])
        return ч
    темы = бд["темы"]
    т = темы.get(ид, {})
    назв = next((x["название"] for x in бд["справ"]["правовые_темы"] if x["id"] == ид), т.get("title", ид))
    return {"вопрос": текст, "ответ_вид": "ответ", "область": обл, "id": ид, "уверенность": round(a.get("p", 0), 3),
            "заголовок": назв, "что_это": (т.get("answer_hint") or "")[:600],
            "текст_человеку": "%s. %s" % (назв, (т.get("answer_hint") or "")[:600])}


def main():
    в = sys.argv[1] if len(sys.argv) > 1 else "пришла повестка, учусь в вузе, что будет?"
    вар = sys.argv[2] if len(sys.argv) > 2 else "основная_внешние"
    print(json.dumps(ответить(в, вар), ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
