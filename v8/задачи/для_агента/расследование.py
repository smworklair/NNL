# -*- coding: utf-8 -*-
"""Ядро диалога: состояние расследования и выбор следующего шага. Чистая математика, ни одного обращения к модели и ни одной
фразы для пользователя: разговорный язык — забота внешней модели, а истина и порядок вопросов — здесь.

Модель.
  У человека может быть сразу несколько статей Расписания. Для каждой статьи a есть скрытая бинарная величина z_a
  («статья действительно относится к этому человеку»). Состояние — логарифмы шансов l_a = ln P(z_a=1)/P(z_a=0), независимые
  по статьям (много меток, не одна). Начало: l_a = logit(ПРИОР).

Журнал улик. Состояние не накапливается шагами, а каждый раз ПЕРЕСЧИТЫВАЕТСЯ С НУЛЯ из журнала действующих улик (см. _состояние).
Поэтому любую улику можно снять целиком, и результат не зависит от порядка записей:
  * упоминание «есть»: вклад в l_a = ln LR_a, где LR_a = odds(p_блока(a)) / odds(1/N) — отношение правдоподобия, которое даёт
    свой обученный блок для фразы (N=88 — число статей); «было» — то же с весом 0,5 (прошлое — слабая улика); «нет» — со знаком минус;
    «чужое» — не меняет ничего. Вклад одной улики ограничен потолком по её конкретности (потолок_улики);
  * несколько упоминаний об одной статье в ОДНОЙ реплике — слова одного человека и один разбор, они зависимы: вместе дают не больше, чем сильнейшее
    плюс ПРИБАВКА_ЗА_СОГЛАСИЕ (иначе три пересказа одной жалобы дают уверенность 0,98 и ядро перестаёт спрашивать); повтор жалобы в другой реплике
    складывается: это новое высказывание, и именно так человек «достучится», если один ответ или один разбор оказались ошибочными;
  * человек поправился («нет, не у меня», «это у брата», «было давно») — новое упоминание с другим статусом о том же предмете
    СНИМАЕТ прежнее целиком: вместе с его вкладом и с подтверждением врачом; повтор с уточнением (число, врач) заменяет прежнее;
  * «да» и «нет» к одной статье из разных упоминаний — противоречие: статья держится на уровне кандидата, и ядро спрашивает;
  * ответ на вопрос о статье a: LR = P(ответ | z_a=1) / P(ответ | z_a=0) из таблицы вопроса (её предложила внешняя модель или банк,
    ядро её режет в [0,05; 0,95] и требует монотонности).
Сверка с живыми словами (сверить_реплику). Разбор реплики делает внешняя модель, и его ошибки — главный вход каскада. Поэтому ядро
проверяет разбор независимым путём — словами самого человека: отрицание и «чужое» требуют маркера в той же фразе, «врач» требует слова
о враче или обследовании, статья, на которую явно указывает фраза, а разбор её не учёл, остаётся кандидатом и получает вопрос, статья,
которую разбор поднял, а слова человека не подтверждают, не растёт выше предела. При расхождении ядро не повышает уверенность, а спрашивает.

Выбор вопроса: ожидаемый информационный выигрыш EIG = I(z_a ; ответ) при текущем p_a — на сколько нат в среднем сожмётся
неопределённость о статье. Спрашиваем вопрос с наибольшим EIG; если лидер почти определён (p ≥ 0,8), хотя бы раз проверяем
конкурента (защита от подтверждающей ошибки). Остановка: неопределённых статей не осталось (EIG ниже порога), либо исчерпан
бюджет вопросов, либо человек сам хочет закончить."""
import math
import re

N_СТАТЕЙ = 88
ПРИОР = 0.03
L_МИН, L_МАКС = -5.0, 7.0
ВЕС_БЫЛО = 0.5
П_КАНДИДАТ = 0.15           # с какой вероятности статья считается кандидатом
П_ЛИДЕР = 0.8               # лидер «почти определён»
EIG_МИН = 0.03              # ниже — вопрос ничего не добавляет
БЮДЖЕТ_ВОПРОСОВ = 6
ТАБЛИЦА_МИН, ТАБЛИЦА_МАКС = 0.05, 0.95
# Потолок вклада ОДНОЙ улики (нат). Блок говорит «о какой статье эта фраза», а не «у человека эта статья есть»: голое слово («близорукость»)
# не должно поднимать статью выше уровня кандидата, иначе ядро перестаёт спрашивать, и ошибка тянется в итог (каскад).
# Конкретность добавляет вес: названо число или степень, диагноз подтвердил врач.
ПОТОЛОК_УЛИКИ, ПРИБАВКА_ЗА_ЧИСЛО, ПРИБАВКА_ЗА_ВРАЧА = 2.5, 1.5, 1.5
МИН_РАЗРЫВ_ТАБЛИЦЫ = 0.15
# --- защита от каскада (см. каскады/ОТЧЁТ.md: у каждого числа есть замер)
ПРИБАВКА_ЗА_СОГЛАСИЕ = 1.0      # сколько нат добавляют к сильнейшей улике остальные упоминания той же статьи
ПОРОГ_ПРОТИВОРЕЧИЯ = 1.5        # «да» и «нет» к одной статье считаются противоречием, если обе улики не слабее
П_ПОЛ = 0.2                     # спорная или пропущенная разбором статья держится не ниже этой вероятности (уровень кандидата)
ПОРОГ_ТЕКСТА = 4.0              # фраза реплики «указывает на статью», если её отношение правдоподобия не меньше (нат)
ДОЛЯ_ПОДТВЕРЖДЕНИЯ = 0.5        # разбор «учёл» статью, если его вклад не меньше такой доли от вклада самой фразы реплики
ПРЕДЕЛ_БЕЗ_ПОДТВЕРЖДЕНИЯ = 2.0  # выше этого статья не растёт по упоминаниям, которых слова человека не подтверждают (нат)
ЗАЩИТА = {"снятие": True, "согласие": True, "противоречие": True, "сверка": True}      # каждый механизм отдельно выключается для замера


def потолок_улики(уточнение, подтверждено):
    return ПОТОЛОК_УЛИКИ + (ПРИБАВКА_ЗА_ЧИСЛО if re.search(r"\d", уточнение or "") else 0.0) + (ПРИБАВКА_ЗА_ВРАЧА if подтверждено == "врач" else 0.0)


def logit(p):
    p = min(max(p, 1e-9), 1 - 1e-9)
    return math.log(p / (1 - p))


def sigm(x):
    return 1 / (1 + math.exp(-x)) if x >= 0 else math.exp(x) / (1 + math.exp(x))


def H(p):
    p = min(max(p, 1e-12), 1 - 1e-12)
    return -(p * math.log(p) + (1 - p) * math.log(1 - p))


def eig(p, да_если_есть, да_если_нет):
    """Ожидаемый информационный выигрыш (нат) вопроса да/нет о бинарной величине с P(z=1)=p."""
    a, b = да_если_есть, да_если_нет
    py = p * a + (1 - p) * b
    if py <= 1e-9 or py >= 1 - 1e-9:
        return 0.0
    p_да = p * a / py
    p_нет = p * (1 - a) / (1 - py)
    return H(p) - (py * H(p_да) + (1 - py) * H(p_нет))


def ln_lr(p):
    """Сколько нат говорит блок в пользу статьи: ln отношения шансов p к фоновым шансам 1/N (не меньше нуля)."""
    фон = 1.0 / N_СТАТЕЙ
    p = min(max(p, 1e-9), 1 - 1e-9)
    return max(0.0, math.log((p / (1 - p)) / (фон / (1 - фон))))


def _основы(текст):
    return {w[:5] for w in re.findall(r"[а-яa-z0-9]+", текст.lower().replace("ё", "е")) if len(w) >= 4}


def цитата_в_тексте(цитата, текст, доля=0.75):
    """Проверка по документу: вопрос принимается, только если цитата критерия, на которой он держится, есть в тексте статьи
    (по основам слов длиной от 4 букв; цитата — не меньше трёх таких слов). Ядро не верит таблицам модели на слово."""
    слова = [w[:5] for w in re.findall(r"[а-яa-z0-9]+", (цитата or "").lower().replace("ё", "е")) if len(w) >= 4]
    if len(слова) < 3 or not текст:
        return False
    известные = _основы(текст)
    return sum(w in известные for w in слова) / len(слова) >= доля


def очистить_таблицу(а, б):
    """Режет вероятности и проверяет монотонность. Возвращает (а, б) или None, если вопрос ничего не различает."""
    try:
        а, б = float(а), float(б)
    except (TypeError, ValueError):
        return None
    а = min(max(а, ТАБЛИЦА_МИН), ТАБЛИЦА_МАКС)
    б = min(max(б, ТАБЛИЦА_МИН), ТАБЛИЦА_МАКС)
    return (а, б) if а - б >= МИН_РАЗРЫВ_ТАБЛИЦЫ else None


# ------------------------------------------------------------------ слова человека: независимая проверка разбора
# Маркеры живой речи. Это русский язык и медицинская тема, поэтому они здесь (приложение), а не в архитектуре NNL.
_ОТРИЦАНИЕ = re.compile(r"\bнет\b|\bне\b|\bни\b|\bбез\b|никогда|ничего|отсутств|в\s+норме|нормальн|в\s+порядке|здоров|чисто\b|всё\s+хорошо|все\s+хорошо|"
                        r"не\s+беспоко", re.I)
_ТРЕТЬЕ_ЛИЦО = re.compile(r"брат|сестр|отец|отц[аеу]|пап[аеуы]|мам[аеуы]|матер|друг[аеу]?\b|подруг|приятел|знаком|одноклассник|сосед|коллег|муж\b|мужа|жен[аыуе]\b|"
                          r"сын|доч|дяд|тёт|тет[яеи]|бабушк|дедушк|\bдед|родствен|\bу\s+него|\bу\s+неё|\bу\s+нее|\bон\b|\bона\b|\bони\b", re.I)
_ВРАЧ = re.compile(r"врач|доктор|окулист|офтальмолог|терапевт|невролог|кардиолог|пульмонолог|хирург|травматолог|ортопед|отоларинголог|\bлор\b|уролог|психиатр|нарколог|"
                   r"эндокринолог|гастроэнтеролог|дерматолог|ревматолог|диагноз|поставил|обследова|\bмрт\b|\bкт\b|узи|экг|рентген|анализ|справк|выписк|заключени|больниц|"
                   r"поликлиник|стационар|комисси|медосмотр|осмотр|диспансер|госпитал", re.I)


def _слова(текст):
    return [w for w in re.findall(r"[а-яa-z0-9]+", (текст or "").lower().replace("ё", "е")) if len(w) >= 3]


def _совпали(x, y):
    if min(len(x), len(y)) <= 4:
        return x == y
    общая = 0
    for a, b in zip(x, y):
        if a != b:
            break
        общая += 1
    return общая >= max(4, min(len(x), len(y)) - 2)


def тот_же_предмет(термин1, термин2):
    """Два упоминания говорят об одном и том же, если не меньше половины слов более короткого названия есть в другом (по началу слова: «астма» = «астмы»)."""
    a, b = _слова(термин1), _слова(термин2)
    if not a or not b:
        return (термин1 or "").strip().lower() == (термин2 or "").strip().lower()
    меньше, больше = (a, b) if len(a) <= len(b) else (b, a)
    return sum(any(_совпали(x, y) for y in больше) for x in меньше) / len(меньше) >= 0.5


def _окно_упоминания(запись, реплика, после=20):
    """Окружение названия упоминания в словах человека: предложение, в котором названия совпало больше всего слов, без самого названия
    (слева — всё предложение, справа — несколько слов: «не болел: …», «у брата …», «… нет»). Маркер отрицания или третьего лица должен стоять рядом
    с названием, а не внутри него и не в соседнем предложении. Названия нет в словах человека — вся реплика."""
    слова = _слова(запись["термин"])
    низ = реплика.lower().replace("ё", "е")
    название = запись["термин"].lower().replace("ё", "е").strip()
    лучшее, счёт = None, 0
    начало_предложения = 0
    for m in re.finditer(r"[.!?;\n]|$", низ):
        предложение = низ[начало_предложения:m.start()]
        начало_предложения = m.end()
        i = предложение.find(название) if название else -1
        if i >= 0:                                                 # название дословно в предложении: его границы известны точно
            лучшее, счёт = (предложение, i, i + len(название)), 10 ** 6
            break
        места = [x for x in re.finditer(r"[а-яa-z0-9]+", предложение) if len(x.group()) >= 3 and any(_совпали(w, x.group()) for w in слова)]
        if len(set(x.group() for x in места)) > счёт:
            счёт, лучшее = len(set(x.group() for x in места)), (предложение, min(x.start() for x in места), max(x.end() for x in места))
    if not лучшее:
        return низ
    предложение, начало, конец = лучшее
    return предложение[:начало] + " " + предложение[конец:конец + после]


def _доля_слов_в_реплике(запись, реплика):
    """Какая доля слов названия упоминания есть в словах человека. Разбор мог пересказать жалобу другими словами, но выдуманное в реплике не найдётся."""
    слова = _слова(запись["термин"])
    имеющиеся = _слова(реплика)
    return sum(any(_совпали(w, x) for x in имеющиеся) for w in слова) / len(слова) if слова else 1.0


def _сложить(вклады):
    """Вклады одного знака к одной статье → общий (нат). вклады: [(вклад, потолок, номер реплики)].
    Упоминания одной реплики зависимы (слова одного человека, один разбор): вместе не больше сильнейшего потолка плюс прибавка за согласие.
    Повтор жалобы в другой реплике — новое высказывание, оно складывается."""
    по_репликам = {}
    for c, потолок, реплика in вклады or []:
        по_репликам.setdefault(реплика, []).append((c, потолок))
    итого = 0.0
    for группа in по_репликам.values():
        сумма = sum(c for c, _ in группа)
        итого += min(сумма, max(п for _, п in группа) + ПРИБАВКА_ЗА_СОГЛАСИЕ) if ЗАЩИТА["согласие"] and len(группа) > 1 else сумма
    return итого


class Расследование:
    def __init__(self, статьи, бюджет=БЮДЖЕТ_ВОПРОСОВ):
        self.статьи = list(статьи)
        self.журнал = []            # все записи в порядке поступления, в том числе снятые: ничего не стирается, снятое помечено
        self.задано = []            # [(статья, текст)]
        self.бюджет = бюджет
        self.ожидается = None       # вопрос, на который ждём ответ
        self.полы = {}              # статья -> причина: слова человека указывают на статью, а разбор её не учёл (остаётся кандидатом); остальные полы и пределы — в записях улик
        self._реплика = 0
        self._кэш = None

    # -------------------------------------------------------------- состояние: каждый раз с нуля из журнала
    @property
    def улики(self):
        """Действующие улики (снятые остаются в журнале, но в состояние и в досье не идут)."""
        return [з for з in self.журнал if з["действует"]]

    @property
    def значения(self):
        """(статья или None, текст значения) — степени, числа, чем подтверждено: идёт в итог. Только от действующих улик."""
        out = []
        for з in self.улики:
            if з["тип"] == "упоминание" and з["уточнение"]:
                out.append((None, "%s: %s" % (з["термин"], з["уточнение"])))
            elif з["тип"] == "ответ" and з.get("значение"):
                out.append((з.get("статья"), "%s → %s" % (з["вопрос"], з["значение"])))
        return out

    @property
    def чужое(self):
        return [з["термин"] for з in self.улики if з["тип"] == "упоминание" and з["статус"] == "чужое"]

    @property
    def l(self):
        return self._состояние()["l"]

    def _состояние(self):
        if self._кэш is not None:
            return self._кэш
        приор = logit(ПРИОР)
        плюс, минус, ответы = {}, {}, {}
        for з in self.журнал:
            if not з["действует"]:
                continue
            if з["тип"] == "ответ":
                if з.get("статья") in self.статьи and з["ln_lr"]:
                    ответы[з["статья"]] = ответы.get(з["статья"], 0.0) + з["ln_lr"]
                continue
            if з["статус"] == "чужое":
                continue
            вес = ВЕС_БЫЛО if з["статус"] == "было" else 1.0
            for a, e in з["вклад"].items():
                c = min(e * вес, з["потолок"])                     # сначала вес статуса, потом потолок конкретности
                if з["статус"] == "нет":
                    if not з.get("не_подтверждено"):               # отрицание без маркера в словах человека не снижает статью
                        минус.setdefault(a, []).append((c, з["потолок"], з["реплика"]))
                else:
                    плюс.setdefault(a, []).append((c, з["потолок"], з["реплика"]))
        полы, пределы = dict(self.полы), {}
        for з in self.журнал:                                      # полы и пределы упоминаний живут, пока жива сама улика: поправка человека снимает и их
            if з["действует"] and з["тип"] == "упоминание":
                полы.update(з.get("пол", {}))
                for a, предел in з.get("предел", {}).items():
                    пределы[a] = min(пределы.get(a, предел), предел)
        l, спорные = {}, {}
        for a in self.статьи:
            п, м = _сложить(плюс.get(a)), _сложить(минус.get(a))
            if a in пределы:
                п = min(п, пределы[a])
            база = приор + п - м
            if ЗАЩИТА["противоречие"] and п >= ПОРОГ_ПРОТИВОРЕЧИЯ and м >= ПОРОГ_ПРОТИВОРЕЧИЯ:
                спорные[a] = "«есть» и «нет» к одной статье из разных упоминаний"
            if a in спорные or a in полы:
                база = max(база, logit(П_ПОЛ))
            l[a] = min(max(база + ответы.get(a, 0.0), L_МИН), L_МАКС)
        self._кэш = {"l": l, "спорные": спорные}
        return self._кэш

    def _сбросить(self):
        self._кэш = None

    # -------------------------------------------------------------- чтение
    def p(self, a):
        return sigm(self.l[a])

    def рейтинг(self, n=8):
        l = self.l
        return sorted(((a, sigm(l[a])) for a in self.статьи), key=lambda x: -x[1])[:n]

    def кандидаты(self, порог=П_КАНДИДАТ, n=4):
        return [(a, p) for a, p in self.рейтинг(n) if p >= порог]

    def есть_улики(self):
        return any(з["действует"] for з in self.журнал)

    def подтверждено_врачом(self):
        """Вердикт по категории допустим, только если хоть что-то «есть» подтверждено врачом: диагноз, обследование, замер в медучреждении."""
        return any(з["действует"] and з["тип"] == "упоминание" and з["статус"] == "есть" and з.get("подтверждено") == "врач" for з in self.журнал)

    # -------------------------------------------------------------- обновления
    def _сдвиги(self, до, причины, n=4):
        после = {a: sigm(v) for a, v in self.l.items()}
        строки = []
        for a in self.статьи:
            if abs(после[a] - до[a]) >= 1e-4:
                строки.append({"статья": a, "до": round(до[a], 4), "после": round(после[a], 4), "причина": причины.get(a, "пересчёт журнала улик")})
        return sorted(строки, key=lambda s: -abs(s["после"] - s["до"]))[:n]

    def _p_все(self):
        return {a: sigm(v) for a, v in self.l.items()}

    def _снять(self, запись, кем, причина):
        запись["действует"] = False
        запись["снято"] = {"кем": кем, "причина": причина}

    def учесть_упоминание(self, термин, статус, уточнение, p_блока, p_ничего, подтверждено="нет_данных"):
        ключ = (термин.strip().lower(), статус)
        потолок = потолок_улики(уточнение, подтверждено)
        до = self._p_все()
        причины, снятые = {}, []
        действующие = [з for з in self.журнал if з["действует"] and з["тип"] == "упоминание"]
        for з in действующие:
            if (з["термин"].strip().lower(), з["статус"]) == ключ:
                if ЗАЩИТА["снятие"] and подтверждено == "сам" and з.get("подтверждено") == "врач":
                    self._снять(з, len(self.журнал) + 1, "человек поправился: врач этого не подтверждал, это его собственное мнение")
                    снятые.append(з)
                    continue
                if ЗАЩИТА["снятие"] and потолок > з["потолок"] + 1e-9:
                    self._снять(з, len(self.журнал) + 1, "уточнено: тот же факт, но с числом или подтверждением врача")
                    снятые.append(з)
                else:
                    return {"повтор": ключ}                        # повтор того же упоминания не считается дважды
        for з in действующие:
            if з["действует"] and ЗАЩИТА["снятие"] and з["статус"] != статус and тот_же_предмет(з["термин"], термин):
                self._снять(з, len(self.журнал) + 1, "человек поправился: теперь «%s»" % статус)
                снятые.append(з)
        вектор = {}
        for a, p in p_блока.items():
            e = ln_lr(p)
            if a in self.статьи and e >= 0.5:                      # блок почти не связывает фразу с остальными статьями
                вектор[a] = e
                причины[a] = "блок: p=%.3f" % min(max(p, 1e-9), 1 - 1e-9)
        запись = {"тип": "упоминание", "н": len(self.журнал) + 1, "реплика": self._реплика, "термин": термин, "статус": статус, "уточнение": уточнение,
                  "подтверждено": подтверждено, "p_ничего": round(p_ничего, 3), "потолок": round(потолок, 2), "действует": True, "снято": None, "проверки": [],
                  "вектор": вектор, "вклад": {} if статус == "чужое" else dict(вектор), "сдвиги": []}
        for з in снятые:
            for a in з["вклад"]:
                причины.setdefault(a, "снята прежняя улика «%s» (%s): %s" % (з["термин"], з["статус"], з["снято"]["причина"]))
        вес = ВЕС_БЫЛО if статус == "было" else 1.0
        for a, e in запись["вклад"].items():
            if e * вес > потолок:
                причины[a] += ", ограничено потолком %.1f нат" % потолок
        self.журнал.append(запись)
        self._сбросить()
        запись["сдвиги"] = self._сдвиги(до, причины)
        запись["снято_прежних"] = [з["термин"] for з in снятые]
        return запись

    def учесть_ответ(self, вопрос, ответ, значение=""):
        """ответ: 'да' | 'нет' | 'не_знаю'. Вопрос — dict из выбрать_вопрос()."""
        до = self._p_все()
        запись = {"тип": "ответ", "н": len(self.журнал) + 1, "реплика": self._реплика, "вопрос": вопрос["текст"], "ответ": ответ, "статья": вопрос.get("статья"),
                  "значение": значение or "", "ln_lr": 0.0, "действует": True, "снято": None, "сдвиги": []}
        причины = {}
        if вопрос.get("вид") == "да_нет" and ответ in ("да", "нет"):
            а, б = вопрос["таблица"]
            lr = (а / б) if ответ == "да" else ((1 - а) / (1 - б))
            запись["ln_lr"] = math.log(lr)
            причины[вопрос["статья"]] = "ответ «%s», LR=%.2f" % (ответ, lr)
        self.журнал.append(запись)
        self._сбросить()
        запись["сдвиги"] = self._сдвиги(до, причины, n=1) if причины else []
        self.ожидается = None
        return запись

    def сверить_реплику(self, клаузы, слова_человека):
        """Независимая проверка разбора реплики словами самого человека. Вызывать один раз на реплику, после учёта её упоминаний.
        клаузы: [{'текст', 'p' (статья → p блока), 'p0', 'целиком'}] — предложения реплики (и она целиком), оценённые тем же блоком по сырому тексту, без разбора.
        слова_человека: все реплики человека от первой до текущей. Возвращает {'флаги': [...]} для следа. Ничего не отвергает: расхождение
        снимает уверенность (потолок, пол «кандидат») и приводит к вопросу."""
        флаги = []
        мои = [з for з in self.журнал if з["действует"] and з["тип"] == "упоминание" and з["реплика"] == self._реплика]
        self._реплика += 1
        if not ЗАЩИТА["сверка"] or not мои or not клаузы:
            return {"флаги": флаги}
        до = self._p_все()
        все_слова = " ".join(слова_человека).lower().replace("ё", "е")
        # 1. статус и «кто подтвердил» — по словам человека в той же фразе
        for з in мои:
            if з["статус"] in ("нет", "чужое"):
                маркер = _ОТРИЦАНИЕ if з["статус"] == "нет" else _ТРЕТЬЕ_ЛИЦО
                if not маркер.search(_окно_упоминания(з, слова_человека[-1])):
                    з["не_подтверждено"] = True
                    з["проверки"].append("статус «%s» не подтверждён словами человека" % з["статус"])
                    флаги.append({"вид": "статус_без_маркера", "термин": з["термин"], "статус": з["статус"]})
                    for a, e in з["вектор"].items():
                        if e >= 2.0:                                # может быть, статья как раз у человека: держим её кандидатом и спрашиваем (пока улика действует)
                            з.setdefault("пол", {})[a] = "разбор сказал «%s», а в словах человека этого нет" % з["статус"]
            if з.get("подтверждено") == "врач" and not _ВРАЧ.search(все_слова):
                з["подтверждено_заявлено"], з["подтверждено"] = "врач", "нет_данных"
                з["потолок"] = round(потолок_улики(з["уточнение"], "нет_данных"), 2)
                з["проверки"].append("«подтвердил врач» не подтверждено: в словах человека нет врача, обследования или документа")
                флаги.append({"вид": "врач_без_слов", "термин": з["термин"]})
        # 2. охват статей: что говорят фразы реплики и что учёл разбор
        e_текст, главные = {}, {}
        for к in клаузы:
            for a, p in к["p"].items():
                e_текст[a] = max(e_текст.get(a, 0.0), ln_lr(p))
            верх = max(к["p"], key=к["p"].get) if к["p"] else None
            if верх is not None and к["p"][верх] >= 0.5 and not к.get("целиком"):      # на что предложение указывает прямо; смесь из нескольких предложений блок читает размыто
                главные[верх] = max(главные.get(верх, 0.0), ln_lr(к["p"][верх]))
        e_разбор = {}
        for з in мои:
            for a, e in з["вектор"].items():
                e_разбор[a] = max(e_разбор.get(a, 0.0), e)
        for a, e in главные.items():
            if a in self.статьи and e >= ПОРОГ_ТЕКСТА and e_разбор.get(a, 0.0) < ДОЛЯ_ПОДТВЕРЖДЕНИЯ * e:
                self.полы[a] = "слова человека указывают на статью, а разбор её не учёл"
                флаги.append({"вид": "пропущено_разбором", "статья": a, "e_текст": round(e, 1), "e_разбор": round(e_разбор.get(a, 0.0), 1)})
        for з in мои:
            if з["статус"] in ("есть", "было"):
                for a, e in з["вклад"].items():
                    if e >= 2.0 and e_текст.get(a, 0.0) < ДОЛЯ_ПОДТВЕРЖДЕНИЯ * e and _доля_слов_в_реплике(з, слова_человека[-1]) < 0.5:
                        з.setdefault("предел", {})[a] = ПРЕДЕЛ_БЕЗ_ПОДТВЕРЖДЕНИЯ
                        з["проверки"].append("слова человека не подтверждают связь со ст.%s" % a)
                        флаги.append({"вид": "не_подтверждено_словами", "термин": з["термин"], "статья": a, "e_разбор": round(e, 1), "e_текст": round(e_текст.get(a, 0.0), 1)})
        self._сбросить()
        после = self._p_все()
        return {"флаги": флаги, "сдвиги": [{"статья": a, "до": round(до[a], 4), "после": round(после[a], 4)} for a in self.статьи if abs(после[a] - до[a]) >= 1e-4][:4]}

    # -------------------------------------------------------------- решение
    def выбрать_вопрос(self, предложения, тексты_статей=None):
        """предложения: [{'вид': 'да_нет'|'значение', 'статья', 'текст', 'таблица': (а, б) | None, ...}].
        Возвращает (выбранный или None, разбор) — разбор показываем в студии: у каждого кандидата EIG и причина отказа."""
        канд = dict(self.кандидаты(порог=0.05, n=6))
        тексты = тексты_статей or {}
        спрошено = {(s, t) for s, t in self.задано}
        разбор, годные = [], []
        for q in предложения:
            r = {"статья": q.get("статья"), "текст": q.get("текст"), "вид": q.get("вид")}
            if not q.get("текст") or q.get("статья") not in канд:
                r["отказ"] = "статья не среди кандидатов"
            elif (q["статья"], q["текст"]) in спрошено:
                r["отказ"] = "уже спрашивали"
            elif тексты and not цитата_в_тексте(q.get("по_критерию", ""), тексты.get(q["статья"], "")):
                r["отказ"] = "цитата критерия не найдена в тексте статьи"
            elif q.get("вид") == "да_нет":
                т = очистить_таблицу(*(q.get("таблица") or (None, None)))
                if т is None:
                    r["отказ"] = "таблица не различает гипотезы"
                else:
                    r["таблица"] = т
                    r["eig"] = round(eig(self.p(q["статья"]), *т), 4)
                    годные.append(dict(q, таблица=т, eig=r["eig"]))
            elif q.get("вид") == "значение":
                r["значение_для_степени"] = True
                годные.append(dict(q, eig=0.0))
            разбор.append(r)
        да_нет = sorted([q for q in годные if q["вид"] == "да_нет"], key=lambda q: -q["eig"])
        значения = [q for q in годные if q["вид"] == "значение"]
        лидер = self.рейтинг(1)[0]
        выбран = None
        # защита от подтверждающей ошибки: лидер почти определён — раз проверяем конкурента
        if лидер[1] >= П_ЛИДЕР and not any(s != лидер[0] for s, _ in self.задано):
            конк = [q for q in да_нет if q["статья"] != лидер[0] and q["eig"] >= EIG_МИН / 2]
            if конк:
                выбран = dict(конк[0], причина="контроль: лидер почти определён (p=%.2f), проверяем конкурента" % лидер[1])
        if выбран is None and да_нет and да_нет[0]["eig"] >= EIG_МИН:
            выбран = dict(да_нет[0], причина="наибольший информационный выигрыш (%.3f нат)" % да_нет[0]["eig"])
        if выбран is None and значения and лидер[1] >= 0.5:
            ст = лидер[0]
            подходящие = [q for q in значения if q["статья"] == ст and (ст, q["текст"]) not in спрошено]
            if подходящие:
                выбран = dict(подходящие[0], причина="статья-лидер подтверждается — уточняем степень")
        return выбран, разбор

    def следующий_шаг(self, хочет_завершить=False):
        """Решение ядра до обращения к модели: 'завершить' | 'спросить' | 'открытый_вопрос' и причина."""
        k = self.кандидаты()
        if хочет_завершить and self.есть_улики():
            return "завершить", "человек сам просит итог"
        if len(self.задано) >= self.бюджет:
            return "завершить", "исчерпан бюджет вопросов (%d)" % self.бюджет
        if not k:
            return "открытый_вопрос", "ни одна статья не набрала %.2f — нужны конкретные жалобы или диагнозы" % П_КАНДИДАТ
        return "спросить", "кандидаты: %s" % ", ".join("ст.%s %.2f" % x for x in k)


