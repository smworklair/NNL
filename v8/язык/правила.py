"""Язык NNL-1 — правила перевода вопроса на язык. Обученных чисел нет: только списки слов и алгоритмы.

Вопрос превращается в мешок «слов языка» (токенов). Каждая форма токена имеет точный смысл (стандарт.json):
  с:<основа>             основа слова, слово утверждается (стеммер Snowball, русский, копия в snowball_ru/);
  н:<основа>             основа слова, которое человек отрицает («нет астмы», «астмы не было»);
  п:<основа>|<основа>    две соседние утверждаемые основы;
  к:<кусок>              кусок утверждаемого слова из 3–5 букв с метками начала и конца «<», «>»;
  м:<метка>              метка из списка меток стандарта (кто говорит, время, отрицание, вопрос, число).
Служебные слова (предлоги, местоимения, союзы) в основы не идут, но по ним ставятся метки.

Отрицание — по образцу NegEx (как в v6/ядро/язык.py, правила перенесены в язык без изменений по смыслу):
слово-отрицание действует вперёд («нет астмы»), а если за ним сразу граница — назад («астмы нет»), не дальше 4 слов
и не через границу (знак препинания, «но», «а», «однако», «зато», «хотя», «только», «есть», «кроме»).
Не отрицание: «или нет», «нет ли», «нет» в начале фразы перед запятой («нет, у меня…»).

Это код языка, а не ядра: ядро вызывает перевод, но само правил языка не содержит."""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from snowball_ru import RussianStemmer  # noqa: E402

_stemmer = RussianStemmer()
_cache = {}


def основа(слово):
    s = _cache.get(слово)
    if s is None:
        s = _stemmer.stemWord(слово)
        if len(_cache) < 200000:
            _cache[слово] = s
    return s


STOP = frozenset("""
и в во на с со к ко о об обо от до по за из изо у а но да или либо ли же бы б ведь вот ну то это этот эта эти этого этой
этим этих тот та те того той тем тех так как что чтобы когда где куда откуда если чем при для под над про через между
я мы ты вы он она оно они меня мне мной нас нам нами тебя тебе тобой вас вам вами его ему им её ее ей ею их ими него нему
нем нём ней нее неё них ним ними мой моя мое моё мои моего моей моему моим моих свой своя свое своё свои своего своей
своему своим своих себя себе собой твой твоя твое твоё твои ваш ваша ваше ваши наш наша наше наши уже ещё еще тоже также
даже лишь вообще просто типа нибудь
""".split())

# ---- метки ----
ЯЯ = frozenset("я меня мне мной мой моя мое моё мои моего моей моему моим моих моем моём сам сама".split())
ДРУГОЙ = frozenset("""брат брата брату братом брате братик братишка братишке сестра сестры сестре сестру сестрой
сын сына сыну сыном сыне сынок сынка сыночек сыночка дочь дочка дочки дочери отец отца отцу отцом папа папы папе папу
мама мамы маме маму мать матери муж мужа мужу мужем жена жены жене жену друг друга другу другом подруга подруги
знакомый знакомого знакомому знакомая знакомой товарищ товарища племянник племянника внук внука ребенок ребенка
ребенку дети детей парня парню парнем одноклассник одноклассника однокурсник однокурсника сосед соседа""".split())
ПРОШЛОЕ = frozenset("""был была было были болел болела болели перенес перенесла перенесли лечился лечилась лечили лежал
лежала ставили поставили выявили обнаружили раньше ранее детстве когда-то давно прошлом прошлого прошлой прошлый""".split())
БУДУЩЕЕ = frozenset("буду будет будут будем пойду пойдет собираюсь собирается планирую планирует скоро весной осенью потом".split())
ВОПРОС = frozenset("можно ли как что где когда сколько какой какая какие какую почему зачем могут обязан обязаны нужно надо".split())

# ---- отрицание (NegEx) ----
TRIGGERS = [t.split() for t in (
    "никогда не было", "никогда не болел", "никогда не болела",
    "не было", "не бывало", "не болел", "не болела", "не болею", "не болеет", "не болели", "не страдаю", "не страдал",
    "не страдала", "не страдает", "не имею", "не имел", "не выявили", "не выявлено", "не выявлен", "не выявлена",
    "не обнаружили", "не обнаружено", "не обнаружен", "не обнаружена", "не нашли", "не находили", "не ставили",
    "не поставили", "не подтвердили", "не подтвердился", "не подтвердилось", "не подтвердилась", "не диагностировали",
    "нет", "нету", "отсутствует", "отсутствуют", "исключили", "исключен", "исключена")]
TRIGGERS.sort(key=len, reverse=True)
BOUNDARY_WORDS = frozenset("но а однако зато хотя только есть кроме".split())
SCOPE = 4
_TOK = re.compile(r"[а-яa-z0-9]+(?:-[а-яa-z0-9]+)?|[^\sа-яa-z0-9]")


def _is_word(tok):
    return tok[0].isalnum()


def _boundary(tok):
    return not _is_word(tok) or tok in BOUNDARY_WORDS


def _negations(toks):
    """toks — список слов и знаков. Возвращает (места слов-отрицаний, места отрицаемых слов, описания)."""
    trig, scoped, found = set(), set(), []
    i, n = 0, len(toks)
    while i < n:
        hit = next((t for t in TRIGGERS if toks[i:i + len(t)] == t), None)
        if hit is None:
            i += 1
            continue
        j = i + len(hit)
        prev = toks[i - 1] if i > 0 else None
        nxt = toks[j] if j < n else None
        if hit == ["нет"] and ((prev == "или") or (nxt == "ли")
                               or ((prev is None or not _is_word(prev)) and nxt is not None and not _is_word(nxt))):
            i = j
            continue
        scope = []
        if nxt is not None and not _boundary(nxt):
            k = j
            while k < n and len(scope) < SCOPE and not _boundary(toks[k]) and not any(
                    toks[k:k + len(t)] == t for t in TRIGGERS):
                scope.append(k)
                k += 1
        else:
            k = i - 1
            while k >= 0 and len(scope) < SCOPE and not _boundary(toks[k]):
                scope.insert(0, k)
                k -= 1
        if scope:
            trig.update(range(i, j))
            scoped.update(scope)
            found.append({"отрицание": " ".join(toks[i:j]), "что": " ".join(toks[x] for x in scope)})
        i = j
    return trig, scoped, found


def куски(слово):
    g = "<" + слово + ">"
    return [g[i:i + n] for n in (3, 4, 5) for i in range(len(g) - n + 1)]


def разобрать(текст):
    """Полный разбор: токены языка и пояснения (что отрицается, какие метки). Детерминировано."""
    t = (текст or "").lower().replace("ё", "е")
    toks = [m.group(0) for m in _TOK.finditer(t)]
    trig, scoped, found = _negations(toks)
    метки = set()
    words = [w for w in toks if _is_word(w)]
    ws = set(words)
    if ws & ЯЯ:
        метки.add("кто:я")
    if ws & ДРУГОЙ:
        метки.add("кто:другой")
    if ws & ПРОШЛОЕ:
        метки.add("время:прошлое")
    if ws & БУДУЩЕЕ:
        метки.add("время:будущее")
    if "?" in toks or (words and (words[0] in ВОПРОС)) or "ли" in ws:
        метки.add("вопрос")
    if any(ch.isdigit() for ch in t):
        метки.add("число")
    if found:
        метки.add("отрицание")
    out, aff = [], []
    for i, w in enumerate(toks):
        if not _is_word(w) or i in trig or w in STOP:
            continue
        s = основа(w)
        if i in scoped:
            out.append("н:" + s)
            aff.append(None)
        else:
            out.append("с:" + s)
            aff.append(s)
            out.extend("к:" + g for g in куски(w))
    for a, b in zip(aff, aff[1:]):
        if a is not None and b is not None:
            out.append("п:%s|%s" % (a, b))
    out.extend("м:" + m for m in sorted(метки))
    return {"токены": out, "метки": sorted(метки), "отрицания": found}


def перевести(текст):
    """Вопрос → список токенов языка (мешок, повторы сохраняются)."""
    return разобрать(текст)["токены"]
