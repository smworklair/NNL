"""Обучение систем лабораторной v8. Запуск: python обучение/обучить.py <вариант> [зерно]

Варианты (данные одни и те же, обучение одно и то же; разница — только устройство):
  основная     — блоки «здоровье» и «право», 2 прохода: каждый читает на шине понятия соседа; выходные 0,3;
  один_проход  — те же блоки, но во втором проходе шину не читают (только свой вопрос); выходные 0,3;
  без_выходных — основная без выходных (все блоки всегда на месте);
  монолит      — один блок «целое»: все 132 ответа и все понятия, шину не читает.
Блоки пишутся в блоки/<вариант>.з<зерно>/<блок>/ (веса.npz, паспорт.json, контроль.jsonl)."""
import datetime
import json
import os
import random
import sys
import time

import numpy as np

sys.dont_write_bytecode = True
V8 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, V8)
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
from ядро import Язык, sha256_file  # noqa: E402
from обучение import данные as D  # noqa: E402
from обучение import сеть as С  # noqa: E402

ЯЗЫК = Язык(os.path.join(V8, "язык"))
ОБЛ = ["область:здоровье", "область:право"]
ГЛАВЫ = ["глава:%d" % n for n in range(1, 18)]
АКТЫ = list(D.АКТЫ.values())
НАСТРОЙКИ = {"корзины": 1 << 16, "размер": 48, "граница": 8.0, "свёртка": "корень", "масштаб_чтения": 8.0}
ОБУЧЕНИЕ = {"эпох": 20, "терпение": 3, "пакет": 64, "lr": 0.01, "λ": 1.0, "градиент_через_шину": False, "шум_шины": 0.0}


def перевести(rows):
    for r in rows:
        r["токены"] = ЯЗЫК.перевести(r["текст"])["токены"]
    return [r for r in rows if r["токены"]]


def устройство(вариант):
    """[(имя, область, ответы, пишет, читает, размер)], проходов, p_выходной."""
    zh, pr = D.ответы_здоровья(), D.ответы_права()
    if вариант == "монолит":
        return [("целое", "здоровье+право", zh + pr, ОБЛ + ГЛАВЫ + АКТЫ, [], 96)], 1, 0.0
    з_пишет, п_пишет = ["область:здоровье"] + ГЛАВЫ, ["область:право"] + АКТЫ
    if вариант == "один_проход":
        return [("здоровье", "здоровье", zh, з_пишет, [], 48), ("право", "право", pr, п_пишет, [], 48)], 1, 0.3
    p = 0.0 if вариант == "без_выходных" else 0.3
    return [("здоровье", "здоровье", zh, з_пишет, п_пишет, 48), ("право", "право", pr, п_пишет, з_пишет, 48)], 2, p


def контроль(dev, b, n_фон=300, seed=1):
    """Контрольный набор блока: все dev-вопросы областей и живые + 300 фона. Ядро проверяет на нём язык блока."""
    rnd = random.Random(seed)
    фон = [r for r in dev if r.get("группа") == "фон"]
    rnd.shuffle(фон)
    rows = [r for r in dev if r.get("группа") != "фон"] + фон[:n_фон]
    out = []
    for r in rows:
        out.append({"вопрос": r["текст"], "понятия": {k: r["понятия"].get(k) for k in b.пишет},
                    "ответы": [a for a in r["ответы"] if a in b.ответы]})
    return out


def сохранить(b, папка, вариант, seed, итог, сведения, схема, родитель=None, роль=""):
    os.makedirs(папка, exist_ok=True)
    w = os.path.join(папка, "веса.npz")
    b.сохранить(w)
    with open(os.path.join(папка, "контроль.jsonl"), "w", encoding="utf-8") as f:
        for r in итог["контроль"]:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    ps = {"имя": b.имя, "версия": итог.get("версия", 1), "роль": роль or b.роль, "область": b.область,
          "архитектура": "мешок_шина", "настройки": {"корзины": b.B, "размер": b.d, "граница": b.L, "соль": b.соль, "свёртка": b.свёртка,
                                                       "масштаб_чтения": b.масштаб},
          "веса": {"файл": "веса.npz", "sha256": sha256_file(w), "чисел": b.чисел()},
          "язык": ЯЗЫК.паспорт_языка(b.пишет, b.читает),
          "пишет": b.пишет, "читает": b.читает, "ответы": b.ответы,
          "контроль": {"файл": "контроль.jsonl", "вопросов": len(итог["контроль"])},
          "обучение": {"скрипт": итог.get("скрипт", "обучение/обучить.py"), "вариант": вариант, "зерно": seed,
                       "когда": datetime.datetime.now().isoformat(timespec="seconds"), "схема": схема,
                       "данные": сведения, "эпох": итог["эпох"], "лучший_dev": итог["лучший_dev"],
                       "выходные": итог["выходные"], "настройки_обучения": итог["настройки"],
                       "вместе_с": итог.get("вместе_с", [])},
          "родитель": родитель}
    json.dump(ps, open(os.path.join(папка, "паспорт.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    return ps


def main(вариант, seed=1, эпох=None):
    t0 = time.time()
    train, dev, сведения = D.собрать(seed=1)
    train, dev = перевести(train), перевести(dev)
    print("данные", сведения, "перевод %.0f с" % (time.time() - t0), flush=True)
    устр, проходов, p_off = устройство(вариант)
    блоки = [С.БлокУч(имя, ответы, пишет, читает, корзины=НАСТРОЙКИ["корзины"], размер=d, граница=НАСТРОЙКИ["граница"],
                      seed=seed * 100 + i, область=обл, роль="блок области «%s»" % обл, свёртка=НАСТРОЙКИ["свёртка"],
                      масштаб_чтения=float(os.environ.get("V8_SCALE", НАСТРОЙКИ["масштаб_чтения"])))
             for i, (имя, обл, ответы, пишет, читает, d) in enumerate(устр)]
    понятия = list(ЯЗЫК.понятия)
    tr = С.Набор(train, блоки, понятия)
    dv = С.Набор(dev, блоки, понятия)
    for r in train + dev:
        r.pop("токены", None)
    cfg = dict(ОБУЧЕНИЕ)
    if эпох:
        cfg["эпох"] = эпох
    if os.environ.get("V8_LR"):
        cfg["lr"] = float(os.environ["V8_LR"])
    if os.environ.get("V8_JOINTGRAD"):
        cfg["градиент_через_шину"] = True
    if os.environ.get("V8_NOISE"):
        cfg["шум_шины"] = float(os.environ["V8_NOISE"])
    сеть = С.Сеть(блоки, проходов=проходов, смешивание="среднее", градиент_через_шину=cfg["градиент_через_шину"], шум_шины=cfg["шум_шины"])
    out = os.path.join(V8, "блоки", "%s.з%d" % (вариант, seed))
    if os.environ.get("V8_TUNE"):
        out = os.path.join(V8, "подбор", "%s.з%d.lr%s.стоп%d.шум%s.масштаб%s" % (вариант, seed, cfg["lr"], not cfg["градиент_через_шину"],
                                                                                  cfg["шум_шины"], os.environ.get("V8_SCALE", "1")))
    os.makedirs(out, exist_ok=True)
    журнал = os.path.join(out, "обучение.jsonl")
    if os.path.exists(журнал):
        os.remove(журнал)
    итог = С.обучить(сеть, tr, dv, эпох=cfg["эпох"], терпение=cfg["терпение"], пакет=cfg["пакет"], lr=cfg["lr"], λ=cfg["λ"],
                     p_выходной=p_off, seed=seed, журнал=журнал, имя="%s.з%d" % (вариант, seed))
    схема = {"проходов": проходов, "смешивание": "среднее"}
    for b in блоки:
        info = dict(итог, контроль=контроль(dev, b), выходные=p_off, настройки=cfg, вместе_с=[x.имя for x in блоки if x is not b])
        сохранить(b, os.path.join(out, b.имя), вариант, seed, info, сведения, схема)
    print("готово %s.з%d за %.0f с, лучший dev %.4f" % (вариант, seed, time.time() - t0, итог["лучший_dev"]), flush=True)


if __name__ == "__main__":
    main(sys.argv[1], int(sys.argv[2]) if len(sys.argv) > 2 else 1, int(sys.argv[3]) if len(sys.argv) > 3 else None)
