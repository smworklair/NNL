# -*- coding: utf-8 -*-
"""Обучение одного блока при работающих остальных. Остальные блоки заморожены (их числа не меняются — проверяется по sha256),
но участвуют в каждом шаге: их вклады лежат на шине, их ответы — в общей сборке. Новый блок учится, читая их вклады.
Запуск: python обучение/дообучить.py <режим> [вариант] [зерно]
  новый_без_шины — то же, но новый блок шину не читает (для сравнения: что даёт чтение вкладов старых блоков).
  новый     — новый блок «команды» (голосовые команды MASSIVE ru, 60 команд, CC BY 4.0): пишет «область:команды»,
              читает понятия старых блоков. Его данные — только свои команды и общий фон (данных старых блоков у автора нового
              блока нет). Нужен язык 1.1 (понятие «область:команды» зарегистрировано).
  замена    — новый блок «здоровье» с другим устройством (размер 32, свёртка «среднее», другое зерно) вместо старого; «право» работает.
  дообучить [вариант зерно блок] — по схеме схемы/основная_право_заморожено.json; замороженный блок дообучать нельзя
              (python обучение/дообучить.py дообучить основная 1 право → отказ).
              Старый блок «здоровье» дообучается на новых данных (учитель test_t, 219 вопросов, нигде не использованы) с
              повтором части старых данных; «право» заморожено в схеме. Получается «здоровье» версии 2 с родителем.
"""
import json
import os
import random
import sys
import time

import numpy as np

sys.dont_write_bytecode = True
V8 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, V8)
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
from ядро import Схема, Ядро, Язык, sha256_file  # noqa: E402
from обучение import данные as D  # noqa: E402
from обучение import обучить as O  # noqa: E402
from обучение import сеть as С  # noqa: E402

ARCH = os.path.join(V8, "архитектуры")


def старые_блоки(вариант, seed, язык, схема):
    k = Ядро(язык, ARCH, схема=схема)
    папка = os.path.join(V8, "блоки", "%s.з%d" % (вариант, seed))
    out = []
    for имя in sorted(os.listdir(папка)):
        p = os.path.join(папка, имя)
        if not (os.path.isdir(p) and os.path.exists(os.path.join(p, "паспорт.json"))):
            continue
        if json.load(open(os.path.join(p, "паспорт.json"), encoding="utf-8"))["обучение"].get("вариант") != вариант:
            continue                      # только исходные блоки системы (без замен, новых версий и сторонних блоков)
        ok, msg, _ = k.подключить(p)
        assert ok, (p, msg)
        b = k.блоки[msg]
        P = dict(np.load(os.path.join(p, "веса.npz"), allow_pickle=False))
        cfg = b.паспорт["настройки"]
        out.append((p, b.паспорт, С.БлокУч(b.имя, b.ответы, b.пишет, b.читает, корзины=cfg["корзины"], размер=cfg["размер"],
                                            граница=cfg["граница"], соль=cfg["соль"], init=P, заморожен=True,
                                            свёртка=cfg.get("свёртка", "среднее"), масштаб_чтения=cfg.get("масштаб_чтения", 1.0),
                                            область=b.паспорт.get("область", ""))))
    return k, out


def main(режим, вариант="основная", seed=1, цель_имя="здоровье"):
    t0 = time.time()
    я = Язык(os.path.join(V8, "язык"))
    O.ЯЗЫК = я
    схема_путь = os.path.join(V8, "схемы", "%s.json" % вариант)
    схема = Схема.из_файла(схема_путь)
    k, старые = старые_блоки(вариант, seed, я, схема)
    sha_до = {ps["имя"]: sha256_file(os.path.join(p, "веса.npz")) for p, ps, _ in старые}
    cfg = dict(O.ОБУЧЕНИЕ)
    rnd = random.Random(seed)
    if режим in ("новый", "новый_без_шины"):
        assert "область:команды" in я.понятия, "в языке нет понятия «область:команды» — нужен язык 1.1"
        метки = D.метки_команд()
        ответы = ["ответ:команды:%s" % m for m in метки]
        читает = [x for x in я.понятия if x != "область:команды"] if режим == "новый" else []
        новый = С.БлокУч("команды", ответы, ["область:команды"], читает, корзины=1 << 16, размер=48, seed=seed * 100 + 7,
                         область="команды", роль="блок голосовых команд (сторонний автор: учился при работающих «здоровье» и «право»)"
                         + ("" if читает else "; шину не читает (для сравнения)"),
                         свёртка="корень", масштаб_чтения=O.НАСТРОЙКИ["масштаб_чтения"])
        def ряд(t, lab, гр=None):
            return {"текст": t, "понятия": {"область:команды": int(lab is not None)}, "ответы": ["ответ:команды:%s" % lab] if lab else [],
                    "источник": "команды" if lab else "фон", "группа": гр}
        train = [ряд(t, y) for t, y in D.команды("train")] + [ряд(t, None) for t in D.фон("train", 12000, seed)]
        dev = [ряд(t, y, "команды") for t, y in D.команды("dev")] + [ряд(t, None, "фон") for t in D.фон("dev", 1500, seed)]
        блоки = [b for _, _, b in старые] + [новый]
        p_off = 0.3
        сведения = {"train": len(train), "dev": len(dev), "данные": "MASSIVE ru train + фон v2 (12000); данных старых блоков нет"}
        out_name, версия, родитель = ("команды" if режим == "новый" else "команды_без_шины"), 1, None
    elif режим == "замена":
        старые = [x for x in старые if x[1]["имя"] != "здоровье"]
        train, dev, сведения = D.собрать(seed=1)
        зд = [b for b in (O.устройство(вариант)[0]) if b[0] == "здоровье"][0]
        _, обл, ответы, пишет, читает, _ = зд
        новый = С.БлокУч("здоровье", ответы, пишет, читает, корзины=1 << 16, размер=32, seed=seed * 100 + 55, область=обл,
                         роль="блок области «здоровье», замена: другое устройство (размер 32, свёртка «среднее»), учился при работающем «право»",
                         свёртка="среднее", масштаб_чтения=O.НАСТРОЙКИ["масштаб_чтения"])
        блоки = [b for _, _, b in старые] + [новый]
        p_off = 0.3
        out_name, версия, родитель = "здоровье@замена", 1, None
    elif режим == "дообучить":
        схема = Схема.из_файла(os.path.join(V8, "схемы", "основная_право_заморожено.json"))
        if цель_имя in (схема.заморожены or []):
            raise SystemExit("ОТКАЗ: блок «%s» заморожен в схеме «%s» — дообучать нельзя" % (цель_имя, схема.имя))
        цель = [x for x in старые if x[1]["имя"] == цель_имя][0]
        цель[2].заморожен = False
        b = цель[2]
        b.M = {kk: np.zeros_like(v) for kk, v in b.P.items()}
        b.S = {kk: np.zeros_like(v) for kk, v in b.P.items()}
        for _, ps, bb in старые:
            if ps["имя"] in схема.заморожены:
                bb.заморожен = True
        teach = D.jl(os.path.join(D.ПРОЕКТ, "train/data/queries_claude_teacher.jsonl"))
        новые = [D.строка(q["text"], 1, 0, [q["article_no"]], (), "учитель test_t") for q in teach if q["split"] == "test_t"]
        base_train, dev, сведения = D.собрать(seed=1)
        rnd.shuffle(base_train)
        train = []
        for r in новые:
            train += [r, r] + [dict(r, текст=x) for x in D.live(r["текст"], rnd, 4)]
        train += base_train[:4000]
        блоки = [bb for _, _, bb in старые]
        p_off = 0.3
        cfg.update(эпох=3, терпение=2, lr=0.002)
        сведения = dict(сведения, новые_вопросы=len(новые), повтор_старых=4000, train=len(train))
        out_name, версия = "здоровье@2", 2
        родитель = {"имя": "здоровье", "версия": цель[1]["версия"], "sha256": цель[1]["веса"]["sha256"]}
    else:
        raise SystemExit("режим: новый | новый_без_шины | замена | дообучить")
    train = O.перевести(train)
    dev = O.перевести(dev)
    понятия = list(я.понятия)
    tr = С.Набор(train, блоки, понятия)
    dv = С.Набор(dev, блоки, понятия)
    for r in train + dev:
        r.pop("токены", None)
    сеть = С.Сеть(блоки, проходов=схема.проходов, смешивание=схема.смешивание, градиент_через_шину=cfg["градиент_через_шину"])
    журнал = os.path.join(V8, "блоки", "%s.з%d" % (вариант, seed), "обучение_%s.jsonl" % режим)
    итог = С.обучить(сеть, tr, dv, эпох=cfg["эпох"], терпение=cfg["терпение"], пакет=cfg["пакет"], lr=cfg["lr"], λ=cfg["λ"],
                     p_выходной=p_off, seed=seed, журнал=журнал, имя=режим)
    учили = [b for b in блоки if not b.заморожен]
    assert len(учили) == 1, [b.имя for b in учили]
    b = учили[0]
    info = dict(итог, контроль=O.контроль(dev, b), выходные=p_off, настройки=cfg, версия=версия,
                скрипт="обучение/дообучить.py %s" % режим, вместе_с=[x.имя for x in блоки if x is not b])
    O.сохранить(b, os.path.join(V8, "блоки", "%s.з%d" % (вариант, seed), out_name), "%s:%s" % (вариант, режим), seed, info, сведения,
                {"проходов": схема.проходов, "смешивание": схема.смешивание, "заморожены": [x.имя for x in блоки if x.заморожен]},
                родитель=родитель)
    sha_после = {ps["имя"]: sha256_file(os.path.join(p, "веса.npz")) for p, ps, _ in старые}
    print("веса старых блоков не изменились:", sha_до == {**sha_до, **sha_после} and all(sha_до[n] == sha_после[n] for n in sha_после))
    print("готово %s за %.0f с, лучший dev %.4f" % (режим, time.time() - t0, итог["лучший_dev"]), flush=True)


if __name__ == "__main__":
    a = sys.argv[1:]
    main(a[0], a[1] if len(a) > 1 else "основная", int(a[2]) if len(a) > 2 else 1, a[3] if len(a) > 3 else "здоровье")
