# -*- coding: utf-8 -*-
"""Пересборка «набор вместо одного» на 61 стыковом вопросе.
Сравнивает стратегии сборки ответов без изменения весов блоков:
  1. v8 один ответ (baseline).
  2. Набор из двух соло-блоков: берём топ-1 каждого (независимо от порога 0,5).
  3. Набор из топ-3 полной системы: берём лучший ответ здоровья и лучший ответ права из кандидатов v8.
Метрики: оба верны, хотя бы один верен, верен только здоровье/право, оба неверны.
Пишет v9/результаты/лаба_набор_вместо_одного.json."""
import collections
import json
import os
import sys

sys.dont_write_bytecode = True
from лаба_общее import О  # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

sys.path.insert(0, О.V8)
from обучение import данные as D  # noqa: E402
from ядро import Ядро, Язык  # noqa: E402

ВХОД = os.path.join(О.БАЗА, "v9", "результаты", "лаба_стыки_полные.json")
ВЫХОД = os.path.join(О.БАЗА, "v9", "результаты", "лаба_набор_вместо_одного.json")


def соло(кого, язык):
    k = Ядро(язык, О.ARCH, схема=os.path.join(О.V8, "схемы", "основная_внешние.json"))
    ok, msg, _ = k.подключить(os.path.join(О.V8, "блоки", "основная_внешние.з1", кого))
    assert ok, (кого, msg)
    return k


def ключ(a):
    if a == О.НЕ_ЗНАЮ or a.get("вид") != "ответ":
        return ""
    return "ответ:%s:%s" % (a["область"], a.get("id") or "")


def первый_кандидат(сист, текст):
    """Возвращает (топ1_ответ, выше_порога_0_5) для одной системы."""
    a, rec = сист.спросить(текст)
    канд = rec.get("кандидаты") or []
    if not канд:
        return "", False
    return канд[0]["ответ"], (канд[0].get("p") or 0) >= 0.5


def метрики(зд, пр, зд_эт, пр_эт):
    """зд/пр — множества выданных ответов; зд_эт/пр_эт — эталонные множества."""
    зд_верно = bool(зд & зд_эт)
    пр_верно = bool(пр & пр_эт)
    return {
        "оба_верны": зд_верно and пр_верно,
        "хотя_бы_один": зд_верно or пр_верно,
        "только_зд": зд_верно and not пр_верно,
        "только_пр": not зд_верно and пр_верно,
        "оба_неверны": not зд_верно and not пр_верно,
        "зд_верно": зд_верно,
        "пр_верно": пр_верно,
    }


def main():
    стык = json.load(open(ВХОД, encoding="utf-8"))["вопросы"]
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    сз, сп = соло("здоровье", язык), соло("право", язык)

    стратегии = {"v8_один_ответ": [], "набор_соло_топ1": [], "набор_полная_топ3": []}
    for r in стык:
        зд_эт, пр_эт = set(r["эталон_зд"]), set(r["эталон_пр"])

        # 1. v8 один ответ (один ключ проверяется против обеих областей)
        один = set([r["топ1"]]) if r["топ1"] else set()
        стратегии["v8_один_ответ"].append(метрики(один, один, зд_эт, пр_эт))

        # 2. набор из двух соло-блоков
        топ_зд, _ = первый_кандидат(сз, r["текст"])
        топ_пр, _ = первый_кандидат(сп, r["текст"])
        набор_зд = set([топ_зд]) if топ_зд else set()
        набор_пр = set([топ_пр]) if топ_пр else set()
        стратегии["набор_соло_топ1"].append(метрики(набор_зд, набор_пр, зд_эт, пр_эт))

        # 3. набор из топ-3 кандидатов полной системы
        топ3 = r["топ3"]
        зд_в_топ3 = set(x["ответ"] for x in топ3 if x["ответ"].startswith("ответ:здоровье:"))
        пр_в_топ3 = set(x["ответ"] for x in топ3 if x["ответ"].startswith("ответ:право:"))
        стратегии["набор_полная_топ3"].append(метрики(зд_в_топ3, пр_в_топ3, зд_эт, пр_эт))

    n = len(стык)
    итог = {}
    для_суммы = ("оба_верны", "хотя_бы_один", "только_зд", "только_пр", "оба_неверны", "зд_верно", "пр_верно")
    for имя, список in стратегии.items():
        с = collections.Counter()
        for m in список:
            for k in для_суммы:
                с[k] += bool(m[k])
        итог[имя] = {k: "%d/%d" % (с[k], n) for k in для_суммы}
        if имя == "набор_соло_топ1":
            # уточнить: оба блока дали ответы выше порога?
            оба_набрали_порог = 0
            for r in стык:
                топ_зд, з_п = первый_кандидат(сз, r["текст"])
                топ_пр, п_п = первый_кандидат(сп, r["текст"])
                if з_п and п_п:
                    оба_набрали_порог += 1
            итог[имя]["оба_ответа_выше_порога_0_5"] = "%d/%d" % (оба_набрали_порог, n)

    итог["n"] = n
    итог["вопросы"] = стык

    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    json.dump(итог, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps({k: v for k, v in итог.items() if k != "вопросы"}, ensure_ascii=False, indent=1))
    print("записано:", ВЫХОД)


if __name__ == "__main__":
    main()
