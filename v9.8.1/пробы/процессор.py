def _sigmoid(z):
    if z >= 0:
        return 1.0 / (1.0 + math.exp(-z))
    e = math.exp(z)
    return e / (1.0 + e)


class Процессор:
    def __init__(self, ядро):
        """ядро — готовое v8-ядро с подключёнными блоками."""
        self.ядро = ядро
        self.язык = ядро.язык

    @staticmethod
    def _смешать(вклады):
        """То же смешивание, что в ядре v8: среднее по писателям."""
        if not вклады:
            return {}, {}
        сумма = {}
        счёт = {}
        for имя, c in вклады.items():
            for k, v in c.items():
                сумма[k] = сумма.get(k, 0.0) + v
                счёт[k] = счёт.get(k, 0.0) + 1
        return {k: сумма[k] / счёт[k] for k in сумма}, {k: [(n, 1.0) for n in [имя for имя in вклады]] for k in сумма}

    def _прогоны(self, текст):
        """Возвращает (токены, вклады, шина, писатели, счёты, видел)."""
        разбор = self.язык.перевести(текст)
        токены = разбор["токены"]
        блоки = list(self.ядро.блоки.values())
        вклады = {}
        for b in блоки:
            if not b.пишет:
                continue
            c = b.arch.проход1(b.obj, токены)
            if set(c) != set(b.пишет):
                raise ValueError("блок %s положил на шину не то, что обещал" % b.имя)
            вклады[b.имя] = c
        шина, писатели = self._смешать(вклады)
        счёты, видел = {}, {}
        for b in блоки:
            if not b.ответы:
                continue
            v = {k: шина[k] for k in b.читает if k in шина} if self.ядро.схема.проходов == 2 else {}
            s = b.arch.проход2(b.obj, токены, v)
            if set(s) != set(b.ответы):
                raise ValueError("блок %s вернул счёты не для своих ответов" % b.имя)
            for a, x in s.items():
                счёты[a] = x
            видел[b.имя] = v
        return токены, вклады, шина, писатели, счёты, видел

    def _набор(self, текст, n=1):
        """Стратегия "набор": для каждого блока независимый softmax, потом берём топ-n из каждого блока.
        Возвращает (ответ, запись)."""
        токены, вклады, шина, писатели, счёты, видел = self._прогоны(текст)
        # группируем счёты по области
        by_area = {}
        for a, x in счёты.items():
            обл = a.split(":")[1]
            by_area.setdefault(обл, {})[a] = x
        # для каждой области — softmax против "ничего" и топ-n
        набор = []
        for обл, s in by_area.items():
            m = max([0.0] + list(s.values()))
            z = math.exp(-m) + sum(math.exp(x - m) for x in s.values())
            p = {a: math.exp(x - m) / z for a, x in s.items()}
            топ = sorted(p, key=lambda a: (-p[a], a))[:n]
            for a in топ:
                _, обл, ид = a.split(":", 2)
                набор.append({"вид": "ответ", "область": обл, "id": ид, "p": round(p[a], 4), "ключ": a})
        # главный ответ — лучший по p в любом блоке (для совместимости с v8)
        if набор:
            главный = max(набор, key=lambda x: x["p"])
            ответ = {"вид": "ответ", "область": главный["область"], "id": главный["id"], "p": главный["p"],
                     "блок": self.ядро._владелец[главный["ключ"]]}
        else:
            ответ = НЕ_ЗНАЮ  # fallback
        запись = {
            "вопрос": текст, "сборка": "набор", "ответ": ответ,
            "набор": набор,
            "шина": {k: round(v, 4) for k, v in sorted(шина.items())},
            "схема": self.ядро.схема.имя,
        }
        return ответ, запись

    def _k2(self, текст, мост, значения):
        """Стратегия K2: условный прогон по мосту.
        мост — понятие на шине (ключ), значения — список возможных значений.
        p(ответ) = Σ_v p_A(мост=v) · p_B(ответ | мост=v).
        """
        токены, вклады, шина, писатели, счёты, видел = self._прогоны(текст)
        # определяем писателя моста и читателя
        блоки = list(self.ядро.блоки.values())
        писатель = None
        читатели = []
        for b in блоки:
            if any(k == мост or k.startswith(мост + ":") for k in b.пишет):
                писатель = b
            if any(k == мост or k.startswith(мост + ":") for k in b.читает):
                читатели.append(b)
        if писатель is None or not читатели:
            raise ValueError("мост %s: писатель=%s, читатели=%s" % (мост, писатель, читатели))

        # ключи моста на шине
        ключи_моста = [k for k in шина if k == мост or k.startswith(мост + ":")]
        # если значения не переданы — берём из шины
        if значения is None:
            значения = []
            for k in ключи_моста:
                части = k.split(":", 1)
                if len(части) == 2:
                    значения.append(части[1])
                else:
                    значения.append("")
        # распределение писателя — softmax по сырым счётам моста
        сырые = {v: шина.get(мост + ":" + str(v), 0.0) for v in значения}
        m = max(сырые.values()) if сырые else 0.0
        e = {v: math.exp(x - m) for v, x in сырые.items()}
        z = sum(e.values())
        p_A = {v: e[v] / z for v in значения} if z > 0 else {v: 0.0 for v in значения}

        # условный прогон читателя: для каждого v строим шину, где остаётся только одно значение моста
        результат = {}
        for b in читатели:
            for v in значения:
                v_шина = {k: val for k, val in шина.items() if not (k == мост or k.startswith(мост + ":"))}
                ключ_v = мост if мост in шина else мост + ":" + str(v)
                v_шина[ключ_v] = шина.get(ключ_v, 0.0)
                s = b.arch.проход2(b.obj, токены, v_шина)
                for a, x in s.items():
                    # переводим логиты читателя в вероятности через softmax внутри его ответов
                    # пока что накапливаем в пространстве вероятностей с весом p_A(v)
                    результат[a] = результат.get(a, 0.0) + p_A.get(v, 0.0) * math.exp(x)
        # нормализация итогового распределения
        if not результат:
            ответ = НЕ_ЗНАЮ
        else:
            z = sum(результат.values())
            p = {a: x / z for a, x in результат.items()}
            a = sorted(p, key=lambda a: (-p[a], a))[0]
            _, обл, ид = a.split(":", 2)
            ответ = {"вид": "ответ", "область": обл, "id": ид, "p": round(p[a], 4)}
        return ответ, {"вопрос": текст, "сборка": "k2", "ответ": ответ,
                       "мост": мост, "значения": значения, "p_A": {v: round(p, 4) for v, p in p_A.items()}}

    def _системы(self, текст, цепь, порог_уверенности=0.9):
        """System 1 / System 2: быстрая эвристика → рассуждение через цепочку.

        System 1 — набор (быстрый softmax): если top-1 уверен, сразу ответ.
        Иначе System 2 — причинно-следственная цепочка.
        """
        # System 1: быстрый отбор
        ответ_s1, запись_s1 = self._набор(текст)
        набор = запись_s1.get("набор", [])
        if набор:
            уверенность = max(x["p"] for x in набор)
        else:
            уверенность = 0.0

        система = "System 1"
        if уверенность < порог_уверенности:
            # System 2: медленное рассуждение через причинно-следственную связь
            ответ_s2, запись_s2 = self._цепочка(текст, цепь)
            система = "System 2"
            ответ = ответ_s2
            запись = запись_s2
        else:
            ответ = ответ_s1
            запись = запись_s1

        запись["система"] = система
        запись["уверенность_s1"] = round(уверенность, 4)
        return ответ, запись

    def _цепочка(self, текст, цепь):
        """Стратегия «цепочка»: последовательность причинно-следственных шагов.

        цепь — список dict, описанных в причинная_связь.Цепочка.
        Возвращает (ответ, запись)."""
        токены, вклады, шина, писатели, счёты, видел = self._прогоны(текст)
        цепь_obj = ПС.Цепочка(цепь)
        текущее = None
        итоговое = None
        for i, шаг in enumerate(цепь):
            # промежуточные шаги без цель_блок просто преобразуют распределение
            цель = шаг.get("цель_блок")
            выход = шаг.get("выход", "ответы")
            текущее, ответ_расп = цепь_obj.шаг(шаг, текущее, шина, токены, self.ядро.блоки)
            if выход == "ответы" and ответ_расп is not None:
                итоговое = ответ_расп
        if not итоговое:
            return НЕ_ЗНАЮ, {"вопрос": текст, "сборка": "цепочка", "ответ": НЕ_ЗНАЮ,
                               "цепь": цепь, "шина": {k: round(v, 4) for k, v in sorted(шина.items())}}
        # выбираем top-1 по вероятности
        a = max(итоговое, key=lambda x: (итоговое[x], x))
        p = итоговое[a]
        # ключ ответа должен соответствовать формату «ответ:<область>:<id>»
        if a.startswith("ответ:"):
            _, обл, ид = a.split(":", 2)
        else:
            # для несовместимых ключей используем имя как id и первую область из блока
            обл, ид = "абстракт", a
        ответ = {"вид": "ответ", "область": обл, "id": ид, "p": round(p, 4)}
        return ответ, {"вопрос": текст, "сборка": "цепочка", "ответ": ответ,
                       "цепь": цепь, "распределение": {k: round(v, 4) for k, v in итоговое.items()},
                       "шина": {k: round(v, 4) for k, v in sorted(шина.items())}}

    def спросить(self, текст, стратегия="набор", **kwargs):
        if стратегия == "набор":
            return self._набор(текст, **kwargs)
        if стратегия == "k2":
            return self._k2(текст, **kwargs)
        if стратегия == "цепочка":
            return self._цепочка(текст, **kwargs)
        if стратегия == "системы":
            return self._системы(текст, **kwargs)
        raise ValueError("стратегия %s не поддерживается" % стратегия)


