# -*- coding: utf-8 -*-
"""K2 + набор в процессоре.

Схемы:
  - k2_глава_плюс_набор: K2 через мост "глава" (здоровье -> право) даёт ответ права;
    "набор" даёт ответ здоровья. Итог: пара (здоровье, право).
  - k2_акт_плюс_набор: K2 через мост "акт" (право -> здоровье) даёт ответ здоровья;
    "набор" даёт ответ права. Итог: пара (здоровье, право).
  - baseline: v8 один ответ, процессор "набор".
"""
import json
import os
import sys

sys.dont_write_bytecode = True
from лаба_общее import О, Процессор  # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

ВЫХОД = os.path.join(О.БАЗА, "v9", "результаты", "лаба_процессор_k2_плюс_набор.json")


def main():
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    ядро, _ = О.система("основная_внешние", 1, язык=язык)
    проц = Процессор(ядро)

    стык = json.load(open(os.path.join(О.БАЗА, "v9", "результаты", "лаба_стыки_полные.json"), encoding="utf-8"))["вопросы"]

    главы = [str(i) for i in range(1, 18)]
    акты = ["53фз", "пп565", "пп663", "пп719", "кас", "коап", "укрф", "127фз", "59фз"]

    counts = {
        "v8": {"оба": 0, "хотя_бы_один": 0, "зд": 0, "пр": 0},
        "набор": {"оба": 0, "хотя_бы_один": 0, "зд": 0, "пр": 0},
        "k2_глава_плюс_набор": {"оба": 0, "хотя_бы_один": 0, "зд": 0, "пр": 0},
        "k2_акт_плюс_набор": {"оба": 0, "хотя_бы_один": 0, "зд": 0, "пр": 0},
    }

    вопросы = []

    for r in стык:
        текст = r["текст"]
        зд_эт = set(r["эталон_зд"])
        пр_эт = set(r["эталон_пр"])

        # v8
        ответ_v8, _ = ядро.спросить(текст)
        v8_зд = set() if ответ_v8 == О.НЕ_ЗНАЮ or ответ_v8.get("вид") != "ответ" else {"ответ:%s:%s" % (ответ_v8["область"], ответ_v8["id"])}
        v8_пр = v8_зд.copy()
        v8_оба = (v8_зд & зд_эт) and (v8_пр & пр_эт)

        # набор
        ответ_набор, запись_набор = проц.спросить(текст, "набор")
        набор_зд = set(x["ключ"] for x in запись_набор.get("набор", []) if x["ключ"].startswith("ответ:здоровье:"))
        набор_пр = set(x["ключ"] for x in запись_набор.get("набор", []) if x["ключ"].startswith("ответ:право:"))

        # k2 глава + набор
        try:
            ответ_k2_глава, _ = проц.спросить(текст, "k2", мост="глава", значения=главы)
            k2_глава_пр = set() if ответ_k2_глава == О.НЕ_ЗНАЮ else {"ответ:%s:%s" % (ответ_k2_глава["область"], ответ_k2_глава["id"])}
            k2_глава_зд = набор_зд
        except Exception as e:
            k2_глава_зд = набор_зд
            k2_глава_пр = set()

        # k2 акт + набор
        try:
            ответ_k2_акт, _ = проц.спросить(текст, "k2", мост="акт", значения=акты)
            k2_акт_зд = set() if ответ_k2_акт == О.НЕ_ЗНАЮ else {"ответ:%s:%s" % (ответ_k2_акт["область"], ответ_k2_акт["id"])}
            k2_акт_пр = набор_пр
        except Exception as e:
            k2_акт_зд = set()
            k2_акт_пр = набор_пр

        def метрики(зд, пр):
            return {
                "оба": bool((зд & зд_эт) and (пр & пр_эт)),
                "хотя_бы_один": bool((зд & зд_эт) or (пр & пр_эт)),
                "зд": bool(зд & зд_эт),
                "пр": bool(пр & пр_эт),
            }

        for имя, (зд, пр) in [
            ("v8", (v8_зд, v8_пр)),
            ("набор", (набор_зд, набор_пр)),
            ("k2_глава_плюс_набор", (k2_глава_зд, k2_глава_пр)),
            ("k2_акт_плюс_набор", (k2_акт_зд, k2_акт_пр)),
        ]:
            m = метрики(зд, пр)
            for k in counts[имя]:
                counts[имя][k] += m[k]

        вопросы.append({
            "i": r["i"],
            "текст": текст[:120],
            "эталон_зд": sorted(зд_эт),
            "эталон_пр": sorted(пр_эт),
            "v8": sorted(v8_зд | v8_пр),
            "набор": sorted(набор_зд | набор_пр),
            "k2_глава_плюс_набор": sorted(k2_глава_зд | k2_глава_пр),
            "k2_акт_плюс_набор": sorted(k2_акт_зд | k2_акт_пр),
        })

    n = len(стык)
    рез = {
        "n": n,
        "метрики": {
            k: {m: "%d/%d" % (v, n) for m, v in c.items()}
            for k, c in counts.items()
        },
        "вопросы": вопросы,
    }

    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    json.dump(рез, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps(рез["метрики"], ensure_ascii=False, indent=1))
    print("записано:", ВЫХОД)


if __name__ == "__main__":
    main()
