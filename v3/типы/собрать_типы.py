V3 = os.path.dirname(HERE)
sys.path.insert(0, V3)

from обучение import данные  # noqa: E402
from типы import канон  # noqa: E402


def main():
    out_types = os.path.join(HERE, "типы.json")
    if os.path.exists(out_types) and "--force" not in sys.argv:
        sys.exit("типы.json уже зафиксирован; пересборка только с --force (и тогда все блоки надо обучать заново)")
    vocab = set()
    for d in данные.DOMAINS:
        for text, _ in данные.domain_data(d, "train"):
            vocab.update(канон.stems(text))
    vocab = sorted(vocab)
    vtxt = "\n".join(vocab) + "\n"
    with open(os.path.join(HERE, "словарь.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(vtxt)
    import snowballstemmer
