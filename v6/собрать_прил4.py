# -*- coding: utf-8 -*-
"""Блок «здоровье.прил4» = здоровье.прил3 (те же веса модели приложения) + просьба к ядру убирать отрицаемое.
«кроме» — то, отсутствие чего для области «здоровье» само признак (органы, части тела, функции): это знание блока, не ядра.
Запуск: python собрать_прил4.py"""
import json
import os
import shutil
import sys

V6 = os.path.dirname(os.path.abspath(__file__))
KEEP = ["ух", "уш", "раковин", "глаз", "зрен", "слух", "зуб", "резц", "клык", "коренн", "пал", "кист", "рук", "ног", "стоп", "конечн",
        "почк", "селез", "желч", "легк", "яичк", "яичн", "матк", "менстр", "месячн", "овуляц", "голос", "реч", "челюст", "нос", "сустав",
        "кост", "мышц", "орган", "функц", "чувствит", "движен", "подвижн"]
src, dst = os.path.join(V6, "блоки", "здоровье.прил3"), os.path.join(V6, "блоки", "здоровье.прил4")
shutil.rmtree(dst, ignore_errors=True)
shutil.copytree(src, dst)
p = os.path.join(dst, "паспорт.json")
ps = json.load(open(p, encoding="utf-8"))
ps["имя"] = "здоровье.прил4"
ps["отрицание"] = {"поле": "текст", "кроме": KEEP}
ps["роль"] += "; просит ядро убирать то, что человек отрицает («нет астмы»), кроме отсутствия органов и функций"
json.dump(ps, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print("записан", dst)
