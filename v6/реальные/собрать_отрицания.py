# -*- coding: utf-8 -*-
"""Набор «отрицания» (v6): 30 болезней × шаблоны. Собран ДО замеров, шаблонами, без подбора под модель.
  есть     — человек называет свою болезнь → ждём её статью (контроль: правило не должно ломать обычные вопросы);
  нет      — человек отрицает болезнь → правильно «не знаю»; плохо — назвать статью отрицаемой болезни;
  смесь    — отрицает одну и называет другую → ждём статью второй, плохо — статья первой.
Запуск: python собрать_отрицания.py → отрицания.jsonl"""
import hashlib
import json
import sys

sys.stdout.reconfigure(encoding="utf-8")
D = [("астма", "астмы", "астмой", ["52"]), ("эпилепсия", "эпилепсии", "эпилепсией", ["21"]), ("гастрит", "гастрита", "гастритом", ["59"]),
     ("язва желудка", "язвы желудка", "язвой желудка", ["58"]), ("плоскостопие", "плоскостопия", "плоскостопием", ["68"]),
     ("сколиоз", "сколиоза", "сколиозом", ["66"]), ("гипертония", "гипертонии", "гипертонией", ["43"]),
     ("сахарный диабет", "сахарного диабета", "сахарным диабетом", ["13"]), ("туберкулез", "туберкулеза", "туберкулезом", ["2", "3"]),
     ("псориаз", "псориаза", "псориазом", ["62"]), ("экзема", "экземы", "экземой", ["62"]), ("близорукость", "близорукости", "близорукостью", ["34"]),
     ("геморрой", "геморроя", "геморроем", ["46"]), ("энурез", "энуреза", "энурезом", ["87"]), ("гайморит", "гайморита", "гайморитом", ["49"]),
     ("остеохондроз", "остеохондроза", "остеохондрозом", ["66"]), ("вич", "вич", "вич", ["5"]), ("пиелонефрит", "пиелонефрита", "пиелонефритом", ["72"]),
     ("заикание", "заикания", "заиканием", ["88"]), ("грыжа", "грыжи", "грыжей", ["60"]), ("тахикардия", "тахикардии", "тахикардией", ["42", "47"]),
     ("шизофрения", "шизофрении", "шизофренией", ["15"]), ("депрессия", "депрессии", "депрессией", ["17", "15"]),
     ("бронхит", "бронхита", "бронхитом", ["51"]), ("глаукома", "глаукомы", "глаукомой", ["32"]), ("косоглазие", "косоглазия", "косоглазием", ["33"]),
     ("тугоухость", "тугоухости", "тугоухостью", ["40"]), ("ожирение", "ожирения", "ожирением", ["13"]),
     ("хронический панкреатит", "хронического панкреатита", "хроническим панкреатитом", ["59"]), ("варикоцеле", "варикоцеле", "варикоцеле", ["73"])]
POS = ["у меня {n}. берут ли в армию?", "{n}, годен ли я к службе?"]
NEG = ["у меня нет {g}. берут ли в армию?", "{g} у меня нет, годен ли я к службе?", "я никогда не болел {i}, возьмут ли меня в армию?"]
MIX = ["у меня нет {g1}, но есть {n2}. берут ли в армию?", "{g1} не обнаружили, а {n2} есть. какая будет категория?"]
rows = []
for k, (n, g, i, a) in enumerate(D):
    rows += [{"вид": "есть", "текст": t.format(n=n), "ответы": a, "плохо": []} for t in POS]
    rows += [{"вид": "нет", "текст": t.format(g=g, i=i), "ответы": [], "плохо": a} for t in NEG]
    n2, g2, i2, a2 = D[(k + 7) % len(D)]
    assert not set(a) & set(a2)
    rows += [{"вид": "смесь", "текст": t.format(g1=g, n2=n2), "ответы": a2, "плохо": a} for t in MIX]
with open("отрицания.jsonl", "w", encoding="utf-8") as f:
    for r in rows:
        f.write(json.dumps(r, ensure_ascii=False) + "\n")
print(len(rows), "sha256", hashlib.sha256(open("отрицания.jsonl", "rb").read()).hexdigest())
