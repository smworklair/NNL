"""Собирает ЯДРО_NNL.html — описание архитектуры ядра v4 (стиль как у ОТЧЁТ_NNL.html). Запуск: python собрать_ядро.py"""
import os

from собрать_отчёт import BG, BLUE, CSS, GRN, GRY, MUT, ORG, TX, esc, svg, text

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ЯДРО_NNL.html")
CORE = "#DFE6EB"


def box(x, y, w, h, title, sub=None, fill=BG, bold=False, size=14, dash=False):
    s = '<rect x="%s" y="%s" width="%s" height="%s" rx="4" fill="%s" stroke="%s" stroke-width="%s"%s/>' % (
        x, y, w, h, fill, TX, 2 if bold else 1, ' stroke-dasharray="5 4"' if dash else "")
    lines = sub if isinstance(sub, list) else ([sub] if sub else [])
    ty = y + h / 2 - 8 * len(lines) + 5
    s += text(x + w / 2, ty, title, size, TX, "middle", "700" if bold else "600")
    for i, ln in enumerate(lines):
        s += text(x + w / 2, ty + 18 + i * 16, ln, 11.5, TX if fill == BLUE else MUT, "middle")
    return s


def arrow(x1, y1, x2, y2, col=TX, dash=False, label=None):
    s = '<line x1="%s" y1="%s" x2="%s" y2="%s" stroke="%s" stroke-width="1.6" marker-end="url(#a)"%s/>' % (
        x1, y1, x2, y2, col, ' stroke-dasharray="5 4"' if dash else "")
    if label:
        s += text((x1 + x2) / 2, (y1 + y2) / 2 - 6, label, 11.5, MUT, "middle")
    return s


DEFS = '<defs><marker id="a" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse">' \
       '<path d="M0,0 L10,5 L0,10 z" fill="%s"/></marker></defs>' % TX


# 1. общая схема: три сущности
def d_overview():
    b = DEFS
    b += box(330, 20, 240, 120, "ЯДРО", ["обычный код · 674 строки", "0 обученных чисел", "только стандартная библиотека"], CORE, True, 17)
    b += box(30, 210, 240, 90, "ТИПЫ", ["типы/<набор>/набор.json", "что можно передавать"], BG)
    b += box(330, 210, 240, 90, "АРХИТЕКТУРЫ", ["архитектуры/*.py", "код сети без весов"], BG)
    b += box(630, 210, 240, 90, "БЛОКИ", ["блоки/<имя>/веса.npz + паспорт", "единственное место с числами"], BLUE)
    b += arrow(390, 140, 160, 208) + text(215, 168, "читает схемы", 12, MUT, "end")
    b += arrow(450, 140, 450, 208) + text(458, 180, "вызывает", 12, MUT, "start")
    b += arrow(510, 140, 740, 208) + text(690, 168, "проверяет паспорт", 12, MUT, "start")
    b += arrow(570, 255, 628, 255, MUT, True)
    b += text(600, 245, "считает по", 11, MUT, "middle")
    return svg(900, 320, b)


# 2. путь запроса
def d_route():
    b = DEFS
    b += box(10, 150, 120, 60, "запрос", ["«вич на ранней", "стадии»"])
    b += arrow(130, 180, 178, 180)
    b += box(180, 120, 150, 120, "ЗАЯВКИ", ["каждый входной", "блок: «насколько", "вопрос мой?»"], CORE, True)
    claims = [("здоровье.заявка", "1,000", BLUE), ("право.заявка", "0,000", GRY), ("команды.заявка", "0,000", GRY), ("задачи.заявка", "0,000", GRY)]
    for i, (n, p, c) in enumerate(claims):
        y = 20 + i * 82
        b += box(380, y, 160, 56, n, ["заявка " + p], GRN if c == BLUE else BG, c == BLUE, 12.5)
        b += '<line x1="330" y1="180" x2="378" y2="%s" stroke="%s" stroke-width="%s"/>' % (y + 28, TX if c == BLUE else GRY, 2 if c == BLUE else 1)
    b += text(460, 352, "наибольшая ≥ 0,5 побеждает; ниже — «не знаю»", 12, MUT, "middle")
    b += arrow(540, 48, 590, 48, label="")
    b += box(590, 14, 150, 68, "Направление", ["[область=здоровье]"], CORE)
    b += arrow(740, 48, 770, 48)
    b += box(770, 14, 120, 68, "здоровье", ["знание → ст. 5"], BLUE, True)
    b += arrow(830, 82, 830, 150)
    b += box(740, 150, 150, 70, "проверка типа", ["список ответов,", "арифметика шагов"], CORE)
    b += arrow(815, 220, 815, 270)
    b += box(740, 270, 150, 60, "ОТВЕТ + след", None, BG, True)
    return svg(900, 365, b)


# 3. десять проверок при подключении
def d_attach():
    checks = ["поля паспорта", "типы входа/выхода", "отпечатки типов", "sha256 весов", "веса загрузились",
              "число чисел", "классы = ответы", "нет конфликта входа", "заявки у входных", "бюджет чисел"]
    b = DEFS
    w, gap = 78, 8
    b += box(0, 60, 90, 70, "паспорт", ["+ веса"])
    for i, c in enumerate(checks):
        x = 104 + i * (w + gap)
        b += '<rect x="%s" y="60" width="%s" height="70" rx="3" fill="%s" stroke="%s"/>' % (x, w, CORE, TX)
        b += text(x + w / 2, 82, str(i + 1), 13, TX, "middle", "700")
        words = c.split(" ")
        lines = [" ".join(words[:2]), " ".join(words[2:])] if len(words) > 2 else [" ".join(words[:1]), " ".join(words[1:])]
        for j, ln in enumerate(lines):
            b += text(x + w / 2, 102 + j * 14, ln, 10.5, TX, "middle")
    xe = 104 + 10 * (w + gap) - gap
    b += text(xe - 4, 160, "все прошли → блок в реестре, перезапуск не нужен", 12, BLUE, "end", "700")
    b += text(104, 160, "любая не прошла → отказ с причиной, блок не подключён", 12, ORG, "start", "700")
    return svg(xe + 4, 175, b)


# 4. анатомия области
def d_block():
    b = DEFS
    b += box(20, 30, 360, 220, "", None, BG, False, 14, True)
    b += text(200, 22, "область «здоровье» = два блока", 13, MUT, "middle")
    b += box(45, 60, 140, 160, "заявка", ["0,52 млн чисел", "знает: «какие", "вопросы мои»", "ответов не знает"], GRN, True)
    b += arrow(185, 140, 213, 140)
    b += box(215, 60, 140, 160, "знание", ["1,57 млн чисел", "88 статей", "выбирает ответ"], BLUE, True)
    b += text(450, 70, "вынули знание:", 14, TX, "start", "700")
    b += text(450, 92, "заявка остаётся и забирает свои вопросы,", 13, TX)
    b += text(450, 110, "а ядро не находит блок-знание и говорит", 13, TX)
    b += text(450, 128, "«нет блока для Направление[область=здоровье]»", 13, ORG)
    b += text(450, 160, "→ 99–100 % вопросов области — «не знаю»", 13, BLUE, "start", "700")
    b += text(450, 182, "→ остальные области не меняются", 13, BLUE, "start", "700")
    b += text(450, 214, "вынули оба блока: 2–20 % вопросов уходят к соседу", 12, MUT)
    return svg(900, 265, b)


