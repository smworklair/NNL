def main():
    html = HTML
    for k, v in {"css": CSS, "overview": d_overview(), "route": d_route(), "attach": d_attach(), "block": d_block(), "trace": esc(TRACE)}.items():
        html = html.replace("@@%s@@" % k, v)
    open(OUT, "w", encoding="utf-8").write(html)
    print("записан", OUT)


if __name__ == "__main__":
    main()
