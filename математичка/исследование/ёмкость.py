"""Ёмкость суперпозиции. M случайных векторов из ±1 длины D. Берём K из них и складываем. Достаём назад: считаем скалярное
произведение суммы с каждым из M векторов и берём K наибольших. Успех, если взяты именно те K, что складывали.
Считаем долю успехов и ищем наименьшее D из сетки, при котором доля успехов не меньше 0,95.
Нужен numpy. Запуск: python ёмкость.py (несколько минут)."""
import numpy as np

СЕТКА = (50, 100, 150, 200, 300, 400, 600, 800, 1200, 1600, 2400, 3200)


def доля_успехов(D, K, M, попыток, rng):
    ок = 0
    for _ in range(попыток):
        предметы = rng.choice(np.array([-1, 1], dtype=np.int8), size=(M, D))
        сумма = предметы[:K].astype(np.int32).sum(0)
        счёт = предметы.astype(np.int32) @ сумма
        лучшие = set(np.argpartition(-счёт, K - 1)[:K].tolist())
        ок += лучшие == set(range(K))
    return ок / попыток


def наименьшее_D(K, M, попыток, rng):
    for D in СЕТКА:
        if доля_успехов(D, K, M, попыток, rng) >= 0.95:
            return D
    return None


if __name__ == "__main__":
    rng = np.random.default_rng(1)
    print("M = 1000, K меняется:")
    for K in (5, 10, 20):
        print("  K = %2d: наименьшее D из сетки с долей успехов >= 0,95: %s" % (K, наименьшее_D(K, 1000, 200, rng)), flush=True)
    print("K = 10, M меняется:")
    for M in (100, 1000, 10000):
        print("  M = %5d: наименьшее D из сетки с долей успехов >= 0,95: %s" % (M, наименьшее_D(10, M, 100, rng)), flush=True)
