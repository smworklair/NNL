# -*- coding: utf-8 -*-
"""Собирает таблицы для математички из файлов репозитория. Только стандартная библиотека.
Запуск из любой папки:  python собрать.py
Формат таблиц: разделитель «;», запятая в дробях, кодировка utf-8 с BOM, открываются в Excel и LibreOffice.
Откуда что взято: см. ОТКУДА.md рядом."""
import csv
import json
import os

ЭТА = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(os.path.dirname(ЭТА))
КОНТРОЛЬ = os.path.join(КОРЕНЬ, "система", "блоки", "основная_внешние.з1")


def jl(путь):
    with open(путь, encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def запись(имя, шапка, строки):
    def ячейка(x):
        return str(x).replace(".", ",") if isinstance(x, float) else x
    with open(os.path.join(ЭТА, имя), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(шапка)
        for r in строки:
            w.writerow([ячейка(x) for x in r])
    print("%-28s строк: %d" % (имя, len(строки)))


def статья_глава():
    сводка = {}
    for r in jl(os.path.join(КОНТРОЛЬ, "здоровье", "контроль.jsonl")):
        if len(r["ответы"]) != 1:      # у вопроса с несколькими эталонами метка главы общая на все ответы
            continue
        главы = [k for k, v in r["понятия"].items() if k.startswith("глава:") and v == 1]
        for a in r["ответы"]:
            s = сводка.setdefault(a.split(":")[2], {"главы": set(), "n": 0})
            s["главы"].update(главы)
            s["n"] += 1
    строки = []
    for статья in sorted(сводка, key=int):
        g = сводка[статья]["главы"]
        assert len(g) == 1, ("у статьи %s не одна глава: %s" % (статья, g))
        строки.append([int(статья), int(next(iter(g)).split(":")[1]), сводка[статья]["n"]])
    запись("статья_глава.csv", ["статья", "глава", "примеров_в_контроле"], строки)


def тема_акты():
    сводка = {}
    for r in jl(os.path.join(КОНТРОЛЬ, "право", "контроль.jsonl")):
        if len(r["ответы"]) != 1:
            continue
        акты = tuple(sorted(k.split(":")[1] for k, v in r["понятия"].items() if k.startswith("акт:") and v == 1))
        for a in r["ответы"]:
            s = сводка.setdefault(a.split(":", 2)[2], {"варианты": set(), "n": 0})
            s["варианты"].add(акты)
            s["n"] += 1
    строки = []
    for тема in sorted(сводка):
        варианты = сводка[тема]["варианты"]
        объединение = sorted({a for v in варианты for a in v})
        строки.append([тема, " + ".join(объединение), len(объединение), сводка[тема]["n"], len(варианты)])
    запись("тема_акты.csv", ["тема", "акты", "число_актов", "примеров_в_контроле", "разных_наборов_актов"], строки)


def вклад_соседа():
    d = json.load(open(os.path.join(КОРЕНЬ, "лаборатория", "результаты", "лаба_совместность.json"), encoding="utf-8"))
    строки = []
    for i, q in enumerate(d["вопросы"], 1):
        через = round(sum(q["через_шину"].values()), 4)
        прямой = q["прямой"]
        доля = round(abs(через) / abs(прямой), 4) if прямой else ""
        строки.append([i, q["хозяин"], q["топ"], q["p"], прямой, через, доля,
                       1 if прямой and abs(через) >= 0.2 * abs(прямой) else 0, q["текст"][:100]])
    запись("вклад_соседа_v9.csv",
           ["№", "хозяин_ответа", "ответ", "p", "прямой_вклад", "вклад_соседа_через_шину", "доля_соседа", "соседа_не_меньше_20%", "начало_вопроса"],
           строки)


def устройства_v92():
    d = json.load(open(os.path.join(КОРЕНЬ, "лаборатория", "общий_ствол", "результаты", "опыт_общий_ствол.json"), encoding="utf-8"))
    метрики = ["здоровье_перефраз", "право_перефраз", "здоровье_живые", "право_живые",
               "смесь_здоровье_топ1_в_своей_области", "смесь_право_топ1_в_своей_области",
               "смесь_оба_в_общей_двойке", "смесь_двойка_из_одной_области"]
    строки = []
    for зерно, прогон in zip(d["зёрна"], d["по_зёрнам"]):
        for устройство, значения in прогон.items():
            if устройство.startswith("_"):
                continue
            строки.append([зерно, устройство[0], устройство] + [round(значения[m], 4) for m in метрики])
    запись("устройства_v9.2.csv", ["зерно", "буква", "устройство"] + метрики, строки)


def ошибки_систем():
    bench = jl(os.path.join(КОРЕНЬ, "бенчмарки", "bench", "bench.jsonl"))
    pred = {}
    for f in ("v4.json", "v6.json"):
        with open(os.path.join(КОРЕНЬ, "диагностика", f), encoding="utf-8") as fh:
            pred.update(json.load(fh))
    системы = ["TINY_1.6", "v4_знание", "v3_цепочка", "NNL_Д"]
    строки = []
    for i, r in enumerate(bench):
        строки.append([i + 1, r["область"]] + [1 if pred[s][i] != r["ответ"] else 0 for s in системы])
    запись("ошибки_систем.csv", ["№", "область"] + ["ошибка_" + s for s in системы], строки)


def сетка():
    запись("сетка_11x11.csv", ["x", "y", "категория"], [[x, y, ""] for x in range(11) for y in range(11)])


if __name__ == "__main__":
    статья_глава()
    тема_акты()
    вклад_соседа()
    устройства_v92()
    ошибки_систем()
    сетка()
