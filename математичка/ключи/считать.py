def суммируется_перебором(n, K):
    шкала = [x + 0.5 for x in range(-K, K)]          # полуцелые, чтобы не было равенства нулю
    найдено = set()
    for A in itertools.product(шкала, repeat=n):
        for B in itertools.product(шкала, repeat=n):
            найдено.add(tuple(1 if A[i] + B[j] > 0 else 0 for i in range(n) for j in range(n)))
    return найдено


def вложены(таблица, n):
    строки = [frozenset(j for j in range(n) if таблица[i * n + j]) for i in range(n)]
    return all(x <= y or y <= x for x, y in itertools.combinations(строки, 2))


