def пары_и_матрица(n):
    """Таблица (c+g) mod n: оценка ответа y в клетке (c,g) = A[y][c] + B[y][g]. Условие «y побеждает конкурента k» даёт столбец матрицы."""
    пары = [(c, g, k) for c in range(n) for g in range(n) for k in range(n) if k != (c + g) % n]
    M = [[Fraction(0)] * len(пары) for _ in range(2 * n * n)]
    for j, (c, g, k) in enumerate(пары):
        y = (c + g) % n
        M[y * n + c][j] += 1
        M[k * n + c][j] -= 1
        M[n * n + y * n + g][j] += 1
        M[n * n + k * n + g][j] -= 1
    return пары, M


def сертификат(M):
    """Точный симплекс (дроби, правило Бланда): ищет w >= 0, sum w = 1, M w = 0. Нашёл: чисел A и B не существует (теорема о переносе)."""
    m, N = len(M), len(M[0])
    A = [row[:] + [Fraction(0)] * (m + 1) for row in M] + [[Fraction(1)] * N + [Fraction(0)] * (m + 1)]
    b = [Fraction(0)] * m + [Fraction(1)]
    R = m + 1
    for i in range(R):
        A[i][N + i] = Fraction(1)
    базис = [N + i for i in range(R)]
    while True:
        цена = [Fraction(0)] * (N + R)
        for i in range(R):
            if базис[i] >= N:
                for j in range(N + R):
                    цена[j] -= A[i][j]
        for j in range(N, N + R):
            цена[j] += 1
        вход = next((j for j in range(N + R) if цена[j] < 0), None)
        if вход is None:
            break
        строка = min((b[i] / A[i][вход], базис[i], i) for i in range(R) if A[i][вход] > 0)[2]
        p_ = A[строка][вход]
        A[строка] = [x / p_ for x in A[строка]]
        b[строка] /= p_
        for i in range(R):
            if i != строка and A[i][вход] != 0:
                f = A[i][вход]
                A[i] = [x - f * y for x, y in zip(A[i], A[строка])]
                b[i] -= f * b[строка]
        базис[строка] = вход
    if sum(b[i] for i in range(R) if базис[i] >= N) != 0:
        return None
    w = [Fraction(0)] * N
    for i in range(R):
        if базис[i] < N:
            w[базис[i]] = b[i]
    assert all(x >= 0 for x in w) and sum(w) == 1
    assert all(sum(M[i][j] * w[j] for j in range(N)) == 0 for i in range(len(M)))
    return w


