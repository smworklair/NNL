# -*- coding: utf-8 -*-
"""Замер цены хода в режиме «NNL + API»: сценарии бенчмарка с банком вопросов и без него, без кэша.
Для каждого сценария: вызовов API по ролям, токены, время, действие ядра на каждом ходе и непройденные проверки наблюдения.
Запуск: python замер_хода.py [провайдер:модель]   (по умолчанию alibaba:qwen3.8-flash)"""
import os
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
import бенч as Б  # noqa: E402
import диалог as Д  # noqa: E402
import наблюдение as Н  # noqa: E402


def прогон(система, роли, метка):
    итого = {"вызовов": 0, "токены": 0, "мс": 0, "плохих_проверок": 0}
    print("\n=== %s" % метка)
    print("%-26s %8s %8s %8s  %s" % ("сценарий", "вызовов", "токены", "время, с", "по ролям · действия ядра"))
    for сц in Б.СЦЕНАРИИ:
        ходы = Б._прогнать(сц, роли, система, None, "ядро")
        _, свод, сум = Н.аудит_сценария(ходы, сц["реплики"])
        по_ролям = {}
        for х in ходы:
            for е in х["след"]:
                if е["кто"] == "API" and е.get("статус") == "готово":
                    по_ролям[е["роль"]] = по_ролям.get(е["роль"], 0) + 1
        действия = " → ".join(х.get("действие", "?") for х in ходы)
        плохих = sum(с["всего"] - с["ок"] for с in свод.values())
        провалы = ["%s: %s" % (имя, "; ".join(с["заметки"])[:90]) for имя, с in свод.items() if с["ок"] < с["всего"]]
        print("%-26s %8d %8d %8.1f  %s · %s%s" % (сц["id"], сум["вызовов_апи"], сум["токены"], сум["мс_всего"] / 1000, ", ".join("%s %d" % (k, v) for k, v in по_ролям.items()), действия,
                                                  ("  · непройденных проверок: %d" % плохих) if плохих else ""))
        for п in провалы:
            print("      ✗ " + п)
        итого["вызовов"] += сум["вызовов_апи"]
        итого["токены"] += сум["токены"]
        итого["мс"] += сум["мс_всего"]
        итого["плохих_проверок"] += плохих
    print("%-26s %8d %8d %8.1f  непройденных проверок: %d" % ("ИТОГО", итого["вызовов"], итого["токены"], итого["мс"] / 1000, итого["плохих_проверок"]))
    return итого


if __name__ == "__main__":
    модель = sys.argv[1] if len(sys.argv) > 1 else "alibaba:qwen3.8-flash"
    система = Д.Система()
    роли = Б._роли_кандидата(модель)
    банк = система.банк
    print("модель: %s; статей в банке: %s" % (модель, len(банк.актуальные) if банк else "банка нет"))
    с_банком = прогон(система, роли, "с банком вопросов") if банк else None
    система.банк = None
    без_банка = прогон(система, роли, "без банка (вопросы просит модель)")
    if с_банком:
        print("\nвызовов: %d → %d (%.0f %%), токенов: %d → %d (%.0f %%), время: %.0f → %.0f с (%.0f %%)" % (
            без_банка["вызовов"], с_банком["вызовов"], 100 * с_банком["вызовов"] / max(1, без_банка["вызовов"]),
            без_банка["токены"], с_банком["токены"], 100 * с_банком["токены"] / max(1, без_банка["токены"]),
            без_банка["мс"] / 1000, с_банком["мс"] / 1000, 100 * с_банком["мс"] / max(1, без_банка["мс"])))
