# -*- coding: utf-8 -*-
"""Ссылки ответа на Расписание болезней: «ст. 34 п. «в»», «статья 34», «статьи 34, 35».
Чистый код без моделей: находит ссылки в тексте и проверяет по документу, что статья и пункт существуют.
Нормализованные цитаты проверяются как подстрока текста статьи (иначе это выдумка)."""
import re

_СТ = re.compile(r"(?:ст\.|статья|статьи|статье|статью|статей)\s*(\d{1,2}(?:\s*(?:,|и)\s*\d{1,2})*)(?:\s*,?\s*п(?:\.|ункт\w*)\s*[«\"]?([а-е])[»\"]?)?", re.I)


def найти(текст, база):
    """[{текст, статья, пункт, ок, название, причина}] — по каждой ссылке; ок=False если статьи или пункта нет в документе."""
    out, видели = [], set()
    for m in _СТ.finditer(текст or ""):
        номера = re.findall(r"\d+", m.group(1))
        пункт = (m.group(2) or "").lower() or None
        for i, н in enumerate(номера):
            ключ = (н, пункт if i == len(номера) - 1 else None)
            if ключ in видели:
                continue
            видели.add(ключ)
            п = ключ[1]
            а = база.статьи.get(н)
            if а is None:
                out.append({"текст": m.group(0).strip(), "статья": н, "пункт": п, "ок": False, "название": "", "причина": "в Расписании нет статьи %s" % н})
                continue
            if п and not any(x["буква"] == п for x in а.пункты):
                out.append({"текст": m.group(0).strip(), "статья": н, "пункт": п, "ок": False, "название": а.название, "причина": "в статье %s нет пункта «%s»" % (н, п)})
                continue
            out.append({"текст": m.group(0).strip(), "статья": н, "пункт": п, "ок": True, "название": а.название, "причина": ""})
    return out


def _норм(t):
    return re.sub(r"[\s ]+", " ", re.sub(r"[«»\"'‘’“”]", "", (t or "").lower().replace("ё", "е"))).strip()


def цитата_в_статье(цитата, статья):
    """Точная проверка: цитата (без кавычек, регистра и лишних пробелов) — подстрока полного текста статьи."""
    ц = _норм(цитата)
    if len(ц) < 8:
        return False
    полный = _норм(статья.сырой) + " " + _норм(статья.текст_для_модели(30000))
    return ц in полный
