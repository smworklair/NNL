# -*- coding: utf-8 -*-
"""След хода: что на самом деле делали блоки, ядро, API и охрана, в порядке времени.

Это не пересказ задним числом и не «объяснение от модели»: каждое событие пишет код в тот момент, когда шаг выполняется.
Участники (поле «кто»):
  блоки   — свои обученные блоки: оценивают текст, ничего не решают;
  ядро    — вероятности по статьям, выбор вопроса, допуск вердикта: решает только оно;
  API     — внешняя модель: слушает человека, формулирует; видит только то, что ей дали блоки и ядро (вход записан в событие);
  охрана  — проверка чисел, ссылок и категории в тексте API;
  система — служебное (приём реплики, готовый ответ).

Событие API живёт в два приёма: «идёт» (в момент отправки) и «готово» (с входом, выходом, рассуждением модели, токенами) — тот же номер «н».
Событие можно дополнять: так страница видит шаг сразу, а не после ответа модели.
"""
import time

КТО = ("система", "блоки", "ядро", "API", "охрана")


class След:
    def __init__(self, на_шаг=None):
        self.t0 = time.time()
        self.события = []
        self.на_шаг = на_шаг            # функция(dict): куда сразу отправить событие (потоковая передача); None — только копить
        self._н = 0

    def _отправить(self, событие):
        if self.на_шаг:
            try:
                self.на_шаг(событие)
            except Exception:  # noqa: BLE001 — отправка следа не должна ломать сам ход
                self.на_шаг = None

    def шаг(self, кто, название, детали=None, **поля):
        """Новое событие. «детали» — короткий поясняющий текст, остальные поля — данные (для таблиц и проверок)."""
        assert кто in КТО, кто
        self._н += 1
        е = {"н": self._н, "кто": кто, "название": название, "мс": int(1000 * (time.time() - self.t0))}
        if детали:
            е["детали"] = детали
        е.update({k: v for k, v in поля.items() if v is not None})
        self.события.append(е)
        self._отправить({"т": "шаг", "шаг": е})
        return е

    def дополнить(self, событие, **поля):
        """Обновить уже показанное событие (например, «идёт» → «готово»). Номер и автор не меняются."""
        поля = {k: v for k, v in поля.items() if v is not None and k not in ("н", "кто")}
        событие.update(поля)
        событие["мс_конец"] = int(1000 * (time.time() - self.t0))
        self._отправить({"т": "обновление", "н": событие["н"], "поля": dict(поля, мс_конец=событие["мс_конец"])})
        return событие
