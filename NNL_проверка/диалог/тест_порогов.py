# -*- coding: utf-8 -*-
"""Тест размера модели на ОДНОМ точно проверяемом навыке: применить пороги статьи 34 к числам человека.

Истина вычисляется из текста документа (не моделью): близорукость любого глаза, графа I (призывник):
  более 12,0 дптр → пункт «а», Д;  более 8,0 до 12,0 → «б», В;  более 6,0 до 8,0 → «в», В;  более 3,0 до 6,0 → «г», Б-3;  до 3,0 включительно → статья не применяется.
Границы («ровно 6,0», «ровно 8,0») — самая трудная часть: «более 6,0» значит строго больше, «до 6,0» включает 6,0.
Модели получают тот же текст статьи, что и в диалоге, и тот же короткий JSON-ответ. Один тест не отвечает на вопрос «нужны ли сотни миллиардов
параметров» вообще, но показывает, с какого размера этот навык перестаёт зависеть от размера.

  python NNL/диалог/тест_порогов.py groq:openai/gpt-oss-20b groq:qwen/qwen3.8-27b groq:openai/gpt-oss-120b gemini:gemini-3.8-flash
Новые модели (например Alibaba) добавляются так же: провайдер:модель."""
import concurrent.futures
import json
import os
import sys
import time

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
import клиент as К  # noqa: E402
import знания as З  # noqa: E402

ПАРЫ = [(2.5, 2.0), (3.0, 2.5), (3.0, 3.0), (3.25, 1.0), (4.5, 4.0), (5.5, 5.25), (5.75, 6.25), (6.0, 6.0), (6.0, 5.5), (6.25, 6.0), (6.5, 7.0),
        (7.75, 7.5), (8.0, 8.0), (8.0, 7.0), (8.25, 8.0), (10.0, 9.5), (11.75, 12.0), (12.0, 12.0), (12.25, 11.0), (14.0, 13.5), (4.0, 6.5),
        (9.0, 3.0), (6.75, 6.5), (3.5, 2.0)]
СХЕМА = {"type": "object", "properties": {
    "сравнение": {"type": "string"},
    "пункт": {"type": "string", "enum": ["а", "б", "в", "г", "не_применяется"]},
    "категория": {"type": "string", "enum": ["А", "Б", "Б-3", "В", "Г", "Д", "нет_категории"]}},
    "required": ["сравнение", "пункт", "категория"]}
СИСТЕМА = ("Ты применяешь текст статьи Расписания болезней буквально. Для призывника берёшь ТОЛЬКО поле «КАТЕГОРИЯ ДЛЯ ПРИЗЫВНИКА (графа I)». "
           "Числа сравнивай строго: «более X» — строго больше X; «до Y» — включая Y. Если ни один пункт не подходит, пункт — «не_применяется», "
           "категория — «нет_категории». Сначала в поле «сравнение» одной-двумя фразами сравни худший глаз с границами, потом дай пункт и категорию.")


def истина(пара):
    x = max(пара)
    return ("а", "Д") if x > 12 else ("б", "В") if x > 8 else ("в", "В") if x > 6 else ("г", "Б-3") if x > 3 else ("не_применяется", "нет_категории")


def прогон(кандидат, статья):
    пров, _, мод = кандидат.partition(":")
    ок_пункт = ок_кат = 0
    ошибки, мс, ток = [], 0, 0
    for od, os_ in ПАРЫ:
        ожид = истина((od, os_))
        вопрос = ("Окулист после закапывания капель написал: правый глаз −%s дптр, левый глаз −%s дптр (близорукость). "
                  "К какому пункту статьи 34 относится случай и какая категория для призывника?" % (od, os_))
        try:
            r = К.спросить(пров, мод, СИСТЕМА + "\n\n" + статья, [("user", вопрос)], схема=СХЕМА, температура=0.0, макс_токенов=500, кэш=False, таймаут=120)
        except К.Ошибка as e:
            ошибки.append((od, os_, "ОШИБКА: " + str(e)[:60]))
            continue
        д = r["данные"]
        if isinstance(д, list) and д and isinstance(д[0], dict):       # некоторые модели оборачивают объект в список
            д = д[0]
        if not isinstance(д, dict) or not {"пункт", "категория"} <= set(д):
            ошибки.append((od, os_, "ОШИБКА: ответ не по схеме: " + str(д)[:60]))
            continue
        мс += r["мс"]
        ток += r["токены_вход"] + r["токены_выход"]
        п_ок = д["пункт"] == ожид[0]
        к_ок = (д["категория"] == ожид[1]) or (ожид[0] == "не_применяется" and д["пункт"] == "не_применяется")
        ок_пункт += п_ок
        ок_кат += к_ок
        if not (п_ок and к_ок):
            ошибки.append((od, os_, "ожидалось %s/%s, ответ %s/%s" % (ожид[0], ожид[1], д["пункт"], д["категория"])))
    n = len(ПАРЫ)
    return {"модель": кандидат, "пункт_верен": ок_пункт, "категория_верна": ок_кат, "из": n, "мс_на_случай": int(мс / max(1, n - sum(1 for e in ошибки if e[2].startswith("ОШИБКА")))),
            "токены": ток, "ошибки": ошибки}


def main():
    кандидаты = sys.argv[1:] or ["groq:openai/gpt-oss-20b", "groq:qwen/qwen3.8-27b", "groq:openai/gpt-oss-120b"]
    статья = З.База().статьи["34"].текст_для_модели(1400)
    print("случаев: %d; в каждом худший глаз против границ 3,0 / 6,0 / 8,0 / 12,0 (граничных значений: %d)\n" % (
        len(ПАРЫ), sum(1 for p in ПАРЫ if max(p) in (3.0, 6.0, 8.0, 12.0))), flush=True)
    t0 = time.time()
    with concurrent.futures.ThreadPoolExecutor(max_workers=len(кандидаты)) as ex:       # у каждой модели свой лимит — идём параллельно
        результаты = list(ex.map(lambda к: прогон(к, статья), кандидаты))
    print("%-34s %8s %10s %12s %10s" % ("модель", "пункт", "категория", "мс/случай", "токены"))
    for р in результаты:
        print("%-34s %5d/%d %7d/%d %12d %10d" % (р["модель"], р["пункт_верен"], р["из"], р["категория_верна"], р["из"], р["мс_на_случай"], р["токены"]))
    for р in результаты:
        if р["ошибки"]:
            print("\nОШИБКИ", р["модель"])
            for od, os_, текст in р["ошибки"]:
                print("   −%s / −%s: %s" % (od, os_, текст))
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "результаты_порогов.json"), "w", encoding="utf-8") as f:
        json.dump(результаты, f, ensure_ascii=False, indent=1)
    print("\nвсего %.0f с" % (time.time() - t0))


if __name__ == "__main__":
    main()
