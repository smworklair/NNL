"""Выбор модели для ролей диалога по ИЗМЕРЕННОМУ качеству, задержке и цене. Запуск:

  python NNL/диалог/выбор_модели.py                      # кандидаты по умолчанию: две модели Groq из пресета диалога
  python NNL/диалог/выбор_модели.py groq:qwen/qwen3.8-27b groq:openai/gpt-oss-120b --повторов 2

Три задачи — ровно те роли, которые модель играет в диалоге:
  1. разбор реплики в факты (8 фраз с известным эталоном: статус «есть/нет/было/чужое», числа словами → цифры);
  2. предложение вопросов (фиксированное состояние ядра: «очки минус шесть» — пограничный случай; ядро выбирает вопрос по информационному выигрышу);
  3. итог (фиксированное досье: −6,25/−5,75 после капель; по документу ст. 34, пункт «в», категория для призывника — В).
Проверки автоматические (число, статус, нужная категория, охрана чисел, повторы слов, предупреждение в конце); тексты итогов читать глазами.
Цена считается по реальным токенам ответа API (размышление тарифицируется как вывод). Результат пишется в NNL/диалог/результаты_выбора.json."""
