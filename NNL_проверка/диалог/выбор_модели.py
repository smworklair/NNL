КЛЮЧЕВОЙ_ВОПРОС = re.compile(r"диоптр|дптр|рефракц|циклоплег|капл|заключени\w* окулист|точн\w+ (?:знач|цифр|сил)", re.I)


def _роль(кандидат):
    пров, _, мод = кандидат.partition(":")
    return (пров, мод)


def _совпало(m, основа, статус, число):
    t = (m["термин"] + " " + (m.get("уточнение") or "")).lower().replace("ё", "е")
    if основа not in t or m["статус"] != статус:
        return False
    return число is None or число in {К_ for К_ in re.findall(r"-?\d+(?:\.\d+)?", t.replace(",", "."))} or число.lstrip("-") in re.findall(r"\d+(?:\.\d+)?", t.replace(",", "."))


def _сложить_цены(значения):
    известные = [v for v in значения if v is not None]
    неполная = len(известные) != len(значения)
    if not известные:
        return None, True
    return round(sum(известные), 6), неполная


def задача_разбор(с, роль):
    Д.РОЛИ["разбор"] = роль
    ses = с.сессия()
    попал = всего = лишних = 0
    мс = ток = 0
    цены = []
    for фраза, эталон in РАЗБОР:
        r = ses._вызов("разбор", Д.СИСТЕМА_РАЗБОРА, [("user", "Реплика человека: " + фраза)], схема=Д.СХЕМА_РАЗБОРА, температура=0.0, макс_токенов=700, кэш=False)
        ум = r["данные"]["упоминания"]
        for основа, статус, число in эталон:
            всего += 1
            попал += any(_совпало(m, основа, статус, число) for m in ум)
        лишних += sum(1 for m in ум if not any(_совпало(m, о, с_, ч) for о, с_, ч in эталон))
        мс += r["мс"]
        ток += r["токены_вход"] + r["токены_выход"]
        цены.append(r.get("usd"))
    usd, неполная = _сложить_цены(цены)
    return {"точность_разбора": round(попал / всего, 3), "лишних_упоминаний": лишних, "мс_на_фразу": int(мс / len(РАЗБОР)), "токены": ток, "usd": usd, "usd_неполная": неполная}


def _сессия_с_состоянием(с):
    ses = с.сессия()
    for термин, статус, уточнение in (("болит спина", "есть", ""), ("зрение падает, очки минус шесть", "есть", "-6")):
        p, p0 = с.блоки.статьи((термин + " " + уточнение).strip())
        ses.ср.учесть_упоминание(термин, статус, уточнение, p, p0)
    ses.слова_человека.append("Мне 18, у меня болит спина и сильно падает зрение, очки минус шесть. Возьмут в армию?")
    return ses


def задача_вопросы(с, роль, повторов):
    Д.РОЛИ["вопросы"] = роль
    рез = {"успешных": 0, "ключевой_вопрос_найден": 0, "ядро_выбрало_ключевой": 0, "годных_вопросов": [], "числа_вне_источника": 0}
    мс = ток = 0
    цены = []
    for _ in range(повторов):
        ses = _сессия_с_состоянием(с)
        канд = ses.ср.кандидаты(порог=0.05, n=4)
        try:
            r = ses._вызов("вопросы", Д.СИСТЕМА_ВОПРОСОВ, [("user", ses._запрос_вопросов(канд[:3], ses.слова_человека[-1]))],
                           схема=ses._схема_вопросов(канд[:3]), температура=0.3, макс_токенов=1300, кэш=False)
        except К.Ошибка as e:
            print("   вопросы: ошибка:", str(e)[:140])
            continue
        мс += r["мс"]
        ток += r["токены_вход"] + r["токены_выход"]
        цены.append(r.get("usd"))
        пр = r["данные"]
        предложения = [{"вид": q["вид"], "статья": Д._ид_статьи(q["статья"]), "текст": q["текст"],
                        "таблица": (q["p_да_если_есть"], q["p_да_если_нет"]), "по_критерию": q["по_критерию"]} for q in пр["вопросы"]]
        выбран, разбор = ses.ср.выбрать_вопрос(предложения, {ид: с.база.статьи[ид].текст_для_модели(20000) for ид, _ in канд})
        рез["успешных"] += 1
        рез["годных_вопросов"].append(sum(1 for x in разбор if "отказ" not in x))
        рез["ключевой_вопрос_найден"] += any(q["статья"] == "34" and КЛЮЧЕВОЙ_ВОПРОС.search(q["текст"]) for q in предложения)
        рез["ядро_выбрало_ключевой"] += bool(выбран and выбран["статья"] == "34" and КЛЮЧЕВОЙ_ВОПРОС.search(выбран["текст"]))
        разреш = ses._разрешённые_числа([ид for ид, _ in канд])
        рез["числа_вне_источника"] += len(Д.проверка_чисел(пр["реакция"], разреш)["нет_в_источнике"])
        рез["пример_вопроса"] = (выбран or {}).get("текст")
    n = max(1, рез["успешных"])
    usd, неполная = _сложить_цены(цены)
    return dict(рез, мс_в_среднем=int(мс / n), токены=ток, usd=usd, usd_неполная=неполная)


def задача_итог(с, роль, повторов):
    Д.РОЛИ["итог"] = роль
    рез = {"успешных": 0, "категория_В_названа": 0, "графы_II_III_упомянуты": 0, "числа_вне_источника": 0, "вырождение": 0,
           "предупреждение_в_конце": 0, "про_спину_обследование": 0}
    мс = ток = 0
    цены = []
    тексты = []
    for _ in range(повторов):
        ses = _сессия_с_состоянием(с)
        ses.ср.учесть_упоминание("близорукость", "есть", "-6.25 на левом глазу, -5.75 на правом, измерено после капель", *с.блоки.статьи("близорукость -6.25"))
        ses.слова_человека += ["Зрение проверял у окулиста с каплями, минус 6.25 на левом глазу и минус 5.75 на правом.",
                               "Спину не обследовал, просто болит после тренировок. Больше ничего нет, что в итоге?"]
        н = len(К.ЖУРНАЛ)
        try:
            текст, охрана = ses._итог({})
        except К.Ошибка as e:
            print("   итог: ошибка:", str(e)[:140])
            continue
        в = К.ЖУРНАЛ[н:]
        мс += sum(x["мс"] for x in в)
        ток += sum((x["вход"] or 0) + (x["выход"] or 0) for x in в)
        for x in в:
            if not x.get("кэш") and not x.get("ошибка"):
                цены.append(x.get("usd"))
        рез["успешных"] += 1
        рез["категория_В_названа"] += bool(re.search(r"[«\"]В[»\"]|категори\w*\s+\**В\b", текст))
        рез["графы_II_III_упомянуты"] += bool(re.search(r"граф\w*\s+(?:II|III)\b", текст))
        рез["числа_вне_источника"] += len(охрана["нет_в_источнике"])
        рез["вырождение"] += bool(охрана.get("вырождение"))
        рез["предупреждение_в_конце"] += bool(охрана.get("предупреждение_в_конце"))
        рез["про_спину_обследование"] += bool(re.search(r"МРТ|рентген|невролог|ортопед", текст, re.I))
        тексты.append(текст)
    n = max(1, рез["успешных"])
    usd, неполная = _сложить_цены(цены)
    return dict(рез, мс_в_среднем=int(мс / n), токены=ток, usd=usd, usd_неполная=неполная, тексты=тексты)


def main():
    арг = [a for a in sys.argv[1:] if not a.startswith("--")]
    повторов = int(sys.argv[sys.argv.index("--повторов") + 1]) if "--повторов" in sys.argv else 3
    if "--повторов" in sys.argv:
        арг = [a for a in арг if a != str(повторов)]
    кандидаты = арг or ПО_УМОЛЧАНИЮ
    с = Д.Система()
    итог = {}
    for к in кандидаты:
        роль = _роль(к)
        print("=" * 90, "\nКАНДИДАТ:", к, flush=True)
        t0 = time.time()
        try:
            итог[к] = {"разбор": задача_разбор(с, роль), "вопросы": задача_вопросы(с, роль, повторов), "итог": задача_итог(с, роль, max(1, повторов - 1))}
        except К.Ошибка as e:
            итог[к] = {"ошибка": str(e)}
            print("  ОШИБКА:", e)
            continue
        р = итог[к]
        части = [р[x].get("usd") for x in ("разбор", "вопросы", "итог")]
        известные = [v for v in части if v is not None]
        if not известные:
            р["всего_usd"] = None
            р["всего_usd_неполная"] = True
        else:
            р["всего_usd"] = round(sum(известные), 5)
            р["всего_usd_неполная"] = any(р[x].get("usd") is None or р[x].get("usd_неполная") for x in ("разбор", "вопросы", "итог"))
        # типичный диалог: 4 разбора реплик, 3 вызова вопросов, 1 итог
        try:
            кусочки = []
            неполная_тип = False
            if р["разбор"].get("usd") is None:
                неполная_тип = True
            else:
                кусочки.append(4 * р["разбор"]["usd"] / len(РАЗБОР))
                неполная_тип = неполная_тип or bool(р["разбор"].get("usd_неполная"))
            if р["вопросы"].get("usd") is None:
                неполная_тип = True
            else:
                кусочки.append(3 * р["вопросы"]["usd"] / max(1, р["вопросы"]["успешных"]))
                неполная_тип = неполная_тип or bool(р["вопросы"].get("usd_неполная"))
            if р["итог"].get("usd") is None:
                неполная_тип = True
            else:
                кусочки.append(р["итог"]["usd"] / max(1, р["итог"]["успешных"]))
                неполная_тип = неполная_тип or bool(р["итог"].get("usd_неполная"))
            if not кусочки and неполная_тип:
                р["usd_типичный_диалог"] = None
            else:
                р["usd_типичный_диалог"] = round(sum(кусочки), 5)
            р["usd_типичный_неполная"] = неполная_тип
        except Exception:  # noqa: BLE001
            р["usd_типичный_диалог"] = None
            р["usd_типичный_неполная"] = True
        print("  разбор : точность %.2f, лишних %d, %d мс/фраза, %s" % (р["разбор"]["точность_разбора"], р["разбор"]["лишних_упоминаний"], р["разбор"]["мс_на_фразу"], К.цена_строкой(р["разбор"].get("usd"), р["разбор"].get("usd_неполная"))))
        print("  вопросы: ключевой вопрос найден %d/%d, ядро выбрало ключевой %d/%d, годных %s, %d мс, чисел вне источника %d, %s" % (
            р["вопросы"]["ключевой_вопрос_найден"], р["вопросы"]["успешных"], р["вопросы"]["ядро_выбрало_ключевой"], р["вопросы"]["успешных"],
            р["вопросы"]["годных_вопросов"], р["вопросы"]["мс_в_среднем"], р["вопросы"]["числа_вне_источника"], К.цена_строкой(р["вопросы"].get("usd"), р["вопросы"].get("usd_неполная"))))
        print("  итог   : категория В названа %d/%d, графы II/III %d, чисел вне источника %d, вырождение %d, предупреждение %d, про спину %d, %d мс, %s" % (
            р["итог"]["категория_В_названа"], р["итог"]["успешных"], р["итог"]["графы_II_III_упомянуты"], р["итог"]["числа_вне_источника"],
            р["итог"]["вырождение"], р["итог"]["предупреждение_в_конце"], р["итог"]["про_спину_обследование"], р["итог"]["мс_в_среднем"], К.цена_строкой(р["итог"].get("usd"), р["итог"].get("usd_неполная"))))
        print("  ИТОГО: %s за прогон; типичный диалог ≈ %s; %.0f с" % (К.цена_строкой(р["всего_usd"], р["всего_usd_неполная"]), К.цена_строкой(р["usd_типичный_диалог"], р["usd_типичный_неполная"]), time.time() - t0), flush=True)
    with open(ВЫХОД, "w", encoding="utf-8") as f:
        json.dump(итог, f, ensure_ascii=False, indent=1)
    print("\nрезультаты:", ВЫХОД)


if __name__ == "__main__":
    main()
