# -*- coding: utf-8 -*-
"""Шесть тестов (бенч_шесть/промты.json) из терминала, без сервера и браузера. Сырые ответы и разбор кладутся в бенч_шесть/результаты/<метка>/.

Режимы:
  api      — модель сама (как чат без инструментов): весь промт одним сообщением, без блоков и ядра (контрольная группа);
  свободно — NNL + API без ограничений: блоки дают досье по каждому случаю, пачка идёт в API целиком (тест 6 без досье);
  ядро     — настоящий NNL + API: каждый случай своим диалогом через ядро (тест 5 — диалоги по репликам); тест 6 не применим.

Примеры:
  python -X utf8 -I прогон_шести.py --режимы api,свободно --тесты 1,2,3,4 --прогонов 3 --пресет groq
  python -X utf8 -I прогон_шести.py --режимы ядро --тесты 5 --прогонов 1
Кэш ответов выключен и перенаправлен во временный файл: прогоны независимы. Ключей (правильных ответов) здесь нет: счёт делается отдельно по разобранному JSON."""
import argparse
import concurrent.futures
import json
import os
import re
import sys
import tempfile
import time
import traceback

sys.dont_write_bytecode = True
КАТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, КАТ)
import клиент as К  # noqa: E402

К.КЭШ_ФАЙЛ = os.path.join(tempfile.gettempdir(), "nnl_шесть_кэш.jsonl")     # прошлые ответы не подмешиваются
К._кэш = None
import диалог as Д  # noqa: E402

ПАПКА = os.path.join(КАТ, "бенч_шесть")
ПРОМТЫ = json.load(open(os.path.join(ПАПКА, "промты.json"), encoding="utf-8"))
_СТРОКА = re.compile(r"^\s*(\d{1,3})\.\s*(.*)$")
_СИСТЕМА_ТЕОРЕТИКА = "Ты исследователь-теоретик. Решай рассуждением, без инструментов."


def разобрать_строки(текст):
    """{номер: строка ответа}: для тестов 1–4 (в тесте 5 — «Диалог N:»)."""
    out = {}
    for x in текст.splitlines():
        m = _СТРОКА.match(x) or re.match(r"^\s*Диалог\s+(\d+)\s*:\s*(.*)$", x)
        if m:
            out[int(m.group(1))] = m.group(2).strip()
    return out


def сессия(роли, глубже=False):
    s = Д.Система_общая.сессия()
    s.кэш = False
    s.роли = роли
    s.глубже = глубже
    return s


def учёт(вызовы):
    return {"вызовов": sum(1 for в in вызовы if not в["кэш"]), "токены": sum((в["вход"] or 0) + (в["выход"] or 0) for в in вызовы)}


# ------------------------------------------------------------------ режимы
def режим_api(тест, роли):
    п = ПРОМТЫ[тест]
    s = сессия(роли)
    t0 = time.time()
    if тест == "6":
        метка = К.метка_журнала()
        r = s._вызов("базовая", _СИСТЕМА_ТЕОРЕТИКА, [("user", п["текст"])], температура=0.3, макс_токенов=14000, размышление=True, таймаут=900)
        return {"ответ": r["текст"], "мс": int(1000 * (time.time() - t0)), **учёт(К.вызовы_после(метка))}
    t = s.ход_базовой(п["текст"])
    return {"ответ": t["ответ"], "мс": t["мс"], "вызовов": t["вызовов_модели"], "токены": t["токены"]}


def режим_свободно(тест, роли):
    п = ПРОМТЫ[тест]
    if тест == "6":
        return режим_api(тест, роли)            # у абстрактной задачи нет статей: досье нечем наполнить
    t = сессия(роли).ход_свободный(п["текст"])
    return {"ответ": t["ответ"], "мс": t["мс"], "вызовов": t["вызовов_модели"], "токены": t["токены"]}


def режим_ядро(тест, роли, потоков):
    п = ПРОМТЫ[тест]
    if тест == "6":
        return {"пропущен": "нет блоков для абстрактной задачи: NNL здесь не применим"}
    t0 = time.time()
    if тест == "5":
        def диалог(и_д):
            и, реплики = и_д
            s = сессия(роли)
            ответы, вызовы, ток = [], 0, 0
            for р in реплики:
                t = s.ход(р)
                ответы.append({"человек": р, "ответ": t["ответ"], "действие": t.get("действие")})
                вызовы += t["вызовов_модели"]
                ток += t["токены"]
            return {"диалог": и + 1, "ходы": ответы, "итог": ответы[-1]["ответ"], "вызовов": вызовы, "токены": ток}
        эл = list(map(диалог, enumerate(п["диалоги"])))
    else:
        def случай(и_с):
            и, фраза = и_с
            try:
                t = сессия(роли).ход(фраза)
                return {"номер": и + 1, "случай": фраза, "действие": t.get("действие"), "ответ": t["ответ"],
                        "рейтинг": [(r["статья"], r["p"]) for r in (t.get("рейтинг") or [])[:3]], "вызовов": t["вызовов_модели"], "токены": t["токены"]}
            except Exception as e:  # noqa: BLE001
                return {"номер": и + 1, "случай": фраза, "ошибка": str(e)[:200], "вызовов": 0, "токены": 0}
        with concurrent.futures.ThreadPoolExecutor(max_workers=потоков) as ex:
            эл = list(ex.map(случай, enumerate(п["случаи"])))
    return {"случаи": эл, "мс": int(1000 * (time.time() - t0)), "вызовов": sum(x.get("вызовов", 0) for x in эл), "токены": sum(x.get("токены", 0) for x in эл)}


def режим_код(тест, роли):
    """Ответы кодом: блоки + решатель + ядро; API только слушатель в тестах 4–5 (см. код_ответ.py)."""
    п = ПРОМТЫ[тест]
    if тест == "6":
        return {"пропущен": "нет блоков для абстрактной задачи: NNL здесь не применим"}
    import код_ответ as КО
    ко = КО.КодОтвет(Д.Система_общая, роли)
    t0 = time.time()
    вызовы = []
    if тест == "1":
        ответ = ко.тест1([(str(i + 1), ф) for i, ф in enumerate(п["случаи"])])
    elif тест == "2":
        ответ = ко.тест2([(str(i + 1), ф) for i, ф in enumerate(п["случаи"])])
    elif тест == "3":
        ответ = ко.тест3([(str(i + 1), ф) for i, ф in enumerate(п["случаи"])])
    elif тест == "4":
        ответ, вызовы = ко.тест4([(str(i + 1), ф) for i, ф in enumerate(п["случаи"])])
    else:
        ответ, вызовы = ко.тест5([(str(i + 1), д) for i, д in enumerate(п["диалоги"])])
    return {"ответ": ответ, "мс": int(1000 * (time.time() - t0)), **учёт(вызовы)}


def main():
    ар = argparse.ArgumentParser()
    ар.add_argument("--режимы", default="api,свободно,ядро")
    ар.add_argument("--тесты", default="1,2,3,4,5,6")
    ар.add_argument("--прогонов", type=int, default=3)
    ар.add_argument("--пресет", default=Д.ПРЕСЕТ, help="набор ролей: " + ", ".join(Д.ПРЕСЕТЫ))
    ар.add_argument("--модель", default="", help="одна модель на все роли, «провайдер:модель» (пул — через | в имени модели); перекрывает пресет")
    ар.add_argument("--потоков", type=int, default=3, help="параллельных диалогов в режиме «ядро»")
    ар.add_argument("--метка", default=time.strftime("%Y%m%d-%H%M%S"))
    а = ар.parse_args()
    if а.модель:
        пров, _, мод = а.модель.partition(":")
        роли = {к: (пров, мод) for к in ("разбор", "вопросы", "итог", "речь", "базовая")}
    else:
        роли = dict(Д.ПРЕСЕТЫ[а.пресет])
    Д.Система_общая = Д.Система()
    выход = os.path.join(ПАПКА, "результаты", а.метка)
    os.makedirs(выход, exist_ok=True)
    json.dump({"роли": {k: list(v) for k, v in роли.items()}, "аргументы": vars(а)}, open(os.path.join(выход, "условия.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    for реж in а.режимы.split(","):
        for тест in а.тесты.split(","):
            for k in range(1, а.прогонов + 1):
                t0 = time.time()
                try:
                    r = {"api": lambda: режим_api(тест, роли), "свободно": lambda: режим_свободно(тест, роли), "ядро": lambda: режим_ядро(тест, роли, а.потоков), "код": lambda: режим_код(тест, роли)}[реж]()
                    if "ответ" in r and тест in "12345":
                        r["строки"] = разобрать_строки(r["ответ"])
                except Exception as e:  # noqa: BLE001
                    traceback.print_exc()
                    r = {"ошибка": str(e)[:300]}
                r.update(режим=реж, тест=тест, прогон=k)
                json.dump(r, open(os.path.join(выход, "%s_тест%s_прогон%d.json" % (реж, тест, k)), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
                print("%-9s тест %s прогон %d: %5.1f с, вызовов %s, токенов %s%s" % (реж, тест, k, time.time() - t0, r.get("вызовов"), r.get("токены"),
                      "  ОШИБКА " + r["ошибка"] if "ошибка" in r else ("  (пропущен)" if "пропущен" in r else "")), flush=True)
    print("результаты:", выход)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
