# -*- coding: utf-8 -*-
"""Ядро NNL, опыт v1: один запрос — один блок-специалист.

Ядро — обычная программа. В нём НЕТ ни одного обученного числа:
ядро не понимает текст, не рассуждает, не отвечает само.
Всё обученное лежит только в блоках (блоки/ИМЯ/weights.npz).

Логика ядра (код, не ИИ):
- ТИПЫ: известный набор типов данных; паспорт блока проверяется при подключении.
- Подключение/снятие на ходу без перезапуска и без переобучения остальных.
- МАРШРУТ: детерминированный алгоритм по правилам и типам из паспортов.
  Один и тот же запрос при тех же блоках всегда идёт тем же путём.
  Обученного классификатора и вызова языковой модели в маршрутизаторе НЕТ.
- СЛЕД: на каждый ответ записывается, какие блоки участвовали и в каком порядке.
- Доступ к параметрам: список параметров блока, заморозка, дообучение только его.
- ОТКАЗ: если подходящего блока нет — «не знаю», а не ответ наугад.

Проверка понимания: если удалить все блоки, в системе не остаётся ни одного
обученного числа, а ядро продолжает запускаться и на любой запрос отвечает «не знаю».
"""
import json
import os
import re
import hashlib

НЕ_ЗНАЮ = "не знаю"

# Известные ядру типы данных. Блок с типами вне этого набора не принимается.
ТИПЫ = {
    "текст.вопрос:str",
    "метка.статья:str",
    "метка.тема:str",
    "ответ.цитата:str",
}

ТОКЕН = re.compile(r"[а-яёa-z0-9]+", re.IGNORECASE)


def токены(текст):
    """Детерминированная токенизация без обучения: нижний регистр + слова."""
    return ТОКЕН.findall((текст or "").lower())


def стемы(токены_списка):
    """Грубое правило-стеммирование без обучения (окончания), детерминированное.

    Это НЕ нейросеть и НЕ обученный классификатор: набор правил зафиксирован кодом.
    Пробуем snowballstemmer (правила Портера, без обучения), иначе — обрезка окончаний.
    """
    try:
        import snowballstemmer
        stemmer = snowballstemmer.stemmer("russian")
        return [stemmer.stemWord(t) for t in токены_списка]
    except Exception:
        out = []
        for t in токены_списка:
            w = t
            for end in ("ами", "ями", "его", "ого", "ому", "ыми", "ими", "ого",
                        "ая", "яя", "ое", "ее", "ые", "ие", "ой", "ей",
                        "ом", "ем", "ам", "ям", "ах", "ях", "ов", "ев",
                        "ей", "ью", "ью", "а", "я", "о", "е", "ы", "и", "ь", "у", "ю"):
                if len(w) > len(end) + 3 and w.endswith(end):
                    w = w[: -len(end)]
                    break
            out.append(w)
        return out


def sha256_файла(путь):
    h = hashlib.sha256()
    with open(путь, "rb") as f:
        for ч in iter(lambda: f.read(1 << 20), b""):
            h.update(ч)
    return h.hexdigest()


class Блок:
    """Подключённый блок: паспорт + веса + словарь + знания (цитаты)."""

    def __init__(self, путь):
        self.путь = путь
        with open(os.path.join(путь, "passport.json"), encoding="utf-8") as f:
            self.паспорт = json.load(f)
        with open(os.path.join(путь, "vocab.json"), encoding="utf-8") as f:
            self.словарь = json.load(f)
        with open(os.path.join(путь, "knowledge.json"), encoding="utf-8") as f:
            self.знания = json.load(f)
        import numpy as np
        вес = np.load(os.path.join(путь, "weights.npz"))
        self.W1 = вес["W1"]
        self.b1 = вес["b1"]
        self.W2 = вес["W2"]
        self.b2 = вес["b2"]
        self.метки = list(self.паспорт["метки"])
        self.порог = float(self.паспорт.get("порог", 0.30))
        self.слово_в_id = {w: i for i, w in enumerate(self.словарь["слова"])}
        self.маркеры = set(self.паспорт.get("маркеры", []))

    def вектор(self, текст):
        import numpy as np
        v = np.zeros(len(self.словарь["слова"]), dtype=np.float32)
        for s in стемы(токены(текст)):
            i = self.слово_в_id.get(s)
            if i is not None:
                v[i] += 1.0
        return v

    def предсказать(self, текст):
        """Чистый прямой проход MLP (архитектура без весов — обычный код типа блока)."""
        import numpy as np
        v = self.вектор(текст)
        h = v @ self.W1 + self.b1
        np.maximum(h, 0, out=h)  # ReLU
        z = h @ self.W2 + self.b2
        z = z - z.max()
        e = np.exp(z)
        p = e / e.sum()
        j = int(p.argmax())
        return self.метки[j], float(p[j]), [round(float(x), 4) for x in p[:5]]


class Ядро:
    def __init__(self):
        self.блоки = {}  # имя -> Блок
        self.заморожены = set()

    # ---------- типы и подключение ----------
    def проверить_паспорт(self, паспорт):
        ошибки = []
        for поле in ("имя", "область", "тип_входа", "тип_выхода",
                     "зависимости", "чем_обучен", "на_чём_обучен", "метки", "маркеры"):
            if поле not in паспорт:
                ошибки.append("нет поля паспорта: %s" % поле)
        if паспорт.get("тип_входа") not in ТИПЫ:
            ошибки.append("неизвестный тип входа: %r" % паспорт.get("тип_входа"))
        if паспорт.get("тип_выхода") not in ТИПЫ:
            ошибки.append("неизвестный тип выхода: %r" % паспорт.get("тип_выхода"))
        if паспорт.get("тип_входа") != "текст.вопрос:str":
            ошибки.append("ядро v1 принимает только блоки с входом текст.вопрос:str")
        if паспорт.get("тип_выхода") not in ("метка.статья:str", "метка.тема:str"):
            ошибки.append("ядро v1 принимает только выходы метка.статья / метка.тема")
        if not паспорт.get("метки"):
            ошибки.append("пустой список меток")
        return ошибки

    def подключить(self, путь_блока):
        проба = json.load(open(os.path.join(путь_блока, "passport.json"), encoding="utf-8"))
        ошибки = self.проверить_паспорт(проба)
        if ошибки:
            raise ValueError("блок не принят по типам: " + "; ".join(ошибки))
        имя = проба["имя"]
        if имя in self.блоки:
            self.снять(имя)
        self.блоки[имя] = Блок(путь_блока)
        return имя

    def снять(self, имя):
        if имя in self.блоки:
            del self.блоки[имя]
        self.заморожены.discard(имя)

    def список_блоков(self):
        return sorted(self.блоки.keys())

    # ---------- маршрут (детерминированный, без нейросети) ----------
    def оценка(self, текст):
        """Счёт каждого блока = число его маркеров-стемов, встреченных в вопросе.

        Маркеры берутся из паспортов (описаны человеком/из базы знаний, не обучены).
        Подсчёт — детерминированная функция (текст, паспорта).
        """
        s = set(стемы(токены(текст)))
        return {имя: len(s & set(б.маркеры)) for имя, б in self.блоки.items()}

    def выбрать(self, текст):
        """Один блок с максимальным счётом; ничья или ноль — «не знаю» (None)."""
        if not self.блоки:
            return None, {}
        счёты = self.оценка(текст)
        лучший = max(счёты.values())
        if лучший <= 0:
            return None, счёты
        лидеры = [и for и, sc in счёты.items() if sc == лучший]
        if len(лидеры) != 1:
            return None, счёты
        return лидеры[0], счёты

    # ---------- запрос ----------
    def спросить(self, текст):
        """Один запрос — один блок. Возвращает ответ + след."""
        имя, счёты = self.выбрать(текст)
        if имя is None:
            return {"вопрос": текст, "ответ": НЕ_ЗНАЮ, "цитата": "",
                    "след": [], "блок": None, "счёты": счёты,
                    "уверенность": 0.0, "отказ": True}
        б = self.блоки[имя]
        метка, ув, _ = б.предсказать(текст)
        if ув < б.порог:
            return {"вопрос": текст, "ответ": НЕ_ЗНАЮ, "цитата": "",
                    "след": [{"блок": имя, "действие": "отказ_низкая_уверенность"}],
                    "блок": имя, "счёты": счёты,
                    "уверенность": round(ув, 4), "отказ": True}
        знание = б.знания.get(метка, {})
        цитаты = знание.get("цитаты", [])
        цитата = цитаты[0] if цитаты else знание.get("заголовок", "")
        return {"вопрос": текст, "ответ": метка, "цитата": цитата,
                "след": [{"блок": имя, "действие": "ответ"}],
                "блок": имя, "счёты": счёты,
                "уверенность": round(ув, 4), "отказ": False}

    # ---------- доступ к параметрам ----------
    def список_параметров(self, имя):
        б = self.блоки[имя]
        return {"W1": list(б.W1.shape), "b1": list(б.b1.shape),
                "W2": list(б.W2.shape), "b2": list(б.b2.shape),
                "чисел": int(б.W1.size + б.b1.size + б.W2.size + б.b2.size),
                "sha256": sha256_файла(os.path.join(б.путь, "weights.npz"))}

    def заморозить(self, имя):
        self.заморожены.add(имя)

    def разморозить(self, имя):
        self.заморожены.discard(имя)

    def заморожен(self, имя):
        return имя in self.заморожены
