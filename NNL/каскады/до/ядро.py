# -*- coding: utf-8 -*-
"""NNL (Neural Network Lego) — Слой 4: Ядро причинности (Causality Core).

Отвечает за проверку причинных связей между понятиями на шине:
  1. Не проверяет имена блоков через if/elif — работает исключительно с абстрактными понятиями шины.
  2. Проецирует локальные выводы блока в стандартные понятия шины согласно манифесту (паспорту).
  3. Проверяет совместную причинную совместимость и консистентность графа понятий.
"""
import os


class ЯдроПричинности:
    def __init__(self, база_путь=None):
        self.база_путь = база_путь
        self.правила_совместимости = []
        self._онтология_глав = {}
        self._онтология_актов = {}
        if база_путь:
            self._загрузить_базовую_онтологию(база_путь)

    def _загрузить_базовую_онтологию(self, корень):
        # Опциональная фоновая база для обратной совместимости со старыми блоками v8
        sg_path = os.path.join(корень, "математичка", "данные", "статья_глава.csv")
        if os.path.exists(sg_path):
            with open(sg_path, encoding="utf-8") as f:
                f.readline()
                for line in f:
                    if line.strip():
                        p = line.strip().split(";")
                        self._онтология_глав[p[0]] = p[1]

        ta_path = os.path.join(корень, "математичка", "данные", "тема_акты.csv")
        if os.path.exists(ta_path):
            with open(ta_path, encoding="utf-8") as f:
                f.readline()
                for line in f:
                    if line.strip():
                        p = line.strip().split(";")
                        topic = p[0]
                        acts = []
                        for a in p[1].split("+"):
                            a = a.strip().lower()
                            if "53фз" in a: acts.append("акт:53фз")
                            elif "пп565" in a: acts.append("акт:пп565")
                            elif "пп663" in a: acts.append("акт:пп663")
                            elif "пп719" in a: acts.append("акт:пп719")
                            elif "кас" in a: acts.append("акт:кас")
                            elif "коап" in a: acts.append("акт:коап")
                            elif "укрф" in a: acts.append("акт:укрф")
                            elif "127фз" in a: acts.append("акт:127фз")
                            elif "59фз" in a: acts.append("акт:59фз")
                        self._онтология_актов[topic] = acts

    def проецировать(self, блок, ответ_id):
        """Универсальная проекция вывода блока в понятия шины.
        1. В первую очередь читает объявленные проекции из паспорта самого блока.
        2. Если в паспорте нет — использует правила онтологии понятий.
        """
        # 1. Декларативная проекция из паспорта блока
        if ответ_id in блок.проекции:
            return dict(блок.проекции[ответ_id])

        # 2. Обратная совместимость с форматом v8
        проекция = {}
        if hasattr(блок, "паспорт") and "область" in блок.паспорт:
            проекция[f"область:{блок.паспорт['область']}"] = 16.0

        raw_id = ответ_id.split(":")[-1]
        if raw_id in self._онтология_глав:
            chap = self._онтология_глав[raw_id]
            проекция[f"глава:{chap}"] = 16.0
            проекция["область:здоровье"] = 16.0
        elif raw_id in self._онтология_актов:
            for act in self._онтология_актов[raw_id]:
                проекция[act] = 16.0
            проекция["область:право"] = 16.0

        return проекция

    def проверить_цепочку(self, отклики, шина):
        """Проверяет причинную совместимость понятий на шине.
        Оперирует исключительно понятиями шины, не завязываясь на имена блоков.
        """
        финал = dict(отклики)
        активные_понятия = list(шина.keys())

        # Выделяем ключевые группы понятий на шине
        главы = [k for k in активные_понятия if k.startswith("глава:")]
        акты = [k for k in активные_понятия if k.startswith("акт:")]
        выводы = [k for k in активные_понятия if k.startswith("вывод_")]

        цепочка = {
            "активные_выводы": выводы,
            "главы_на_шине": главы,
            "акты_на_шине": акты,
            "число_фактов": len(активные_понятия),
            "статус": "согласовано" if (главы or акты) else "изолировано",
        }

        # Если какой-либо блок синтезировал живой ответ — сохраняем
        for имя, отклик in отклики.items():
            if isinstance(отклик, dict) and "живой_текст" in отклик:
                цепочка["живой_текст"] = отклик["живой_текст"]

        финал["_причинная_цепочка"] = цепочка
        return финал
