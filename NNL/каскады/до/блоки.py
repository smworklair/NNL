# -*- coding: utf-8 -*-
"""Свои обученные блоки (здоровье, право) через матплату NNL. Здесь они только оценивают текст; решает ядро диалога.

Что даёт блок:
  * оценка упоминания: вероятность каждой из 88 статей для короткой фразы («близорукость -5.5»), с опорным «ничего» (якорь 0):
    p_ничего — масса, которую блок отдаёт на «ни одна статья не подходит»;
  * ворота области: число «область:здоровье» / «область:право» из прохода 1 (логарифм шансов, блок сам его пишет и сам откалиброван
    на экзамене языка) — по проверке NNL именно этот сигнал отличает «моё» от «не моего» (AUROC 0,95–0,99), а не разрыв top1−top2;
  * тема права: лучшая правовая тема с её вероятностью против якоря."""
import math
import os
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
for п in (КОРЕНЬ, os.path.join(КОРЕНЬ, "v8", "замер")):
    if п not in sys.path:
        sys.path.insert(0, п)
import общее as О  # noqa: E402  (v8/замер/общее.py: загрузка языка NNL-1 и пути к архитектурам)
from NNL.матплата import Матплата  # noqa: E402

ВАРИАНТ = "основная_внешние.з1"


def _softmax_с_якорем(счёты):
    m = max([0.0] + list(счёты.values()))
    z = math.exp(-m) + sum(math.exp(x - m) for x in счёты.values())
    return {a: math.exp(x - m) / z for a, x in счёты.items()}, math.exp(-m) / z


class Блоки:
    def __init__(self, вариант=ВАРИАНТ):
        self.язык = О.Язык(О.ЯЗЫК_ПАПКА)
        self.матплата = Матплата(self.язык, О.ARCH)
        for имя in ("здоровье", "право"):
            ok, msg = self.матплата.подключить(os.path.join(О.V8, "блоки", вариант, имя))
            if not ok:
                raise RuntimeError("блок %s не подключился: %s" % (имя, msg))

    def токены(self, текст):
        return self.язык.перевести(текст)["токены"]

    def паспорта(self):
        return {n: {"версия": b.паспорт["версия"], "sha256": b.паспорт["веса"]["sha256"][:12], "чисел": b.чисел}
                for n, b in self.матплата.блоки.items()}

    def область(self, текст):
        """(здоровье, право): логарифмы шансов «вопрос из моей области» — числа шины, которые блоки пишут сами."""
        t = self.токены(текст)
        out = []
        for имя in ("здоровье", "право"):
            b = self.матплата.блоки[имя]
            out.append(b.arch.проход1(b.obj, t)["область:" + имя])
        return tuple(out)

    def статьи(self, текст):
        """{id статьи: p} и p_ничего для короткой фразы."""
        t = self.токены(текст)
        b = self.матплата.блоки["здоровье"]
        s = b.arch.проход2(b.obj, t, {})
        p, p0 = _softmax_с_якорем(s)
        return {a.split(":", 2)[2]: v for a, v in p.items()}, p0

    def право(self, текст, топ=3):
        t = self.токены(текст)
        b = self.матплата.блоки["право"]
        s = b.arch.проход2(b.obj, t, {})
        p, p0 = _softmax_с_якорем(s)
        лучшие = sorted(p.items(), key=lambda x: -x[1])[:топ]
        return [(a.split(":", 2)[2], v) for a, v in лучшие], p0
