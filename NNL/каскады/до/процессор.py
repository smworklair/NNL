# -*- coding: utf-8 -*-
"""NNL (Neural Network Lego) — Слой 3: Процессор тактов (Диспетчер тактов).

Координирует проходы блоков через матплату для любого числа N блоков:
  1. Полная инвариантность к именам блоков: в коде нет ни одного 'if имя == ...'.
  2. Такт 1: параллельный прямой опрос блоков при изолированной шине {} (Lego = 0.0000).
  3. Такт 2: обратная запись фактов уверенных блоков (Delta >= tau_conf) на шину
     и переопрос зависимых блоков (подписанных на появившиеся понятия шины).
  4. Передача состояния шины в Ядро причинности.
"""


class Процессор:
    def __init__(self, матплата, ядро=None, tau_conf=1.0):
        self.матплата = матплата
        self.ядро = ядро
        self.tau_conf = tau_conf

    def выполнить(self, текст):
        токены = self.матплата.язык.перевести(текст)["токены"]
        self.матплата.очистить_шину()

        # ======================================================== ТАКТ 1: ИЗОЛЯЦИЯ
        отклики_т1 = {}
        уверенные_блоки = set()

        for имя, блок in self.матплата.блоки.items():
            срез_т1 = self.матплата.срез_шины(имя, такт=1)
            счёты = блок.arch.проход2(блок.obj, токены, срез_т1)
            сортировка = sorted(счёты.items(), key=lambda x: x[1], reverse=True)
            top1_ans, top1_score = сортировка[0]
            top2_score = сортировка[1][1] if len(сортировка) > 1 else top1_score
            margin = top1_score - top2_score

            отклики_т1[имя] = {
                "счёты": счёты,
                "top1": top1_ans,
                "score": top1_score,
                "margin": margin,
            }
            if margin >= self.tau_conf:
                уверенные_блоки.add(имя)

        # ======================================================== ТАКТ 2: ШИНА И ОБРАТНАЯ СВЯЗЬ
        нужен_такт2 = len(уверенные_блоки) > 0 and any(len(b.читает) > 0 for b in self.матплата.блоки.values())
        отклики_т2 = dict(отклики_т1)

        if нужен_такт2:
            # 1. Запись подтверждённых выводов уверенных блоков на шину матплаты
            for имя in уверенные_блоки:
                блок = self.матплата.блоки[имя]
                top1 = отклики_т1[имя]["top1"]
                # Базовый факт вывода
                self.матплата.записать_на_шину(f"вывод_{имя}:{top1}", 1.0)

                # Декларированные проекции блока в понятия шины
                if self.ядро:
                    проекции = self.ядро.проецировать(блок, top1)
                    for k, v in проекции.items():
                        self.матплата.записать_на_шину(k, v)

            # 2. Опрос блоков, читающих шину (или неуверенных блоков) на такте 2
            for имя, блок in self.матплата.блоки.items():
                if имя not in уверенные_блоки or len(блок.читает) > 0:
                    срез_т2 = self.матплата.срез_шины(имя, такт=2)
                    if срез_т2:
                        счёты_т2 = блок.arch.проход2(блок.obj, токены, срез_т2)
                        сортировка = sorted(счёты_т2.items(), key=lambda x: x[1], reverse=True)
                        top1_ans, top1_score = сортировка[0]
                        top2_score = сортировка[1][1] if len(сортировка) > 1 else top1_score
                        margin = top1_score - top2_score

                        отклик = {
                            "счёты": счёты_т2,
                            "top1": top1_ans,
                            "score": top1_score,
                            "margin": margin,
                        }
                        # Поддержка генерации payload (живой ответ, карточка, действие)
                        if hasattr(блок.arch, "синтез"):
                            отклик["живой_текст"] = блок.arch.синтез(блок.obj, токены, срез_т2, top1_ans, отклики=отклики_т2)
                        elif hasattr(блок.arch, "экспорт"):
                            отклик["экспорт"] = блок.arch.экспорт(блок.obj, токены, срез_т2, top1_ans)

                        отклики_т2[имя] = отклик

        # ======================================================== ВАЛИДАЦИЯ ЯДРОМ
        отклики_финал = dict(отклики_т2)
        if self.ядро:
            отклики_финал = self.ядро.проверить_цепочку(отклики_т2, self.матплата.шина)

        return {
            "текст": текст,
            "токены": токены,
            "такт1": отклики_т1,
            "такт2": отклики_т2,
            "финал": отклики_финал,
            "шина": dict(self.матплата.шина),
            "уверенные_блоки": list(уверенные_блоки),
        }
