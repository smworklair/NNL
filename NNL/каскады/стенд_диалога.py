def подмена_p(p, p0, как, статья=None, другая=None):
    """Три способа испортить вывод блока: поменять местами массу двух статей, заострить (p²), сгладить (√p)."""
    p = dict(p)
    if как == "обмен":
        p[статья], p[другая] = p[другая], p[статья]
        return p, p0
    k = 2.0 if как == "заострить" else 0.5
    z = p0 ** k + sum(v ** k for v in p.values())
    return {a: v ** k / z for a, v in p.items()}, p0 ** k / z


class ОценкаСИскажением:
    """Обёртка над блоком: искажает ответ для заданных фраз (или для всех), остальное — настоящий блок."""

    def __init__(self, оценка, фразы=None, **параметры):
        self.оценка, self.фразы, self.параметры = оценка, фразы, параметры

    def __call__(self, фраза):
        p, p0 = self.оценка(фраза)
        if self.фразы is None or фраза in self.фразы:
            return подмена_p(p, p0, **self.параметры)
        return p, p0


