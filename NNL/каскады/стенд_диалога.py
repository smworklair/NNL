def odds(p):
    p = min(max(p, 1e-9), 1 - 1e-9)
    return p / (1 - p)


def L1(a, b):
    return sum(abs(a[k] - b[k]) for k in a)


# --------------------------------------------------------------------------------- «как есть»: вклад без потолка, обрезки и вопросов
def линейный_вклад(упоминания, оценка):
    v = collections.defaultdict(float)
    for у in упоминания:
        if у["статус"] == "чужое":
            continue
        p, _ = оценка((у["термин"] + " " + (у.get("уточнение") or "")).strip())
        for a, pa in p.items():
            ln_lr = max(0.0, math.log(odds(pa) / ODDS_ФОН))
            if ln_lr < 0.5:
                continue
            сила = ln_lr * (Р.ВЕС_БЫЛО if у["статус"] == "было" else 1.0)
            v[a] += -сила if у["статус"] == "нет" else сила
    return v


def L1_вкладов(a, b):
    return sum(abs(a.get(k, 0.0) - b.get(k, 0.0)) for k in set(a) | set(b))


