"""Стенд каскадных ошибок, уровень приложения-диалога: разбор реплики → оценка блоком → учёт ядром → ответы и выбор вопроса → итог.

Идея. Настоящий `Сессия.ход` (диалог.py) идёт целиком, без сети: внешняя модель заменена заготовкой (сценарии.ФейкAPI). Разбор реплики по построению
известен, поэтому ошибку можно внести в любую стадию точечно и заранее известным способом, а потом сравнить прогон с ошибкой с чистым прогоном
того же случая и той же честной беседы. Блок «здоровье», ядро (расследование.py), банк вопросов (снимок) и стоп-правило — настоящие.

Что мерим (везде сравнение «с ошибкой» против «чисто», на одном и том же случае):
  ε_вход   — размер самой ошибки «как есть»: на сколько нат сдвинулись бы логарифмы шансов статей, если бы вклады просто складывались
             (без потолка улики, без обрезки состояния, без последующих вопросов). Это масштаб, с которым ошибку надо сравнивать.
  ε_ядро   — расстояние (L1 по 88 статьям, нат) между состояниями ядра после первой реплики: с ошибкой и без.
  ε_итог   — то же в конце беседы, когда ядро решило завершить (после честных ответов на вопросы).
  усиление — ε_итог / ε_вход. Больше 1: ошибка по пути выросла; меньше 1: система её погасила.
  исходы   — доли случаев, где ошибка изменила то, что заметит человек: статья-лидер (топ-1), ложный лидер (не та статья с p ≥ 0,5),
             потеря истины (p истинной статьи < 0,15), решение ядра на первом ходу, число вопросов, допуск вердикта по категории без врача.
Запуск: python NNL/каскады/стенд_диалога.py [--профиль до|после] [--случаев 120] [--выход файл.json]"""
