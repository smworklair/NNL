def _зерно(*части):
    return zlib.crc32("|".join(map(str, части)).encode("utf-8"))


def чистые_упоминания(с):
    return [С.упоминание(с["фраза"], "есть"), С.упоминание(с["отрицаемое"]["фраза"], "нет"), С.упоминание(с["чужое"]["фраза"], "чужое")]


def _с_заменой(с, индекс, **поля):
    у = чистые_упоминания(с)
    у[индекс].update(поля)
    return у


