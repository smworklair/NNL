def естественные_ошибки(система, фейк, естественные, оценка, пишет=print):
    """Реплика — одна жалоба; блок «здоровье» на этой фразе сам ошибается (топ-1 ≠ истина). Чего это стоит в конце беседы."""
    итог = collections.Counter()
    for с in естественные:
        p, _ = оценка(с["фраза"])
        верх = max(p, key=p.get)
        с_ = dict(с, отрицаемое={"фраза": ""}, чужое={"фраза": ""})
        with Блок(система, оценка):
            r = С.провести(система, фейк, с_, С.разбор_реплики([С.упоминание(с["фраза"], "есть")]), {с["истина"]}, реплика=с["фраза"])
        лидер, p_лидера = r["рейтинг"][0]
        группа = "блок_уверен(p≥0,8)" if p[верх] >= 0.8 else "блок_сомневается"
        for г in (группа, "все"):
            итог[г, "n"] += 1
            итог[г, "истина_лидер"] += лидер == с["истина"]
            итог[г, "ложный_лидер"] += лидер != с["истина"] and p_лидера >= 0.5
            итог[г, "истина_потеряна"] += Р.sigm(r["lN"][с["истина"]]) < Р.П_КАНДИДАТ
            итог[г, "вопросов"] += r["вопросов"]
            итог[г, "тупик"] += r["исход"] == "тупик"
    return {г: {"n": итог[г, "n"], "истина_лидер": round(итог[г, "истина_лидер"] / итог[г, "n"], 3), "ложный_лидер": round(итог[г, "ложный_лидер"] / итог[г, "n"], 3),
                "истина_потеряна": round(итог[г, "истина_потеряна"] / итог[г, "n"], 3), "вопросов_среднее": round(итог[г, "вопросов"] / итог[г, "n"], 2),
                "тупик": round(итог[г, "тупик"] / итог[г, "n"], 3)} for г in ("все", "блок_уверен(p≥0,8)", "блок_сомневается") if итог[г, "n"]}


