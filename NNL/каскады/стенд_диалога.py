# --------------------------------------------------------------------------------- прогон
class Блок:
    """Подмена Блоки.статьи на время одного прогона."""

    def __init__(self, система, оценка):
        self.система, self.оценка = система, оценка

    def __enter__(self):
        self._было = self.система.блоки.__dict__.get("статьи")
        self.система.блоки.статьи = self.оценка
        return self

    def __exit__(self, *a):
        if self._было is None:
            del self.система.блоки.статьи
        else:
            self.система.блоки.статьи = self._было


def сравнить(чист, ош, истина, ε_вход):
    def верх(з):
        a, p = з["рейтинг"][0]
        return a, p

    def p_истины(з):
        return dict(з["рейтинг"]).get(next(iter(истина)), 0.0)
    a_ч, a_о = верх(чист)[0], верх(ош)[0]
    return {
        "ε_вход": ε_вход, "ε_ядро": L1(чист["l1"], ош["l1"]), "ε_итог": L1(чист["lN"], ош["lN"]),
        "лидер_сменился": a_ч != a_о,
        "ложный_лидер": a_о not in истина and верх(ош)[1] >= 0.5,
        "истина_потеряна": Р.sigm(ош["lN"][next(iter(истина))]) < Р.П_КАНДИДАТ,
        "решение_1_изменилось": чист["д1"] != ош["д1"],
        "вопросов_изменилось": чист["вопросов"] != ош["вопросов"], "вопросов_разница": ош["вопросов"] - чист["вопросов"],
        "вердикт_без_врача": ош["вердикт_разрешён"] and not чист["вердикт_разрешён"],
        "исход_изменился": чист["исход"] != ош["исход"],
    }


def ε_ответа(таблица, ответ):
    a, b = таблица
    return math.log(a / b) if ответ == "да" else math.log((1 - a) / (1 - b)) if ответ == "нет" else 0.0


def запустить(система, фейк, случаи, оценка_настоящая, профиль, пишет=print):
    строки = collections.defaultdict(list)
    чистые = []
    for с in случаи:
        with Блок(система, оценка_настоящая):
            чист = С.провести(система, фейк, с, С.разбор_реплики(чистые_упоминания(с)), {с["истина"]})
        чистые.append(чист)
        for стадия, имя, внести in ошибки_каталога(с, оценка_настоящая):
            вн = внести()
            упоминания, оценка = вн.get("упоминания", чистые_упоминания(с)), вн.get("оценка", оценка_настоящая)
            ошибки_ответов = {вн["инверсия_ответа"]: "__инверсия__"} if "инверсия_ответа" in вн else {}
            with Блок(система, оценка):
                ош = С.провести(система, фейк, с, С.разбор_реплики(упоминания), {с["истина"]}, ошибки_ответов=ошибки_ответов, подмена_таблицы=вн.get("подмена_таблицы"))
            if "инверсия_ответа" in вн:
                k = вн["инверсия_ответа"]
                if k >= len(ош.get("ответы", [])) or ош["ответы"][k]["правда"] not in ("да", "нет"):
                    continue                                       # ошибке негде появиться: такого ответа в диалоге не было
                з = ош["ответы"][k]
                ε_вход = abs(ε_ответа(з["таблица"], з["правда"]) - ε_ответа(з["таблица"], з["передано"]))
            elif "подмена_таблицы" in вн:
                k = next(iter(вн["подмена_таблицы"]))
                if k >= len(ош.get("ответы", [])) or ош["ответы"][k]["передано"] not in ("да", "нет"):
                    continue
                з = ош["ответы"][k]
                ε_вход = abs(ε_ответа(з["таблица_использована"], з["передано"]) - ε_ответа(з["таблица"], з["передано"]))
            else:
                ε_вход = L1_вкладов(линейный_вклад(упоминания, оценка), линейный_вклад(чистые_упоминания(с), оценка_настоящая))
            строки[(стадия, имя)].append(сравнить(чист, ош, {с["истина"]}, ε_вход))
        if len(чистые) % 20 == 0:
            пишет("  случаев %d из %d" % (len(чистые), len(случаи)))
    return строки, чистые


def бутстреп_отношения(ряд, раз=400, зерно=11):
    """95 %-й интервал отношения средних Σε_итог / Σε_вход по случаям."""
    рнд = random.Random(зерно)
    n = len(ряд)
    оценки = []
    for _ in range(раз):
        выб = [ряд[рнд.randrange(n)] for _ in range(n)]
        знам = sum(x["ε_вход"] for x in выб)
        if знам > 0:
            оценки.append(sum(x["ε_итог"] for x in выб) / знам)
    оценки.sort()
    return (оценки[int(0.025 * len(оценки))], оценки[int(0.975 * len(оценки))]) if оценки else (float("nan"), float("nan"))


def свод(строки):
    out = []
    for (стадия, имя), ряд in строки.items():
        n = len(ряд)
        доля = lambda к: sum(1 for x in ряд if x[к]) / n          # noqa: E731
        ε_в = sum(x["ε_вход"] for x in ряд) / n
        ε_я = sum(x["ε_ядро"] for x in ряд) / n
        ε_и = sum(x["ε_итог"] for x in ряд) / n
        низ, верх = бутстреп_отношения(ряд)
        out.append({
            "стадия": стадия, "ошибка": имя, "n": n, "ε_вход": round(ε_в, 3), "ε_ядро": round(ε_я, 3), "ε_итог": round(ε_и, 3),
            "усиление": round(ε_и / ε_в, 3) if ε_в > 1e-9 else None, "усиление_95": [round(низ, 2), round(верх, 2)],
            "после_ядра_к_входу": round(ε_я / ε_в, 3) if ε_в > 1e-9 else None, "после_беседы_к_ядру": round(ε_и / ε_я, 3) if ε_я > 1e-9 else None,
            "лидер_сменился": round(доля("лидер_сменился"), 3), "ложный_лидер": round(доля("ложный_лидер"), 3), "истина_потеряна": round(доля("истина_потеряна"), 3),
            "решение_1_изменилось": round(доля("решение_1_изменилось"), 3), "вопросов_изменилось": round(доля("вопросов_изменилось"), 3),
            "вопросов_в_среднем_больше": round(sum(x["вопросов_разница"] for x in ряд) / n, 2), "вердикт_без_врача": round(доля("вердикт_без_врача"), 3)})
    return out


