def шрифт(имя, размер):
    return ImageFont.truetype(os.path.join(ШРИФТЫ, имя), размер * S)


def цвет_токена(t):
    while t not in ЦВЕТА and t.parent:
        t = t.parent
    return ЦВЕТА.get(t, ЦВЕТА[Name])


def карточка(данные, имя_файла):
    код = данные["код"].split("\n")
    моно, мономужской = шрифт("consola.ttf", 25), шрифт("consolab.ttf", 25)
    гротеск, гротеск_ж = шрифт("segoeui.ttf", 24), шрифт("segoeuib.ttf", 30)
    метка = шрифт("segoeui.ttf", 21)
    шаг = 40 * S
    W = 1800 * S
    поле = 90 * S
    окно_х, окно_у = поле, поле
    окно_w = W - 2 * поле
    шапка = 64 * S
    высота_кода = len(код) * шаг + 70 * S
    подвал = 190 * S
    окно_h = шапка + высота_кода + подвал
    H = окно_h + 2 * поле
    акцент = данные["акцент"]

    # фон: тёмный с цветным свечением
    фон = Image.new("RGB", (W, H), (13, 15, 22))
    свет = Image.new("RGB", (W, H), (0, 0, 0))
    d = ImageDraw.Draw(свет)
    d.ellipse([-W * 0.2, -H * 0.3, W * 0.55, H * 0.55], fill=tuple(int(c * 0.55) for c in акцент))
    d.ellipse([W * 0.5, H * 0.55, W * 1.2, H * 1.3], fill=(40, 70, 190))
    свет = свет.filter(ImageFilter.GaussianBlur(220 * S))
    фон = Image.blend(фон, Image.eval(свет, lambda v: v), 0.55)
    img = фон.convert("RGBA")

    # тень окна
    тень = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    ImageDraw.Draw(тень).rounded_rectangle([окно_х, окно_у + 26 * S, окно_х + окно_w, окно_у + окно_h + 26 * S], 34 * S, fill=(0, 0, 0, 170))
    img.alpha_composite(тень.filter(ImageFilter.GaussianBlur(36 * S)))

    # окно
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([окно_х, окно_у, окно_х + окно_w, окно_у + окно_h], 30 * S, fill=(24, 27, 38), outline=(255, 255, 255, 38), width=2)
    d.rounded_rectangle([окно_х, окно_у, окно_х + окно_w, окно_у + шапка + 30 * S], 30 * S, fill=(31, 35, 48))
    d.rectangle([окно_х, окно_у + шапка, окно_х + окно_w, окно_у + шапка + 30 * S], fill=(24, 27, 38))
    for i, c in enumerate(((255, 95, 86), (255, 189, 46), (39, 201, 63))):
        r = 9 * S
        cx, cy = окно_х + 40 * S + i * 34 * S, окно_у + шапка // 2
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=c)
    d.text((окно_х + окно_w // 2, окно_у + шапка // 2), данные["заголовок"], font=гротеск, fill=(150, 158, 178), anchor="mm")
    # плашка темы справа
    текст_темы = данные["тема"]
    tw = d.textlength(текст_темы, font=метка)
    d.rounded_rectangle([окно_х + окно_w - tw - 70 * S, окно_у + 16 * S, окно_х + окно_w - 24 * S, окно_у + шапка - 14 * S], 16 * S, fill=tuple(int(c * 0.28) for c in акцент))
    d.text((окно_х + окно_w - 47 * S - tw / 2, окно_у + шапка // 2), текст_темы, font=метка, fill=акцент, anchor="mm")

    # код с подсветкой
    x0, y0 = окно_х + 50 * S, окно_у + шапка + 38 * S
    полоса = Image.new("RGBA", (6 * S, высота_кода - 40 * S), акцент + (200,))
    img.alpha_composite(полоса, (окно_х + 22 * S, окно_у + шапка + 20 * S))
    d = ImageDraw.Draw(img)
    # разбираем весь текст, раскладываем по строкам
    y = y0
    x = x0
    for тип, значение in lex(данные["код"], PythonLexer()):
        for кусок in значение.split("\n"):
            pass
        части = значение.split("\n")
        for i, кусок in enumerate(части):
            if i > 0:
                y += шаг
                x = x0
            if кусок:
                f = мономужской if тип in Keyword else моно
                d.text((x, y), кусок, font=f, fill=цвет_токена(тип))
                x += d.textlength(кусок, font=f)

    # подвал: метрики
    py = окно_у + шапка + высота_кода + 18 * S
    d.line([окно_х + 40 * S, py, окно_х + окно_w - 40 * S, py], fill=(255, 255, 255, 30), width=2)
    метрики = данные["метрики"]
    ширина_плашки = (окно_w - 80 * S - (len(метрики) - 1) * 22 * S) / len(метрики)
    for i, (название, значение) in enumerate(метрики):
        bx = окно_х + 40 * S + i * (ширина_плашки + 22 * S)
        by = py + 30 * S
        d.rounded_rectangle([bx, by, bx + ширина_плашки, by + 108 * S], 22 * S, fill=tuple(int(c * 0.16) + 14 for c in акцент), outline=tuple(int(c * 0.55) for c in акцент), width=2)
        d.text((bx + ширина_плашки / 2, by + 40 * S), значение, font=гротеск_ж, fill=акцент, anchor="mm")
        d.text((bx + ширина_плашки / 2, by + 82 * S), название, font=метка, fill=(170, 178, 198), anchor="mm")

    итог = img.convert("RGB").resize((W // S, H // S), Image.LANCZOS)
    os.makedirs(ВЫХОД, exist_ok=True)
    путь = os.path.join(ВЫХОД, имя_файла)
    итог.save(путь, optimize=True)
    return путь


