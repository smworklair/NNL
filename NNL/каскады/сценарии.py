def jl(путь):
    with open(путь, encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def упоминание(термин, статус, уточнение="", кто="нет_данных"):
    return {"термин": термин, "статус": статус, "уточнение": уточнение, "кто_подтвердил": кто}


def разбор_реплики(упоминания, ответ="нет_вопроса", значение="", завершить=False):
    return {"упоминания": [dict(у) for у in упоминания], "ответ_на_вопрос": ответ, "значение": значение, "хочет_завершить": завершить}


class Кэш:
    """Оценки блока по фразам: блок детерминирован, повторять расчёт ни к чему."""

    def __init__(self, блоки):
        self._оценить, self._м = блоки.статьи, {}              # настоящий метод запоминаем сразу: потом стенд подменяет блоки.статьи этим же кэшем

    def __call__(self, фраза):
        if фраза not in self._м:
            self._м[фраза] = self._оценить(фраза)
        return self._м[фраза]


def собрать_случаи(блоки, n=120, зерно=7):
    """Случаи для замера. Каждый: истина (номер статьи), фраза, парафразы и по одной фразе-«помехе» от разных других статей."""
    оценка = Кэш(блоки)
    бенч = [r for r in jl(БЕНЧ) if r["область"] == "здоровье"]
    по_статьям = {}
    for r in бенч:
        по_статьям.setdefault(r["ответ"], []).append(r["вопрос"])
    чистые, ошибочные = [], []
    for r in бенч:
        p, _ = оценка(r["вопрос"])
        верх = max(p, key=p.get)
        (чистые if верх == r["ответ"] and p[верх] >= 0.5 else ошибочные if верх != r["ответ"] else []).append((r["ответ"], r["вопрос"]))
    rnd = random.Random(зерно)
    rnd.shuffle(чистые)
    rnd2 = random.Random(зерно + 1)

    def помеха(исключить):
        while True:
            а, ф = rnd2.choice(чистые)
            if а not in исключить:
                return {"статья": а, "фраза": ф}

    случаи = []
    for i, (а, ф) in enumerate(чистые[:n]):
        исключить = {а}
        отриц = помеха(исключить)
        исключить.add(отриц["статья"])
        чужое = помеха(исключить)
        исключить.add(чужое["статья"])
        фантом = помеха(исключить)
        исключить.add(фантом["статья"])
        подмена = помеха(исключить)
        парафразы = [x for x in по_статьям[а] if x != ф][:3]
        фантом["парафразы"] = [x for x in по_статьям[фантом["статья"]] if x != фантом["фраза"]][:3]
        случаи.append({"id": i, "истина": а, "фраза": ф, "парафразы": парафразы, "отрицаемое": отриц, "чужое": чужое, "фантом": фантом, "подмена": подмена})
    естественные = [{"id": 1000 + i, "истина": а, "фраза": ф, "парафразы": [x for x in по_статьям[а] if x != ф][:3]} for i, (а, ф) in enumerate(ошибочные)]
    return случаи, естественные, оценка


def реплика_человека(с):
    """Текст, который сказал бы человек: жалоба, отрицание и чужая болезнь. Блок читает мешок слов, грамматика не важна."""
    return "%s. Не болел: %s. У брата: %s." % (с["фраза"], с["отрицаемое"]["фраза"], с["чужое"]["фраза"])


def чистый_разбор(с):
    return разбор_реплики([упоминание(с["фраза"], "есть"), упоминание(с["отрицаемое"]["фраза"], "нет"), упоминание(с["чужое"]["фраза"], "чужое")])


