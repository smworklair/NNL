class ФейкAPI:
    """Заменяет клиент.спросить: разбор реплики отдаёт заготовленный (чистый или с внесённой ошибкой), вопросы — пустые (идёт банк), итог и речь — заглушки.
    Досье итога записывается: по нему видно, допущен ли вердикт по категории."""

    def __init__(self):
        self.разбор = None
        self.досье_итога = []
        self.вызовов = {}

    def __call__(self, провайдер, модель, система, история, схема=None, **kw):
        база = {"мс": 0, "токены_вход": 0, "токены_выход": 0, "из_кэша": False, "модель": "фейк", "рассуждение": ""}
        if система == Д.СИСТЕМА_РАЗБОРА:
            роль, ответ = "разбор", {"данные": self.разбор, "текст": json.dumps(self.разбор, ensure_ascii=False)}
        elif система == Д.СИСТЕМА_ВОПРОСОВ:
            роль, ответ = "вопросы", {"данные": {"реакция": "", "вопросы": []}, "текст": ""}
        elif система == Д.СИСТЕМА_ИТОГА:
            роль = "итог"
            self.досье_итога.append(next((x[1] for x in история if x[0] == "user"), ""))
            ответ = {"текст": "Картина по документу такова; это опора для визита к врачу, не диагноз: я не врач."}
        else:
            роль, ответ = "речь", {"текст": "Расскажите подробнее."}
        self.вызовов[роль] = self.вызовов.get(роль, 0) + 1
        return dict(база, **ответ)


class Подмена:
    """Контекст: клиент.спросить заменён на ФейкAPI, банк вопросов — на снимок. После выхода всё как было."""

    def __init__(self, система):
        self.система, self.фейк = система, ФейкAPI()

    def __enter__(self):
        self._спросить, self._банк = К.спросить, self.система.банк
        К.спросить = self.фейк
        self.система.банк = Банк.Банк(self.система.база, СНИМОК_БАНКА)
        return self.фейк

    def __exit__(self, *a):
        К.спросить, self.система.банк = self._спросить, self._банк


# --------------------------------------------------------------------------------- один диалог с честным собеседником
МАКС_ХОДОВ = 10


def ответ_честного(вопрос, истина):
    """Честный собеседник отвечает так, как ответил бы, скорее всего, человек с этой болезнью (или без неё) по таблице самого вопроса:
    статья у него есть — «да», если p(да | есть) ≥ 0,5; статьи нет — «да», только если p(да | нет) ≥ 0,5. Открытый вопрос о значении — «не знаю»."""
    if вопрос.get("вид") != "да_нет":
        return "не_знаю"
    а, б = вопрос["таблица"]
    return "да" if (а if вопрос["статья"] in истина else б) >= 0.5 else "нет"


def провести(система, фейк, с, разбор1, истина, реплика=None, ошибки_ответов=None, подмена_таблицы=None, повторить=True):
    """Диалог: реплика → вопросы ядра → честные ответы, пока ядро не завершит. Если ядро отвечает «открытый вопрос» (кандидатов нет), человек один раз
    повторяет жалобу другими словами (парафраз той же статьи; разбор на этот раз верный) — как сделал бы живой собеседник.
    ошибки_ответов: {номер ответа: что разбор сообщил вместо правды; «__инверсия__» — противоположное правде}. подмена_таблицы: {номер вопроса: (p_да_если_есть, p_да_если_нет)}
    (имитирует завышенную таблицу). Возвращает записи состояния после первого хода и в конце, а также ответы и сессию."""
    сессия = система.сессия()
    сессия.роли = {р: ("фейк", "м") for р in ("разбор", "вопросы", "итог", "речь", "базовая")}
    сессия.кэш = False
    фейк.досье_итога.clear()
    ошибки_ответов = ошибки_ответов or {}
    подмена_таблицы = подмена_таблицы or {}
    фейк.разбор = разбор1
    т = сессия.ход(реплика or реплика_человека(с))
    запись = {"д1": т["действие"], "l1": dict(сессия.ср.l), "действия": [т["действие"]], "ответов": 0, "повторов": 0}
    номер_вопроса = 0
    while not сессия.закончено and len(запись["действия"]) < МАКС_ХОДОВ:
        if т["действие"] == "спросить" and сессия.ср.ожидается is not None:
            вопрос = сессия.ср.ожидается
            таблица_настоящая = tuple(вопрос["таблица"]) if вопрос.get("таблица") else None
            правда = ответ_честного(вопрос, истина)                       # человек отвечает по правде, а не по испорченной таблице
            if номер_вопроса in подмена_таблицы and вопрос.get("вид") == "да_нет":
                вопрос["таблица"] = подмена_таблицы[номер_вопроса]
            передано = ошибки_ответов.get(запись["ответов"], правда) if вопрос.get("вид") == "да_нет" else правда
            if передано == "__инверсия__":
                передано = "нет" if правда == "да" else "да"
            запись.setdefault("ответы", []).append({"статья": вопрос["статья"], "таблица": таблица_настоящая, "таблица_использована": tuple(вопрос["таблица"]) if вопрос.get("таблица") else None,
                                                    "правда": правда, "передано": передано})
            номер_вопроса += 1
            запись["ответов"] += 1
            фейк.разбор = разбор_реплики([], передано, "", False)
            т = сессия.ход({"да": "да", "нет": "нет"}.get(передано, "не знаю"))
        elif т["действие"] == "открытый_вопрос" and повторить and запись["повторов"] == 0:
            слова = (с.get("парафразы") or [с["фраза"]])[0]
            запись["повторов"] += 1
            фейк.разбор = разбор_реплики([упоминание(слова, "есть")])
            т = сессия.ход(слова)
        else:
            break
        запись["действия"].append(т["действие"])
    запись.update(
        lN=dict(сессия.ср.l), вопросов=len(сессия.ср.задано), исход="итог" if сессия.закончено else "тупик",
        вердикт_разрешён=bool(фейк.досье_итога) and "ВЕРДИКТ ПО КАТЕГОРИИ: разрешён" in фейк.досье_итога[-1],
        рейтинг=[(a, round(p, 4)) for a, p in сессия.ср.рейтинг(5)], подтверждено_врачом=сессия.ср.подтверждено_врачом(),
        сессия=сессия)
    return запись
