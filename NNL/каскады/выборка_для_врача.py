# -*- coding: utf-8 -*-
"""Выборка вопросов из банка для ручной проверки (врач, эксперт, внешняя модель). Пишет NNL/каскады/для_проверки/вопросы_на_проверку.md:
готовый к вставке промпт и 25 вопросов (по одному на разные статьи) с цитатой критерия и таблицей вероятностей.
Запуск: python NNL/каскады/выборка_для_врача.py [число вопросов] [зерно]"""
import json
import os
import random
import sys

КАТАЛОГ = os.path.dirname(os.path.abspath(__file__))
ДИАЛОГ = os.path.join(os.path.dirname(КАТАЛОГ), "диалог")
sys.path.insert(0, ДИАЛОГ)
sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
import знания as З  # noqa: E402

ПРОМПТ = """Ты — эксперт по военно-врачебной экспертизе в России. Проверь вопросы, которые мой диалоговый помощник задаёт призывнику, чтобы выявить, относится ли к нему статья Расписания болезней.

ВАЖНО: проверяй по самым свежим данным, а не по памяти. Найди и используй действующую редакцию Расписания болезней (приложение к Положению о военно-врачебной экспертизе, Постановление Правительства РФ № 565 от 04.07.2013 с последними изменениями, включая изменения 2025–2026 годов) и актуальные разъяснения. Для каждой статьи сначала открой действующий текст, потом оценивай вопрос. Если не нашёл актуальный текст статьи, так и скажи, а не додумывай. Укажи дату и источник редакции, которую использовал.

Для каждого вопроса ниже дай ответ по полям:
1. Критерий действительно есть в действующей редакции статьи? (да / нет / изменён) — приведи точную формулировку и пункт.
2. Соответствует ли вопрос критерию? Не искажает ли пороги, термины, пункты? (да / частично / нет)
3. Понятен ли вопрос человеку без медобразования и может ли он честно на него ответить? (да / нет)
4. Проверь таблицу: p(да | статья у человека есть) и p(да | статьи нет). Реалистичны ли эти оценки? Предложи свои числа, если нет. Помни: чем лучше вопрос различает «есть» и «нет», тем больше разрыв.
5. Вердикт: ОК / ИСПРАВИТЬ (дай исправленную формулировку) / УДАЛИТЬ (почему).

В конце дай сводку: сколько ОК, сколько исправить, сколько удалить, и самые частые типы ошибок (устаревшие критерии, неверные пороги, неоднозначные формулировки, нереалистичные таблицы). Отвечай таблицей и коротко, без вступлений. Не ставь диагнозов и не давай юридических советов."""


def главное():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 25
    зерно = int(sys.argv[2]) if len(sys.argv) > 2 else 5
    with open(os.path.join(КАТАЛОГ, "данные", "банк_снимок.json"), encoding="utf-8") as f:
        банк = json.load(f)["статьи"]
    база = З.База()
    рнд = random.Random(зерно)
    ид = sorted(банк, key=int)
    выбранные = рнд.sample(ид, n)
    выбранные.sort(key=int)
    строки = [ПРОМПТ, "", "---", "", "# Вопросы на проверку", ""]
    for i, а in enumerate(выбранные, 1):
        вопросы = [q for q in банк[а]["вопросы"] if q["вид"] == "да_нет" and q.get("таблица")]
        if not вопросы:
            continue
        q = рнд.choice(вопросы)
        таблица = q["таблица"]
        строки += ["## %d. Статья %s. %s" % (i, а, база.статьи[а].название[:160]),
                   "**Вопрос:** %s" % q["текст"],
                   "**Опирается на критерий (цитата из статьи, как её видит помощник):** «%s»" % q["по_критерию"],
                   "**Таблица помощника:** p(ответ «да» | статья у человека есть) = %.2f; p(ответ «да» | статьи нет) = %.2f" % (таблица[0], таблица[1]),
                   "**Тема вопроса:** %s" % q.get("тема", "другое"), ""]
    путь = os.path.join(КАТАЛОГ, "для_проверки")
    os.makedirs(путь, exist_ok=True)
    файл = os.path.join(путь, "вопросы_на_проверку.md")
    with open(файл, "w", encoding="utf-8") as f:
        f.write("\n".join(строки))
    print(файл, "вопросов:", len([s for s in строки if s.startswith("## ")]))


if __name__ == "__main__":
    главное()
