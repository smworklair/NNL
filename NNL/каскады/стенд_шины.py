def опыт_конфликт(профиль, предел, вопросов=2000, зерно=3):
    """Два независимых датчика (верны в 80 %) пишут понятие «факт» знаком: +16 «да», −16 «нет». Читатели ответов «0/1» обучены на шине своего профиля."""
    Матплата, Процессор, Ядро = модули(профиль)
    rng = np.random.default_rng(зерно)
    сила = {"с": 3.0, "с0": 0.8}

    def датчик_выводит(f):
        return [(f if rng.random() < 0.8 else 1 - f) for _ in range(2)]

    def обучить(семантика):
        """V читателя: один вход — значение понятия «факт» после сведения (конфликт → 0 при новой семантике, последний писавший → при старой)."""
        X, Y = [], []
        for _ in range(вопросов):
            f = int(rng.integers(0, 2))
            a, b = датчик_выводит(f)
            знач = lambda y: 16.0 if y == 1 else -16.0       # noqa: E731
            if семантика == "последний":
                x = знач(b)
            else:
                x = 0.0 if a != b else знач(a)
            X.append(x / И.МАСШТАБ_ЧТЕНИЯ)
            Y.append(f if rng.random() < 0.9 else 1 - f)
        X, Y = np.array(X), np.array(Y)
        V = np.zeros((1, 2))
        for _ in range(300):
            z = np.stack([np.zeros_like(X), np.zeros_like(X)], 1) + X[:, None] * V[0][None, :]
            z -= z.max(1, keepdims=True)
            p = np.exp(z)
            p /= p.sum(1, keepdims=True)
            p[np.arange(len(Y)), Y] -= 1
            V -= 0.5 * (X[:, None] * p).sum(0, keepdims=True) / len(Y)
        return V

    семантика = "последний" if профиль == "до" else "сведение"
    V = обучить(семантика)

    def собрать(порядок):
        м, каталог = И.новая_матплата(Матплата)
        for имя in порядок:
            И.записать_блок(м, каталог, имя, ["0", "1"], [], {"0": {"факт": -16.0}, "1": {"факт": 16.0}}, np.zeros((0, 2)))
        И.записать_блок(м, каталог, "читатель", ["0", "1"], ["факт"], {"0": {"читатель:0": 16.0}, "1": {"читатель:1": 16.0}}, V)
        return м
    м = собрать(["датчик1", "датчик2"])
    пр = процессор(профиль, Процессор, м, Ядро(None), предел)
    rng2 = np.random.default_rng(99)
    итог = collections.Counter()
    for _ in range(вопросов):
        f = int(rng2.integers(0, 2))
        a, b = [(f if rng2.random() < 0.8 else 1 - f) for _ in range(2)]
        цель_читателя = f if rng2.random() < 0.9 else 1 - f
        свой = "читатель:%d:с0" % (f if rng2.random() < 0.6 else 1 - f)
        прямой = пр.выполнить("датчик1:%d:с датчик2:%d:с %s" % (a, b, свой))
        обмен = пр.выполнить("датчик1:%d:с датчик2:%d:с %s" % (b, a, свой))      # те же два наблюдения, но датчики поменялись местами
        итог["n"] += 1
        итог["верно"] += прямой["такт2"]["читатель"]["top1"] == str(цель_читателя)
        итог["конфликтов"] += bool(прямой.get("конфликты"))
        итог["расхождение_при_обмене"] += прямой["такт2"]["читатель"]["top1"] != обмен["такт2"]["читатель"]["top1"]
        итог["датчики_расходятся"] += a != b
    return {"точность_читателя": round(итог["верно"] / итог["n"], 3), "датчики_расходятся": round(итог["датчики_расходятся"] / итог["n"], 3),
            "конфликтов_на_шине": round(итог["конфликтов"] / итог["n"], 3), "ответ_меняется_если_датчики_поменять_местами": round(итог["расхождение_при_обмене"] / итог["n"], 3)}


