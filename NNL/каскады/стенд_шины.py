class Искажение:
    """Прокси архитектуры: на такте 1 (пустой срез шины) блок выдаёт заданный неверный лидер с уверенным отрывом, на такте 2 работает как обычно."""

    def __init__(self, арх, цель):
        self.арх, self.цель = арх, цель        # цель: функция(счёты) → ответ, который станет лидером

    def __getattr__(self, k):
        return getattr(self.арх, k)

    def проход2(self, obj, токены, срез):
        s = self.арх.проход2(obj, токены, срез)
        if срез:
            return s
        s = dict(s)
        s[self.цель(s)] = max(s.values()) + 3.0
        return s


def с_искажением(блоки, подмены, действие):
    """Временно подменить arch у блоков; подмены: {имя: цель}."""
    исходные = {}
    try:
        for имя, цель in подмены.items():
            исходные[имя] = блоки[имя].arch
            блоки[имя].arch = Искажение(исходные[имя], цель)
        return действие()
    finally:
        for имя, арх in исходные.items():
            блоки[имя].arch = арх


