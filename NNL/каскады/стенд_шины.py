    с = collections.Counter()
    for r in стыки:
        чист = пр.выполнить(r["текст"])
        for имя in эталон:
            эт = set(r[эталон[имя]])
            с[имя, "такт1_верно"] += чист["такт1"][имя]["top1"] in эт
            с[имя, "такт2_верно"] += чист["такт2"][имя]["top1"] in эт
    результат = {"стыков": len(стыки), "без_ошибок": {имя: {"такт1_верно": с[имя, "такт1_верно"], "такт2_верно": с[имя, "такт2_верно"]} for имя in эталон}}
    внесено = {}
    for источник in эталон:
        сосед = "право" if источник == "здоровье" else "здоровье"
        for как in ("второй", "случайный"):
            счёт = collections.Counter()
            for r in стыки:
                чист = пр.выполнить(r["текст"])
                эт = set(r[эталон[сосед]])

                def цель(s, r=r):
                    упор = sorted(s, key=lambda a: -s[a])
                    return упор[1] if как == "второй" else упор[2 + r["i"] % max(1, len(упор) - 2)]
                ош = с_искажением(м.блоки, {источник: цель}, lambda: пр.выполнить(r["текст"]))
