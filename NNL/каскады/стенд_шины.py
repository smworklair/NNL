def опыт_масштаб(профиль, предел, размеры=(3, 10, 30, 60), вопросов=250, зерна=(0,)):
    Матплата, Процессор, Ядро = модули(профиль)
    строки = []
    for плотность in ("3 писателя", "все"):
        for N in размеры:
            степень = 3 if плотность == "3 писателя" else N - 1
            if N <= 3 and плотность == "3 писателя":
                continue
            счёт = collections.Counter()
            for зерно in зерна:
                мир = И.Мир(N, степень, зерно=зерно)
                мир.обучить(вопросов=2500, шагов=250)
                м = И.собрать_матплату(мир, Матплата)
                пр = процессор(профиль, Процессор, м, Ядро(None), предел)
                читатели = {b: [w for w in range(N) if b in мир.писатели[w]] for b in range(N)}     # кто читает блок b
                rng = np.random.default_rng(100 + зерно)
                for _ in range(вопросов):
                    токены, истина = мир.вопрос(rng)
                    текст = " ".join(токены)
                    чист = пр.выполнить(текст)
                    for b in range(N):
                        счёт["верно_такт1"] += чист["такт1"][мир.имена[b]]["top1"] == str(истина[b])
                        счёт["верно_такт2"] += чист["такт2"][мир.имена[b]]["top1"] == str(истина[b])
                        счёт["блоков"] += 1
                    X = int(rng.integers(0, N))
                    if not читатели[X]:
                        continue

                    def цель(s, X=X, истина=истина):
                        return str((истина[X] + 1 + int(rng.integers(0, И.K - 1))) % И.K)        # любой неверный класс
                    ош = с_искажением(м.блоки, {мир.имена[X]: цель}, lambda: пр.выполнить(текст))
                    счёт["внесений"] += 1
                    счёт["читателей"] += len(читатели[X])
                    for w in читатели[X]:
                        имя = мир.имена[w]
                        верно_было = чист["такт2"][имя]["top1"] == str(истина[w])
                        верно_стало = ош["такт2"][имя]["top1"] == str(истина[w])
                        счёт["вред"] += верно_было and not верно_стало
                        счёт["польза_от_ошибки"] += (not верно_было) and верно_стало
                        счёт["сдвиг"] += ош["такт2"][имя].get("сдвиг_шины", 0.0)
                    счёт["вред_всего_блоков"] += sum(1 for b in range(N) if b != X and чист["такт2"][мир.имена[b]]["top1"] == str(истина[b]) and ош["такт2"][мир.имена[b]]["top1"] != str(истина[b]))
            строки.append({"плотность": плотность, "блоков": N, "писателей_на_читателя": степень,
                           "точность_такт1": round(счёт["верно_такт1"] / счёт["блоков"], 3), "точность_такт2": round(счёт["верно_такт2"] / счёт["блоков"], 3),
                           "внесений": счёт["внесений"], "читателей_у_блока": round(счёт["читателей"] / max(1, счёт["внесений"]), 1),
                           "вред_читателю": round(счёт["вред"] / max(1, счёт["читателей"]), 3), "испорченных_блоков_на_ошибку": round(счёт["вред_всего_блоков"] / max(1, счёт["внесений"]), 2),
                           "сдвиг_среднее": round(счёт["сдвиг"] / max(1, счёт["читателей"]), 2)})
    return строки


def опыт_согласованный_сбой(профиль, предел, N=30, сбоев=(1, 3, 10, 29), вопросов=250):
    """Каждый блок читает всех. m писателей уверенно и согласованно называют не то состояние мира; вред — сколько из остальных верных блоков стали неверными."""
    Матплата, Процессор, Ядро = модули(профиль)
    мир = И.Мир(N, N - 1, зерно=5)
    мир.обучить(вопросов=2500, шагов=250)
    м = И.собрать_матплату(мир, Матплата)
    пр = процессор(профиль, Процессор, м, Ядро(None), предел)
    rng = np.random.default_rng(7)
    строки = []
    for m_ in сбоев:
        счёт = collections.Counter()
        for _ in range(вопросов):
            токены, истина = мир.вопрос(rng)
            текст = " ".join(токены)
            чист = пр.выполнить(текст)
            писавшие = [int(x) for x in rng.choice(N, size=m_, replace=False)]
            ложное_g = int(rng.integers(1, И.K))
            подмены = {мир.имена[b]: (lambda s, b=b, ложное_g=ложное_g: str((int(max(s, key=s.get)) + ложное_g) % И.K)) for b in писавшие}
            ош = с_искажением(м.блоки, подмены, lambda: пр.выполнить(текст))
            for b in range(N):
                if b in писавшие:
                    continue
                было = чист["такт2"][мир.имена[b]]["top1"] == str(истина[b])
                стало = ош["такт2"][мир.имена[b]]["top1"] == str(истина[b])
                счёт["остальных"] += 1
                счёт["вред"] += было and not стало
                счёт["обрезано"] += bool(ош["такт2"][мир.имена[b]].get("обрезано"))
        строки.append({"согласно_ошибаются": m_, "вред_остальным": round(счёт["вред"] / счёт["остальных"], 3), "доля_обрезанных": round(счёт["обрезано"] / счёт["остальных"], 3)})
    return строки


