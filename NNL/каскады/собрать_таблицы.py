# -*- coding: utf-8 -*-
"""Собирает таблицы для ОТЧЁТ.md из результатов стендов (результаты/*.json). Числа не переписываются руками: отчёт берёт их отсюда.
Запуск: python NNL/каскады/собрать_таблицы.py  → печатает markdown в stdout и пишет результаты/таблицы.md"""
import json
import os
import sys

КАТАЛОГ = os.path.dirname(os.path.abspath(__file__))
Р = os.path.join(КАТАЛОГ, "результаты")
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def загрузить(имя):
    with open(os.path.join(Р, имя), encoding="utf-8") as f:
        return json.load(f)


def pct(x):
    return "%.0f %%" % (100 * x)


def рост(r):
    """Во сколько раз ошибка выросла (или упала) после первого учёта: ε в конце беседы / ε сразу после учёта; для ошибок в ответах — к размеру самого ответа."""
    знам = r["ε_ядро"] if r["ε_ядро"] > 1e-9 else r["ε_вход"]
    return r["ε_итог"] / знам if знам > 1e-9 else None


def таблицы():
    до, после = загрузить("диалог_до.json"), загрузить("диалог_после.json")
    out = []
    ключи = [(r["стадия"], r["ошибка"]) for r in до["таблица"]]
    д = {(r["стадия"], r["ошибка"]): r for r in до["таблица"]}
    п = {(r["стадия"], r["ошибка"]): r for r in после["таблица"]}

    out.append("### Таблица 1. Где течёт ошибка (диалог, замер «до»)\n")
    out.append("ε — расстояние между состоянием с ошибкой и чистым (L1 по 88 статьям, нат). «Рост в беседе» = ε в конце беседы / ε сразу после первого учёта "
               "(для ошибок в ответах — к размеру самой ошибки): больше 1 — вопросы и остановка ошибку усилили, меньше 1 — погасили.\n")
    out.append("| стадия | ошибка | ε сразу после учёта | ε в конце | рост в беседе | лидер сменился | истина потеряна | ложный лидер | вердикт без врача |")
    out.append("|---|---|---:|---:|---:|---:|---:|---:|---:|")
    for k in sorted(ключи, key=lambda k: -(д[k]["истина_потеряна"] + д[k]["ложный_лидер"] + д[k]["вердикт_без_врача"])):
        r = д[k]
        out.append("| %s | %s | %s | %.2f | %s | %s | %s | %s | %s |" % (
            k[0], k[1], ("%.2f" % r["ε_ядро"]) if r["ε_ядро"] > 1e-9 else "—", r["ε_итог"], ("×%.1f" % рост(r)) if рост(r) else "—",
            pct(r["лидер_сменился"]), pct(r["истина_потеряна"]), pct(r["ложный_лидер"]), pct(r["вердикт_без_врача"])))

    out.append("\n### Таблица 2. До → после (диалог, %d случаев, одни и те же ошибки в тех же случаях)\n" % после["случаев"])
    out.append("| ошибка | истина потеряна | ложный лидер | вердикт без врача | лидер сменился | вопросов в среднем больше |")
    out.append("|---|---:|---:|---:|---:|---:|")
    for k in sorted(ключи, key=lambda k: -(д[k]["истина_потеряна"] + д[k]["ложный_лидер"] + д[k]["вердикт_без_врача"])):
        a, b = д[k], п[k]
        ячейка = lambda ключ: "%s → %s" % (pct(a[ключ]), pct(b[ключ]))      # noqa: E731
        out.append("| %s | %s | %s | %s | %s | %+.2f → %+.2f |" % (k[1], ячейка("истина_потеряна"), ячейка("ложный_лидер"), ячейка("вердикт_без_врача"), ячейка("лидер_сменился"),
                                                              a["вопросов_в_среднем_больше"], b["вопросов_в_среднем_больше"]))
    out.append("\nЧистый диалог (без ошибок): вопросов в среднем %.2f → %.2f; статья-лидер верна с p≥0,8: %s → %s." % (
        до["чистый_прогон"]["вопросов_среднее"], после["чистый_прогон"]["вопросов_среднее"], pct(до["чистый_прогон"]["истина_лидер_p≥0,8"]), pct(после["чистый_прогон"]["истина_лидер_p≥0,8"])))

    out.append("\n### Таблица 3. Человек поправился (диалог)\n")
    out.append("Первая реплика: «есть»; вторая: «нет, не у меня» или «это у брата»; третья: «что в итоге?». Идеал: от первой улики не осталось ничего «в пользу» статьи, вердикт по категории закрыт.\n")
    out.append("| поправка | остаток улики в пользу статьи, нат | p статьи | врач всё ещё подтверждает | вердикт по категории открыт в итоге |")
    out.append("|---|---:|---:|---:|---:|")
    for название in до["отзыв_улики"]:
        a, b = до["отзыв_улики"][название], после["отзыв_улики"][название]
        out.append("| %s | %.2f → %.2f | %.3f → %.3f | %s → %s | %s → %s |" % (название, a["остаток_улики_нат"], b["остаток_улики_нат"], a["p_истины_после_отзыва"], b["p_истины_после_отзыва"],
                                                                       pct(a["врач_всё_ещё_подтверждает"]), pct(b["врач_всё_ещё_подтверждает"]), pct(a["вердикт_открыт_в_итоге"]), pct(b["вердикт_открыт_в_итоге"])))
    out.append("\nЗависимость от порядка упоминаний в одной реплике (наибольшее расхождение состояний при 5 перестановках, нат): %.3f → %.3f; доля случаев с расхождением %s → %s." % (
        до["порядок_упоминаний"]["наибольшее_расхождение_нат_среднее"], после["порядок_упоминаний"]["наибольшее_расхождение_нат_среднее"],
        pct(до["порядок_упоминаний"]["доля_случаев_с_расхождением"]), pct(после["порядок_упоминаний"]["доля_случаев_с_расхождением"])))

    out.append("\n### Таблица 4. Настоящие ошибки блока «здоровье» (без внесения): реплика — одна жалоба, на которой блок сам ошибается\n")
    out.append("| подгруппа | n | статья-лидер верна | истина потеряна | вопросов | тупик |")
    out.append("|---|---:|---:|---:|---:|---:|")
    for г in до["естественные_ошибки_блока"]:
        a, b = до["естественные_ошибки_блока"][г], после["естественные_ошибки_блока"][г]
        out.append("| %s | %d | %s → %s | %s → %s | %.2f → %.2f | %s → %s |" % (г, a["n"], pct(a["истина_лидер"]), pct(b["истина_лидер"]), pct(a["истина_потеряна"]), pct(b["истина_потеряна"]),
                                                                           a["вопросов_среднее"], b["вопросов_среднее"], pct(a["тупик"]), pct(b["тупик"])))

    if os.path.exists(os.path.join(Р, "диалог_абляция.json")):
        аб = загрузить("диалог_абляция.json")
        имена = list(аб)
        ошибки = list(аб[имена[0]]["ошибки"])
        out.append("\n### Таблица 5. Вклад каждого механизма (диалог, абляция)\n")
        out.append("Что остаётся от ошибки, если механизм выключить: «истина потеряна» / «ложный лидер» / «вердикт без врача» (то, что для этой ошибки главное).\n")
        out.append("| ошибка | " + " | ".join(имена) + " |")
        out.append("|---|" + "---:|" * len(имена))
        for e in ошибки:
            ячейки = []
            for и in имена:
                v = аб[и]["ошибки"][e]
                главное = max(("истина_потеряна", "ложный_лидер", "вердикт_без_врача"), key=lambda ключ: аб[имена[0]]["ошибки"][e][ключ])
                ячейки.append(pct(v[главное]))
            out.append("| %s (%s) | %s |" % (e, max(("истина_потеряна", "ложный_лидер", "вердикт_без_врача"), key=lambda ключ: аб[имена[0]]["ошибки"][e][ключ]).replace("_", " "), " | ".join(ячейки)))
        out.append("| вопросов в чистом диалоге | " + " | ".join("%.2f" % аб[и]["вопросов_в_чистом_диалоге"] for и in имена) + " |")
        out.append("| отзыв «это у брата» (число и врач): p статьи | " + " | ".join("%.2f" % аб[и]["отзыв_«это у брата» (число и врач): p статьи"] for и in имена) + " |")
        out.append("| отзыв «нет, не у меня» (число и врач): вердикт открыт | " + " | ".join(pct(аб[и]["отзыв_«нет, не у меня» (число и врач): вердикт открыт"]) for и in имена) + " |")

    if os.path.exists(os.path.join(Р, "шина_до.json")) and os.path.exists(os.path.join(Р, "шина_после.json")):
        шд, шп = загрузить("шина_до.json"), загрузить("шина_после.json")
        out.append("\n### Таблица 6. Шина: настоящие блоки на 61 стыковом вопросе (до → после)\n")
        out.append("Верных ответов на такте 1 / после такта 2: " + "; ".join(
            "%s %d → %d" % (и, шд["настоящие_блоки"]["без_ошибок"][и]["такт1_верно"], шд["настоящие_блоки"]["без_ошибок"][и]["такт2_верно"]) for и in шд["настоящие_блоки"]["без_ошибок"]) +
            " (после: " + "; ".join("%s %d → %d" % (и, шп["настоящие_блоки"]["без_ошибок"][и]["такт1_верно"], шп["настоящие_блоки"]["без_ошибок"][и]["такт2_верно"]) for и in шп["настоящие_блоки"]["без_ошибок"]) + ").\n")
        out.append("| внесённый неверный вывод | сосед изменился | верно → неверно | стал уверенно неверным |")
        out.append("|---|---:|---:|---:|")
        for к, a in шд["настоящие_блоки"]["внесённая_ошибка"].items():
            b = шп["настоящие_блоки"]["внесённая_ошибка"][к]
            out.append("| %s | %s → %s | %s → %s | %s → %s |" % (к, pct(a["сосед_изменился"]), pct(b["сосед_изменился"]), pct(a["верно_стало_неверно"]), pct(b["верно_стало_неверно"]),
                                                              pct(a["уверенно_неверным_стал"]), pct(b["уверенно_неверным_стал"])))
        out.append("\n### Таблица 7. Шина: рост числа блоков (игрушечный мир, читающие блоки обучены на шумных выводах писателей)\n")
        out.append("Одному блоку внесён уверенный неверный вывод; «вред читателю» — доля читающих его блоков, у которых верный ответ стал неверным.\n")
        out.append("| плотность | блоков | писателей на читателя | точность такт 1 | точность такт 2 | читателей у блока | вред читателю | испорченных блоков на одну ошибку |")
        out.append("|---|---:|---:|---:|---:|---:|---:|---:|")
        for r in шп["масштаб"]:
            out.append("| %s | %d | %d | %.3f | %.3f | %.1f | %s | %.2f |" % (r["плотность"], r["блоков"], r["писателей_на_читателя"], r["точность_такт1"], r["точность_такт2"], r["читателей_у_блока"], pct(r["вред_читателю"]), r["испорченных_блоков_на_ошибку"]))
        out.append("\n### Таблица 8. Шина: согласованный сбой m писателей из 30 (каждый блок читает всех)\n")
        out.append("| m писателей согласно ошибаются | вред остальным блокам: до → после | предел влияния 0,5 | 0,75 | 1,0 | 1,5 |")
        out.append("|---:|---:|---:|---:|---:|---:|")
        свёртка = {}
        for к in ("0.5", "0.75", "1.0", "1.5"):
            f = os.path.join(Р, "шина_предел_%s.json" % к)
            if os.path.exists(f):
                свёртка[к] = {r["согласно_ошибаются"]: r["вред_остальным"] for r in загрузить("шина_предел_%s.json" % к)["согласованный_сбой"]}
        for a, b in zip(шд["согласованный_сбой"], шп["согласованный_сбой"]):
            m = a["согласно_ошибаются"]
            out.append("| %d | %s → %s | %s |" % (m, pct(a["вред_остальным"]), pct(b["вред_остальным"]), " | ".join(pct(свёртка[к][m]) if к in свёртка else "—" for к in ("0.5", "0.75", "1.0", "1.5"))))
        out.append("\nЦена предела влияния на настоящих блоках (верных ответов «здоровья» после такта 2 из 61; без предела 41): " + "; ".join(
            "предел %s → %d" % (к, загрузить("шина_предел_%s.json" % к)["настоящие_блоки"]["без_ошибок"]["здоровье"]["такт2_верно"]) for к in ("0.5", "0.75", "1.0", "1.5") if os.path.exists(os.path.join(Р, "шина_предел_%s.json" % к))) + ".")
        out.append("\n### Таблица 9. Шина: конфликт на общем понятии (два независимых датчика верны в 80 %)\n")
        out.append("| | до | после |")
        out.append("|---|---:|---:|")
        for ключ in ("точность_читателя", "датчики_расходятся", "конфликтов_на_шине", "ответ_меняется_если_датчики_поменять_местами"):
            out.append("| %s | %s | %s |" % (ключ.replace("_", " "), pct(шд["конфликт"][ключ]), pct(шп["конфликт"][ключ])))
    живые = {"до": [], "после": []}
    for профиль in живые:
        for суффикс in ("", "_2", "_3"):
            f = os.path.join(Р, "замер_хода_%s%s.txt" % (профиль, суффикс))
            if os.path.exists(f):
                строки = [l for l in open(f, encoding="utf-8").read().splitlines() if l.startswith("{")]
                if строки:
                    живые[профиль].append(json.loads(строки[-1]))
    if живые["до"] and живые["после"]:
        out.append("\n### Таблица 10. Живой замер хода (настоящий API, сценарии бенчмарка с банком вопросов, без кэша)\n")
        out.append("Те же четыре сценария, модель alibaba:qwen3.8-flash. Каждый профиль прогнан %d раза; разброс между прогонами — разброс самой модели (перегенерация итога охраной чисел и т. п.).\n" % len(живые["до"]))
        out.append("| профиль | вызовов API по прогонам | токенов | время, с | непройденных проверок наблюдения |")
        out.append("|---|---|---|---|---|")
        for профиль in ("до", "после"):
            r = живые[профиль]
            out.append("| %s | %s | %s | %s | %s |" % (профиль, " / ".join(str(x["вызовов"]) for x in r), " / ".join(str(x["токены"]) for x in r),
                                                         " / ".join("%.0f" % (x["мс"] / 1000) for x in r), " / ".join(str(x["плохих_проверок"]) for x in r)))
    return "\n".join(out)


if __name__ == "__main__":
    текст = таблицы()
    print(текст)
    with open(os.path.join(Р, "таблицы.md"), "w", encoding="utf-8") as f:
        f.write(текст + "\n")
    шаблон = os.path.join(КАТАЛОГ, "ОТЧЁТ_шаблон.md")
    if os.path.exists(шаблон):                      # в шаблоне отчёта места таблиц помечены {{Т1}} … {{Т10}}
        куски = {}
        for кусок in текст.split("### Таблица ")[1:]:
            куски["Т" + кусок.split(".", 1)[0]] = "### Таблица " + кусок.rstrip() + "\n"
        отчёт = open(шаблон, encoding="utf-8").read()
        for k, v in куски.items():
            отчёт = отчёт.replace("{{%s}}" % k, v)
        with open(os.path.join(КАТАЛОГ, "ОТЧЁТ.md"), "w", encoding="utf-8") as f:
            f.write(отчёт)
