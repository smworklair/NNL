# -*- coding: utf-8 -*-
"""Очередь на дообучение блоков: фразы, на которых справочник ошибся, не смог выбрать или получил подтверждение от человека.

Зачем. Блоки учились на готовых текстах, а люди пишут иначе («колет сердце», «повышенный сахар»). Каждая такая фраза — урок. Раньше
уроки пропадали: ответ ушёл, сессия забыта. Теперь умный поиск (сервер.умный_поиск) отдаёт сюда события, а человек раз в какое-то время
смотрит свод и решает, что из этого идёт в обучающие данные. Блок сам себя не переучивает: очередь только собирает и размечает кандидатов.

Причины (что именно записано):
  лидер_не_подтвердился — блок назвал статью с p ≥ 0,4, человек на её вопрос ответил «нет»: вероятная ошибка блока (фраза → НЕ эта статья);
  слабая_метка          — до ответов лидер был слабым (p ≤ 0,45, потолок расплывчатой фразы), после ответов p ≥ 0,8: фраза → эта статья (слабая метка, проверить глазами);
  вне_темы              — ворота закрыты и статей нет: либо правда не про здоровье, либо пробел в словаре блока;
  нет_различающего      — вопросов от банка не осталось, а лидер слабый (p < 0,5): банк не различает кандидатов;
  человек_не_знает      — на вопрос банка ответили «не знаю»: вопрос слишком специальный (кандидат на замену в банке).

Хранение: локальный файл очередь_дообучения.jsonl рядом с кодом (в сеть не уходит). Из фразы убираются длинные числа (телефоны, документы).
Запуск:
  python очередь_дообучения.py свод                      — что накопилось, по причинам и частотам
  python очередь_дообучения.py выгрузить [файл]          — кандидаты на разметку: фраза, причина, подсказка; человек заполняет «метка»
  python очередь_в_обучение.py <размеченный.jsonl>       — размеченные фразы → обучающие строки блоков"""
import collections
import json
import os
import re
import sys
import time

sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

ФАЙЛ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "очередь_дообучения.jsonl")
ВКЛЮЧЕНА = True
_ДЛИННОЕ_ЧИСЛО = re.compile(r"\d[\d\s\-]{6,}\d")
_видели = set()                       # поиск при вводе шлёт один запрос много раз: в одном процессе одно и то же событие пишем раз


def нормализовать(фраза):
    return " ".join(re.findall(r"[\w\-\.]+", (фраза or "").lower().replace("ё", "е")))


def _очистить(фраза):
    return _ДЛИННОЕ_ЧИСЛО.sub("№", (фраза or "").strip())[:300]


def записать(фраза, причина, статья=None, **доп):
    """Добавляет событие в очередь. Возвращает True, если записано (повтор в этом процессе и выключенная очередь — False)."""
    ключ = (нормализовать(фраза), причина, статья)
    if not ВКЛЮЧЕНА or not ключ[0] or ключ in _видели:
        return False
    _видели.add(ключ)
    строка = {"t": time.strftime("%Y-%m-%dT%H:%M:%S"), "фраза": _очистить(фраза), "причина": причина, "статья": статья}
    строка.update({к: v for к, v in доп.items() if v is not None})
    try:
        with open(ФАЙЛ, "a", encoding="utf-8") as ф:
            ф.write(json.dumps(строка, ensure_ascii=False) + "\n")
    except OSError:
        return False
    return True


def события_поиска(фраза, до, ответы, вопрос, вне_темы):
    """Решает, что записать по одному результату умного поиска. до: (ид, p) лидера до ответов или None; вопрос — результат следующий_вопрос."""
    записано = []
    if вне_темы:
        if записать(фраза, "вне_темы"):
            записано.append("вне_темы")
        return записано
    if not до or not вопрос:
        return записано
    ид, p0 = до
    р = вопрос.get("р", {})
    for о in ответы:
        if о.get("ответ") == "не_знаю" and записать(фраза, "человек_не_знает", о.get("статья"), вопрос=о.get("текст")):
            записано.append("человек_не_знает")
        if о.get("ответ") == "нет" and о.get("статья") == ид and p0 >= 0.4 and р.get(ид, 1.0) < 0.5 * p0:
            if записать(фраза, "лидер_не_подтвердился", ид, p_до=round(p0, 3), p_после=round(р.get(ид, 0.0), 3), вопрос=о.get("текст")):
                записано.append("лидер_не_подтвердился")
    if ответы and вопрос.get("p_лидера", 0) >= 0.8 and p0 <= 0.45 and вопрос.get("лидер") == ид:
        if записать(фраза, "слабая_метка", ид, p_до=round(p0, 3), p_после=вопрос["p_лидера"], ответов=len(ответы)):
            записано.append("слабая_метка")
    if ответы and "вопроса_нет" in вопрос and вопрос.get("p_лидера", 1.0) < 0.5:
        if записать(фраза, "нет_различающего", вопрос.get("лидер"), p_после=вопрос.get("p_лидера")):
            записано.append("нет_различающего")
    return записано


def прочитать(путь=None):
    путь = путь or ФАЙЛ
    if not os.path.exists(путь):
        return []
    with open(путь, encoding="utf-8") as ф:
        return [json.loads(с) for с in ф if с.strip()]


def свести(строки=None):
    """{причина: [(фраза, статья, сколько раз), ...]} по убыванию частоты."""
    строки = прочитать() if строки is None else строки
    группы = collections.defaultdict(collections.Counter)
    for с in строки:
        группы[с["причина"]][(нормализовать(с["фраза"]), с.get("статья"))] += 1
    return {п: [(ф, ст, n) for (ф, ст), n in c.most_common()] for п, c in группы.items()}


def выгрузить(путь):
    """Кандидаты на разметку. Предположение системы — только подсказка; решает человек, заполняя поле «метка»
    («34», «34,35» — статьи; «право:тема»; «вне» — не про здоровье и не про права; пусто — пропустить). Дальше: очередь_в_обучение.py."""
    правила = {"слабая_метка": "статья", "лидер_не_подтвердился": "не_статья", "вне_темы": "не_здоровье_или_пробел", "нет_различающего": "уточнить"}
    n = 0
    with open(путь, "w", encoding="utf-8") as ф:
        for п, спис in свести().items():
            if п not in правила:
                continue
            for фраза, ст, раз in спис:
                подсказка = ст if п == "слабая_метка" else None
                ф.write(json.dumps({"фраза": фраза, "причина": п, "статья": ст, "предположение": правила[п], "раз": раз,
                                    "метка_подсказка": подсказка, "метка": None}, ensure_ascii=False) + "\n")
                n += 1
    return n


if __name__ == "__main__":
    команда = sys.argv[1] if len(sys.argv) > 1 else "свод"
    if команда == "свод":
        с = свести()
        if not с:
            print("очередь пуста: %s" % ФАЙЛ)
        for п, спис in с.items():
            print("%s — %d фраз" % (п, len(спис)))
            for ф, ст, n in спис[:10]:
                print("   %s%s  ×%d" % (ф, " → ст.%s" % ст if ст else "", n))
    elif команда == "выгрузить":
        out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(ФАЙЛ), "фразы_на_разметку.jsonl")
        print("выгружено %d кандидатов → %s" % (выгрузить(out), out))
    else:
        print(__doc__)
