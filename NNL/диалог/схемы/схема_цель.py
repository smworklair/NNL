# -*- coding: utf-8 -*-
"""Целевая архитектура NNL: куда движется система. Без привязки к предметной области.
У каждого элемента пометка: есть · в работе · цель (по состоянию кода на дату в подписи).
Запуск: python NNL/диалог/схемы/схема_цель.py  →  схема_цель.png и .svg рядом со скриптом."""
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import Circle, FancyBboxPatch, Wedge  # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

ПАПКА = os.path.dirname(os.path.abspath(__file__))
UNIT, DPI = 0.07, 150
plt.rcParams["font.family"] = "Segoe UI"
plt.rcParams["svg.fonttype"] = "path"
W, H = 330, 226
ТЕКСТ = "#1A1A1A"
FS_З, FS_Т, FS_М = 11.2, 10.2, 9.2

# (фон полосы, акцент)
ЦВЕТА = {"прил": ("#F1F1F1", "#3A3A3A"), "язык": ("#FCE6DA", "#A8431D"), "ядро": ("#DCEAF9", "#1D5CA6"), "блоки": ("#E7E3F9", "#4A3FA6"),
         "фабрика": ("#DDF2E7", "#1B7A4B"), "набл": ("#FFF0CC", "#8A5F00")}
СТАТУС = {"есть": "#1B9E5A", "работа": "#E0A000", "цель": "#9A9A9A"}

_fig = plt.figure(figsize=(4, 4), dpi=DPI)
_rend = _fig.canvas.get_renderer()
ПРЕДУПРЕЖДЕНИЯ = []


def ширина(s, fs, bold=False):
    t = _fig.text(0, 0, s, fontsize=fs, fontweight="bold" if bold else "normal")
    w = t.get_window_extent(_rend).width / DPI / UNIT
    t.remove()
    return w


def перенос(s, fs, макс, bold=False):
    out = []
    for абзац in s.split("\n"):
        тек = ""
        for слово in абзац.split():
            проба = (тек + " " + слово).strip()
            if ширина(проба, fs, bold) <= макс or not тек:
                тек = проба
            else:
                out.append(тек)
                тек = слово
        out.append(тек)
    return out


def лш(fs):
    return fs * 1.28 / 72 / UNIT


def плашка(ax, x, y, w, h, fc, ec, lw=1.2, ls="-", r=2.0, z=2):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle=f"round,pad=0,rounding_size={r}", fc=fc, ec=ec, lw=lw, ls=ls, zorder=z))


def метка_статуса(ax, x, y, статус):
    """Кружок: заполнен — есть, половина — в работе, пустой — цель."""
    цв = СТАТУС[статус]
    r = 1.9
    ax.add_patch(Circle((x, y), r, fc="white", ec=цв, lw=1.4, zorder=6))
    if статус == "есть":
        ax.add_patch(Circle((x, y), r, fc=цв, ec=цв, lw=1.4, zorder=7))
    elif статус == "работа":
        ax.add_patch(Wedge((x, y), r, 90, 270, fc=цв, ec=цв, lw=0.5, zorder=7))


def узел(ax, x, y, w, h, заг, под, ключ, статус, жирно=False):
    фон, ак = ЦВЕТА[ключ]
    плашка(ax, x, y, w, h, "white", ак, lw=1.9 if жирно else 1.2, z=3)
    строки_з = перенос(заг, FS_Т + 0.8, w - 9, True)
    строки_п = перенос(под, FS_М, w - 5) if под else []
    нужно = 2.2 + len(строки_з) * лш(FS_Т + 0.8) + len(строки_п) * лш(FS_М) + 1.6
    if нужно > h + 0.2:
        ПРЕДУПРЕЖДЕНИЯ.append("не помещается: %s (нужно %.1f, есть %.1f)" % (заг, нужно, h))
    yy = y + 2.2
    for s in строки_з:
        ax.text(x + 2.6, yy + лш(FS_Т + 0.8) / 2, s, fontsize=FS_Т + 0.8, fontweight="bold", color=ак, va="center", zorder=5)
        yy += лш(FS_Т + 0.8)
    for s in строки_п:
        ax.text(x + 2.6, yy + лш(FS_М) / 2 + 0.2, s, fontsize=FS_М, color="#333333", va="center", zorder=5)
        yy += лш(FS_М)
    метка_статуса(ax, x + w - 3.2, y + 3.4, статус)


def полоса(ax, x, y, w, h, ключ, заг, подпись=""):
    фон, ак = ЦВЕТА[ключ]
    плашка(ax, x, y, w, h, фон, ак, lw=1.5, z=1, r=2.6)
    ax.text(x + 3.2, y + 4.2, заг, fontsize=FS_З + 0.6, fontweight="bold", color=ак, va="center", zorder=5)
    if подпись:
        ax.text(x + 3.2 + ширина(заг, FS_З + 0.6, True) + 3, y + 4.4, подпись, fontsize=FS_М, color="#555555", va="center", zorder=5)


def стрелка(ax, p1, p2, цвет="#555555", две=False, ls="-"):
    ax.annotate("", xy=p2, xytext=p1, arrowprops=dict(arrowstyle="<|-|>" if две else "-|>", color=цвет, lw=1.5, shrinkA=0, shrinkB=0, mutation_scale=12, ls=ls), zorder=4)


def рисовать():
    fig = plt.figure(figsize=(W * UNIT, H * UNIT), dpi=DPI, facecolor="white")
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, W)
    ax.set_ylim(H, 0)
    ax.axis("off")

    ax.text(8, 9, "NNL: целевая архитектура", fontsize=21, fontweight="bold", color=ТЕКСТ, va="center")
    ax.text(8, 17.2, "Куда движется система. Предметной области здесь нет: она живёт только в блоках, данных и приложениях.", fontsize=10.5, color="#555555", va="center")
    # легенда
    lx = 232
    ax.text(lx - 3, 9, "Статус на 12.10.2026:", fontsize=9.2, color="#555555", va="center", ha="right")
    for i, (ст, подпись) in enumerate([("есть", "есть"), ("работа", "в работе"), ("цель", "цель")]):
        x = lx + i * 27
        метка_статуса(ax, x, 9, ст)
        ax.text(x + 4, 9, подпись, fontsize=9.4, color=ТЕКСТ, va="center")

    X0, WM = 8, 214
    XR, WR = 232, 90

    # ---------- A. приложения
    полоса(ax, X0, 28, WM, 23, "прил", "Приложения", "используют NNL, в архитектуру не входят")
    чипы = [("Диалог", "есть"), ("Документы пользователя", "цель"), ("Агент, который сам зовёт блоки", "цель"), ("Другие области", "цель")]
    wч = (WM - 8 - 3 * 3) / 4
    for i, (т, ст) in enumerate(чипы):
        узел(ax, X0 + 4 + i * (wч + 3), 36, wч, 12, т, "", "прил", ст)

    # ---------- B. язык
    полоса(ax, X0, 56, WM, 31, "язык", "Язык", "внешняя модель только говорит и слушает")
    wb = (WM - 8 - 2 * 4) / 3
    узел(ax, X0 + 4, 65, wb, 19, "Слушатель", "реплика → факты. Видит только реплику", "язык", "есть")
    узел(ax, X0 + 4 + (wb + 4), 65, wb, 19, "Рассказчик", "досье → текст. Ничего не ищет и не решает", "язык", "есть")
    узел(ax, X0 + 4 + 2 * (wb + 4), 65, wb, 19, "Охрана вывода", "числа, ссылки, запреты. Проверка по источнику", "язык", "есть")

    # ---------- C. ядро решений
    полоса(ax, X0, 92, WM, 54, "ядро", "Ядро решений", "быстрое, детерминированное, без вызовов модели")
    wc2 = (WM - 8 - 4) / 2
    узел(ax, X0 + 4, 101, wc2, 15, "Маршрутизатор", "выбирает, каких блоков спросить: не всех, а нужных", "ядро", "цель")
    узел(ax, X0 + 4 + wc2 + 4, 101, wc2, 15, "Процессор тактов", "такт 1 в изоляции, такт 2 по шине", "ядро", "работа")
    wc3 = (WM - 8 - 2 * 4) / 3
    узел(ax, X0 + 4, 120, wc3, 22, "Ядро причинности", "консенсус, конфликты, предел влияния такта 2", "ядро", "работа")
    узел(ax, X0 + 4 + wc3 + 4, 120, wc3, 22, "Решатель", "калибровка, порог, честное «не знаю»", "ядро", "работа")
    узел(ax, X0 + 4 + 2 * (wc3 + 4), 120, wc3, 22, "Состояние", "журнал улик, пересчёт, потолок уверенности", "ядро", "работа")

    # ---------- D. реестр блоков
    полоса(ax, X0, 151, WM, 42, "блоки", "Реестр блоков", "независимые, с паспортом, подключаются на ходу")
    wk = (WM - 8 - 3 * 3) / 4
    карточки = [("Блок знаний", "документ или область", "есть"), ("Блок навыка", "стиль, формулировки", "есть"), ("Блок проверки", "независимый контролёр", "цель"), ("… N", "добавляются рядом", "цель")]
    for i, (т, п, ст) in enumerate(карточки):
        узел(ax, X0 + 4 + i * (wk + 3), 160, wk, 19, т, п, "блоки", ст)
    ax.text(X0 + 4, 186.6, "паспорт · версия · sha256 · калибровка · метрики качества.  Откат версии. На такте 1 блок не видит соседей.", fontsize=FS_М, color="#444444", va="center", zorder=5)
    метка_статуса(ax, X0 + WM - 5, 186.6, "работа")

    # ---------- F. фабрика блоков
    полоса(ax, XR, 28, WR, 165, "фабрика", "Фабрика блоков", "")
    ax.text(XR + 3.2, 37.4, "новый документ → новый блок", fontsize=FS_М, color="#555555", va="center", zorder=5)
    шаги = [("Данные", "документ или область: сырьё", "есть"), ("Вопросы и разметка", "реальные и синтетические примеры", "работа"), ("Обучение", "новый блок, старые заморожены", "есть"),
            ("Калибровка", "оценки сопоставимы с соседями", "цель"), ("Линтер и гейт ε", "соседи меняются не больше ε", "работа"), ("Публикация", "версия в реестр, откат", "цель")]
    yy = 42
    ys = []
    for i, (т, п, ст) in enumerate(шаги):
        узел(ax, XR + 4, yy, WR - 8, 17.2, "%d  %s" % (i + 1, т), п, "фабрика", ст)
        ys.append(yy)
        if i < len(шаги) - 1:
            стрелка(ax, (XR + WR / 2, yy + 17.2), (XR + WR / 2, yy + 21.2), ЦВЕТА["фабрика"][1])
        yy += 21.2
    # банки артефактов
    узел(ax, XR + 4, yy + 1.5, WR - 8, 17.2, "Банки артефактов", "вопросы и таблицы, подготовленные заранее", "фабрика", "есть")

    # ---------- E. наблюдение
    полоса(ax, 8, 199, 314, 23, "набл", "Наблюдение", "каждый шаг записан и проверяется независимо от модели")
    чипы = [("След", "кто, что, мс, вход, выход", "есть"), ("Журнал", "нажатия и шаги по сессии", "есть"), ("Аудит", "6 проверок кодом, без модели-судьи", "есть"), ("Бенчмарки", "цена, скорость, границы входа", "есть"),
            ("Ошибки → примеры", "замкнутый цикл обучения", "цель")]
    wn = (314 - 8 - 4 * 3) / 5
    for i, (т, п, ст) in enumerate(чипы):
        узел(ax, 12 + i * (wn + 3), 206, wn, 14.2, т, п, "набл", ст)

    # ---------- стрелки
    cx = X0 + WM / 2
    for a, b in [(51, 56), (87, 92), (146, 151)]:
        стрелка(ax, (cx, a), (cx, b), "#555555", две=(a == 146))
    # фабрика → реестр
    yb = ys[5] + 8.6
    стрелка(ax, (XR, yb), (X0 + WM, yb), ЦВЕТА["фабрика"][1])
    # наблюдение → фабрика (цикл)
    стрелка(ax, (XR + WR - 8, 199), (XR + WR - 8, 193.4), ЦВЕТА["набл"][1], ls=(0, (3, 2)))
    ax.text(XR + WR - 11.5, 196.2, "ошибки становятся данными", fontsize=FS_М - 0.4, color=ЦВЕТА["набл"][1], ha="right", va="center", zorder=5)

    for расш in ("png", "svg"):
        путь = os.path.join(ПАПКА, "схема_цель." + расш)
        fig.savefig(путь, dpi=DPI, facecolor="white")
        print("записано:", путь)
    for п in ПРЕДУПРЕЖДЕНИЯ:
        print("ВНИМАНИЕ:", п)


if __name__ == "__main__":
    рисовать()
