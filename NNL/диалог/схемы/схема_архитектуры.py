"""Схема архитектуры NNL (Neural Network Lego): пять слоёв, без привязки к предметной области.

Нарисована по NNL/README.md, матплата.py, процессор.py, ядро.py, решатель.py, СТАНДАРТ_БЛОКА.md и тесту тест_системы.py.
Диалог, байесовский учёт и внешняя модель в архитектуру NNL не входят: это приложение поверх неё.
Запуск: python NNL/диалог/схемы/схема_архитектуры.py  →  схема_архитектуры.png и .svg рядом со скриптом."""
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import Circle, FancyBboxPatch  # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

ПАПКА = os.path.dirname(os.path.abspath(__file__))
UNIT, DPI = 0.07, 150
plt.rcParams["font.family"] = "Segoe UI"
plt.rcParams["svg.fonttype"] = "path"
ТЕКСТ = "#1A1A1A"
FS_З, FS_Т, FS_М = 12.5, 10.2, 9.4

_fig = plt.figure(figsize=(4, 4), dpi=DPI)
_rend = _fig.canvas.get_renderer()


def ширина(s, fs, bold=False):
    t = _fig.text(0, 0, s, fontsize=fs, fontweight="bold" if bold else "normal")
    w = t.get_window_extent(_rend).width / DPI / UNIT
    t.remove()
    return w


def перенос(s, fs, макс, bold=False):
    out = []
    for абзац in s.split("\n"):
        тек = ""
        for слово in абзац.split():
            проба = (тек + " " + слово).strip()
            if ширина(проба, fs, bold) <= макс or not тек:
                тек = проба
            else:
                out.append(тек)
                тек = слово
        out.append(тек)
    return out


def лш(fs):
    return fs * 1.3 / 72 / UNIT


W = 300
X0, ШИР = 8, 196           # левая колонка со слоями
XR, ШИР_R = 214, 78        # правая колонка
СЛОИ = [("#ECECEC", "#3A3A3A"), ("#E5E2F8", "#4A3FA6"), ("#DAE9F9", "#1D5CA6"), ("#DAF0E3", "#1B7A4B"), ("#FFEFC8", "#8A5F00")]


def плашка(ax, x, y, w, h, fc, ec, lw=1.3, ls="-", r=1.8, z=2):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle=f"round,pad=0,rounding_size={r}", fc=fc, ec=ec, lw=lw, ls=ls, zorder=z))


def текст_блоком(ax, x, y, w, строки_спец, fs, цвет=ТЕКСТ, bold=False, маркер=None):
    """Пишет абзацы с переносом. Возвращает y после текста."""
    for s in строки_спец:
        строки = перенос(s, fs, w - (3 if маркер else 0), bold)
        for i, л in enumerate(строки):
            if маркер and i == 0:
                ax.text(x, y + лш(fs) / 2, маркер, fontsize=fs, color=цвет, va="center", zorder=5)
            ax.text(x + (3 if маркер else 0), y + лш(fs) / 2, л, fontsize=fs, color=цвет, va="center", fontweight="bold" if bold else "normal", zorder=5)
            y += лш(fs)
        y += 0.7
    return y


def высота_текста(строки_спец, fs, w, bold=False, маркер=None):
    return sum(len(перенос(s, fs, w - (3 if маркер else 0), bold)) * лш(fs) + 0.7 for s in строки_спец)


def стрелка(ax, p1, p2, цвет="#444444", ls="-"):
    ax.annotate("", xy=p2, xytext=p1, arrowprops=dict(arrowstyle="-|>", color=цвет, lw=1.5, shrinkA=0, shrinkB=0, mutation_scale=12, ls=ls), zorder=4)


