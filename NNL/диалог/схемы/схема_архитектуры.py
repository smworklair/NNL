    h3_т = (max(len(перенос(такт1.split('. ', 1)[1], FS_Т, w_т - 4)), len(перенос(такт2.split('. ', 1)[1], FS_Т, w_т - 4))) + 1) * лш(FS_Т) + 5
    h3 = h3_т + 2 + высота_текста(пункты_3, FS_Т, w_внутр, маркер="•")
    h4 = высота_текста(пункты_4, FS_Т, w_внутр, маркер="•")
    h5 = высота_текста(пункты_5, FS_Т, w_внутр, маркер="•")

