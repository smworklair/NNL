    такт1 = "Такт 1. Каждый блок отвечает при пустой шине. Считается уверенность: margin = s(1) − s(2) (лучший счёт минус второй)."
    такт2 = "Такт 2. Уверенные блоки пишут свой вывод на шину. Блоки, которые читают шину, отвечают заново."
