def собрать():
    пад, межстр = 2.0, 6.5
    y = 22.0
    разм = {}
    расклад = []
    for r in СТРОКИ:
        if "шапка" in r:
            расклад.append(dict(r, y=y, h=7.5))
            y += 7.5 + 3.0
            continue
        hs = []
        for ид, дор, ном, заг, под in r["узлы"]:
            строк_з = перенос(заг, FS_ЗАГ, ШИР_УЗЛА - 2 * пад - 1, True)
            строк_п = перенос(под, FS_ПОД, ШИР_УЗЛА - 2 * пад)
            h = 2 * пад + len(строк_з) * высота_строки(FS_ЗАГ) + len(строк_п) * высота_строки(FS_ПОД) + 0.6
            hs.append(h)
            разм[ид] = dict(дор=дор, ном=ном, з=строк_з, п=строк_п, h=h)
        hп = 0
        if r.get("прим"):
            hп = len(перенос(r["прим"][1], FS_ПРИМ, ШИР_ПРИМЕЧАНИЙ - 8)) * высота_строки(FS_ПРИМ) + 2
        hкр = 0
        if r.get("решение"):
            hкр = sum(len(перенос(t, FS_ПОД, 2 * ШИР_ДОРОЖКИ - 6 - 9)) for _, t in КРИТЕРИИ) * высота_строки(FS_ПОД) + 2.2 * len(КРИТЕРИИ) + 4.6
        h = max(max(hs), hп, hкр)
        for (ид, *_), hh in zip(r["узлы"], hs):
            разм[ид].update(y=y, строка_h=h, yc=y + h / 2)
        расклад.append(dict(r, y=y, h=h))
        y += h + межстр
    return расклад, разм, y


