var ПОМ_ХРАНИЛИЩЕ = 'справка_помощник', ПОМ_СЕКРЕТ = 'справка_ключ';
var помощник = (function(){
  var о = {режим:null, провайдер:'', модель:''};
  try{
    var с = JSON.parse(localStorage.getItem(ПОМ_ХРАНИЛИЩЕ) || 'null');
    if(с && typeof с === 'object'){
      if(['nnl','свой','сервер'].indexOf(с.режим) !== -1) о.режим = с.режим;
      о.провайдер = String(с.провайдер || ''); о.модель = String(с.модель || '');
    }
  }catch(еП){}
  return о;
})();
var списокПровайдеров = null;      // ответ /api/провайдеры; null — ещё не знаем или сервер без подключения ключа
function ключПомощника(){ try{ return localStorage.getItem(ПОМ_СЕКРЕТ) || ''; }catch(еК){ return ''; } }
function сохранитьПомощника(){ try{ localStorage.setItem(ПОМ_ХРАНИЛИЩЕ, JSON.stringify(помощник)); }catch(еС){} }
function серверИмеетКлючи(){ return !!(списокПровайдеров && списокПровайдеров.some(function(п){ return п.ключ_на_сервере; })); }
function режимПомощника(){
  var р = помощник.режим;
  if(р === 'свой' && !(ключПомощника() && помощник.провайдер && помощник.модель)) р = null;
  if(р === 'сервер' && списокПровайдеров && !серверИмеетКлючи()) р = null;
  if(р) return р;
  return (списокПровайдеров && !серверИмеетКлючи()) ? 'nnl' : 'сервер';
}
function заголовкиХода(){
  if(режимПомощника() !== 'свой') return {};
  return {'X-NNL-Provider': помощник.провайдер, 'X-NNL-Model': помощник.модель, 'X-NNL-Key': ключПомощника()};
}
function режимЗапроса(){ return режимПомощника() === 'nnl' ? 'nnl' : БЭК_РЕЖИМ; }
function описаниеПомощника(){
  var р = режимПомощника();
  if(р === 'nnl') return {имя:'Только ядро NNL', под:'без модели и без ключа'};
  if(р === 'свой') return {имя:'NNL + моя модель', под:помощник.провайдер+' · '+помощник.модель};
  return {имя:'NNL + модель сервера', под:'режим стенда'};
}
