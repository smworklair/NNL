function отправить(){
  var т = реплика.value.trim();
  if(!т || состояние.фаза === 'думает') return;
  var х = {р:т, фаза:'думает', итог:null};
  список.push(х);
  состояние = {фаза:'думает', реплика:т, итог:null};
  реплика.value = '';
  авторазмер();
  рендер();
  запросХода(т).then(function(итог){
    if(состояние.фаза !== 'думает' || состояние.реплика !== т || х.р !== т) return;
    х.фаза = 'итог'; х.итог = итог;
    состояние = {фаза:'итог', реплика:т, итог:итог};
    рендер();
    сохранить(т, итог);
  }).catch(function(е){
    if(состояние.фаза !== 'думает' || состояние.реплика !== т || х.р !== т) return;
    х.фаза = 'ошибка';
    х.причина = (е && !(е instanceof TypeError)) ? String(е.message || '').slice(0, 160) : '';
    состояние = {фаза:'ошибка', реплика:т, итог:null};
    реплика.value = т;
    авторазмер();
    рендер();
  });
}

