function времяСтр(ts){
  var д = new Date(ts), теперь = new Date();
  var чч = ('0'+д.getHours()).slice(-2), мм = ('0'+д.getMinutes()).slice(-2);
  var день = 24*60*60*1000;
  var начало = new Date(теперь.getFullYear(), теперь.getMonth(), теперь.getDate()).getTime();
  if(ts >= начало) return 'сегодня, '+чч+':'+мм;
  if(ts >= начало - день) return 'вчера, '+чч+':'+мм;
  return ('0'+д.getDate()).slice(-2)+'.'+('0'+(д.getMonth()+1)).slice(-2)+' '+чч+':'+мм;
}

