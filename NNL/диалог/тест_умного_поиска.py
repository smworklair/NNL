# -*- coding: utf-8 -*-
"""Тест умного поиска справочника (сервер.умный_поиск): числа из слов → расчёты, пункт вместо статьи, потолок уверенности на расплывчатых фразах.
Без сети и без моделей: работают только блоки NNL и текст Расписания.
Запуск: python NNL/диалог/тест_умного_поиска.py"""
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
import клиент as К  # noqa: E402
К.КЭШ_ФАЙЛ = os.path.join(tempfile.mkdtemp(prefix="nnl_поиск_"), "кэш.jsonl")
import диалог as Д  # noqa: E402
import сервер as S  # noqa: E402
import очередь_дообучения as Оч  # noqa: E402
Оч.ВКЛЮЧЕНА = False                       # тестовые фразы в настоящую очередь не пишем

S.СИСТЕМА = Д.Система()
ошибки = []


def проверить(что, условие, подробность=""):
    print(("  ок   " if условие else "  ОШИБКА ") + что + ("" if условие else "  " + str(подробность)))
    if not условие:
        ошибки.append(что)


def поиск(q):
    return S.умный_поиск(q)


def расчёт(р, ид):
    return next((х for х in р["числа"] if х["ид"] == ид), None)


print("числа из слов:")
for q in ("минус 7", "близорукость -7,5", "Сам решил, что минус семь", "у меня 7 дптр", "очки минус 3 с половиной"):
    р = расчёт(поиск(q), "34")
    проверить("диоптрии из «%s»" % q, р is not None, поиск(q)["числа"])
р = расчёт(поиск("минус 7"), "34")
проверить("−7 → пункт «в»", р["результат"]["пункт"] == "в", р)
проверить("−3,5 → пункт «г»", расчёт(поиск("очки минус 3 с половиной"), "34")["результат"]["пункт"] == "г")
for q in ("давление 150/95", "10-12 дней", "хочу в отпуск", "мне 18 лет"):
    проверить("нет ложных расчётов: «%s»" % q, not поиск(q)["числа"], поиск(q)["числа"])
р = расчёт(поиск("правое ухо не слышит, левое слышит шёпот на 3 метрах"), "40")
проверить("слух: одно ухо не слышит, другое 3 м → пункт «б»", р and р["результат"]["пункт"] == "б", р)
р = расчёт(поиск("шёпот 2 м"), "40")
проверить("слух: сторона не названа → обе одинаково, пометка есть", р and р["результат"]["пункт"] == "в" and "не названа" in р["заметка"], р)
р = расчёт(поиск("рост 148, вес 44"), "86")
проверить("рост и масса ниже порога → пункт «б»", р and р["результат"]["пункт"] == "б", р)
проверить("рост и масса названы → есть и ИМТ", расчёт(поиск("рост 148, вес 44"), "13") is not None)
проверить("рост в норме → расчёт по ст. 86 не показывается", расчёт(поиск("вешу 58 кг рост 175 см"), "86") is None)
р = расчёт(поиск("мой рост 140"), "86")
проверить("назван только рост → масса помечена как принятая", р and "Масса не названа" in р["заметка"], р)

print("пункт вместо статьи:")
р = поиск("тяжёлая бронхиальная астма")
проверить("ст. 52 найдена", р["статьи"] and р["статьи"][0]["ид"] == "52", р["статьи"][:1])
проверить("ближайший пункт — «а» (тяжёлая степень)", р["статьи"][0].get("пункт") == "а", р["статьи"][0])
р = поиск("диабет")
проверить("без явного совпадения с пунктом пункт не выдумывается", "пункт" not in р["статьи"][0], р["статьи"][0])

print("честность на расплывчатых фразах:")
р = поиск("колет сердце")
проверить("короткая фраза без слов врача и чисел → уверенность не выше 0,45", р["статьи"][0]["p_показ"] <= 0.45 and р["статьи"][0]["ограничено"], р["статьи"][0])
проверить("при этом есть подсказка что добавить", "добавьте" in р["подсказка"], р["подсказка"])
р = поиск("диабет")
проверить("«диабет» — слово есть в тексте статьи → потолка нет", р["статьи"][0]["ид"] == "13" and not р["статьи"][0]["ограничено"] and р["статьи"][0]["p_показ"] >= 0.8, р["статьи"][0])
р = поиск("давление дома 150 на 95")
проверить("есть цифры → потолка нет", р["статьи"] and not р["статьи"][0]["ограничено"], р["статьи"][:1])
р = поиск("окулист написал близорукость")
проверить("слова врача → потолка нет", р["статьи"] and not р["статьи"][0]["ограничено"], р["статьи"][:1])
проверить("слова врача → подтверждение «врач»", поиск("окулист написал близорукость")["подтверждение"] == "врач")
проверить("без слов врача → подтверждение «слова»", поиск("колет сердце")["подтверждение"] == "слова")
р = поиск("хочу в отпуск")
проверить("вне темы остаётся вне темы", р["вне_темы"], р)
р = поиск("сколько служить")
проверить("правовая тема находится", р["право"] and not р["статьи"], р)

print("\nОШИБОК: %d" % len(ошибки))
sys.exit(1 if ошибки else 0)
