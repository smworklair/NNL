class Внешний(http.server.BaseHTTPRequestHandler):
    def do_POST(self):
        данные = json.loads(self.rfile.read(int(self.headers.get("Content-Length", 0) or 0)).decode("utf-8") or "{}")
        ЗАПРОСЫ.append(данные)
        система = ((данные.get("messages") or [{}])[0].get("content")) or ""
        if "думать" in данные:                               # провайдер не принимает просьбу о рассуждении
            тело = json.dumps({"error": {"message": "unknown field"}}).encode("utf-8")
            self.send_response(400)
        else:
            схема = (((данные.get("response_format") or {}).get("json_schema") or {}).get("schema") or {}).get("properties") or {}
            сообщение = {"role": "assistant"}
            if "упоминания" in схема:
                сообщение["content"] = json.dumps({"упоминания": [dict(ФЕЙК_УПОМИНАНИЕ)],
                                                   "ответ_на_вопрос": "нет_вопроса", "значение": "-7", "хочет_завершить": False}, ensure_ascii=False)
                сообщение["reasoning_content"] = ДУМЫ
            elif "вопросы" in схема:
                сообщение["content"] = json.dumps({"реакция": "Понял вас.", "вопросы": []}, ensure_ascii=False)
                сообщение["reasoning_content"] = ДУМЫ
            elif "ТЕГ_THINK" in система:
                сообщение["content"] = "<think>мысль в теге</think>Готовый ответ."
            elif "ТЕГ_THOUGHT" in система:
                сообщение["content"] = "<thought>мысль Gemini</thought>Готовый ответ."
            else:
                сообщение["content"] = "Понял, расскажите подробнее."
                сообщение["reasoning"] = ДУМЫ
            тело = json.dumps({"id": "x", "object": "chat.completion", "model": данные.get("model"), "choices": [{"index": 0, "message": сообщение, "finish_reason": "stop"}],
                               "usage": {"prompt_tokens": 7, "completion_tokens": 5, "completion_tokens_details": {"reasoning_tokens": 3}}}, ensure_ascii=False).encode("utf-8")
            self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(тело)))
        self.end_headers()
        self.wfile.write(тело)

    def log_message(self, *a):
        pass


class Сервер(socketserver.ThreadingMixIn, http.server.HTTPServer):
    daemon_threads = True
    allow_reuse_address = True


