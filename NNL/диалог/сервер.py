_СТОП_СЛОВА = {"меня", "мне", "есть", "очень", "сильно", "после", "когда", "этого", "такое", "который", "какая", "какой", "иногда", "часто", "давно", "опять"}


def _основы_слов(текст):
    """Основы (первые 5 букв) значимых слов: так «диабет» находит «диабета», а «колет» — нет."""
    return {w[:5] for w in re.findall(r"[а-я]{4,}", текст.lower().replace("ё", "е")) if w not in _СТОП_СЛОВА}


def врач_подтвердил(текст):
    """Слова врача в фразе и НЕ отрицание: «окулист написал минус 7» — да; «сам решил, к окулисту не ходил» — нет. Осторожно в сторону «нет»:
    при любой оговорке («сам решил», «врач не…», «без обследования») подтверждения нет, категорию ядро не назовёт."""
    if not Д._ВРАЧ.search(текст) or Д._ВРАЧА_НЕ_БЫЛО.search(текст):
        return False
    return not _САМ_РЕШИЛ.search(текст)


_САМ_РЕШИЛ = re.compile(r"\bсам(?:а|и)?\s+(?:себе\s+)?(?:решил\w*|поставил\w*|определил\w*|понял\w*|думаю|думал\w*|считаю|считал\w*|диагностировал\w*)|без\s+(?:врач\w*|диагноз\w*|обследован\w*|справк\w*)|не\s+у\s+врач\w*|никто\s+не\s+(?:ставил|говорил|писал)|не\s+обследовал\w*", re.I)


# Сокращения, которые люди пишут вместо диагноза. Блоки обучены на полных словах и сокращений не знают («гб 2 стадии» уходило на ВИЧ).
# Только однозначные: «ад», «пмк» и подобное, где слово значит разное, сюда не входят.
_СОКРАЩЕНИЯ = {
    "гб": "гипертоническая болезнь", "ибс": "ишемическая болезнь сердца", "всд": "вегетососудистая дистония", "нцд": "нейроциркуляторная дистония",
    "хобл": "хроническая обструктивная болезнь лёгких", "мкб": "мочекаменная болезнь", "жкб": "желчнокаменная болезнь", "впс": "врождённый порок сердца",
    "хсн": "хроническая сердечная недостаточность", "хпн": "хроническая почечная недостаточность", "дцп": "детский церебральный паралич",
    "сд": "сахарный диабет", "гэрб": "гастроэзофагеальная рефлюксная болезнь", "рс": "рассеянный склероз",
}
_РЕГ_СОКРАЩЕНИЙ = re.compile(r"(?<![\w-])(" + "|".join(sorted(_СОКРАЩЕНИЯ, key=len, reverse=True)) + r")(?![\w-])", re.I)


def _расшифровать(текст):
    """«гб 2 стадии» → «гипертоническая болезнь 2 стадии». Возвращает (текст, [{сокращение, значение}]); человеку расшифровка показывается."""
    найдено = []

    def подставить(м):
        ключ = м.group(1)
        значение = _СОКРАЩЕНИЯ[ключ.lower()]
        if not any(н["сокращение"].lower() == ключ.lower() for н in найдено):
            найдено.append({"сокращение": ключ, "значение": значение})
        return значение
    return _РЕГ_СОКРАЩЕНИЙ.sub(подставить, текст), найдено


_РАЗДЕЛ_КЛАУЗ = re.compile(r"[.!?;\n]+|,\s+(?=\S)")


def _клаузы(текст):
    """Предложения и части через запятую, в которых есть смысл оценивать отдельно (не меньше двух слов или есть цифра)."""
    части = [ч.strip(" ,—-") for ч in _РАЗДЕЛ_КЛАУЗ.split(текст)]
    return [ч for ч in части if len(ч.split()) >= 2 or re.search(r"\d", ч)]


def _по_предложениям(p_целиком, cz_целиком, клаузы):
    """Каждое предложение блоки оценивают как самостоятельную жалобу. Статья, на которую указывают несколько предложений, набирает вес
    (вероятности независимых указаний складываются как «хотя бы одно верно»), но не выше 0,99; оценка по тексту целиком не теряется.
    Предложение без смысла («что в итоге?») проходит те же ворота области, что и целая фраза, и вклада не даёт."""
    вклады, учтено, лучший_cz = {}, [], cz_целиком
    for к in клаузы:
        czк, _ = СИСТЕМА.блоки.область(к)
        pк, _ = СИСТЕМА.блоки.статьи(к)
        pк2, _ = СИСТЕМА.блоки.статьи(_без_вводных(к))
        if pк2 and max(pк2.values()) > max(pк.values() or [0.0]):
            pк = pк2
        if not pк:
            continue
        лучшая = max(pк.values())
        if czк > 0 or (czк > -2.5 and лучшая >= 0.2):
            for ид, v in pк.items():
                if v >= 0.2:
                    вклады.setdefault(ид, []).append(v)
            лучший_cz = max(лучший_cz, czк)
            ид_л = max(pк, key=pк.get)
            учтено.append({"текст": к, "статья": ид_л, "p": round(лучшая, 3)})
    итог = dict(p_целиком)
    for ид, vs in вклады.items():
        ост = 1.0
        for v in vs:
            ост *= (1 - v)
        итог[ид] = max(итог.get(ид, 0.0), min(0.99, 1 - ост))
    return итог, лучший_cz, учтено


def умный_поиск(текст, ответы=None):
    """Поиск по Расписанию болезней и правовым темам блоками NNL. Состояния нет: каждый запрос оценивается отдельно, ничего в сессии не копится.
    Сверх ответа блоков: пункт, ближайший по словам (код_ответ.пункт_по_словам); расчёты по числам из фразы (пороги.из_слов);
    потолок уверенности, как в режиме «ядро» (диалог.py): одна короткая фраза без чисел и без слов врача не получает уверенности выше 0,45,
    кроме случая, когда все её значимые слова есть в тексте самой статьи."""
    текст = (текст or "").strip()[:300]
    if len(текст) < 2:
        return {"запрос": текст, "статьи": [], "право": [], "числа": [], "вне_темы": False, "ворота": None}
    исходный_текст = текст
    текст, расшифровано = _расшифровать(текст)           # «гб» блоки не знают: до поиска сокращения превращаются в слова
    cz, cp = СИСТЕМА.блоки.область(текст)
    числа = ПР.из_слов(СИСТЕМА.база, текст, СИСТЕМА.код_решатель)
    статьи, право = [], []
    p, p0 = СИСТЕМА.блоки.статьи(текст)
    p2, p02 = СИСТЕМА.блоки.статьи(_без_вводных(текст))            # «у меня кажется диабет» блок читает мешком слов: вводные размывают жалобу (как и в воротах области)
    if p2 and max(p2.values()) > max(p.values() or [0.0]) and p02 <= p0:
        p, p0 = p2, p02
    клаузы = _клаузы(текст)
    по_предложениям = []
    if len(клаузы) >= 2:                      # несколько предложений: каждое оценивается отдельно, а не мешком слов всего текста
        p, cz, по_предложениям = _по_предложениям(p, cz, клаузы)
    лучшая = max(p.values()) if p else 0.0
    if cz > 0 or (cz > -2.5 and лучшая >= 0.2 and p0 < 0.5):      # короткая фраза с цифрой («сахар 9») ворота проходит чуть ниже нуля, но статья при этом явная
        скудно = len(текст.split()) < 5 and not re.search(r"\d", текст) and not Д._ВРАЧ.search(текст)
        основы = _основы_слов(текст)
        for ид, v in sorted(p.items(), key=lambda x: -x[1])[:8]:
            if v >= 0.03 or not статьи:
                а = СИСТЕМА.база.статьи[ид]
                слова_есть = bool(основы) and основы <= _основы_слов(а.название + " " + а.сырой)
                огр = скудно and not слова_есть and v > 0.45
                запись = {"ид": ид, "название": а.название, "p": round(v, 3), "p_показ": round(min(v, 0.45) if огр else v, 3), "ограничено": огр}
                пункт = СИСТЕМА.код_решатель.пункт_по_словам(ид, текст) if v >= 0.2 else None
                if пункт:
                    запись["пункт"] = пункт[0]
                статьи.append(запись)
    if cp > 0:
        лучшие, _ = СИСТЕМА.блоки.право(текст, топ=3)
        for ид, v in лучшие:
            if v >= 0.15 and ид in СИСТЕМА.база.темы:
                т = СИСТЕМА.база.темы[ид]
                право.append({"тема": ид, "название": т["название"], "суть": т["суть"], "p": round(v, 3)})
    подсказка = "Фраза короткая: добавьте диагноз, что сказал врач или измеренные значения — станет точнее." if статьи and статьи[0]["ограничено"] else ""
    до = (статьи[0]["ид"], статьи[0]["p_показ"]) if статьи else None     # лидер до ответов человека и его близость, как её видит человек (с потолком для расплывчатых фраз)
    вопрос = следующий_вопрос(статьи, ответы or [], cz)
    if ответы and вопрос and вопрос.get("р"):              # ответы человека — тоже улики: плашка статьи показывает уже обновлённую близость
        for з in статьи:
            if з["ид"] in вопрос["р"]:
                з["p"] = з["p_показ"] = round(вопрос["р"][з["ид"]], 3)
                з["ограничено"] = False
        статьи.sort(key=lambda з: -з["p"])
        подсказка = ""
    вне = not статьи and not право and not числа
    try:
        Оч.события_поиска(текст, до, ответы or [], вопрос, вне)      # уроки для дообучения; сбой очереди ответ человеку не ломает
    except Exception:
        traceback.print_exc()
    return {"запрос": исходный_текст, "расшифровано": расшифровано, "статьи": статьи[:6], "право": право[:2], "числа": числа, "подсказка": подсказка,
            "подтверждение": "врач" if врач_подтвердил(текст) else "слова",
            "вне_темы": вне,
            "ворота": {"здоровье": round(cz, 2), "право": round(cp, 2)}, "вопрос": вопрос, "предложения": по_предложениям}


def следующий_вопрос(статьи, ответы, здоровье=9.0):
    """Что спросить у человека дальше, без модели: из банка (вопросы и таблицы p(да|есть), p(да|нет) готовы заранее, по тексту статей) берётся
    вопрос с наибольшим информационным выигрышем (расследование.eig) среди статей-кандидатов. Состояния нет: уже данные ответы приходят в запросе
    [{статья, текст, ответ: да|нет}] и сдвигают p своей статьи по отношению правдоподобия. Нет вопроса — нет и причины спрашивать: либо ясно, либо банк пуст."""
    банк = getattr(СИСТЕМА, "банк", None)
    if not статьи or not банк:
        return None
    if здоровье < 1.0 and max(з["p"] for з in статьи) < 0.5:         # «хочу пиццу»: ворота едва открыты и лидер слабый — спрашивать не о чем
        return {"вопроса_нет": "фраза не похожа на жалобу", "ответов": len(ответы)}
    р = {з["ид"]: (з["p_показ"] if з["ограничено"] else з["p"]) for з in статьи if з["p_показ"] >= 0.05}
    заданные = set()
    for о in ответы:
        ид, т = str(о.get("статья", "")), str(о.get("текст", ""))
        заданные.add((ид, т))
        for q in банк.актуальные.get(ид, {}).get("вопросы", []):
            if q["текст"] == т and q.get("таблица") and ид in р and о.get("ответ") in ("да", "нет"):
                а, б = Р.очистить_таблицу(*q["таблица"]) or (0.5, 0.5)
                lr = (а / б) if о["ответ"] == "да" else ((1 - а) / (1 - б))
                р[ид] = р[ид] * lr / (р[ид] * lr + 1 - р[ид])
    лучшие = []
    for ид, p in sorted(р.items(), key=lambda x: -x[1])[:3]:
        for q in банк.актуальные.get(ид, {}).get("вопросы", []):
            if q["вид"] != "да_нет" or (ид, q["текст"]) in заданные:
                continue
            т = Р.очистить_таблицу(*(q.get("таблица") or (None, None)))
            if т is not None:
                лучшие.append((Р.eig(p, *т), ид, q, т))
    лидер = max(р.items(), key=lambda x: x[1]) if р else (None, 0.0)
    итог = {"лидер": лидер[0], "p_лидера": round(лидер[1], 3), "ответов": len(ответы), "р": {k: round(v, 4) for k, v in р.items()}}
    лучшие.sort(key=lambda x: -x[0])
    if not лучшие or лучшие[0][0] < Р.EIG_МИН:
        итог["вопроса_нет"] = "ничего не различает статьи" if лучшие else "банк не покрывает кандидатов"
        return итог
    e, ид, q, т = лучшие[0]
    итог.update({"статья": ид, "текст": q["текст"], "тема": q.get("тема"), "eig": round(e, 3), "таблица": list(т),
                 "почему": "ответ сильнее всего сдвинет ст. %s (p=%.2f): «да» → %.2f, «нет» → %.2f" % (
                     ид, р[ид], р[ид] * т[0] / (р[ид] * т[0] + (1 - р[ид]) * т[1]), р[ид] * (1 - т[0]) / (р[ид] * (1 - т[0]) + (1 - р[ид]) * (1 - т[1]))),
                 "ещё": [{"статья": i2, "текст": q2["текст"], "eig": round(e2, 3)} for e2, i2, q2, _ in лучшие[1:3]]})
    return итог


