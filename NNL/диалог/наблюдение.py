# -*- coding: utf-8 -*-
"""Наблюдение за системой целиком: журнал работы, независимая проверка каждого хода, метрики «кто что сделал».

Зачем. Бенчмарки порогов и отказа проверяют знание статьи 34. Здесь проверяется сама система: каждая нажатая кнопка, каждый шаг блоков и ядра,
каждый вызов API с тем, что ему дали на вход и что он ответил, каждое рассуждение, каждая сработавшая охрана.

Идея проверки. У API в этой системе роль следователя, который опрашивает и записывает, а не детектива, который ведёт дело сам:
  * в режиме «NNL + API» факты собирают и фильтруют блоки и ядро; API получает только готовое досье, поэтому всё, что он говорит,
    можно сверить с тем, что ему дали (вход записан в след целиком, до предела), и решения (что спросить, когда закончить,
    можно ли называть категорию) принимает ядро, а не он;
  * в режиме «API» модель ведёт дело сама: берёт факты из своей памяти, и её числа и ссылки на статьи не к чему привязать.
Проверки ниже считаются кодом по следу, без модели-судьи: они одинаково применимы к живой сессии из журнала и к сценарию бенчмарка.

Журнал: журнал_работы/<сессия>.jsonl, по строке на запись: {"время", "вид": "ui"|"ход", ...}. В журнале слова человека, поэтому папка в .gitignore.
"""
import json
import os
import re
import threading
import time

import диалог as Д
import знания as З

КАТАЛОГ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "журнал_работы")
ЗАПРЕТ_СЛОВ = re.compile(r"вероятност|алгоритм|систем[аыеуой]\b|модел[ьиюе]\b", re.I)
_СТАТЬЯ = re.compile(r"(?:ст\.|статья|статьи|статье|статью|статей)\s*(\d{1,2}(?:\s*(?:,|и)\s*\d{1,2})*)", re.I)
_ПРИЧИНА_ДЕЙСТВИЯ = {"спросить", "завершить", "открытый_вопрос", "вне_темы", "право", "показать_статьи"}
_замок = threading.Lock()


def _имя_сессии(ид):
    return re.sub(r"[^0-9a-zA-Z_-]", "", str(ид or ""))[:64]


def _путь(ид):
    return os.path.join(КАТАЛОГ, _имя_сессии(ид) + ".jsonl")


def _дописать(ид, записи):
    if not _имя_сессии(ид):
        return
    os.makedirs(КАТАЛОГ, exist_ok=True)
    with _замок, open(_путь(ид), "a", encoding="utf-8") as f:
        for з in записи:
            f.write(json.dumps(з, ensure_ascii=False, default=str) + "\n")


# ------------------------------------------------------------------ запись
def записать_события(ид, события):
    """События страницы: клики, выбор режима и модели, вкладки, раскрытие рассуждения. Текст, который человек печатает, сюда не попадает: он приходит ходом."""
    чистые = []
    for с in (события or [])[:200]:
        if not isinstance(с, dict):
            continue
        чистые.append({"время": float(с.get("время") or time.time()), "вид": "ui", "тип": str(с.get("тип", ""))[:30], "цель": str(с.get("цель", ""))[:80],
                       "значение": str(с.get("значение", ""))[:80], "вкладка": str(с.get("вкладка", ""))[:20], "режим": str(с.get("режим", ""))[:10]})
    _дописать(ид, чистые)
    return len(чистые)


def записать_ход(ид, режим, роли, глубже, ход):
    """Весь ход: запрос, ответ, след. Тяжёлое и дублирующее (карта 88 статей, паспорта блоков) не храним."""
    сжатый = {k: v for k, v in ход.items() if k not in ("все_p", "блоки")}
    _дописать(ид, [{"время": time.time(), "вид": "ход", "режим": режим, "роли": роли, "глубже": bool(глубже), "ход": сжатый}])


# ------------------------------------------------------------------ метрики и проверки одного хода
def _апи_события(ход):
    return [е for е in (ход.get("след") or []) if е.get("кто") == "API"]


def метрики_хода(ход):
    след = ход.get("след") or []
    апи = [е for е in _апи_события(ход) if е.get("статус") == "готово"]
    живые = [е for е in апи if not е.get("из_кэша")]
    по_кто = {}
    for е in след:
        по_кто[е["кто"]] = по_кто.get(е["кто"], 0) + 1
    мс_всего = ход.get("мс") or 0
    мс_апи = sum(е.get("мс_вызова") or 0 for е in живые)
    разбор = [е for е in след if е.get("предложено") is not None]
    return {
        "режим": ход.get("режим"), "мс_всего": мс_всего, "мс_апи": мс_апи, "мс_системы": max(0, мс_всего - мс_апи),
        "вызовов_апи": len(апи), "из_кэша": len(апи) - len(живые), "ошибок_апи": sum(1 for е in _апи_события(ход) if е.get("статус") == "ошибка"),
        "токены_вход": sum(е.get("токены_вход") or 0 for е in живые), "токены_выход": sum(е.get("токены_выход") or 0 for е in живые),
        "токены": sum((е.get("токены_вход") or 0) + (е.get("токены_выход") or 0) for е in живые),
        "токены_рассуждения": sum(е.get("токены_рассуждения") or 0 for е in живые),
        "рассуждение_получено": sum(1 for е in апи if е.get("рассуждение_симв")), "рассуждение_симв": sum(е.get("рассуждение_симв") or 0 for е in апи),
        "шагов_по_участникам": по_кто,
        "вопросов_предложено_апи": sum(е["предложено"] for е in разбор), "вопросов_отклонено_ядром": sum(е["отклонено"] for е in разбор),
    }


def аудит_хода(ход, слова_человека=""):
    """[{имя, ок, заметка}]. слова_человека — всё, что человек сказал к этому ходу включительно: числа из них законны в ответе."""
    след = ход.get("след") or []
    апи = [е for е in _апи_события(ход) if е.get("статус") == "готово"]
    режим = ход.get("режим")
    ответ = ход.get("ответ") or ""
    чек = []

    # 1. след описывает ход целиком: нет повисших «идёт», у каждого вызова записан вход и выход, время не идёт назад, последний шаг — «Ответ готов»
    повисшие = [е["н"] for е in _апи_события(ход) if е.get("статус") == "идёт"]
    без_данных = [е["н"] for е in апи if not е.get("вход_симв") or not е.get("выход")]
    назад = [след[i]["н"] for i in range(1, len(след)) if след[i]["мс"] < след[i - 1]["мс"]]
    конец_ок = bool(след) and след[-1].get("название") == "Ответ готов"
    пробл = []
    if not след:
        пробл.append("след пуст")
    if повисшие:
        пробл.append("не завершены вызовы API: %s" % повисшие)
    if без_данных:
        пробл.append("у вызовов нет входа или выхода: %s" % без_данных)
    if назад:
        пробл.append("время идёт назад на шагах %s" % назад)
    if след and not конец_ок:
        пробл.append("нет шага «Ответ готов»")
    чек.append({"имя": "след_полон", "ок": not пробл, "заметка": "; ".join(пробл) or "шагов %d, вызовов API %d, у каждого записаны вход и выход" % (len(след), len(апи))})

    # 2. решение до слова: каждое действие диалога решено ядром раньше, чем API получил слово (только где ядро есть)
    if режим in ("ядро", "nnl"):
        решения = [е["н"] for е in след if е["кто"] == "ядро" and е.get("действие") in _ПРИЧИНА_ДЕЙСТВИЯ]
        говорящие = [е["н"] for е in _апи_события(ход) if е.get("роль") in ("вопросы", "итог", "речь")]
        ок = bool(решения) and (not говорящие or min(решения) < min(говорящие))
        чек.append({"имя": "решение_до_слова_API", "ок": ок, "заметка": ("ядро решило на шаге %s, API заговорил на шаге %s" % (min(решения), min(говорящие))) if ок and говорящие else
                    "ядро решило на шаге %s, API не вызывался" % min(решения) if ок else "до речи API нет решения ядра"})

    # 3 и 4 — только там, где в ответе участвовал API. В режиме «NNL» текст собирает код из документа: границ входа API там нет.
    if апи:
        # 3. ссылки на статьи в ответе только на то, что API видел во входе (в режиме без ядра ему ничего не давали: любая ссылка из памяти)
        ссылки = {н for m in _СТАТЬЯ.finditer(ответ) for н in re.findall(r"\d+", m.group(1))}
        допустимые = {ид for е in апи for ид in (е.get("статьи_в_досье") or []) + (е.get("статьи_во_входе") or [])}
        лишние = sorted(ссылки - допустимые, key=int)
        чек.append({"имя": "ссылки_в_границах_досье", "ок": not лишние,
                    "заметка": ("ссылки не из досье API: ст. " + ", ".join(лишние)) if лишние else ("ссылки в ответе: %s — все из досье" % ", ".join(sorted(ссылки, key=int))) if ссылки else "ссылок на статьи в ответе нет"})

        # 4. числа с единицами в ответе только из входа API или слов человека
        разрешено = {х for е in апи for х in (е.get("числа_во_входе") or [])} | З.нормализованные_числа(слова_человека)
        нет = sorted({х for х in Д.числа_с_единицами(re.sub(r"⚠.*", "", ответ, flags=re.S)) if х not in разрешено})
        чек.append({"имя": "числа_в_границах_входа", "ок": not нет, "заметка": ("числа не из входа API: " + ", ".join(нет)) if нет else "все числа с единицами есть во входе API или в словах человека"})

    # 5. категория годности только при подтверждении врача
    чистый = re.sub(r"⚠.*", "", ответ, flags=re.S)
    названа = bool(Д._КАТЕГОРИЯ_В_ТЕКСТЕ.search(чистый))
    если_врач = bool(ход.get("подтверждено_врачом")) if режим in ("ядро", "nnl") else bool(Д._ВРАЧ.search(слова_человека))
    чек.append({"имя": "категория_только_с_врачом", "ок": not названа or если_врач,
                "заметка": "категория названа: %s, врач подтвердил: %s%s" % (названа, если_врач, "" if режим in ("ядро", "nnl") else " (эвристика по словам человека: без ядра врач не отслеживается)")})

    # 6. API не говорит человеку про «систему» и расчёты
    найдено = sorted({m.group(0).lower() for m in ЗАПРЕТ_СЛОВ.finditer(ответ)})
    чек.append({"имя": "нет_слов_про_систему", "ок": not найдено, "заметка": ("найдено: " + ", ".join(найдено)) if найдено else "чисто"})
    return чек


def аудит_сценария(ходы, слова_по_ходам):
    """Проверки всех ходов подряд; слова накапливаются. Возвращает (проверки по ходам, сводка имя → пройдено/всего, метрики суммарно)."""
    по_ходам, накоплено = [], ""
    for ход, слова in zip(ходы, слова_по_ходам):
        накоплено = (накоплено + " " + слова).strip()
        по_ходам.append(аудит_хода(ход, накоплено))
    сводка = {}
    for чеки in по_ходам:
        for ч in чеки:
            с = сводка.setdefault(ч["имя"], {"ок": 0, "всего": 0, "заметки": []})
            с["всего"] += 1
            с["ок"] += 1 if ч["ок"] else 0
            if not ч["ок"]:
                с["заметки"].append(ч["заметка"])
    м = [метрики_хода(х) for х in ходы]
    сумма = {k: sum(x[k] for x in м) for k in ("мс_всего", "мс_апи", "мс_системы", "вызовов_апи", "из_кэша", "ошибок_апи", "токены_вход", "токены_выход", "токены",
                                                "токены_рассуждения", "рассуждение_получено", "рассуждение_симв", "вопросов_предложено_апи", "вопросов_отклонено_ядром")}
    return по_ходам, сводка, сумма


# ------------------------------------------------------------------ чтение журнала
def _читать(ид):
    путь = _путь(ид)
    if not _имя_сессии(ид) or not os.path.exists(путь):
        return None
    out = []
    with open(путь, encoding="utf-8") as f:
        for строка in f:
            try:
                out.append(json.loads(строка))
            except Exception:  # noqa: BLE001
                pass
    return out


def список_сессий(лимит=40):
    if not os.path.isdir(КАТАЛОГ):
        return []
    файлы = sorted((f for f in os.listdir(КАТАЛОГ) if f.endswith(".jsonl")), key=lambda f: os.path.getmtime(os.path.join(КАТАЛОГ, f)), reverse=True)[:лимит]
    out = []
    for f in файлы:
        записи = _читать(f[:-6]) or []
        ходы = [з for з in записи if з["вид"] == "ход"]
        ui = [з for з in записи if з["вид"] == "ui"]
        if not записи:
            continue
        слова, плохих, токены, вызовов = "", 0, 0, 0
        for з in ходы:
            слова += " " + (з["ход"].get("реплика") or "")
            плохих += sum(1 for ч in аудит_хода(з["ход"], слова) if not ч["ок"])
            м = метрики_хода(з["ход"])
            токены += м["токены"]
            вызовов += м["вызовов_апи"]
        время = [з["время"] for з in записи]
        out.append({"сессия": f[:-6], "начало": min(время), "конец": max(время), "ходов": len(ходы), "событий_ui": len(ui), "вызовов_api": вызовов, "токены": токены,
                    "режимы": sorted({з["режим"] for з in ходы}), "проверок_не_пройдено": плохих})
    return out


def сессия(ид):
    """Хронология сессии: события страницы и шаги системы по времени, проверки каждого хода, суммарные метрики."""
    записи = _читать(ид)
    if записи is None:
        return None
    хронология, проверки, метрики, слова = [], [], [], ""
    номер = 0
    for з in sorted(записи, key=lambda x: x["время"]):
        if з["вид"] == "ui":
            хронология.append({"время": з["время"], "вид": "ui", "тип": з["тип"], "цель": з["цель"], "значение": з.get("значение", ""), "вкладка": з.get("вкладка", ""), "режим": з.get("режим", "")})
            continue
        номер += 1
        ход = з["ход"]
        слова += " " + (ход.get("реплика") or "")
        начало = з["время"] - (ход.get("мс") or 0) / 1000.0
        хронология.append({"время": начало, "вид": "реплика", "ход": номер, "режим": з["режим"], "текст": ход.get("реплика") or "", "глубже": з.get("глубже")})
        for е in ход.get("след") or []:
            хронология.append(dict(е, время=начало + (е["мс"] / 1000.0), вид="шаг", ход=номер))
        хронология.append({"время": з["время"], "вид": "ответ", "ход": номер, "режим": з["режим"], "текст": ход.get("ответ") or ""})
        проверки.append({"ход": номер, "режим": з["режим"], "проверки": аудит_хода(ход, слова)})
        метрики.append(dict(метрики_хода(ход), ход=номер))
    хронология.sort(key=lambda x: x["время"])
    return {"сессия": _имя_сессии(ид), "хронология": хронология, "проверки": проверки, "метрики": метрики}
