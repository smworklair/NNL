# -*- coding: utf-8 -*-
"""Сборка и проверка пересказа «простыми словами» для страницы статьи.

Проверки (любая ошибка → файл не пишется, код возврата 1):
  1. каждый пункт каждой статьи (263) имеет пересказ — типовой или индивидуальный;
  2. числа пересказа ⊆ числам документа (ничего не выдумано);
  3. числа документа ⊆ числам пересказа (ничего не потеряно), кроме номеров и дат изменений в служебных ссылках пункта 6в ст. 6;
  4. римские цифры (степени, стадии) совпадают.
Результат: NNL/диалог/макеты_военкомат/простыми_словами.js → window.ПРОСТО_ПУНКТЫ = {ид: {буква: текст}}.
Запуск: python NNL/диалог/собрать_простыми_словами.py"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
import простыми_словами as ПС  # noqa: E402

КАТАЛОГ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "макеты")
ДАННЫЕ = os.path.join(КАТАЛОГ, "справочник_данные.js")
ВЫХОД = os.path.join(КАТАЛОГ, "простыми_словами.js")
ЧИСЛО = re.compile(r"\d+(?:[.,]\d+)?")
РИМСКИЕ = re.compile(r"(?<![А-Яа-яЁёA-Za-z])[IVX]{1,3}(?![А-Яа-яЁёA-Za-z])")
# в официальном тексте 6в числа служебных ссылок («от 29.08.2025 N 1314», «редакции»): их пересказ не повторяет
СЛУЖЕБНЫЕ = {("6", "в"): {"29.08", "1314"}}


def числа(т):
    return {x.replace(",", ".") for x in ЧИСЛО.findall(т)}


def главное():
    с = open(ДАННЫЕ, encoding="utf-8").read()
    статьи = json.loads(с[с.index("=") + 1:].strip().rstrip(";"))["статьи"]
    итог, ошибки, из_шаблона = {}, [], 0
    for ид in sorted(статьи, key=int):
        for п in статьи[ид]["пункты"]:
            б, док = п["буква"], п["описание"].strip()
            готово = ПС.ПУНКТЫ.get(ид, {}).get(б)
            if док == "(статья без деления на пункты)":
                готово = ПС.ПУНКТЫ.get(ид, {}).get("—") or ПС.БЕЗ_ПУНКТОВ
            elif готово is None and док in ПС.ШАБЛОНЫ:
                готово = ПС.ШАБЛОНЫ[док]; из_шаблона += 1
            if not готово:
                ошибки.append("нет пересказа: ст. %s п. «%s»: %s" % (ид, б, док[:70])); continue
            нд, нп = числа(док), числа(готово)
            if док != "(статья без деления на пункты)":
                лишние = нп - нд
                if лишние:
                    ошибки.append("ст. %s п. «%s»: в пересказе числа, которых нет в документе: %s" % (ид, б, sorted(лишние)))
                потеряны = нд - нп - СЛУЖЕБНЫЕ.get((ид, б), set())
                if потеряны:
                    ошибки.append("ст. %s п. «%s»: в пересказе потеряны числа: %s" % (ид, б, sorted(потеряны)))
                if set(РИМСКИЕ.findall(док)) != set(РИМСКИЕ.findall(готово)):
                    ошибки.append("ст. %s п. «%s»: римские цифры не совпали: %s ↔ %s" % (ид, б, sorted(set(РИМСКИЕ.findall(док))), sorted(set(РИМСКИЕ.findall(готово)))))
            итог.setdefault(ид, {})[б] = готово
    лишние_ключи = [(ид, б) for ид, д in ПС.ПУНКТЫ.items() for б in д if б != "—" and not any(п["буква"] == б for п in статьи.get(ид, {"пункты": []})["пункты"])]
    for ид, б in лишние_ключи:
        ошибки.append("пересказ для несуществующего пункта: ст. %s п. «%s»" % (ид, б))
    # --- второй слой: уточнения по пунктам и «что важно знать» по статье ---
    def допустимые(ид):
        # всё, что написано в этой статье: описания пунктов и примечания
        текст = " ".join([п["описание"] for п in статьи[ид]["пункты"]] + list(статьи[ид].get("примечания", [])))
        return числа(текст), set(РИМСКИЕ.findall(текст))
    уточнения_итог, общее_итог = {}, {}
    for ид, по_буквам in ПС.УТОЧНЕНИЯ.items():
        if ид not in статьи:
            ошибки.append("уточнения для несуществующей статьи %s" % ид); continue
        ч_док, р_док = допустимые(ид)
        буквы = {п["буква"] for п in статьи[ид]["пункты"]}
        for б, т in по_буквам.items():
            if б not in буквы:
                ошибки.append("уточнение для несуществующего пункта: ст. %s п. «%s»" % (ид, б)); continue
            лишние = числа(т) - ч_док
            if лишние: ошибки.append("уточнение ст. %s п. «%s»: числа, которых нет в статье: %s" % (ид, б, sorted(лишние)))
            лишние_р = set(РИМСКИЕ.findall(т)) - р_док
            if лишние_р: ошибки.append("уточнение ст. %s п. «%s»: римские цифры, которых нет в статье: %s" % (ид, б, sorted(лишние_р)))
            уточнения_итог.setdefault(ид, {})[б] = т
    for ид, строки in ПС.ОБЩЕЕ.items():
        if ид not in статьи:
            ошибки.append("«что важно знать» для несуществующей статьи %s" % ид); continue
        ч_док, р_док = допустимые(ид)
        for т in строки:
            лишние = числа(т) - ч_док
            if лишние: ошибки.append("«важно» ст. %s: числа, которых нет в статье: %s (%s…)" % (ид, sorted(лишние), т[:40]))
            лишние_р = set(РИМСКИЕ.findall(т)) - р_док
            if лишние_р: ошибки.append("«важно» ст. %s: римские цифры, которых нет в статье: %s (%s…)" % (ид, sorted(лишние_р), т[:40]))
        общее_итог[ид] = list(строки)
    всего = sum(len(д) for д in итог.values())
    print("пунктов с пересказом: %d (из типовых формулировок: %d)" % (всего, из_шаблона))
    print("уточнений по пунктам: %d, статей с блоком «важно»: %d" % (sum(len(д) for д in уточнения_итог.values()), len(общее_итог)))
    if ошибки:
        print("ОШИБОК: %d" % len(ошибки))
        for е in ошибки:
            print("  - " + е)
        return 1
    with open(ВЫХОД, "w", encoding="utf-8") as ф:
        ф.write("window.ПРОСТО_ПУНКТЫ = " + json.dumps(итог, ensure_ascii=False, separators=(",", ":")) + ";\n")
        ф.write("window.ПРОСТО_УТОЧНЕНИЯ = " + json.dumps(уточнения_итог, ensure_ascii=False, separators=(",", ":")) + "\n")
        ф.write("window.ПРОСТО_ОБЩЕЕ = " + json.dumps(общее_итог, ensure_ascii=False, separators=(",", ":")) + "\n")
    print("записано: " + ВЫХОД)
    return 0


if __name__ == "__main__":
    sys.exit(главное())
