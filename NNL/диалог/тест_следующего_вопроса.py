# -*- coding: utf-8 -*-
"""Тест выбора следующего вопроса справочником (сервер.следующий_вопрос): вопрос из банка по информационному выигрышу, без сети и моделей.
Запуск: python NNL/диалог/тест_следующего_вопроса.py"""
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
import клиент as К  # noqa: E402
К.КЭШ_ФАЙЛ = os.path.join(tempfile.mkdtemp(prefix="nnl_вопрос_"), "кэш.jsonl")
import диалог as Д  # noqa: E402
import сервер as S  # noqa: E402
import очередь_дообучения as Оч  # noqa: E402
Оч.ВКЛЮЧЕНА = False                       # тестовые фразы в настоящую очередь не пишем

S.СИСТЕМА = Д.Система()
ошибки = []


def проверить(что, условие, подробность=""):
    print(("  ок   " if условие else "  ОШИБКА ") + что + ("" if условие else "  " + str(подробность)))
    if not условие:
        ошибки.append(что)


в = S.умный_поиск("болит спина после падения")["вопрос"]
проверить("расплывчатая жалоба → вопрос из банка с выигрышем", bool(в.get("текст")) and в["eig"] >= 0.03, в)
проверить("в вопросе есть причина: как сдвинут «да» и «нет»", "«да»" in в.get("почему", "") and "«нет»" in в.get("почему", ""))

# цепочка ответов «да»: вопросы не повторяются, p лидера растёт, в конце вопросов нет
ответы, виденные, p_ряд = [], set(), []
for _ in range(8):
    в = S.умный_поиск("болит спина после падения", ответы)["вопрос"]
    p_ряд.append(в["p_лидера"])
    if not в.get("текст"):
        break
    проверить("вопрос не повторяется", (в["статья"], в["текст"]) not in виденные)
    виденные.add((в["статья"], в["текст"]))
    ответы.append({"статья": в["статья"], "текст": в["текст"], "ответ": "да"})
проверить("после «да» уверенность растёт, затем вопросов нет", p_ряд == sorted(p_ряд) and p_ряд[-1] > p_ряд[0] and "вопроса_нет" in в, p_ряд)

в0 = S.умный_поиск("болит спина после падения")["вопрос"]
вн = S.умный_поиск("болит спина после падения", [{"статья": в0["статья"], "текст": в0["текст"], "ответ": "нет"}])["вопрос"]
проверить("ответ «нет» понижает p статьи", вн["p_лидера"] < в0["p_лидера"] or вн.get("лидер") != в0["лидер"], (в0["p_лидера"], вн))
проверить("«не знаю» ничего не двигает", S.умный_поиск("болит спина после падения", [{"статья": в0["статья"], "текст": в0["текст"], "ответ": "не_знаю"}])["вопрос"]["p_лидера"] == в0["p_лидера"])

проверить("«хочу пиццу» → вопросов нет", S.умный_поиск("хочу пиццу")["вопрос"].get("вопроса_нет") == "фраза не похожа на жалобу")
проверить("«у меня кажется диабет» → ст. 13 (вводные слова не сбивают)", S.умный_поиск("у меня кажется диабет")["статьи"][0]["ид"] == "13")
проверить("вне темы → вопроса нет", S.умный_поиск("меня не берут на работу из-за судимости")["вопрос"] is None)
r = S.умный_поиск("болит спина после падения", ответы)
проверить("после ответов плашка статьи показывает обновлённую близость и без потолка",
          r["статьи"][0]["p_показ"] == r["вопрос"]["p_лидера"] > 0.45 and not r["статьи"][0]["ограничено"] and not r["подсказка"], r["статьи"][0])
# слова врача и отрицание: категорию нельзя называть, если человек сам решил или к врачу не ходил
for фраза, ждём in [("окулист в поликлинике написал близорукость минус 7", "врач"), ("сам решил что у меня минус 7, к окулисту не ходил", "слова"),
                    ("минус 7 без врача", "слова"), ("врач не ставил диагноз, но зрение плохое", "слова"), ("сам себе поставил диабет", "слова"),
                    ("по заключению окулиста минус 6", "врач")]:
    проверить("подтверждение врача: «%s» → %s" % (фраза, ждём), S.умный_поиск(фраза)["подтверждение"] == ждём, S.умный_поиск(фраза)["подтверждение"])
# поиск по предложениям: несколько жалоб в одном тексте дают несколько статей, а не одну
р3 = S.умный_поиск("колет сердце, после бега задыхаюсь. А ещё зрение минус 7 на оба глаза")
ид3 = {а["ид"] for а in р3["статьи"]}
проверить("несколько предложений: найдены и сердце (42), и зрение (34)", {"42", "34"} <= ид3, ид3)
проверить("для сложного текста названы предложения, на которых держится ответ", len(р3["предложения"]) >= 2, р3["предложения"])
проверить("одиночная фраза не разбивается: предложений нет", S.умный_поиск("болит спина после падения")["предложения"] == [])
# чеклист по статье: общие пункты и пункты статьи из банка
ч = S.чеклист("42")
проверить("чеклист ст. 42: четыре общих пункта и пункты статьи", ч and len([x for x in ч["пункты"] if x["общий"]]) == 4 and any(not x["общий"] for x in ч["пункты"]), ч)
проверить("чеклист несуществующей статьи — пусто", S.чеклист("999") is None)
проверить("в чеклисте есть оговорка: список ориентировочный", "ориентировочный" in ч["оговорка"])
# сокращения расшифровываются до поиска: блоки их не знают
рг = S.умный_поиск("гб 2 стадии")
проверить("«гб 2 стадии» → ст. 43 (гипертоническая болезнь)", рг["статьи"] and рг["статьи"][0]["ид"] == "43", рг["статьи"][:2])
проверить("расшифровка показана человеку", рг["расшифровано"] and рг["расшифровано"][0]["значение"] == "гипертоническая болезнь", рг["расшифровано"])
проверить("«сдавал анализы» не принимается за «сд»", S.умный_поиск("сдавал анализы")["расшифровано"] == [])
проверить("запрос в ответе остаётся таким, как написал человек", рг["запрос"] == "гб 2 стадии")
print("\nОШИБОК: %d" % len(ошибки))
sys.exit(1 if ошибки else 0)
