# -*- coding: utf-8 -*-
"""Тест превращения размеченных фраз в обучающие строки: метки, отказы, фильтр проверочных, формат как у данные.строка.
Запуск: python NNL/диалог/тест_очереди_в_обучение.py"""
import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "система"))
sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
import очередь_в_обучение as В  # noqa: E402
from обучение import данные as D  # noqa: E402

ошибки = []


def проверить(что, условие, подробность=""):
    print(("  ок   " if условие else "  ОШИБКА ") + что + ("" if условие else "  " + str(подробность)))
    if not условие:
        ошибки.append(что)


папка = tempfile.mkdtemp(prefix="nnl_обуч_")
вход, выход = os.path.join(папка, "в.jsonl"), os.path.join(папка, "из.jsonl")
тема = D.темы()[0]["topic_id"]
проверочный = D.проверочные_тексты()[0]
данные = [
    {"фраза": "колет в груди когда бегаю", "метка": "42"},
    {"фраза": "не берут на работу из-за судимости", "метка": "право:" + тема},
    {"фраза": "хочу пиццу и отдохнуть", "метка": "вне"},
    {"фраза": "болит поясница после падения", "метка": "66, 67"},
    {"фраза": "ничего не решил", "метка": None},
    {"фраза": "ещё не решил", "метка": ""},
    {"фраза": "статья которой нет", "метка": "999"},
    {"фраза": "тема которой нет", "метка": "право:нет_такой"},
    {"фраза": "Колет в груди когда бегаю!", "метка": "42"},
    {"фраза": проверочный, "метка": "34"},
]
with open(вход, "w", encoding="utf-8") as ф:
    for с in данные:
        ф.write(json.dumps(с, ensure_ascii=False) + "\n")
о = В.превратить(вход, выход)
строки = [json.loads(с) for с in open(выход, encoding="utf-8")]
проверить("принято 4 строки: статья, право, вне, две статьи", о["принято"] == 4 == len(строки), о)
проверить("без метки пропущено 2", о["без_метки"] == 2, о)
причины = {п for _, п in о["отвергнуто"]}
проверить("отвергнуты: нет статьи, нет темы, повтор, почти-повтор проверочного", len(о["отвергнуто"]) == 4 and {"повтор", "почти-повтор проверочного вопроса"} <= причины, о["отвергнуто"])
по_тексту = {r["текст"]: r for r in строки}
проверить("формат как у данные.строка (те же понятия, источник «очередь»)",
          all(set(r["понятия"]) == set(D.строка("x", 1, 0, ("42",), (), "очередь")["понятия"]) and r["источник"] == "очередь" for r in строки))
проверить("статья: область здоровье, ответ на статью", по_тексту["колет в груди когда бегаю"]["понятия"]["область:здоровье"] == 1 and по_тексту["колет в груди когда бегаю"]["ответы"] == ["ответ:здоровье:42"])
проверить("две статьи → два ответа", по_тексту["болит поясница после падения"]["ответы"] == ["ответ:здоровье:66", "ответ:здоровье:67"])
проверить("право: область право, ответ на тему", по_тексту["не берут на работу из-за судимости"]["понятия"]["область:право"] == 1 and по_тексту["не берут на работу из-за судимости"]["ответы"] == ["ответ:право:" + тема])
в = по_тексту["хочу пиццу и отдохнуть"]
проверить("«вне»: обе области 0, ответов нет", в["понятия"]["область:здоровье"] == 0 and в["понятия"]["область:право"] == 0 and в["ответы"] == [])
import subprocess  # noqa: E402
р = subprocess.run([sys.executable, "-X", "utf8", os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "система", "обучение", "дообучить.py"), "очередь", "основная_внешние", "1", "здоровье", os.path.join(папка, "нет.jsonl")], capture_output=True, text=True, encoding="utf-8")
проверить("режим «очередь» без файла строк отказывается и ничего не обучает", р.returncode != 0 and "ОТКАЗ" in (р.stderr + р.stdout), р.stderr[-200:])
print("\nОШИБОК: %d" % len(ошибки))
sys.exit(1 if ошибки else 0)
