function загрузитьСтатьи(){
  if(статьиВсе || загрузитьСтатьи.идёт) return;
  загрузитьСтатьи.идёт = true;
  fetch('/api/' + encodeURIComponent('статьи')).then(function(р){ if(!р.ok) throw new Error('нет'); return р.json(); }).then(function(д){
    статьиВсе = д.slice().sort(function(а, б){ return parseInt(а.ид, 10) - parseInt(б.ид, 10); });
    загрузитьСтатьи.идёт = false; отрисовать();
  }).catch(function(){ статьиОшибка = true; загрузитьСтатьи.идёт = false; отрисовать(); });
}
function спросить(q){
  var н = ++счётчик;
  поиск.запрос = q; поиск.ждём = true; поиск.ошибка = false;
  var url = '/api/' + encodeURIComponent('умныйпоиск') + '?q=' + encodeURIComponent(q);
  return fetch(url).then(function(р){ if(!р.ok) throw new Error('нет'); return р.json(); }).then(function(д){
    if(н !== счётчик) return null;
    поиск.данные = д; поиск.ждём = false; return д;
  }).catch(function(){
    if(н !== счётчик) return null;
    поиск.ждём = false; поиск.ошибка = true; поиск.данные = null; return null;
  });
}

