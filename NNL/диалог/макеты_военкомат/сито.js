function отрисовать(){
  var т = элем('сито-тело'), в = элем('сито-вкладки'), р = элем('сито-режимы'), ввод = элем('сито-ввод');
  if(!т) return;
  /* вкладки есть только в поиске; в расследовании экран ведёт тест */
  var скоро = режим === 'расследование' && !РАССЛЕДОВАНИЕ_ГОТОВО;
  в.hidden = режим !== 'поиск';
  Array.prototype.forEach.call(в.querySelectorAll('.сито-вкладка'), function(к){ к.classList.toggle('он', к.getAttribute('data-сито-вкладка') === вкладка); });
  Array.prototype.forEach.call(р.querySelectorAll('.сито-режим'), function(к){ к.classList.toggle('он', к.getAttribute('data-сито-режим') === режим); });
  р.classList.toggle('скрыт', первыйЗапрос && !скоро);
  var ждётВвод = режим === 'поиск' || рс.шаг === 'ввод' || рс.шаг === 'без_врача' || рс.шаг === 'ищем';
  ввод.readOnly = !ждётВвод || скоро;
  ввод.placeholder = режим === 'поиск'
    ? (вкладка === 'статьи' ? 'Найти статью: опишите, что беспокоит' : вкладка === 'документы' ? 'Найти бланк' : 'Найти в моём деле')
    : (скоро ? 'Расследование появится позже' : (ждётВвод ? 'Опишите, что беспокоит' : 'Отвечайте кнопками выше'));
  var бдж = элем('сито-бдж');
  if(бдж){ var n = читатьДело().filter(function(з){ return !СКРЫТЫЕ[з.ид]; }).length; бдж.hidden = !n; бдж.textContent = n; }
  var html;
  if(режим === 'расследование') html = скоро ? htmlСкоро() : htmlРасследование();
  else if(вкладка === 'статьи') html = (поиск.запрос.trim().length >= 2 ? htmlУмный() : htmlСтатьиСписок());
  else if(вкладка === 'документы') html = htmlДокументы();
  else html = htmlДело();
  т.innerHTML = html;
}

