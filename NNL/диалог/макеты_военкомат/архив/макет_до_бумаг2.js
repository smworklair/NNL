function просто(н){
  var части = String(н || '').split(',').map(function(т){ return т.trim(); }).filter(Boolean);
  if(!части.length) return '';
  var т = части[0];
  for(var i = 1; i < части.length && т.length < 16; i++){
    if((т + ', ' + части[i]).length > 40) break;
    т = т + ', ' + части[i];
  }
  if(т.length > 46){
    var срез = т.slice(0, 46);
    var пробел = срез.lastIndexOf(' ');
    if(пробел > 24) т = срез.slice(0, пробел).replace(/[—–-]+$/, '').trim() + '…';
  }
  return т;
}

