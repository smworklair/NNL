function скопироватьТекст(текст, кнопка){
  var был = кнопка.textContent;
  var готово = function(){
    кнопка.textContent = 'Скопировано';
    setTimeout(function(){ кнопка.textContent = был; }, 1600);
  };
  var запас = function(){
    var т = document.createElement('textarea');
    т.value = текст;
    т.setAttribute('readonly', '');
    т.style.position = 'fixed';
    т.style.top = '-100px';
    document.body.appendChild(т);
    т.select();
    try{ document.execCommand('copy'); готово(); }catch(e){}
    document.body.removeChild(т);
  };
  if(navigator.clipboard && navigator.clipboard.writeText){
    navigator.clipboard.writeText(текст).then(готово, запас);
  } else {
    запас();
  }
}

