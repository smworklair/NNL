function подкачатьГрафы(){
  if(!СтатьиКаталог) return;
  var обещания = СтатьиКаталог.map(function(с){
    var и = String(с.ид);
    if(графыЛишь[и]) return null;
    return запросСтатьи(и).then(function(а){
      var графы = [], ключи = {};
      (((а && а.пункты) || [])).forEach(function(п){
        var г = (п.графы || [])[0];
        г = г == null ? '' : String(г).trim();
        if(!г || ключи[г]) return;
        ключи[г] = true;
        графы.push(г);
      });
      if(!графы.length) return;
      графы.sort(function(х, у){
        var ох = ПОРЯДОК_ГРАФ.indexOf(графаПервая(х)), оу = ПОРЯДОК_ГРАФ.indexOf(графаПервая(у));
        if(ох !== оу) return ох - оу;
        return х.localeCompare(у, 'ru');
      });
      графыЛишь[и] = {мин:графы[0], макс:графы[графы.length-1]};
    }).catch(function(){});
  }).filter(Boolean);
  if(!обещания.length) return;
  Promise.all(обещания).then(function(){
    if(document.documentElement.getAttribute('data-режим') === 'документация') отрисоватьДок();
  });
}

