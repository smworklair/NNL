function отфильтрованныеСтатьи(){
  var ф = рсФильтр.trim().toLowerCase();
  if(!ф) return null;
  var толькоЦифры = /^\d+$/.test(ф);
  if(толькоЦифры) return СтатьиКаталог.filter(function(с){ return String(с.ид).indexOf(ф) === 0; }).sort(поНомеру);
  var ток = [ф];
  БЫТОВЫЕ.forEach(function(п){ if(ф.indexOf(п[0]) !== -1) ток = ток.concat(п[1]); });
  return СтатьиКаталог.filter(function(с){
    var н = String(с.название || '').toLowerCase();
    return ток.some(function(т){ return н.indexOf(т) !== -1; });
  }).sort(поНомеру);
}

