var ПОРЯДОК_ГРАФ = ['А','Б','В','Г','Д'];
function графаПервая(г){
  var с = String(г || '').trim().toUpperCase(), н = parseInt(с, 10);
  if(!isNaN(н) && н >= 1 && н <= ПОРЯДОК_ГРАФ.length) return ПОРЯДОК_ГРАФ[н-1];
  for(var i = 0; i < ПОРЯДОК_ГРАФ.length; i++){ if(с.indexOf(ПОРЯДОК_ГРАФ[i]) === 0) return ПОРЯДОК_ГРАФ[i]; }
  return с.charAt(0) || null;
}

