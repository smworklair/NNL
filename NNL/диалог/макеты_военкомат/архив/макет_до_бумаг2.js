var МЕСЯЦЫ_Р = ['января','февраля','марта','апреля','мая','июня','июля','августа','сентября','октября','ноября','декабря'];

function подписьПоля(до, дата){
  var к = до.replace(/«_+»|_+/g, ' ').replace(/\s+/g, ' ').trim();
  var ч = к.split(/[.;—]\s*/); к = (ч.pop() || '').replace(/[:,]\s*$/, '').trim();
  var сл = к.split(' ').slice(-5).join(' ').toLowerCase();
  if(дата){
    var пс = к.toLowerCase().split(' ').pop();
    if(пс === 'с') return 'Начало периода';
    if(пс === 'по') return 'Конец периода';
    var сл3 = к.split(' ').slice(-3).join(' ').toLowerCase();
    return 'Дата' + (сл3 ? ' — ' + сл3 : '');
  }
  return сл ? сл.charAt(0).toUpperCase() + сл.slice(1) : 'Впишите';
}
function разобратьБумагу(н){
  if(бумПоляКэш[н]) return бумПоляКэш[н];
  var б = БУМАГИ[н], абзацы = [], поля = [];
  б.тело.forEach(function(т){
    var сег = [], поз = 0, м, рег = /(«_{2,}»\s*_{3,}\s*20_{2,}\s*г\.)|(_{4,})(\s*\(([^)]{2,}?)\))?/g;
    while((м = рег.exec(т))){
      if(м.index > поз) сег.push({т:т.slice(поз, м.index)});
      var дата = !!м[1], хинт = м[4] || '';
      var подп = хинт ? хинт.replace(/^укажите[,:]?\s*/i, '') : подписьПоля(т.slice(0, м.index), дата);
      подп = подп.charAt(0).toUpperCase() + подп.slice(1);
      var ф = {и:поля.length, дата:дата, исх:м[0], подпись:подп,
        длинное: !дата && (хинт.length > 28 || /опишите|перечислите|обстоятельства|факт|довод/i.test(хинт)),
        контекст: (м.index > 55 ? '…' : '') + т.slice(Math.max(0, м.index - 55), м.index).replace(/«_+»\s*_+\s*20_+\s*г\./g, '__.__.____').replace(/_{3,}/g, '___') +
          '[ ___ ]' + т.slice(м.index + м[0].length, м.index + м[0].length + 40).replace(/«_+»\s*_+\s*20_+\s*г\./g, '__.__.____').replace(/_{3,}/g, '___') + (м.index + м[0].length + 40 < т.length ? '…' : '')};
      поля.push(ф); сег.push({п:ф}); поз = м.index + м[0].length;
    }
    if(поз < т.length) сег.push({т:т.slice(поз)});
    абзацы.push(сег);
  });
  return (бумПоляКэш[н] = {абзацы:абзацы, поля:поля});
}
