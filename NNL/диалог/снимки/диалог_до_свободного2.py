def _обрезать(текст, предел):
    текст = текст or ""
    return текст if len(текст) <= предел else текст[:предел] + "… (+%d симв.)" % (len(текст) - предел)


def числа_с_единицами(текст):
    out = []
    for m in _ЧИСЛО_С_ЕД.finditer(текст):
        out += [З.норм_число(x) for x in re.findall(r"\d+(?:[.,]\d+)?", m.group(1))]
    return out


def проверка_чисел(текст, разрешено):
    найдены = числа_с_единицами(текст)
    нет = sorted({x for x in найдены if x not in разрешено})
    return {"чисел_с_единицами": len(найдены), "нет_в_источнике": нет, "вырождение": bool(_ПОВТОР.search(текст))}


