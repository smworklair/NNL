    def _завершить_ход(self, ответ, тел, t0, начало_журнала, разбор_вопросов):
        self.история += [("user", self.слова_человека[-1]), ("model", ответ)]
        вызовы = К.вызовы_после(начало_журнала)
        self.след.шаг("система", "Ответ готов", "%.1f с · вызовов модели: %d · токенов: %d" % (
            time.time() - t0, sum(1 for в in вызовы if not в["кэш"]), sum((в["вход"] or 0) + (в["выход"] or 0) for в in вызовы)), действие=тел.get("действие"))
        тел.update({
            "след": self.след.события, "реплика": self.слова_человека[-1], "подтверждено_врачом": self.ср.подтверждено_врачом(),
            "ответ": ответ, "закончено": self.закончено,
            "все_p": {ид: round(self.ср.p(ид), 3) for ид in self.ср.статьи}, "рейтинг": [{"статья": ид, "название": self.с.база.статьи[ид].название, "p": round(p, 3)} for ид, p in self.ср.рейтинг(8)],
            "улики": self.ср.улики[-6:], "вопросы_разбор": разбор_вопросов, "задано_вопросов": len(self.ср.задано),
            "вызовы": вызовы, "мс": int(1000 * (time.time() - t0)),
            "вызовов_модели": sum(1 for в in вызовы if not в["кэш"]), "токены": sum((в["вход"] or 0) + (в["выход"] or 0) for в in вызовы),
            "блоки": self.с.блоки.паспорта()})
        return тел

    # ------------------------------------------------------------------ только ядро: ни одного вызова модели
    def ход_ядра(self, текст):
        """Режим «NNL»: ядро само, без внешних моделей. Фраза целиком — одно упоминание для своего блока; отрицание и «кто подтвердил» — по словам-маркерам.
        Ответ строится из текста документа (названия и критерии статей), без пересказа моделью. Ограничение: без модели нет разбора на отдельные жалобы."""
        t0 = time.time()
        начало = К.метка_журнала()
        self.шаг += 1
        self.слова_человека.append(текст)
        тел = {"шаг": self.шаг, "режим": "nnl"}
        self._начать_след("nnl", текст)
        cz, cp = self.с.блоки.область(" ".join(self.слова_человека))
        тел["ворота"] = {"здоровье": round(cz, 2), "право": round(cp, 2)}
        self._след_ворота(cz, cp)
        if not self.ср.есть_улики() and max(cz, cp) < 0:
            тел.update(действие="вне_темы", причина="область:здоровье=%.2f, область:право=%.2f — оба ниже нуля" % (cz, cp))
            self.след.шаг("ядро", "Ядро решило: вне темы", тел["причина"], действие="вне_темы")
            ответ = "Ядро работает с Расписанием болезней и воинским учётом. Опишите жалобы, диагноз или вопрос по призыву."
            return self._завершить_ход(ответ, тел, t0, начало, [])
        if not self.ср.есть_улики() and cp >= 0 > cz:
            право, p0 = self.с.блоки.право(текст, топ=1)
            if право and право[0][1] >= 0.3:
                т = self.с.база.темы[право[0][0]]
                тел.update(действие="право", причина="здоровья в реплике нет, область:право=%.2f" % cp, право={"тема": право[0][0], "p": round(право[0][1], 3)})
                self.след.шаг("блоки", "Блок «право» нашёл тему: %s" % т["название"], "p=%.2f" % право[0][1], тема=право[0][0], p=round(право[0][1], 3))
                self.след.шаг("ядро", "Ядро решило: ответить по правовой теме", тел["причина"], действие="право")
                return self._завершить_ход("Правовая тема: %s.\n%s" % (т["название"], т["суть"]), тел, t0, начало, [])
        статус = "нет" if _ОТРИЦАНИЕ.search(текст) else "есть"
        кто = "врач" if _ВРАЧ.search(текст) else "нет_данных"
        self.след.шаг("ядро", "Без модели: статус и «кто подтвердил» определены по словам-маркерам", "статус «%s», подтверждение «%s»: фраза целиком — одно упоминание" % (статус, кто),
                      статус=статус, кто_подтвердил=кто)
        p, p0 = self.с.блоки.статьи(текст)
        запись = self.ср.учесть_упоминание(текст[:80], статус, "", p, p0, кто)
        self._след_упоминание({"термин": текст[:80], "статус": статус, "кто_подтвердил": кто}, p, p0, запись)
        тел["разбор"] = {"упоминания": [{"термин": текст[:80], "статус": статус, "кто_подтвердил": кто}], "ответ_на_вопрос": "нет_вопроса", "значение": "", "хочет_завершить": False}
        кандидаты = self.ср.кандидаты(порог=0.1, n=3)
        тел.update(действие="показать_статьи" if кандидаты else "открытый_вопрос",
                   причина=("кандидаты: " + ", ".join("ст.%s %.2f" % x for x in кандидаты)) if кандидаты else "ни одна статья не набрала 0.10 — нужны конкретные жалобы или диагнозы")
        self.след.шаг("ядро", "Ядро решило: %s" % _ДЕЙСТВИЯ[тел["действие"]], тел["причина"], действие=тел["действие"],
                      рейтинг=[{"статья": ид, "p": round(pp, 3)} for ид, pp in self.ср.рейтинг(5)])
        врач = self.ср.подтверждено_врачом()
        if not кандидаты:
            ответ = "По этим словам ни одна статья Расписания не набрала заметной вероятности. Опишите жалобы, диагноз или результат обследования."
        else:
            скудно = len(self.ср.улики) == 1 and len(текст.split()) < 5 and not re.search(r"\d", текст) and кто != "врач"      # одна общая фраза без диагноза и чисел: уверенности быть не может
            строки = ["Пока слишком мало данных: это ближайшие по словам статьи, а не вывод." if скудно else "Ближе всего к вашим словам (по тексту Расписания болезней):"]
            for ид, pp in кандидаты:
                строки.append("• ст. %s «%s» — %s" % (ид, self.с.база.статьи[ид].название, _словами(min(pp, 0.45) if скудно else pp)))
            первая = self.с.база.статьи[кандидаты[0][0]]
            строки.append("\nКритерии ст. %s (графа I, призывник):" % первая.ид)
            for пункт in первая.пункты[:6]:
                кат = (" → категория " + пункт["графы"][0]) if врач and пункт["графы"] else ""
                строки.append("  п. «%s»: %s%s" % (пункт["буква"], пункт["описание"][:260], кат))
            строки.append("\n" + ("Врач подтвердил хотя бы часть сказанного, поэтому категории показаны по тексту документа." if врач else
                                  "Категории не называю: врач пока ничего не подтвердил. Напишите, какой диагноз поставлен, чем подтверждён и какие значения измерены."))
            ответ = "\n".join(строки)
        return self._завершить_ход(ответ, тел, t0, начало, [])

    # ------------------------------------------------------------------ та же модель без ядра (для честного сравнения)
