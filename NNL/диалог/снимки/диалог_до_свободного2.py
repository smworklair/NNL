    @staticmethod
    def _схема_вопросов(кандидаты):
        """В поле «статья» разрешены только номера статей-кандидатов: мусор вроде «}, » структурный вывод породить не может."""
        import copy
        схема = copy.deepcopy(СХЕМА_ВОПРОСОВ)
        схема["properties"]["вопросы"]["items"]["properties"]["статья"] = {"type": "string", "enum": [ид for ид, _ in кандидаты]}
        return схема

    def _только_просьба_итога(self, текст):
        return bool(_ИТОГ_ЗАПРОС.search(текст)) and len(текст.split()) <= 6 and not re.search(r"\d", текст) and self.ср.есть_улики()

    def _без_известного(self, предложения):
        """Из банка выкидываем вопросы, ответ на которые человек уже дал: «чем подтверждён диагноз», если врач уже подтвердил."""
        if self.ср.подтверждено_врачом():
            return [q for q in предложения if q.get("тема") != "подтверждение"]
        return предложения

    def _запрос_вопросов(self, кандидаты, последняя):
        спрошено = "\n".join("- (ст.%s) %s" % x for x in self.ср.задано) or "— пока ничего"
        return ("Последняя реплика человека: %s\n\nЧто уже известно:\n%s\n\nУже заданные вопросы:\n%s\n\nСтатьи-кандидаты:\n%s" % (
            последняя, self._что_известно(), спрошено, self._досье_статей(кандидаты[:3], 1400)))

    def _с_охраной_чисел(self, текст, разрешено, метка, переписать=None):
        охрана = проверка_чисел(текст, разрешено)
        охрана["перегенерировано"] = False
        if (охрана["нет_в_источнике"] or охрана["вырождение"]) and переписать:
            охрана["перегенерировано"] = True
            текст2 = переписать(охрана["нет_в_источнике"], охрана["вырождение"])
            охрана2 = проверка_чисел(текст2, разрешено)
            охрана2["перегенерировано"] = True
            текст, охрана = текст2, охрана2
        if охрана["нет_в_источнике"]:
            if переписать is None:
                # короткая реакция: проще убрать фразу с неподтверждёнными числами, чем переписывать
                части = [s for s in re.split(r"(?<=[.!?])\s+", текст) if not any(x in set(числа_с_единицами(s)) for x in охрана["нет_в_источнике"])]
                текст = " ".join(части)
                охрана["убрано_предложений_с_неподтверждёнными_числами"] = True
            else:
                текст += "\n\n⚠ Числа %s в этом тексте не удалось сверить с документом — перепроверьте их по Расписанию." % ", ".join(охрана["нет_в_источнике"])
        охрана["где"] = метка
        нет = охрана["нет_в_источнике"]
        self.след.шаг("охрана", "Охрана чисел: %s" % метка,
                      ("все числа с единицами есть в документе или в словах человека (проверено: %d)" % охрана["чисел_с_единицами"]) if not нет and not охрана["вырождение"]
                      else "вне источника: %s%s%s" % (", ".join(нет) or "—", " · бессмысленные повторы" if охрана["вырождение"] else "", " · текст переписан" if охрана["перегенерировано"] else ""),
                      чисел=охрана["чисел_с_единицами"], вне_источника=нет, перегенерировано=охрана["перегенерировано"], вырождение=охрана["вырождение"])
        return текст, охрана

    def _итог(self, тел):
        кандидаты = self.ср.кандидаты(порог=0.2, n=3) or self.ср.кандидаты(порог=0.05, n=2)
        досье = ["Слова человека:\n" + "\n".join("- " + s for s in self.слова_человека), "Что извлечено:\n" + self._что_известно(),
                 "Насколько вероятно, что статья относится к человеку (для твоей оценки; цифр и слова «система» в ответе не используй):\n" +
                 "\n".join("- статья %s: %s" % (ид, _словами(pp)) for ид, pp in self.ср.рейтинг(5)),
                 "Тексты статей-кандидатов:\n" + self._досье_итога(кандидаты[:2], 2400, 900)]
        разрешён = self.ср.подтверждено_врачом()
        досье.append("ВЕРДИКТ ПО КАТЕГОРИИ: " + ("разрешён: есть данные, подтверждённые врачом." if разрешён else
                     "ЗАПРЕЩЁН. Врач ничего не подтвердил, есть только слова человека. Категорию годности не называй вообще и не говори «ограниченно годен», «освобождение», "
                     "«годен»; объясни, какие критерии документа важны и что нужно подтвердить у врача и чем."))
        право, p0 = self.с.блоки.право(" ".join(self.слова_человека), топ=1)
        if право and право[0][1] >= 0.5:
            т = self.с.база.темы[право[0][0]]
            досье.append("Правовая тема (свой блок «право», p=%.2f): %s\n%s" % (право[0][1], т["название"], т["суть"]))
            тел["право"] = {"тема": право[0][0], "p": round(право[0][1], 3)}
            self.след.шаг("блоки", "Блок «право» нашёл тему: %s" % т["название"], "p=%.2f; тема добавлена в досье" % право[0][1], тема=право[0][0], p=round(право[0][1], 3))
        разрешено = self._разрешённые_числа([ид for ид, _ in кандидаты]) | З.нормализованные_числа(досье[-1])
        запрос = "\n\n".join(досье)
        ид_досье = [ид for ид, _ in кандидаты[:2]] + [ид for ид, _ in self.ср.рейтинг(5)]
        self.след.шаг("ядро", "Ядро собрало досье для API: ст. %s" % ", ".join(sorted(set(ид_досье), key=int)),
                      "API получит только это: слова человека, извлечённые факты, вероятности словами, тексты статей-кандидатов. Категория: %s." %
                      ("разрешена — врач подтвердил" if разрешён else "запрещена — врач ничего не подтвердил"), статьи_в_досье=sorted(set(ид_досье), key=int), категория_разрешена=разрешён)

        def написать(запрещённые=None, вырождение=False, без_категории=False):
            доп = ("\n\nВ прошлом черновике были числа, которых нет в досье: %s. Перепиши без них." % ", ".join(запрещённые)) if запрещённые else ""
            if вырождение:
                доп += "\n\nВ прошлом черновике были бессмысленные повторы слов. Перепиши связным текстом."
            if без_категории:
                доп += "\n\nВ прошлом черновике ты назвал категорию годности, хотя врач ничего не подтвердил. Перепиши: категорию и слова «ограниченно годен», «освобождение» не используй вообще."
            return self._вызов("итог", СИСТЕМА_ИТОГА, [("user", запрос + доп)], температура=0.3 if вырождение else 0.5, макс_токенов=900, досье=ид_досье)["текст"]
        текст = написать()
        текст, охрана = self._с_охраной_чисел(текст, разрешено, "итог", переписать=написать)
        if not разрешён and _КАТЕГОРИЯ_В_ТЕКСТЕ.search(текст):
            охрана["вердикт_без_подтверждения"] = True
            self.след.шаг("охрана", "Охрана категории: API назвал категорию без подтверждения врача", "текст переписывается без категории", вердикт_без_подтверждения=True)
            текст2 = написать(None, False, без_категории=True)
            охрана["перегенерировано_без_категории"] = True
            if _КАТЕГОРИЯ_В_ТЕКСТЕ.search(текст2):
                текст2 += "\n\n⚠ Если выше названа категория годности — не опирайтесь на неё: врач пока ничего не подтвердил."
            текст = текст2
        охрана["вердикт_разрешён"] = разрешён
        охрана["предупреждение_в_конце"] = bool(re.search(r"не\s+врач|не\s+диагноз|не\s+ставлю", текст[-500:], re.I))
        тел["кандидаты_итога"] = [(ид, round(p, 3)) for ид, p in кандидаты]
        return текст, охрана

