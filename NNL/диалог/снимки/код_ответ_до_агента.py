# -*- coding: utf-8 -*-
"""Ответы NNL для бенчмарка БЕЗ участия API в решении: статью даёт блок «здоровье», пункт и категорию решает код по тексту статьи,
право на категорию даёт ядро (подтвердил ли врач). API (если нужен) — только слушатель: переводит слова человека в факты (тесты 4–5).

Режимы по тестам:
  1 — статья = лидер блока при p ≥ ПОРОГ_СТАТЬИ, иначе «не определяется»; категория «нельзя определить без врача»;
  2 — пороги читаются из текста ст. 34 (графа I): «более X» строго, «до Y» включительно, худший глаз; без API;
  3 — ворота области → «вне темы»; иначе «да», если лидер блока — ст. 34 (p ≥ 0,3), иначе «нет»; без API;
  4 — слушатель разбирает слова (кто подтвердил), ядро решает: нет врача → «нельзя определить без врача»; есть врач → пункт по порогам (дптр)
      или по совпадению слов с описаниями пунктов статьи; категория из графы I;
  5 — диалог по репликам: ядро ведёт улики; итог по тем же правилам; поправки берутся из последней реплики с числом."""
import re

import диалог as Д
import клиент as К

ПОРОГ_СТАТЬИ = 0.5
ПОРОГ_ДА = 0.3
_ЧИСЛО = re.compile(r"[−\-–]\s?(\d+(?:[.,]\d+)?)")
СТЕПЕНИ = {"тяжел", "средн", "легка", "легко", "значи", "умере", "незна"}
_ВОПРОС_КАТЕГОРИЯ = re.compile(r"\s*Какая у меня будет категория годности\?\s*$")


def _е(s):
    return s.lower().replace("ё", "е")


def _основы(текст):
    return {w[:5] for w in re.findall(r"[а-яa-z]{4,}", _е(текст))}


class КодОтвет:
    def __init__(self, система, роли=None):
        self.с = система
        self.роли = роли
        self._диапазоны = None

    # ------------------------------------------------------------ пороги из текста ст. 34
    def диапазоны_близорукости(self):
        """[(нижняя, верхняя|None, буква, категория)] — из текста статьи, не из головы."""
        if self._диапазоны is None:
            out = []
            for п in self.с.база.статьи["34"].пункты:
                m = re.search(r"близорукост[^|]*?более\s+([\d,]+)\s*дптр(?:\s+и\s+до\s+([\d,]+)\s*дптр)?", п["описание"])
                if m:
                    low = float(m.group(1).replace(",", "."))
                    up = float(m.group(2).replace(",", ".")) if m.group(2) else None
                    out.append((low, up, п["буква"], п["графы"][0] if п["графы"] else "—"))
            self._диапазоны = out
        return self._диапазоны

    def пункт_по_диоптриям(self, x):
        """Худший глаз x (по модулю): «более» — строго, «до» — включительно. Ничего не подошло — «не применяется»."""
        for low, up, буква, кат in self.диапазоны_близорукости():
            if x > low and (up is None or x <= up):
                return буква, кат, "%s дптр: более %s%s" % (x, low, (" и до %s" % up) if up is not None else "")
        return "не применяется", "нет категории", "%s дптр: не более 3,0" % x

    # ------------------------------------------------------------ блок
    def блок(self, фраза):
        p, p0 = self.с.блоки.статьи(фраза[:400])
        return sorted(p.items(), key=lambda x: -x[1])[:3], p0

    # ------------------------------------------------------------ тест 1
    def тест1(self, случаи):
        строки = []
        for н, ф in случаи:
            топ, p0 = self.блок(ф)
            ид, p = топ[0]
            if p >= ПОРОГ_СТАТЬИ:
                строки.append("%s. статья %s | категория нельзя определить без врача | блок «здоровье»: ст. %s «%s», p=%.2f" % (н, ид, ид, self.с.база.статьи[ид].название[:50], p))
            else:
                строки.append("%s. статья не определяется | категория нельзя определить без врача | блок не уверен: лидер ст. %s, p=%.2f" % (н, ид, p))
        return "\n".join(строки)

    # ------------------------------------------------------------ тест 2
    def тест2(self, случаи):
        строки = []
        for н, ф in случаи:
            m = re.search(r"правый глаз\s*[−\-–]?\s*([\d.,]+)\s*дптр,\s*левый глаз\s*[−\-–]?\s*([\d.,]+)", ф)
            if not m:
                строки.append("%s. пункт не применяется | категория нет категории | числа не найдены" % н)
                continue
            a, b = (float(m.group(i).replace(",", ".")) for i in (1, 2))
            буква, кат, почему = self.пункт_по_диоптриям(max(a, b))
            строки.append("%s. пункт %s | категория %s | худший глаз %s" % (н, буква, кат, почему))
        return "\n".join(строки)

    # ------------------------------------------------------------ тест 3
    def тест3(self, случаи):
        строки = []
        for н, ф in случаи:
            m = re.search(r"у него:\s*([^.]+)\.", ф)
            х = m.group(1).strip() if m else ф
            cz, cp = self.с.блоки.область(х)
            if max(cz, cp) < 0:
                строки.append("%s. вне темы | ворота области: здоровье=%.2f, право=%.2f" % (н, cz, cp))
                continue
            топ, _ = self.блок(х)
            ид, p = топ[0]
            if ид == "34" and p >= ПОРОГ_ДА:
                строки.append("%s. да | блок: ст. 34 «Нарушения рефракции и аккомодации», p=%.2f" % (н, p))
            else:
                строки.append("%s. нет | блок: лучшая статья ст. %s «%s», p=%.2f; ст. 34 не лидер" % (н, ид, self.с.база.статьи[ид].название[:40], p))
        return "\n".join(строки)

    # ------------------------------------------------------------ пункт по словам (ст. 43, 52 и др.)
    def пункт_по_словам(self, ид, текст):
        """Совпадение основ слов с описаниями пунктов; общие для всех пунктов основы не считаются. None — сигнала нет или ничья."""
        пункты = self.с.база.статьи[ид].пункты
        # 1) слова степени («тяжёлой», «умеренным», «незначительным»…): если одно из них названо человеком и стоит в описании одного пункта — это он
        м_осн = _основы(текст)
        по_степени = [i for i, п in enumerate(пункты) if (_основы(п["описание"]) & СТЕПЕНИ & м_осн)]
        if len(по_степени) == 1:
            п = пункты[по_степени[0]]
            return п["буква"], (п["графы"][0] if п["графы"] else "—")
        основы_п = [_основы(п["описание"]) for п in пункты]
        общие = set.intersection(*основы_п) if основы_п else set()
        м = _основы(текст)
        очки = [len((о - общие) & м) for о in основы_п]
        if not очки or max(очки) == 0 or очки.count(max(очки)) > 1:
            return None
        п = пункты[очки.index(max(очки))]
        return п["буква"], (п["графы"][0] if п["графы"] else "—")

    def решение(self, система_слов, фразы):
        """Итог ядра по состоянию сессии: (текст_ответа, структура)."""
        s = система_слов
        рейтинг = s.ср.рейтинг(3)
        врач = s.ср.подтверждено_врачом()
        слова = " ".join(фразы)
        ид, p = (рейтинг[0] if рейтинг else (None, 0.0))
        числа = [float(x.replace(",", ".")) for x in _ЧИСЛО.findall(слова)]
        return врач, ид, p, числа

    # ------------------------------------------------------------ тест 4 и 5 (слушатель — API)
    def _сессия(self):
        s = Д.Сессия(self.с)
        s.роли, s.кэш, s.на_шаг = self.роли, False, None
        s._начать_след("код", "")
        return s

    def тест4(self, случаи):
        строки, вызовы = [], []
        for н, ф in случаи:
            ф = _ВОПРОС_КАТЕГОРИЯ.sub("", ф)
            s = self._сессия()
            метка = К.метка_журнала()
            try:
                s._учесть_реплику(ф)
            except Exception as e:  # noqa: BLE001
                строки.append("%s. статья не определяется | категория нельзя определить без врача | слушатель: %s" % (н, str(e)[:60]))
                continue
            вызовы += К.вызовы_после(метка)
            врач, ид, p, числа = self.решение(s, [ф])
            стат = ("статья %s" % ид) if (ид and p >= ПОРОГ_СТАТЬИ) else "статья не определяется"
            if not врач:
                строки.append("%s. %s | категория нельзя определить без врача | врач ничего не подтвердил (ядро: улики только со слов человека)" % (н, стат))
                continue
            if ид == "34" and числа:
                буква, кат, почему = self.пункт_по_диоптриям(max(числа))
                строки.append("%s. статья 34 | категория %s | врач подтвердил; худший глаз %s (пункт %s)" % (н, кат, почему, буква))
                continue
            рез = self.пункт_по_словам(ид, ф) if ид else None
            if рез:
                строки.append("%s. %s | категория %s | врач подтвердил; пункт «%s» по описанию в статье" % (н, стат, рез[1], рез[0]))
            else:
                строки.append("%s. %s | категория нельзя определить без врача | врач подтвердил, но степень не названа" % (н, стат))
        return "\n".join(строки), вызовы

    def тест5(self, диалоги):
        строки, вызовы = [], []
        for н, реплики in диалоги:
            s = self._сессия()
            метка = К.метка_журнала()
            try:
                for р in реплики:
                    s._учесть_реплику(р)
            except Exception as e:  # noqa: BLE001
                строки.append("Диалог %s: слушатель недоступен: %s" % (н, str(e)[:60]))
                continue
            вызовы += К.вызовы_после(метка)
            врач, ид, p, _ = self.решение(s, реплики)
            # поправка: числа берём из последней реплики, где они есть (человек мог исправиться)
            числа = []
            for р in reversed(реплики):
                числа = [float(x.replace(",", ".")) for x in _ЧИСЛО.findall(р)]
                if числа:
                    break
            последняя = реплики[-1].lower()
            if not s.ср.есть_улики():
                строки.append("Диалог %s: По вашим словам заболеваний, которые относятся к вам, нет; категорию определить нельзя." % н)
            elif числа and (ид == "34" or "близорук" in " ".join(реплики).lower() or "дптр" in " ".join(реплики).lower() or "окулист" in " ".join(реплики).lower()):
                буква, кат, почему = self.пункт_по_диоптриям(max(числа))
                текст = "Ст. 34 по худшему глазу (%s): пункт «%s», категория %s." % (почему, буква, кат)
                if "лучшему" in последняя and len(числа) >= 2:
                    б2, к2, п2 = self.пункт_по_диоптриям(min(числа))
                    текст += " По лучшему глазу (%s) было бы %s, но статья берёт худший глаз." % (п2, к2)
                строки.append("Диалог %s: %s" % (н, текст))
            elif not врач:
                строки.append("Диалог %s: Врач ничего не подтвердил, поэтому категорию определить нельзя; нужны обследование и заключение врача." % н)
            else:
                рез = self.пункт_по_словам(ид, " ".join(реплики)) if ид else None
                if рез:
                    строки.append("Диалог %s: Ст. %s, пункт «%s» по вашим словам, категория %s." % (н, ид, рез[0], рез[1]))
                else:
                    строки.append("Диалог %s: Диагноз подтверждён (ст. %s), но категория зависит от степени тяжести, которой в словах нет; назвать категорию нельзя." % (н, ид))
        return "\n".join(строки), вызовы
