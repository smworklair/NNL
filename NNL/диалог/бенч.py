def _прогнать(сц, роли, система, замок, режим):
    сессия = система.сессия()
    сессия.роли = роли
    сессия.кэш = False             # цену решения считаем по настоящим вызовам: ответ из кэша выглядел бы бесплатным и сравнение с «API» вышло бы нечестным
    ходы = []
    for реплика in сц["реплики"]:
        with (замок or threading.Lock()):              # журнал вызовов общий: один ход за раз на весь сервер
            ходы.append(сессия.ход(реплика) if режим == "ядро" else сессия.ход_базовой(реплика))
    return ходы


def _след_для_файла(ходы, реплики):
    """След сценария для разбора в студии: реплика, ответ, шаги. Длинные вход и рассуждение режем: файл прогона не должен пухнуть."""
    out = []
    for х, р in zip(ходы, реплики):
        шаги = [dict(е, вход=(е["вход"][:1500] if е.get("вход") else None), рассуждение=(е["рассуждение"][:3000] if е.get("рассуждение") else None)) for е in х.get("след", [])]
        out.append({"реплика": р, "ответ": х.get("ответ", "")[:900], "режим": х.get("режим"), "след": шаги})
    return out


