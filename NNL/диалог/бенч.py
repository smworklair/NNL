def _сводка(кандидат, тест, случаи, доп=None):
    ок = sum(1 for c in случаи if c["верно"])
    ошибок = sum(1 for c in случаи if c.get("ошибка"))
    мс = [c["мс"] for c in случаи if c.get("мс")]
    ток = sum(c.get("токены") or 0 for c in случаи)
    р = {"кандидат": кандидат, "тест": тест, "n": len(случаи), "верно": ок, "доля": round(ок / len(случаи), 4) if случаи else 0.0, "ошибок": ошибок,
         "мс_среднее": int(statistics.mean(мс)) if мс else 0, "мс_медиана": int(statistics.median(мс)) if мс else 0,
         "мс_p95": int(sorted(мс)[max(0, int(round(0.95 * len(мс))) - 1)]) if мс else 0, "токены": ток, "случаи": случаи}
    if доп:
        р["доп"] = доп
    return р


