def _проверка(имя, ходы, сессия):
    последний = ходы[-1]
    текст = последний.get("ответ", "")
    рейтинг = [r for r in последний.get("рейтинг", [])]
    if имя == "статья_34_в_тройке":
        return any(r["статья"] == "34" for r in рейтинг[:3]), "первые три: " + ", ".join(r["статья"] for r in рейтинг[:3])
    if имя == "астма_в_тройке":
        return any("астм" in r["название"].lower() or "бронх" in r["название"].lower() for r in рейтинг[:3]), "первые три: " + ", ".join(r["статья"] for r in рейтинг[:3])
    if имя == "чисел_вне_источника":
        нет = sorted({x for х in ходы for x in ((х.get("охрана_чисел") or {}).get("нет_в_источнике") or [])})
        нет += [x for x in Д.проверка_чисел(текст, сессия.с.все_числа_документа | З.нормализованные_числа(" ".join(сессия.слова_человека)))["нет_в_источнике"] if x not in нет]
        return not нет, ("вне источника: " + ", ".join(нет)) if нет else "все числа из документа или слов человека"
    if имя == "нет_слов_про_систему":
        найдено = sorted({m.group(0).lower() for х in ходы for m in _ЗАПРЕТ_СЛОВ.finditer(х.get("ответ", ""))})
        return not найдено, ("найдено: " + ", ".join(найдено)) if найдено else "чисто"
    if имя == "ссылки_существуют":
        битые = [s["причина"] for х in ходы for s in С.найти(х.get("ответ", ""), сессия.с.база) if not s["ок"]]
        return not битые, "; ".join(битые) if битые else "все ссылки на существующие статьи и пункты"
    if имя == "нет_категории_без_врача":
        чистый = re.sub(r"⚠.*", "", текст, flags=re.S)
        return not Д._КАТЕГОРИЯ_В_ТЕКСТЕ.search(чистый) or сессия.ср.подтверждено_врачом(), "категория в тексте: %s, врач подтвердил: %s" % (bool(Д._КАТЕГОРИЯ_В_ТЕКСТЕ.search(чистый)), сессия.ср.подтверждено_врачом())
    if имя == "не_начат_разбор_здоровья":
        return последний.get("действие") not in ("спросить", "итог", "завершить"), "действие: %s" % последний.get("действие")
    if имя == "есть_ответ":
        return len(текст.strip()) > 20 and not Д._ПОВТОР.search(текст), "длина %d, повторов слов: %s" % (len(текст.strip()), bool(Д._ПОВТОР.search(текст)))
    return False, "неизвестная проверка"


def _роли_кандидата(кандидат):
    if кандидат.startswith("пресет:"):
        return dict(Д.ПРЕСЕТЫ[кандидат.split(":", 1)[1]])
    пров, мод = _разбить(кандидат)
    return {р: (пров, мод) for р in ("разбор", "вопросы", "итог", "речь", "базовая")}


def тест_система(кандидат, ход, система=None, замок=None, **_):
    роли = _роли_кандидата(кандидат)
    случаи = []
    for сц in СЦЕНАРИИ:
        c = {"id": сц["id"], "ожидалось": "все проверки пройдены"}
        t0 = time.time()
        ходы = []
        try:
            сессия = система.сессия()
            сессия.роли = роли
            for реплика in сц["реплики"]:
                with (замок or threading.Lock()):          # журнал вызовов общий: один ход за раз на весь сервер
                    ходы.append(сессия.ход(реплика))
            итоги = [(имя,) + _проверка(имя, ходы, сессия) for имя in сц["проверки"]]
            c.update(проверки=[{"имя": a, "ок": bool(b), "заметка": d} for a, b, d in итоги], верно=all(b for _, b, _ in итоги),
                     получено="%d из %d проверок" % (sum(1 for _, b, _ in итоги if b), len(итоги)), мс=int(1000 * (time.time() - t0)),
                     токены=sum(х.get("токены", 0) for х in ходы), вызовов=sum(х.get("вызовов_модели", 0) for х in ходы),
                     ответ=ходы[-1].get("ответ", "")[:700])
        except Exception as e:  # noqa: BLE001
            c.update(получено="", верно=False, ошибка=("%s: %s" % (type(e).__name__, e))[:140], мс=int(1000 * (time.time() - t0)))
        случаи.append(c)
        ход()
    пров = [p for c in случаи for p in c.get("проверки", [])]
    return _сводка(кандидат, "система", случаи, {"проверок_пройдено": "%d/%d" % (sum(1 for p in пров if p["ок"]), len(пров)), "вызовов_модели": sum(c.get("вызовов", 0) for c in случаи)})


