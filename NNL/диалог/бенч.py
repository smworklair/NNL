def запустить(кандидаты, тесты, метка="", система=None, замок=None):
    ид = uuid.uuid4().hex[:10]
    итого = sum(_ЧИСЛО_СЛУЧАЕВ[т] for т in тесты) * len(кандидаты)
    з = {"id": ид, "метка": метка or time.strftime("%H:%M"), "кандидаты": кандидаты, "тесты": тесты, "состояние": "идёт", "сделано": 0, "всего": итого,
         "начато": time.strftime("%Y-%m-%d %H:%M:%S"), "результаты": [], "ошибки": []}
    with _замок_задач:
        ЗАДАЧИ[ид] = з

    def ход():
        with _замок_задач:
            з["сделано"] += 1

    def работа(кандидат):
        for т in тесты:
            try:
                if т not in ("система", "наблюдение") and кандидат.startswith("пресет:"):
                    continue
                if "=>" in кандидат and т != "наблюдение":          # пара «следователь=>детектив» осмысленна только для теста «Наблюдение»
                    continue
                р = _ИСПОЛНИТЕЛИ[т](кандидат, ход, система=система, замок=замок)
                with _замок_задач:
                    з["результаты"].append(р)
            except Exception as e:  # noqa: BLE001
                with _замок_задач:
                    з["ошибки"].append("%s / %s: %s" % (кандидат, т, e))
                    з["сделано"] += _ЧИСЛО_СЛУЧАЕВ[т]

    def главный():
        with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, len(кандидаты))) as ex:
            list(ex.map(работа, кандидаты))
        os.makedirs(КАТАЛОГ, exist_ok=True)
        з["сохранено"] = "%s_%s.json" % (time.strftime("%Y%m%d-%H%M%S"), re.sub(r"[^\w\-]+", "_", з["метка"])[:30])
        with open(os.path.join(КАТАЛОГ, з["сохранено"]), "w", encoding="utf-8") as f:
            json.dump({k: з[k] for k in ("id", "метка", "кандидаты", "тесты", "начато", "результаты", "ошибки")}, f, ensure_ascii=False, indent=1)
        з["состояние"] = "готово"

    threading.Thread(target=главный, daemon=True).start()
    return ид


def статус(ид):
    з = ЗАДАЧИ.get(ид)
    if not з:
        return None
    with _замок_задач:
        return json.loads(json.dumps({k: з.get(k) for k in ("id", "метка", "кандидаты", "тесты", "состояние", "сделано", "всего", "начато", "результаты", "ошибки", "сохранено")}, ensure_ascii=False))


def история():
    os.makedirs(КАТАЛОГ, exist_ok=True)
    out = []
    for имя in sorted(os.listdir(КАТАЛОГ), reverse=True):
        if имя.endswith(".json"):
            try:
                with open(os.path.join(КАТАЛОГ, имя), encoding="utf-8") as f:
                    д = json.load(f)
                out.append({"файл": имя, "метка": д.get("метка"), "начато": д.get("начато"), "кандидаты": д.get("кандидаты"), "тесты": д.get("тесты")})
            except Exception:  # noqa: BLE001
                pass
    return out


def загрузить(файл):
    if "/" in файл or "\\" in файл or not файл.endswith(".json"):
        return None
    путь = os.path.join(КАТАЛОГ, файл)
    if not os.path.exists(путь):
        return None
    with open(путь, encoding="utf-8") as f:
        return json.load(f)
