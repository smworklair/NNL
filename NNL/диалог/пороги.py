# -*- coding: utf-8 -*-
"""Калькуляторы порогов для страницы статьи справочника. Числа берутся из ТЕКСТА статьи кодом, страница их не знает и не угадывает.

Поддержаны только статьи, где текст однозначен:
  40 — слух: расстояние шёпота на каждое ухо (пункты «б», «в»);
  86 — недостаточное физическое развитие: масса и рост (пункт «а», примечание с «и (или)»), «впервые» → пункт «б»;
  13 — индекс массы тела: недостаточность и пониженное питание (примечание про ИМТ), пункт «д».
Статья 34 (диоптрии) считается в код_ответ.КодОтвет. Остальные статьи описательные («со значительным нарушением функций»): без заключения врача число не даёт пункта.
Если формулировка в тексте не разобралась по ожидаемому шаблону, бросается Нельзя: страница тогда просто не показывает калькулятор."""
import re


class Нельзя(Exception):
    """Текст статьи не соответствует ожидаемому шаблону — считать нельзя."""


def _ч(s):
    return float(str(s).replace(",", "."))


def _пункт(ст, буква):
    for п in ст.пункты:
        if п["буква"] == буква:
            return п
    raise Нельзя("в статье %s нет пункта «%s»" % (ст.ид, буква))


def _кат(п):
    return п["графы"][0] if п.get("графы") else "—"


def _примечания(ст):
    return " ".join(ст.примечания)


def _цифра(x):
    return ("%g" % x).replace(".", ",")


# ------------------------------------------------------------------ 40: слух
def _слух_пороги(ст):
    б, в = _пункт(ст, "б"), _пункт(ст, "в")
    ш = r"отсутствии восприятия шепотной речи на одно ухо и при восприятии шепотной речи на расстоянии %s (\d+) м на другое ухо или .*?до (\d+) м на одно ухо и на расстоянии до (\d+) м на другое ухо"
    рб, рв = re.search(ш % "до", б["описание"]), re.search(ш % "более", в["описание"])
    if not рб or not рв:
        raise Нельзя("пункты «б» и «в» ст. 40 разобраны не по шаблону")
    б1, б2, б3 = (int(x) for x in рб.groups())
    в1, в2, в3 = (int(x) for x in рв.groups())
    if б1 != в1:
        raise Нельзя("граница «до %d м» (п. б) и «более %d м» (п. в) не совпадают" % (б1, в1))
    return {"граница": б1, "б": (б2, б3), "в": (в2, в3), "кат": {"а": _кат(_пункт(ст, "а")), "б": _кат(б), "в": _кат(в)}}


def _слух_спец(ст):
    п = _слух_пороги(ст)
    поле = lambda ключ, подпись: {"ключ": ключ, "тип": "число", "подпись": подпись, "мин": 0, "макс": 6, "шаг": 0.5, "ед": "м", "знач": 6, "ноль": "не слышит"}
    return {"заголовок": "Слух: на каком расстоянии слышен шёпот?",
            "подпись": "Двигайте для каждого уха. 0 — не слышит совсем, 6 м — норма. Пороги взяты из пунктов «б» и «в» статьи.",
            "поля": [поле("правое", "Правое ухо"), поле("левое", "Левое ухо")]}


def _слух_решить(ст, з):
    п = _слух_пороги(ст)
    a, b = sorted((_ч(з["правое"]), _ч(з["левое"])))
    с1, с2 = п["б"]; д1, д2 = п["в"]; гр = п["граница"]
    if a == 0 and b == 0:
        return {"пункт": "а", "категория": п["кат"]["а"], "итог": "Глухота на оба уха", "почему": "Нужно удостоверение: глухотой считается отсутствие восприятия крика у ушной раковины, подтверждается специальными методами.", "подсветить": ["а"]}
    if (a == 0 and b <= гр) or (a <= с1 and b <= с2):
        return {"пункт": "б", "категория": п["кат"]["б"], "итог": "Пункт «б»",
                "почему": "Одно ухо не слышит, на другом шёпот до %s м — либо до %s м на одном ухе и до %s м на другом." % (_цифра(гр), _цифра(с1), _цифра(с2)), "подсветить": ["б"]}
    if (a == 0 and b > гр) or (a <= д1 and b <= д2):
        return {"пункт": "в", "категория": п["кат"]["в"], "итог": "Пункт «в»",
                "почему": "Одно ухо не слышит, на другом шёпот дальше %s м — либо до %s м на одном ухе и до %s м на другом." % (_цифра(гр), _цифра(д1), _цифра(д2)), "подсветить": ["в"]}
    return {"пункт": None, "категория": None, "итог": "Ниже порога этой статьи", "почему": "Слух лучше порогов пунктов «б» и «в»: по этой статье ограничений нет.", "подсветить": []}


# ------------------------------------------------------------------ 86: масса и рост
def _рост_пороги(ст):
    а = _пункт(ст, "а"); б = _пункт(ст, "б")
    м = re.search(r"масса тела менее (\d+) кг, рост менее (\d+) см", а["описание"])
    if not м:
        raise Нельзя("пункт «а» ст. 86 разобран не по шаблону")
    масса, рост = int(м.group(1)), int(м.group(2))
    пр = _примечания(ст)
    if not re.search(r"массой тела менее %d кг и \(или\) ростом менее %d см" % (масса, рост), пр):
        raise Нельзя("в примечании ст. 86 нет условия «и (или)»")
    м12 = re.search(r"временно не годными к военной службе на (\d+) месяц", пр)
    return {"масса": масса, "рост": рост, "месяцев": int(м12.group(1)) if м12 else None, "кат": {"а": _кат(а), "б": _кат(б)}}


def _рост_спец(ст):
    п = _рост_пороги(ст)
    return {"заголовок": "Масса тела и рост",
            "подпись": "Хватает одного из двух: масса или рост ниже порога из текста статьи (%s кг, %s см)." % (п["масса"], п["рост"]),
            "поля": [{"ключ": "масса", "тип": "число", "подпись": "Масса тела", "мин": 30, "макс": 100, "шаг": 1, "ед": "кг", "знач": 60},
                     {"ключ": "рост", "тип": "число", "подпись": "Рост", "мин": 130, "макс": 200, "шаг": 1, "ед": "см", "знач": 175},
                     {"ключ": "впервые", "тип": "переключатель", "подпись": "Выявлено впервые, при постановке на учёт или призыве", "знач": True}]}


def _рост_решить(ст, з):
    п = _рост_пороги(ст)
    масса, рост = _ч(з["масса"]), _ч(з["рост"])
    впервые = str(з.get("впервые", "1")).lower() in ("1", "true", "да")
    if масса < п["масса"] or рост < п["рост"]:
        срок = (" на %s мес." % п["месяцев"]) if п["месяцев"] else ""
        if впервые:
            return {"пункт": "б", "категория": п["кат"]["б"], "итог": "Пункт «б»", "почему": "Масса или рост ниже порога, выявлено впервые: временно не годен%s, обследование у эндокринолога." % срок, "подсветить": ["б"]}
        return {"пункт": "а", "категория": п["кат"]["а"], "итог": "Пункт «а»", "почему": "Недостаточное развитие сохраняется после обследования — освидетельствование по пункту «а».", "подсветить": ["а"]}
    return {"пункт": None, "категория": None, "итог": "Не ниже порога", "почему": "Масса не меньше %s кг и рост не меньше %s см: по этой статье ограничений нет (при хорошем физическом развитии)." % (п["масса"], п["рост"]), "подсветить": []}


# ------------------------------------------------------------------ 13: индекс массы тела
def _имт_пороги(ст):
    пр = _примечания(ст)
    м = re.search(r"ИМТ менее ([\d,]+) расценивается как недостаточность питания, от ([\d,]+) до ([\d,]+) \(включительно\) - как пониженное питание", пр)
    if not м:
        raise Нельзя("правило про ИМТ в ст. 13 разобрано не по шаблону")
    п = _пункт(ст, "д")
    if "пониженное питание" not in п["описание"]:
        raise Нельзя("пункт «д» ст. 13 не про пониженное питание")
    return {"недостаток": _ч(м.group(1)), "понижено_от": _ч(м.group(2)), "понижено_до": _ч(м.group(3)), "кат": _кат(п)}


def _имт_спец(ст):
    п = _имт_пороги(ст)
    return {"заголовок": "Индекс массы тела",
            "подпись": "Считаю только недостаток питания: ИМТ ниже %s — недостаточность, от %s до %s — пониженное питание (из примечаний статьи). Ожирение не считаю: степени берутся по клиническим рекомендациям, их в тексте нет." % (_цифра(п["недостаток"]), _цифра(п["понижено_от"]), _цифра(п["понижено_до"])),
            "поля": [{"ключ": "масса", "тип": "число", "подпись": "Масса тела", "мин": 35, "макс": 120, "шаг": 1, "ед": "кг", "знач": 70},
                     {"ключ": "рост", "тип": "число", "подпись": "Рост", "мин": 140, "макс": 210, "шаг": 1, "ед": "см", "знач": 175}]}


def _имт_решить(ст, з):
    п = _имт_пороги(ст)
    масса, рост = _ч(з["масса"]), _ч(з["рост"])
    if масса <= 0 or рост <= 0:
        raise Нельзя("масса и рост должны быть больше нуля")
    имт = round(масса / (рост / 100.0) ** 2, 1)
    метрика = {"подпись": "ИМТ", "значение": _цифра(имт)}
    if имт < п["недостаток"]:
        return {"пункт": "д", "категория": п["кат"], "итог": "Недостаточность питания", "метрика": метрика, "подсветить": ["д"],
                "почему": "Нужно обследование. Если заболеваний, снижающих массу, не найдено — пункт «д»; если найдены — статья по этому заболеванию."}
    if п["понижено_от"] <= имт <= п["понижено_до"]:
        return {"пункт": "д", "категория": п["кат"], "итог": "Пониженное питание", "метрика": метрика, "подсветить": ["д"],
                "почему": "Пункт «д»: пониженное питание. Если найдётся причина-заболевание, статья будет другая."}
    return {"пункт": None, "категория": None, "итог": "По питанию оснований нет", "метрика": метрика, "подсветить": [],
            "почему": "ИМТ выше %s: недостатка питания нет. Ожирение здесь не оцениваю." % _цифра(п["понижено_до"])}


ВИДЫ = {"40": (_слух_спец, _слух_решить), "86": (_рост_спец, _рост_решить), "13": (_имт_спец, _имт_решить)}


def поддерживается(ид):
    return str(ид) in ВИДЫ


def спецификация(база, ид):
    ид = str(ид)
    if ид not in ВИДЫ:
        raise Нельзя("для статьи %s калькулятора нет" % ид)
    ст = база.статьи[ид]
    спец = ВИДЫ[ид][0](ст)
    спец["ид"] = ид
    return спец


def решить(база, ид, значения):
    ид = str(ид)
    if ид not in ВИДЫ:
        raise Нельзя("для статьи %s калькулятора нет" % ид)
    спец = спецификация(база, ид)
    нужно = [п["ключ"] for п in спец["поля"] if п["тип"] == "число"]
    for к in нужно:
        if к not in значения:
            raise Нельзя("не передано поле «%s»" % к)
    return ВИДЫ[ид][1](база.статьи[ид], значения)


# ------------------------------------------------------------------ числа из слов человека («минус 7», «шёпот на 2 метрах», «рост 148»)
_ЧИСЛА_СЛОВАМИ = {"полтора": 1.5, "ноль": 0, "один": 1, "одна": 1, "два": 2, "две": 2, "три": 3, "четыре": 4, "пять": 5, "шесть": 6, "семь": 7, "восемь": 8,
                  "девять": 9, "десять": 10, "одиннадцать": 11, "двенадцать": 12, "тринадцать": 13, "четырнадцать": 14, "пятнадцать": 15,
                  "шестнадцать": 16, "семнадцать": 17, "восемнадцать": 18, "девятнадцать": 19, "двадцать": 20}
_РЕГ_СЛОВ = re.compile(r"\b(%s)(\s+с\s+половин\w+)?\b" % "|".join(sorted(_ЧИСЛА_СЛОВАМИ, key=len, reverse=True)))
_ЧИСЛО = r"(\d+(?:\.\d+)?)"


def _нормализовать(текст):
    т = str(текст).lower().replace("ё", "е")
    т = т.replace("−", "-").replace("–", "-").replace("—", "-")
    т = re.sub(r"(\d),(\d)", r"\1.\2", т)
    т = _РЕГ_СЛОВ.sub(lambda м: "%g" % (_ЧИСЛА_СЛОВАМИ[м.group(1)] + (0.5 if м.group(2) else 0)), т)
    return re.sub(r"(\d+(?:\.\d+)?)\s+с\s+половин\w+", lambda м: "%g" % (float(м.group(1)) + 0.5), т)


def _диоптрии_из_слов(т):
    for рег in (_ЧИСЛО + r"\s*(?:дптр|диоптр\w*)",
                r"(?:близорук\w*|дальнозорк\w*|очки|очках)\D{0,14}?(?:минус\s*|-\s*)?" + _ЧИСЛО,
                r"(?<![\w/.:])минус\s?" + _ЧИСЛО + r"(?![\d/:])",
                r"(?<![\w/.:])-\s?" + _ЧИСЛО + r"(?![\d/:])"):
        м = re.search(рег, т)
        if м:
            v = float(м.group(1))
            if 0.5 <= v <= 25:
                return v
    return None


def _слух_из_слов(т):
    if not re.search(r"шеп|слух|слыш|\bух[оае]|уши", т):
        return None
    зн = {}
    for ключ, корень in (("правое", "прав"), ("левое", "лев")):
        if re.search(корень + r"\w*\s+(?:ух\w*\s+)?не\s+слыш", т) or re.search(r"не\s+слыш\w*\s+(?:на\s+)?" + корень, т):
            зн[ключ] = 0.0
    без_стороны = []
    for м in re.finditer(r"(?:(прав\w*|лев\w*)\D{0,24}?)?" + _ЧИСЛО + r"\s*(?:м\b|метр\w*)", т):
        v = float(м.group(2))
        if not 0 <= v <= 10:
            continue
        if м.group(1):
            зн["правое" if м.group(1).startswith("прав") else "левое"] = v
        else:
            без_стороны.append(v)
    общее = False
    if без_стороны and not зн:
        зн = {"правое": без_стороны[0], "левое": без_стороны[0]}
        общее = True
    return (зн, общее) if зн else None


def _рост_масса_из_слов(т):
    рост = масса = None
    for рег in (r"рост\w*\D{0,8}?" + _ЧИСЛО, _ЧИСЛО + r"\s*(?:см\b|сантиметр\w*)"):
        м = re.search(рег, т)
        if м and 100 <= float(м.group(1)) <= 230:
            рост = float(м.group(1)); break
    for рег in (r"(?:вес\w*|вешу|масс\w*)\D{0,8}?" + _ЧИСЛО, _ЧИСЛО + r"\s*(?:кг\b|килограмм\w*)"):
        м = re.search(рег, т)
        if м and 20 <= float(м.group(1)) <= 250:
            масса = float(м.group(1)); break
    return рост, масса


def из_слов(база, текст, код_решатель):
    """Числа, которые человек назвал словами, → готовые расчёты по порогам из текста статьи.
    Возвращает [{ид, подпись, значения (все поля калькулятора), заданы (что назвал человек), заметка, результат}].
    То, что человек не назвал, берётся из «нормы» калькулятора и помечается в заметке: молча угадывать нельзя."""
    т = _нормализовать(текст)
    out = []
    v = _диоптрии_из_слов(т)
    if v is not None:
        пункт, кат, почему = код_решатель.пункт_по_диоптриям(v)
        прим = пункт != "не применяется"
        out.append({"ид": "34", "подпись": "Диоптрии: −%s" % _цифра(v), "значения": {"диоптрии": v}, "заданы": ["диоптрии"], "заметка": "Считаю худший глаз, по модулю.",
                    "результат": {"пункт": пункт if прим else None, "категория": кат if прим else None, "итог": ("Пункт «%s»" % пункт) if прим else "Ниже порога этой статьи", "почему": почему}})
    найден_слух = _слух_из_слов(т)
    if найден_слух:
        слух, сторона_не_названа = найден_слух
        значения = {"правое": 6.0, "левое": 6.0}
        значения.update(слух)
        не_названо = [("правое", "Правое") , ("левое", "Левое")]
        нет = [имя for ключ, имя in не_названо if ключ not in слух]
        подпись = "Слух: " + ", ".join("%s %s" % (ключ, "не слышит" if значения[ключ] == 0 else _цифра(значения[ключ]) + " м") for ключ in ("правое", "левое") if ключ in слух)
        out.append({"ид": "40", "подпись": подпись, "значения": значения, "заданы": list(слух),
                    "заметка": "Сторона не названа: поставил оба уха одинаково." if сторона_не_названа else (("%s ухо не названо: принял за норму (6 м)." % " и ".join(нет)) if нет else ""),
                    "результат": решить(база, "40", значения)})
    рост, масса = _рост_масса_из_слов(т)
    if рост is not None or масса is not None:
        значения = {"масса": масса if масса is not None else 60.0, "рост": рост if рост is not None else 175.0, "впервые": "1"}
        заданы = [к for к, v in (("масса", масса), ("рост", рост)) if v is not None]
        нет = [к for к in ("масса", "рост") if к not in заданы]
        части = ["%s %s %s" % (к, _цифра(значения[к.lower()]), "кг" if к == "Масса" else "см") for к in ("Рост", "Масса") if к.lower() in заданы]
        подпись = ", ".join(части[:1] + [х[0].lower() + х[1:] for х in части[1:]])
        р86 = решить(база, "86", значения)
        if р86["пункт"] is not None:          # ниже порога статьи 86 — показываем; «всё в норме» в поиск не тащим
            out.append({"ид": "86", "подпись": подпись, "значения": значения, "заданы": заданы,
                        "заметка": ("%s не назван%s: принял %s." % (" и ".join(нет).capitalize(), "а" if нет == ["масса"] else "", "60 кг" if нет == ["масса"] else "175 см")) if нет else "",
                        "результат": р86})
        if рост is not None and масса is not None:
            out.append({"ид": "13", "подпись": "ИМТ по росту и массе", "значения": значения, "заданы": заданы, "заметка": "", "результат": решить(база, "13", значения)})
    return out
