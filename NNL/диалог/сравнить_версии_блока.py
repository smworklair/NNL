# -*- coding: utf-8 -*-
"""Сравнение двух версий блока на проверочном наборе (bench/bench.jsonl, он не входит в обучение): родитель против кандидата.

Зачем. Линтер вставки сравнивает систему «с блоком» и «без блока», а это для связанных блоков всегда даёт несколько процентов (здесь «право»
читает понятия «здоровья»): рабочий блок сам не проходит допуск 1 %. Поэтому для новой версии вопрос другой: чем она отличается от прежней.
Что считается (на таких же вопросах и с тем же процессором, что в линтере):
  * точность блока «здоровье» (итоговый top-1 против эталона) у родителя и кандидата: всего и по тем вопросам, где эталон известен;
  * сколько ответов СОСЕДЕЙ изменила замена родителя кандидатом (допуск ε, по умолчанию 1 %);
  * сколько вопросов кандидат починил и сколько испортил (родитель верно → кандидат неверно).
Запуск: python NNL/диалог/сравнить_версии_блока.py <папка_родителя> <папка_кандидата> <папка_соседа> [<папка_соседа> ...] [--эпсилон 0.01]
Код возврата 0 — кандидат не хуже родителя (не больше испорчено, чем починено, и соседи в допуске); 1 — иначе."""
import json
import os
import sys

sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
for п in (КОРЕНЬ, os.path.join(КОРЕНЬ, "v8", "замер")):
    if п not in sys.path:
        sys.path.insert(0, п)
import общее as О  # noqa: E402
from NNL.матплата import Матплата  # noqa: E402
from NNL.процессор import Процессор  # noqa: E402
from NNL.ядро import ЯдроПричинности  # noqa: E402
from NNL.онтология_v8 import ОнтологияV8  # noqa: E402


def ответы_системы(папка_блока, соседи, вопросы):
    м = Матплата(О.Язык(О.ЯЗЫК_ПАПКА), О.ARCH)
    for п in соседи:
        ok, msg = м.подключить(п)
        assert ok, (п, msg)
    ok, имя = м.подключить(папка_блока)
    assert ok, (папка_блока, имя)
    пр = Процессор(м, ядро=ЯдроПричинности(провайдер=ОнтологияV8(КОРЕНЬ)), tau_conf=1.0)
    out = []
    for q in вопросы:
        r = пр.выполнить(q)["такт2"]
        out.append({n: r[n]["top1"] for n in r})
    return имя, out


def сравнить(родитель, кандидат, соседи, вопросы, эталоны, эпсилон=0.01):
    имя, до = ответы_системы(родитель, соседи, вопросы)
    имя2, после = ответы_системы(кандидат, соседи, вопросы)
    assert имя == имя2, (имя, имя2)
    имена_соседей = [n for n in до[0] if n != имя]
    изменилось = sum(1 for a, b in zip(до, после) for n in имена_соседей if a.get(n) != b.get(n))
    всего = len(вопросы) * len(имена_соседей)
    с_эталоном = [i for i, э in enumerate(эталоны) if э is not None]
    верно_до = {i for i in с_эталоном if до[i].get(имя) == эталоны[i]}
    верно_после = {i for i in с_эталоном if после[i].get(имя) == эталоны[i]}
    отчёт = {"блок": имя, "вопросов": len(вопросы), "с_эталоном": len(с_эталоном),
             "точность_родителя": round(len(верно_до) / len(с_эталоном), 4), "точность_кандидата": round(len(верно_после) / len(с_эталоном), 4),
             "починено": len(верно_после - верно_до), "испорчено": len(верно_до - верно_после),
             "изменилось_ответов_соседей": изменилось, "всего_ответов_соседей": всего, "доля_изменений_соседей": round(изменилось / всего, 5) if всего else 0.0,
             "эпсилон": эпсилон, "испорченные": [вопросы[i] for i in sorted(верно_до - верно_после)][:10]}
    отчёт["не_хуже"] = отчёт["испорчено"] <= отчёт["починено"] and отчёт["доля_изменений_соседей"] <= эпсилон
    return отчёт


if __name__ == "__main__":
    а = sys.argv[1:]
    эпс = 0.01
    if "--эпсилон" in а:
        i = а.index("--эпсилон")
        эпс = float(а[i + 1])
        а = а[:i] + а[i + 2:]
    if len(а) < 3:
        print(__doc__)
        sys.exit(2)
    строки = [json.loads(l) for l in open(os.path.join(КОРЕНЬ, "bench", "bench.jsonl"), encoding="utf-8") if l.strip()]
    вопросы = [r["вопрос"] for r in строки]
    эталоны = [(("ответ:здоровье:%s" % r["ответ"]) if r.get("область") == "здоровье" else None) for r in строки]
    о = сравнить(а[0], а[1], а[2:], вопросы, эталоны, эпс)
    print(json.dumps(о, ensure_ascii=False, indent=2))
    sys.exit(0 if о["не_хуже"] else 1)
