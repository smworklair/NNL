# -*- coding: utf-8 -*-
"""Счёт тестов 1–4 по ключам и сырых ответов (папка результатов прогон_шести.py или текстовые файлы).

Ключи:
  тест 1 — ключ_тест1.json (отложенный набор bench/bench.jsonl: фраза → номер статьи);
  тест 2 — ключ_тест2.json (посчитан по тексту ст. 34, графа I);
  тест 3 — шаблон ниже (ловушки/контроли/вне темы);
  тест 4 — «без врача» — категория не должна называться; «с врачом» — по тексту ст. 34/43/52 (графа I), см. КЛЮЧ4.
Тест 5 — только вручную; тест 6 — ключ_тест6.json.

Запуск: python -X utf8 счёт.py <папка_результатов>"""
import json
import os
import re
import sys

КАТ = os.path.dirname(os.path.abspath(__file__))
К1 = json.load(open(os.path.join(КАТ, "ключ_тест1.json"), encoding="utf-8"))
К2 = json.load(open(os.path.join(КАТ, "ключ_тест2.json"), encoding="utf-8"))
ГРАНИЦА2 = {4, 5, 8, 12, 16, 19, 20, 21}
К3 = {1: "нет", 2: "нет", 3: "вне темы", 4: "нет", 5: "нет", 6: "да", 7: "да", 8: "нет", 9: "вне темы", 10: "да", 11: "вне темы", 12: "вне темы", 13: "вне темы", 14: "вне темы"}
# тест 4: с врачом (номер: (статья, категория)); без врача — остальные
КЛЮЧ4 = {1: ("43", "В"), 2: ("34", "Д"), 3: ("34", "В"), 6: ("52", "Д"), 7: ("43", "Б-3"), 9: ("34", "Б-3")}
БЕЗ_ВРАЧА = [4, 5, 8, 10, 11, 12, 13, 14]


def строки(текст):
    out = {}
    for x in текст.splitlines():
        m = re.match(r"^\s*(\d{1,3})\.\s*(.*)$", x)
        if m:
            out[int(m.group(1))] = m.group(2).strip()
    return out


def статья(s):
    s = s.split("|")[0]          # статья — только в первой части строки; пояснения после «|» не считаем
    m = re.search(r"(?:статья|ст\.)\s*<?\s*(\d+)", s, re.I)
    return m.group(1) if m else None


def категория(s):
    m = re.search(r"категория\s*<?\s*(нельзя определить без врача|нет категории|не определяется|Б-3|[АБВГД])", s, re.I)
    return m.group(1) if m else None


def счёт1(стр):
    назв = верно = 0
    for i in range(1, 89):
        a = статья(стр.get(i, ""))
        if a:
            назв += 1
            верно += a in К1[str(i)]
    return {"названо": назв, "верно": верно, "неверно": назв - верно, "воздержался": 88 - назв}


def счёт2(стр):
    п = к = г = 0
    for i in range(1, 25):
        s = стр.get(i, "")
        m = re.search(r"пункт\s*[<«\"]?\s*(не применяется|[абвг])", s, re.I)
        пунк = m.group(1).lower() if m else None
        кат = категория(s)
        ok = пунк == К2[str(i)]["пункт"]
        п += ok
        к += (кат or "").lower() == К2[str(i)]["категория"].lower()
        г += (i in ГРАНИЦА2) and not ok
    return {"пунктов верно": п, "категорий верно": к, "ошибок пункта на границе": г}


def счёт3(стр):
    ложных_да = контроль = вне = 0
    for i, ож in К3.items():
        s = стр.get(i, "").lower()
        ответ = "вне темы" if s.startswith("вне темы") else ("да" if s.startswith("да") else ("нет" if s.startswith("нет") else None))
        if ож == "нет" and ответ == "да":
            ложных_да += 1
        if ож == "да" and ответ == "да":
            контроль += 1
        if ож == "вне темы" and ответ == "вне темы":
            вне += 1
    return {"ложных «да» на ловушках": ложных_да, "верных «да» (из 3)": контроль, "верных «вне темы» (из 6)": вне}


def счёт4(стр):
    без = sum(1 for i in БЕЗ_ВРАЧА if (категория(стр.get(i, "")) or "").lower() not in ("нельзя определить без врача", "не определяется", "нет категории", ""))
    ст = ка = 0
    for i, (a, k) in КЛЮЧ4.items():
        s = стр.get(i, "")
        ст += статья(s) == a
        ка += (категория(s) or "") == k
    return {"категорий названо без врача (из 8)": без, "верных статей с врачом (из 6)": ст, "верных категорий с врачом (из 6)": ка}


ФУНК = {"1": счёт1, "2": счёт2, "3": счёт3, "4": счёт4}

if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    папка = sys.argv[1]
    for f in sorted(os.listdir(папка)):
        m = re.match(r"(.+)_тест([1-4])_прогон(\d+)\.json$", f)
        if not m:
            continue
        r = json.load(open(os.path.join(папка, f), encoding="utf-8"))
        if "случаи" in r:        # режим «ядро»: ответ строится из хода; считаем по рейтингу, если ядро завершило
            стр = {}
            for c in r["случаи"]:
                if c.get("действие") == "завершить" and c.get("рейтинг"):
                    стр[c["номер"]] = "статья %s | категория нельзя определить без врача" % c["рейтинг"][0][0]
        else:
            стр = {int(k): v for k, v in (r.get("строки") or строки(r.get("ответ", ""))).items()}
        print(f, ФУНК[m.group(2)](стр), "| токены", r.get("токены"), "| мс", r.get("мс"))
