def проверить_новые(ко):
    отв4, _ = ко.тест4(НОВЫЕ_ФРАЗЫ)
    стр4 = СЧ.строки(отв4)
    без_вр = sum(
        1 for i in НОВЫЕ_БЕЗ_ВРАЧА
        if (СЧ.категория(стр4.get(i, "")) or "").lower() not in ("нельзя определить без врача", "не определяется", "нет категории", "")
    )
    ст_верно = кат_верно = 0
    for i, (ож_ст, ож_кат) in КЛЮЧ_НОВЫЕ_С_ВРАЧОМ.items():
        s = стр4.get(i, "")
        ст_верно += (СЧ.статья(s) == ож_ст)
        кат_верно += ((СЧ.категория(s) or "").lower() == ож_кат.lower())
    отв5, _ = ко.тест5(НОВЫЕ_ДИАЛОГИ)
    стр5 = {}
    for x in отв5.splitlines():
        m = re.match(r"^\s*Диалог\s+(\d+)\s*:\s*(.*)$", x)
        if m:
            стр5[int(m.group(1))] = m.group(2).strip()
    д_ок = {
        1: "врач ничего не подтвердил" in стр5.get(1, "").lower() and "категорию определить нельзя" in стр5.get(1, "").lower(),
        2: "ст. 34" in стр5.get(2, "").lower() and "пункт «в»" in стр5.get(2, "").lower() and "категория в" in стр5.get(2, "").lower(),
        3: "ст. 34" in стр5.get(3, "").lower() and "пункт «г»" in стр5.get(3, "").lower() and "Б-3" in стр5.get(3, ""),
        4: "ст. 34" in стр5.get(4, "").lower() and "пункт «б»" in стр5.get(4, "").lower() and "категория в" in стр5.get(4, "").lower() and "не более 3" in стр5.get(4, "").lower(),
    }
    return {
        "ответ_10_фраз": отв4,
        "счёт_10_фраз": {
            "категорий названо без врача (из 4)": без_вр,
            "верных статей с врачом (из 6)": ст_верно,
            "верных категорий с врачом (из 6)": кат_верно,
        },
        "ответ_4_диалогов": отв5,
        "счёт_4_диалогов": {"решено_диалогов (из 4)": sum(д_ок.values()), "по_диалогам": д_ок},
    }


