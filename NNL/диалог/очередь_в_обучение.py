# -*- coding: utf-8 -*-
"""Размеченные фразы очереди → обучающие строки блоков «здоровье» и «право» (формат v8/обучение/данные.строка).

Вход: файл из `очередь_дообучения.py выгрузить`, в котором человек заполнил поле «метка»:
  «34» или «34,35»      — фраза про эти статьи Расписания (блок «здоровье»);
  «право:<тема>»        — фраза про правовую тему (id из rack/data/lex_topics.json), блок «право»;
  «вне»                 — не про здоровье и не про права (отрицательный пример для ворот области);
  пусто / «пропуск»     — не использовать.
Строки без метки в обучение не попадают: слабая метка системы («метка_подсказка») сама решением не является.

Чего конвертер не делает (и почему):
  * не запускает обучение: готовый файл подают в обучение тем же путём, что и прочие живые строки (обучение/дообучить.py),
    а новая версия блока проверяется линтером вставки и тестами как всегда;
  * не берёт почти-повторы проверочных наборов (тот же фильтр, что в данные.живые_пулы): иначе проверка перестала бы быть честной;
  * не придумывает метку для «лидер_не_подтвердился»: система знает только, что статья НЕ подошла, а какая подошла — знает человек.
Запуск: python очередь_в_обучение.py <размеченный.jsonl> [выход.jsonl]"""
import json
import os
import sys

sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(os.path.dirname(ЗДЕСЬ))
for п in (ЗДЕСЬ, os.path.join(КОРЕНЬ, "система")):
    if п not in sys.path:
        sys.path.insert(0, п)
import очередь_дообучения as Оч  # noqa: E402

ВЫХОД = os.path.join(ЗДЕСЬ, "обучающие_из_очереди.jsonl")
ПУСТО = {"", "пропуск", "-"}


def разобрать_метку(метка, статьи, темы):
    """→ ('здоровье', [статьи]) | ('право', [темы]) | ('вне', []) | ('пропуск', []) | ('ошибка', причина)."""
    м = (метка or "").strip().lower().replace("ё", "е")
    if м in ПУСТО:
        return "пропуск", []
    if м == "вне":
        return "вне", []
    if м.startswith("право:"):
        тема = (метка or "").strip()[6:].strip()
        return ("право", [тема]) if тема in темы else ("ошибка", "нет правовой темы «%s»" % тема)
    ид = [x.strip() for x in м.replace(";", ",").split(",") if x.strip()]
    плохие = [x for x in ид if x not in статьи]
    if not ид or плохие:
        return "ошибка", "нет статьи %s" % ", ".join(плохие or [м])
    return "здоровье", sorted(set(ид), key=int)


def превратить(путь_входа, путь_выхода=ВЫХОД, D=None, фильтр=None):
    """Возвращает отчёт {принято, без_метки, отвергнуто: [(фраза, причина)], выход}."""
    if D is None:
        from обучение import данные as D  # noqa: N812
    статьи = {a["article_no"] for a in D.статьи()}
    темы = {t["topic_id"] for t in D.темы()}
    if фильтр is None:
        фильтр = D.Фильтр(D.проверочные_тексты())
    строки, виденные, отчёт = [], set(), {"принято": 0, "без_метки": 0, "отвергнуто": [], "выход": путь_выхода}
    for с in Оч.прочитать(путь_входа):
        фраза = (с.get("фраза") or "").strip()
        вид, что = разобрать_метку(с.get("метка"), статьи, темы)
        if вид == "пропуск":
            отчёт["без_метки"] += 1
            continue
        if вид == "ошибка":
            отчёт["отвергнуто"].append((фраза, что))
            continue
        ключ = Оч.нормализовать(фраза)
        if not ключ or ключ in виденные:
            отчёт["отвергнуто"].append((фраза, "повтор"))
            continue
        if фильтр.близко(фраза):
            отчёт["отвергнуто"].append((фраза, "почти-повтор проверочного вопроса"))
            continue
        виденные.add(ключ)
        if вид == "здоровье":
            строки.append(D.строка(фраза, 1, 0, что, (), "очередь"))
        elif вид == "право":
            строки.append(D.строка(фраза, 0, 1, (), что, "очередь"))
        else:
            строки.append(D.строка(фраза, 0, 0, (), (), "очередь"))
        отчёт["принято"] += 1
    with open(путь_выхода, "w", encoding="utf-8") as ф:
        for r in строки:
            ф.write(json.dumps(r, ensure_ascii=False) + "\n")
    return отчёт


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    о = превратить(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else ВЫХОД)
    print("принято %d, без метки %d, отвергнуто %d → %s" % (о["принято"], о["без_метки"], len(о["отвергнуто"]), о["выход"]))
    for ф, п in о["отвергнуто"]:
        print("  ✗ %s — %s" % (ф, п))
