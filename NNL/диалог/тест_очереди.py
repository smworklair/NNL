# -*- coding: utf-8 -*-
"""Тест очереди дообучения: какие события пишет умный поиск и что показывает свод. Файл очереди временный, настоящий не трогается.
Запуск: python NNL/диалог/тест_очереди.py"""
import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
import клиент as К  # noqa: E402
К.КЭШ_ФАЙЛ = os.path.join(tempfile.mkdtemp(prefix="nnl_оч_"), "кэш.jsonl")
import диалог as Д  # noqa: E402
import очередь_дообучения as Оч  # noqa: E402
import сервер as S  # noqa: E402

Оч.ФАЙЛ = os.path.join(tempfile.mkdtemp(prefix="nnl_оч_"), "очередь.jsonl")
S.СИСТЕМА = Д.Система()
ошибки = []


def проверить(что, условие, подробность=""):
    print(("  ок   " if условие else "  ОШИБКА ") + что + ("" if условие else "  " + str(подробность)))
    if not условие:
        ошибки.append(что)


def причины():
    return [с["причина"] for с in Оч.прочитать()]


S.умный_поиск("меня не берут на работу из-за судимости")
проверить("фраза вне темы попадает в очередь", причины() == ["вне_темы"], причины())
S.умный_поиск("меня не берут на работу из-за судимости")
проверить("повтор той же фразы в процессе не дублируется", причины() == ["вне_темы"], причины())

ф = "болит спина после падения"
в = S.умный_поиск(ф)["вопрос"]
проверить("обычный запрос без ответов ничего не пишет (кроме вне темы)", причины() == ["вне_темы"])
S.умный_поиск(ф, [{"статья": в["статья"], "текст": в["текст"], "ответ": "да"}])
в2 = S.умный_поиск(ф, [{"статья": в["статья"], "текст": в["текст"], "ответ": "да"}])["вопрос"]
S.умный_поиск(ф, [{"статья": в["статья"], "текст": в["текст"], "ответ": "да"}, {"статья": в2["статья"], "текст": в2["текст"], "ответ": "да"}])
проверить("слабый лидер, подтверждённый ответами → слабая метка", "слабая_метка" in причины(), причины())

ф2 = "колет сердце"
в = S.умный_поиск(ф2)["вопрос"]
S.умный_поиск(ф2, [{"статья": в["статья"], "текст": в["текст"], "ответ": "нет"}])
проверить("«нет» на вопрос лидера → лидер не подтвердился (вероятная ошибка блока)", "лидер_не_подтвердился" in причины(), причины())
S.умный_поиск(ф2, [{"статья": в["статья"], "текст": в["текст"], "ответ": "не_знаю"}])
проверить("«не знаю» → вопрос под замену", "человек_не_знает" in причины(), причины())

Оч.записать("мой телефон 89161234567 и колет сердце", "вне_темы")
проверить("длинные числа из фразы убираются", all("89161234567" not in с["фраза"] for с in Оч.прочитать()))

свод = Оч.свести()
проверить("свод группирует по причинам", set(свод) >= {"вне_темы", "слабая_метка", "лидер_не_подтвердился", "человек_не_знает"}, list(свод))
путь = os.path.join(tempfile.mkdtemp(prefix="nnl_оч_"), "разметка.jsonl")
n = Оч.выгрузить(путь)
строки = [json.loads(с) for с in open(путь, encoding="utf-8")]
проверить("выгрузка: человек_не_знает не уходит на разметку, у остальных есть предположение и пустое «проверено»",
          n == len(строки) > 0 and all(с["метка"] is None and с["предположение"] for с in строки) and "человек_не_знает" not in {с["причина"] for с in строки})
Оч.ВКЛЮЧЕНА = False
до = len(Оч.прочитать())
Оч.записать("новая фраза", "вне_темы")
проверить("выключенная очередь ничего не пишет", len(Оч.прочитать()) == до)
print("\nОШИБОК: %d" % len(ошибки))
sys.exit(1 if ошибки else 0)
