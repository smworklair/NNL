    термины = [("близорукость", "есть"), ("астма", "нет"), ("гипертония", "чужое"), ("зрение плохое", "есть")]
    p_блока = {"близорукость": {"1": 0.9}, "астма": {"2": 0.8}, "гипертония": {"3": 0.7}, "зрение плохое": {"1": 0.7}}
    состояния = set()
    for порядок in itertools.permutations(термины):
        р = новое()
        for т, с in порядок:
            р.учесть_упоминание(т, с, "", p_блока[т], 0.05)
        состояния.add(tuple(round(р.l[a], 9) for a in СТАТЬИ))
    отметить(len(состояния) == 1, "состояние не зависит от порядка упоминаний (24 перестановки четырёх упоминаний): прежде расходилось из-за обрезки на каждом шаге")
    р = новое()
    for т in ("близорукость", "зрение плохое", "очки минус семь"):
        р.учесть_упоминание(т, "есть", "", {"1": 0.9}, 0.05)
    одна_реплика = р.p("1")
    предел = Р.sigm(Р.logit(Р.ПРИОР) + Р.ПОТОЛОК_УЛИКИ + Р.ПРИБАВКА_ЗА_СОГЛАСИЕ)
    отметить(abs(одна_реплика - предел) < 1e-9, "три упоминания одной статьи в одной реплике дают не больше потолка + %.1f нат: p=%.2f (без защиты было бы %.2f)" % (Р.ПРИБАВКА_ЗА_СОГЛАСИЕ, одна_реплика, Р.sigm(Р.logit(Р.ПРИОР) + 3 * Р.ПОТОЛОК_УЛИКИ)))
    р = новое()
    for т in ("близорукость", "зрение плохое", "очки минус семь"):
        р.учесть_упоминание(т, "есть", "", {"1": 0.9}, 0.05)
        р.сверить_реплику([клауза(т, {"1": 0.9})], [т])           # каждое — в своей реплике
    отметить(р.p("1") > одна_реплика + 0.2, "повтор жалобы в другой реплике складывается (человек «достучался»): p=%.2f против %.2f в одной реплике" % (р.p("1"), одна_реплика))

    # ------------------------------------------------------------------ сверка с живыми словами
    р = новое()
    р.учесть_упоминание("близорукость", "есть", "-7 дптр", {"1": 0.9}, 0.05, "врач")
    р.сверить_реплику([клауза("близорукость минус семь", {"1": 0.9})], ["близорукость минус семь"])
    отметить(not р.подтверждено_врачом() and р.улики[0]["подтверждено"] == "нет_данных" and р.улики[0].get("подтверждено_заявлено") == "врач",
             "«подтвердил врач» без слов о враче в реплике понижено до «нет_данных»: вердикт по категории закрыт")
    р = новое()
    р.учесть_упоминание("близорукость", "есть", "-7 дптр", {"1": 0.9}, 0.05, "врач")
    р.сверить_реплику([клауза("окулист написал близорукость минус семь", {"1": 0.9})], ["окулист написал близорукость минус семь"])
    отметить(р.подтверждено_врачом(), "«подтвердил врач» со словом «окулист» в реплике остаётся: вердикт допустим")
    р = новое()
    р.учесть_упоминание("астма", "нет", "", {"2": 0.9}, 0.05)
    р.сверить_реплику([клауза("астма", {"2": 0.9})], ["астма"])
    отметить(р.улики[0].get("не_подтверждено") and р.p("2") >= Р.П_ПОЛ - 1e-9, "«нет» без слова отрицания рядом с названием не снижает статью, а держит её кандидатом (p=%.2f)" % р.p("2"))
    р = новое()
    р.учесть_упоминание("астма", "нет", "", {"2": 0.9}, 0.05)
    р.сверить_реплику([клауза("не болел астмой", {"2": 0.9})], ["не болел астмой"])
    отметить(not р.улики[0].get("не_подтверждено") and р.p("2") < ПРИОР, "«нет» с отрицанием рядом снижает статью как обычно (p=%.3f)" % р.p("2"))
    р = новое()
    р.учесть_упоминание("не слышу правым ухом", "нет", "", {"3": 0.9}, 0.05)
    р.сверить_реплику([клауза("не слышу правым ухом", {"3": 0.9})], ["не слышу правым ухом"])
    отметить(р.улики[0].get("не_подтверждено"), "отрицание внутри самого названия не считается: «не слышу правым ухом» с пометкой «нет» неподтверждено")
    р = новое()
    р.учесть_упоминание("эпилепсия", "чужое", "", {"3": 0.9}, 0.05)
    р.сверить_реплику([клауза("эпилепсия", {"3": 0.9})], ["эпилепсия"])
    отметить(р.улики[0].get("не_подтверждено") and р.p("3") >= Р.П_ПОЛ - 1e-9, "«чужое» без слов о другом человеке: статья остаётся кандидатом, а не пропадает")
    р = новое()
    р.учесть_упоминание("эпилепсия", "чужое", "", {"3": 0.9}, 0.05)
    р.сверить_реплику([клауза("у брата эпилепсия", {"3": 0.9})], ["у брата эпилепсия"])
    отметить(not р.улики[0].get("не_подтверждено"), "«чужое» с «у брата» рядом подтверждено")
    р = новое()
    р.учесть_упоминание("давление", "есть", "", {"2": 0.9}, 0.05)
    флаги = р.сверить_реплику([клауза("давление повышенное", {"2": 0.9}), клауза("зрение падает", {"1": 0.95})], ["давление повышенное. зрение падает"])["флаги"]
    отметить(any(ф["вид"] == "пропущено_разбором" and ф["статья"] == "1" for ф in флаги) and р.p("1") >= Р.П_ПОЛ - 1e-9,
             "фраза реплики указывает на статью, а разбор её не учёл: статья держится на уровне кандидата (p=%.2f) и получит вопрос" % р.p("1"))
    р = новое()
    р.учесть_упоминание("давление", "есть", "", {"2": 0.9}, 0.05)
    р.учесть_упоминание("зрение", "есть", "", {"1": 0.9}, 0.05)
    флаги = р.сверить_реплику([клауза("давление повышенное", {"2": 0.9}), клауза("зрение падает", {"1": 0.95})], ["давление повышенное. зрение падает"])["флаги"]
    отметить(not флаги, "когда разбор учёл все статьи, на которые указывают фразы, расхождений нет")
    р = новое()
    р.учесть_упоминание("зелёная гусеница", "есть", "", {"1": 0.9}, 0.05)
    р.сверить_реплику([клауза("болит спина", {"2": 0.9})], ["болит спина"])
    отметить(р.p("1") <= Р.sigm(Р.logit(Р.ПРИОР) + Р.ПРЕДЕЛ_БЕЗ_ПОДТВЕРЖДЕНИЯ) + 1e-9 and any("не подтверждают" in x for x in р.улики[0]["проверки"]),
             "упоминание, которого нет в словах человека и которое не подтверждает ни одна фраза, не растёт выше предела (p=%.2f ≤ %.2f)" % (р.p("1"), Р.sigm(Р.logit(Р.ПРИОР) + Р.ПРЕДЕЛ_БЕЗ_ПОДТВЕРЖДЕНИЯ)))
    р = новое()
    р.учесть_упоминание("спина", "есть", "", {"1": 0.9}, 0.05)
    р.сверить_реплику([клауза("болит спина", {"2": 0.9})], ["болит спина"])
    отметить(р.p("1") > Р.sigm(Р.logit(Р.ПРИОР) + Р.ПРЕДЕЛ_БЕЗ_ПОДТВЕРЖДЕНИЯ) + 1e-6, "название есть в словах человека: предела нет, даже если блок читает фразу иначе")

    # живые формулировки: словарь маркеров на настоящих фразах группы «отрицание»
    строки = [json.loads(l) for l in open(os.path.join(os.path.dirname(os.path.dirname(КАТАЛОГ)), "внешние", "фразы.jsonl"), encoding="utf-8") if l.strip()]
    группа = [r["текст"] for r in строки if r["группа"] == "отрицание"]
    распознано = sum(bool(Р._ОТРИЦАНИЕ.search(t)) for t in группа)
    отметить(распознано / len(группа) >= 0.95, "словарь отрицания распознаёт %d из %d настоящих фраз группы «отрицание»" % (распознано, len(группа)))

    # ------------------------------------------------------------------ сквозные сравнения со стендом
    import сценарии as С
    import стенд_диалога as СД
    система = С.Д.Система()
    случаи, _, оценка = С.собрать_случаи(система.блоки, n=40)

    def серия(профиль):
        СД.применить_профиль(профиль)
        итог = {"вопросов": 0, "чистых_верно": 0, "есть_нет_потеря": 0, "врач_открыт": 0, "ложный_лидер": 0, "отзыв_p": 0.0, "отзыв_вердикт": 0}
        with С.Подмена(система) as фейк:
            for с in случаи:
                with СД.Блок(система, оценка):
                    ч = С.провести(система, фейк, с, С.разбор_реплики(СД.чистые_упоминания(с)), {с["истина"]})
                    итог["вопросов"] += ч["вопросов"]
                    итог["чистых_верно"] += ч["рейтинг"][0][0] == с["истина"]
                    у = СД.чистые_упоминания(с)
                    у[0]["статус"] = "нет"
                    итог["есть_нет_потеря"] += Р.sigm(С.провести(система, фейк, с, С.разбор_реплики(у), {с["истина"]})["lN"][с["истина"]]) < Р.П_КАНДИДАТ
                    у = СД.чистые_упоминания(с)
                    у[0]["кто_подтвердил"] = "врач"
                    # база сравнения — флаг ядра «подтверждено_врачом» (как в стенде, стенд_диалога.py): после правки
                    # «код-решение в живом итоге» строка досье «ВЕРДИКТ ПО КАТЕГОРИИ: разрешён» дополнительно требует
                    # выбранную решателем кода категорию, поэтому в «до»-профиле она больше не отражает исходный
                    # критерий открытия вердикта; флаг одинаково доступен в обоих профилях (до/расследование.py:120)
                    итог["врач_открыт"] += С.провести(система, фейк, с, С.разбор_реплики(у), {с["истина"]})["подтверждено_врачом"]
                    у = СД.чистые_упоминания(с) + [С.упоминание(x, "есть") for x in [с["фантом"]["фраза"]] + с["фантом"]["парафразы"][:2]]
                    р3 = С.провести(система, фейк, с, С.разбор_реплики(у), {с["истина"]})
                    итог["ложный_лидер"] += р3["рейтинг"][0][0] != с["истина"] and р3["рейтинг"][0][1] >= 0.5
                    # отзыв: сказал «есть» с числом и врачом, потом «это у брата»
                    сессия = СД._сессия(система)
                    фейк.досье_итога.clear()
                    фейк.разбор = С.разбор_реплики([С.упоминание(с["фраза"], "есть", "-7 дптр", "врач")])
                    сессия.ход("Окулист в поликлинике написал: " + с["фраза"])         # врач назван и словами: сверка его не снимает, снимать должна только поправка
                    фейк.разбор = С.разбор_реплики([С.упоминание(с["фраза"], "чужое")], ответ="не_по_вопросу")
                    сессия.ход("это у брата")
                    итог["отзыв_p"] += сессия.ср.p(с["истина"])
                    фейк.разбор = С.разбор_реплики([], завершить=True)
                    сессия.ход("Что в итоге?")
                    итог["отзыв_вердикт"] += сессия.ср.подтверждено_врачом()   # флаг ядра: он и был старым критерием открытого вердикта (см. комментарий выше)
        return {k: (round(v / len(случаи), 3) if k != "вопросов" else round(v / len(случаи), 2)) for k, v in итог.items()}
    до, после = серия("до"), серия("после")
    СД.применить_профиль("после")
    print("   до:", до, "\n   после:", после)
    отметить(после["чистых_верно"] >= до["чистых_верно"] and после["вопросов"] <= до["вопросов"] + 0.3, "цена защиты мала: чистый диалог так же находит статью (%.2f → %.2f), вопросов %.2f → %.2f (не больше +0,3)" % (до["чистых_верно"], после["чистых_верно"], до["вопросов"], после["вопросов"]))
    отметить(до["есть_нет_потеря"] > 0.5 and после["есть_нет_потеря"] <= 0.05, "ошибка статуса «есть»→«нет» в разборе: потеря истины %.0f %% → %.0f %%" % (100 * до["есть_нет_потеря"], 100 * после["есть_нет_потеря"]))
    отметить(до["врач_открыт"] > 0.9 and после["врач_открыт"] <= 0.15, "ложное «подтвердил врач»: подтверждение врача в ядре в %.0f %% → %.0f %% случаев (флаг ядра, порог прежний)" % (100 * до["врач_открыт"], 100 * после["врач_открыт"]))
    отметить(до["ложный_лидер"] >= 0.15 and после["ложный_лидер"] <= 0.05, "ложная жалоба, повторённая три раза: ложный лидер с p≥0,5 в %.0f %% → %.0f %% случаев" % (100 * до["ложный_лидер"], 100 * после["ложный_лидер"]))
    отметить(до["отзыв_p"] > 0.5 and после["отзыв_p"] <= 0.05 and до["отзыв_вердикт"] > 0.9 and после["отзыв_вердикт"] == 0, "отзыв «это у брата»: p статьи %.2f → %.2f, подтверждение врача в ядре %.0f %% → %.0f %% случаев" % (до["отзыв_p"], после["отзыв_p"], 100 * до["отзыв_вердикт"], 100 * после["отзыв_вердикт"]))

    # след хода показывает сверку
    СД.применить_профиль("после")
    with С.Подмена(система) as фейк:
        с = случаи[0]
        у = СД.чистые_упоминания(с)
        у[0]["статус"] = "нет"
