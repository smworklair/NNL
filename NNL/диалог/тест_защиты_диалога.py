проверок = прошло = 0


def отметить(условие, название):
    global проверок, прошло
    проверок += 1
    прошло += 1 if условие else 0
    print("проверка %d: %s — %s" % (проверок, название, "совпало" if условие else "НЕ СОВПАЛО"), flush=True)
    return условие


СТАТЬИ = ["1", "2", "3"]
ПРИОР = Р.sigm(Р.logit(Р.ПРИОР))


def новое():
    return Р.Расследование(СТАТЬИ)


def клауза(текст, p, целиком=False):
    return {"текст": текст, "p": p, "p0": 0.0, "целиком": целиком}


def main():
    Р.ЗАЩИТА.update({k: True for k in Р.ЗАЩИТА})

    # ------------------------------------------------------------------ журнал: снятие улик
    р = новое()
