ТЕМЫ = ["подтверждение", "степень", "давность", "лечение", "обследование", "осложнения", "другое"]

СИСТЕМА = """Ты готовишь вопросы для уточняющего диалога по ОДНОЙ статье Расписания болезней (ПП РФ № 565) для призывника. Цель — выявить объективную
картину: человек может ошибаться в диагнозе, степени, пороге. Вопросы пойдут в диалог заранее, без знания реплики человека.
Предложи ровно 6 вопросов, ответы на которые лучше всего РАЗДЕЛЯЮТ случаи «статья относится к человеку» и «не относится»:
- вопрос простым языком, про ОДИН факт, который человек может знать: чем подтверждён диагноз, что показало обследование, как давно, как лечили, какая степень;
- вид «да_нет»: p_да_если_есть — как вероятно человек ответит «да», если эта статья у него действительно есть; p_да_если_нет — если её нет. Это честные оценки,
  они должны различаться сильно (хорошая пара: 0,9 и 0,2; плохая: 0,6 и 0,5);
- вид «значение» — открытый вопрос о степени или значении (диоптрии, давление, степень, частота обострений); для него p_да_если_есть и p_да_если_нет поставь 0,5;
- по_критерию — ДОСЛОВНАЯ короткая цитата (не меньше 4 слов) из текста статьи ниже, на которой держится вопрос;
- тема — одна из: подтверждение, степень, давность, лечение, обследование, осложнения, другое. Вопрос «чем подтверждён диагноз» имеет тему «подтверждение»;
- хотя бы 4 вопроса вида «да_нет», хотя бы 1 вопрос, ответ на который может ОПРОВЕРГНУТЬ версию человека;
- числа и пороги в вопросах — только из текста статьи; не ставь диагнозов; не используй слова «система», «вероятность», «расчёт».
Верни только JSON."""

СХЕМА = {"type": "object", "properties": {"вопросы": {"type": "array", "items": {"type": "object", "properties": {
    "вид": {"type": "string", "enum": ["да_нет", "значение"]}, "тема": {"type": "string", "enum": ТЕМЫ}, "текст": {"type": "string"},
    "p_да_если_есть": {"type": "number"}, "p_да_если_нет": {"type": "number"}, "по_критерию": {"type": "string"}},
    "required": ["вид", "тема", "текст", "p_да_если_есть", "p_да_если_нет", "по_критерию"]}}}, "required": ["вопросы"]}


def хеш_статьи(статья):
    return hashlib.sha256(статья.текст_для_модели(30000).encode("utf-8")).hexdigest()[:16]


def проверить_вопрос(q, статья, числа_документа):
    """(ок, причина). Те же правила, что у ядра на живых вопросах, плюс охрана чисел на самом тексте вопроса."""
    from диалог import проверка_чисел
    текст = (q.get("текст") or "").strip()
    if len(текст) < 10 or not текст.endswith("?"):
        return False, "не похоже на вопрос"
    if not Р.цитата_в_тексте(q.get("по_критерию", ""), статья.текст_для_модели(30000)):
        return False, "цитата критерия не найдена в тексте статьи"
    if q.get("вид") == "да_нет" and Р.очистить_таблицу(q.get("p_да_если_есть"), q.get("p_да_если_нет")) is None:
        return False, "таблица не различает гипотезы"
    нет = проверка_чисел(текст, числа_документа)["нет_в_источнике"]
    if нет:
        return False, "числа не из документа: " + ", ".join(нет)
    return True, ""


def построить_статью(ид, база, модель):
    а = база.статьи[ид]
    пров, _, мод = модель.partition(":")
    r = К.спросить(пров, мод, СИСТЕМА, [("user", "Текст статьи:\n" + а.текст_для_модели(6000))], схема=СХЕМА, температура=0.3, макс_токенов=3500, кэш=False, таймаут=180)
    данные = r["данные"]
    if isinstance(данные, list) and данные:
        данные = данные[0]
    числа = база.числа_документа(ид)
    годные, отклонено, видели = [], [], set()
    for q in данные.get("вопросы", []):
        ок, причина = проверить_вопрос(q, а, числа)
        ключ = (q.get("текст") or "").strip().lower()
        if ок and ключ in видели:
            ок, причина = False, "повтор"
        if ок:
            видели.add(ключ)
            таблица = Р.очистить_таблицу(q["p_да_если_есть"], q["p_да_если_нет"]) if q["вид"] == "да_нет" else None
            годные.append({"вид": q["вид"], "тема": q["тема"], "текст": q["текст"].strip(), "таблица": list(таблица) if таблица else None, "по_критерию": q["по_критерию"].strip()})
        else:
            отклонено.append({"текст": q.get("текст"), "причина": причина})
    return {"хеш": хеш_статьи(а), "вопросы": годные, "отклонено": отклонено, "токены": r["токены_вход"] + r["токены_выход"], "мс": r["мс"]}


def загрузить_файл(путь=None):
    путь = путь or ФАЙЛ
    if not os.path.exists(путь):
        return {"версия": 1, "статьи": {}}
    with open(путь, encoding="utf-8") as f:
        return json.load(f)


def построить(ид_список=None, модель=МОДЕЛЬ, потоков=4, путь=None, пересобрать=False):
    база = З.База()
    банк = загрузить_файл(путь)
    ид_список = ид_список or list(база.статьи)
    сделать = [ид for ид in ид_список if пересобрать or ид not in банк["статьи"] or банк["статьи"][ид].get("хеш") != хеш_статьи(база.статьи[ид])]
    print("к построению статей: %d из %d, модель %s" % (len(сделать), len(ид_список), модель), flush=True)
    t0 = time.time()
    with concurrent.futures.ThreadPoolExecutor(max_workers=потоков) as ex:
        задачи = {ex.submit(построить_статью, ид, база, модель): ид for ид in сделать}
        for f in concurrent.futures.as_completed(задачи):
            ид = задачи[f]
            try:
                банк["статьи"][ид] = f.result()
                р = банк["статьи"][ид]
                print("  ст.%-3s годных %d, отклонено %d, %d токенов, %.0f с" % (ид, len(р["вопросы"]), len(р["отклонено"]), р["токены"], р["мс"] / 1000), flush=True)
            except Exception as e:  # noqa: BLE001
                print("  ст.%-3s ОШИБКА: %s" % (ид, str(e)[:120]), flush=True)
            банк.update({"модель": модель, "создан": time.strftime("%Y-%m-%d %H:%M:%S")})
            with open(путь or ФАЙЛ, "w", encoding="utf-8") as fo:
                json.dump(банк, fo, ensure_ascii=False, indent=1)
    print("готово за %.0f с" % (time.time() - t0))
    return банк


class Банк:
    """Читает банк и отдаёт ядру вопросы в том же виде, в каком раньше их давала модель."""

    def __init__(self, база, путь=None):
        self.данные = загрузить_файл(путь).get("статьи", {})
        self.база = база
        self.актуальные = {ид: s for ид, s in self.данные.items() if ид in база.статьи and s.get("хеш") == хеш_статьи(база.статьи[ид]) and len(s.get("вопросы", [])) >= 3}

    def покрывает(self, ид_список):
        return bool(ид_список) and all(ид in self.актуальные for ид in ид_список)

    def предложения(self, ид_список):
        """Список предложений для Расследование.выбрать_вопрос(): вид, статья, текст, таблица, по_критерию (+ тема). None — банк не покрывает статьи."""
        if not self.покрывает(ид_список):
            return None
        out = []
        for ид in ид_список:
            for q in self.актуальные[ид]["вопросы"]:
                out.append({"вид": q["вид"], "статья": ид, "текст": q["текст"], "таблица": tuple(q["таблица"]) if q.get("таблица") else (0.5, 0.5),
                            "по_критерию": q["по_критерию"], "тема": q.get("тема", "другое"), "из_банка": True})
        return out


def проверить_банк():
    база = З.База()
    б = Банк(база)
    всего, ок = len(база.статьи), len(б.актуальные)
    print("статей в документе: %d; в банке актуальных (≥3 годных вопроса, хеш совпал): %d" % (всего, ок))
    нет = [ид for ид in база.статьи if ид not in б.актуальные]
    if нет:
        print("нет в банке или устарели:", ", ".join(нет))
    токены = sum(s.get("токены", 0) for s in б.данные.values())
    годных = [len(s["вопросы"]) for s in б.актуальные.values()]
    if годных:
        print("вопросов на статью: мин %d, среднее %.1f, макс %d; потрачено на построение %d токенов" % (min(годных), sum(годных) / len(годных), max(годных), токены))
    причины = {}
    for s in б.данные.values():
        for о in s.get("отклонено", []):
            причины[о["причина"].split(":")[0]] = причины.get(о["причина"].split(":")[0], 0) + 1
    print("отклонено при построении:", причины or "ничего")


