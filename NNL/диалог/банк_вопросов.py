"""Банк вопросов: вопросы и таблицы вероятностей по каждой статье готовятся заранее, один раз, а не на каждый ход диалога.

Зачем. Раньше на каждый ход, где ядро решало «спросить», внешняя модель заново придумывала 4–6 вопросов к одним и тем же статьям:
около 9 с и 1,9 тыс. токенов за ход. Вопросы от реплики человека почти не зависят, зависит только выбор (его делает ядро по информационному выигрышу).

Как устроено.
  * Построение (один раз, строго по тексту статьи): модель предлагает вопросы с таблицами p(да | статья есть) и p(да | статьи нет); каждый вопрос
    проходит те же проверки, что и живые вопросы в диалоге: цитата критерия найдена в тексте статьи, таблица различает гипотезы, числа с единицами
    взяты из документа. Отклонённое сохраняется с причиной.
  * Хеш текста статьи записан в банк. Если статья изменилась, вопросы этой статьи считаются устаревшими, и диалог идёт старым путём (через API).
  * В диалоге: Банк.предложения(статьи) отдаёт ядру вопросы в том же виде, что раньше давала модель; выбор и все проверки делает ядро как раньше.
Запуск:
  python банк_вопросов.py построить [--статьи 34,12] [--модель провайдер:модель] [--потоков 4]
  python банк_вопросов.py проверить"""
