class Сессия:
    def __init__(self, система):
        self.с = система
        self.ср = Р.Расследование(list(система.база.статьи))
        self.история = []              # [(роль, текст)] — как видит диалог человек
        self.слова_человека = []
        self.шаг = 0
        self.закончено = False
        self.баз_история = []
        self.св_история = []           # режим «Свободно»: реплики и ответы без досье (досье прикладывается только к последней реплике)
        self.роли = None               # свои роли сессии {роль: (провайдер, модель)}; None — общие РОЛИ
        self.след = След()             # след текущего хода: что делали блоки, ядро, API, охрана
        self.на_шаг = None             # куда сразу отправлять события следа (потоковая передача страницы); None — только копить
        self.глубже = False            # попросить у API рассуждение подробнее (дороже по токенам и времени)
        self.использовать_банк = True  # вопросы из банка без вызова API; False — всегда просить у модели (для сравнения в бенчмарке)
        self.кэш = True                # повтор того же запроса берётся из кэша; бенчмарку цены кэш мешает (вызов выглядит бесплатным), он его выключает

    # ------------------------------------------------------------------ след
    def _начать_след(self, режим, текст):
        self.след = След(self.на_шаг)
        self.след.шаг("система", "Реплика получена", "режим «%s», %d симв." % (режим, len(текст)), режим=режим)

    def _след_ворота(self, cz, cp):
        вывод = "ближе всего «%s»" % ("здоровье" if cz >= cp else "право") if max(cz, cp) >= 0 else "оба числа ниже нуля: это не про здоровье и не про право"
        self.след.шаг("блоки", "Блоки проверили область вопроса", "здоровье %+.2f · право %+.2f — %s" % (cz, cp, вывод), здоровье=round(cz, 2), право=round(cp, 2))

    def _след_упоминание(self, у, p, p0, запись):
        топ = sorted(p.items(), key=lambda x: -x[1])[:3]
        self.след.шаг("блоки", "Блок «здоровье» оценил «%s»" % у["термин"],
                      "ближайшие статьи: %s · «ни одна не подходит»: %.2f" % (", ".join("ст.%s %.2f" % (a, v) for a, v in топ), p0),
                      термин=у["термин"], статус=у["статус"], кто_подтвердил=_кто(у),
                      ближайшие=[{"статья": a, "p": round(v, 3)} for a, v in топ], p_ничего=round(p0, 3))
        if запись.get("повтор"):
            self.след.шаг("ядро", "Ядро: «%s» уже учтено, второй раз не считается" % у["термин"], статус=у["статус"])
            return
        сдвиги = запись.get("сдвиги") or []
        пояснение = {"чужое": "болезнь у другого человека: вероятности не меняются", "нет": "человек это отрицает: вероятности снижаются",
                     "было": "было в прошлом: вес вдвое меньше", "есть": "есть сейчас: вероятности растут"}.get(у["статус"], "")
        self.след.шаг("ядро", "Ядро учло «%s» (%s)" % (у["термин"], у["статус"]),
                      ("; ".join("ст.%s %.2f → %.2f" % (s["статья"], s["до"], s["после"]) for s in сдвиги) or "ни одна статья не сдвинулась: блок почти не связывает фразу со статьями") +
                      (" · " + пояснение if пояснение else ""), сдвиги=сдвиги, подтверждено=запись.get("подтверждено"))

    def _след_сверка(self, сверка):
        флаги = сверка.get("флаги") or []
        if not флаги:
            return
        названия = {"статус_без_маркера": "статус не подтверждён словами человека", "врач_без_слов": "«подтвердил врач» не подтверждено словами человека",
                    "пропущено_разбором": "слова человека указывают на статью, а разбор её не учёл", "не_подтверждено_словами": "разбор поднял статью, а слова человека её не подтверждают"}
        self.след.шаг("ядро", "Ядро сверило разбор реплики со словами человека: расхождений %d" % len(флаги),
                      "; ".join("%s%s" % (названия.get(ф["вид"], ф["вид"]), (" (ст.%s)" % ф["статья"]) if ф.get("статья") else (" «%s»" % ф["термин"]) if ф.get("термин") else "") for ф in флаги[:4]) +
                      " · уверенность не повышена, статья остаётся кандидатом для вопроса", флаги=флаги, сдвиги=сверка.get("сдвиги") or None)

    def _след_ответ(self, вопрос, запись):
        сдвиги = запись.get("сдвиги") or []
        self.след.шаг("ядро", "Ядро учло ответ на вопрос: «%s»" % запись["ответ"], "; ".join("ст.%s %.2f → %.2f" % (s["статья"], s["до"], s["после"]) for s in сдвиги) or "вероятности не менялись",
                      вопрос=вопрос.get("текст"), ответ=запись["ответ"], сдвиги=сдвиги)

    def _след_отбор_вопросов(self, разбор, выбран):
        принято = [r for r in разбор if "отказ" not in r]
        отклонено = [r for r in разбор if "отказ" in r]
        self.след.шаг("ядро", "Ядро проверило вопросы, предложенные API: принято %d из %d" % (len(принято), len(разбор)),
                      "; ".join("«%s» — %s" % ((r.get("текст") or "")[:60], r["отказ"]) for r in отклонено[:3]) or "все вопросы прошли проверку по тексту документа",
                      предложено=len(разбор), отклонено=len(отклонено), разбор=разбор)
        if выбран:
            self.след.шаг("ядро", "Ядро выбрало вопрос по статье %s" % выбран.get("статья"), "«%s» · %s" % (выбран.get("текст", ""), выбран.get("причина", "")),
                          действие="спросить", статья=выбран.get("статья"), eig=выбран.get("eig"))

    # ------------------------------------------------------------------ вызов роли
    def _вызов(self, роль, система, история, схема=None, температура=0.2, досье=None, **kw):
        """Один вызов внешней модели со следом. «досье» — номера статей, которые API увидит во входе (для проверки: ссылаться можно только на них)."""
        рл = self.роли or РОЛИ
        пров, мод = рл[роль] if роль in рл else рл["базовая"]
        идёт, готово = _ЗАГОЛОВКИ_ВЫЗОВОВ.get(роль, ("API работает", "API ответил"))
        вход = "\n\n".join(x[1] for x in история if isinstance(x, (list, tuple)) and len(x) > 1 and x[0] == "user")
        е = self.след.шаг("API", идёт, роль=роль, модель="%s:%s" % (пров, мод), статус="идёт")
        kw.setdefault("кэш", self.кэш)
        думает = bool(self.глубже and роль in РОЛИ_РАССУЖДЕНИЯ)
        if думает:
            kw.setdefault("размышление", True)
            kw["макс_токенов"] = kw.get("макс_токенов", 1500) + ДОБАВКА_ДУМАНИЯ         # рассуждение считается в лимите ответа: без запаса на сам ответ не остаётся места
            kw.setdefault("таймаут", 180)
        # Поток итога на страницу: пока модель генерирует, страница видит черновик (SSE-обновления уже есть для шагов).
        # Только для свободного текста итога в живом диалоге (есть куда слать шаги); бенчмарки и тесты идут прежним путём.
        if роль == "итог" and схема is None and self.на_шаг is not None and "на_часть" not in kw:
            сост = [0, 0.0]

            def _часть(частичный, _е=е, _сост=сост):
                try:
                    сейчас = time.time()
                    if len(частичный) - _сост[0] >= 250 or сейчас - _сост[1] >= 0.5:
                        _сост[0] = len(частичный)
                        _сост[1] = сейчас
                        self.след.дополнить(_е, выход=_обрезать(частичный, ПРЕДЕЛ_ВЫХОДА),
                                            черновик_итога=_обрезать(частичный, ПРЕДЕЛ_ВЫХОДА), черновик_симв=len(частичный))
                except Exception:  # noqa: BLE001
                    pass

            kw["на_часть"] = _часть
        try:
            r = К.спросить(пров, мод, система, история, схема=схема, температура=температура, **kw)
        except Exception as ош:  # noqa: BLE001
            self.след.дополнить(е, статус="ошибка", название=идёт + ": сбой", ошибка=str(ош)[:240])
            raise
        думы = r.get("рассуждение") or ""
        self.след.дополнить(
            е, статус="готово", название=готово, модель=r.get("модель") or "%s:%s" % (пров, мод), мс_вызова=r.get("мс"),
            токены_вход=r.get("токены_вход"), токены_выход=r.get("токены_выход"), токены_рассуждения=r.get("токены_рассуждения"),
            из_кэша=bool(r.get("из_кэша")), глубже=думает,
            вход=_обрезать(вход, ПРЕДЕЛ_ВХОДА), вход_симв=len(вход), статьи_в_досье=sorted(set(досье or [])),
            статьи_во_входе=sorted({н for m in Ссыл._СТ.finditer(вход) for н in re.findall(r"\d+", m.group(1))}),
            числа_во_входе=sorted(З.нормализованные_числа(вход)), выход=_обрезать(r.get("текст") or "", ПРЕДЕЛ_ВЫХОДА),
            рассуждение=_обрезать(думы, ПРЕДЕЛ_РАССУЖДЕНИЯ), рассуждение_симв=len(думы))
        return r

    def _досье_статей(self, статьи_p, лимит):
        return "\n\n".join("### Кандидат: статья %s, вероятность по текущим уликам %.2f\n%s" % (
            ид, p, self.с.база.статьи[ид].текст_для_модели(лимит)) for ид, p in статьи_p)

    def _критерии_статьи(self, ид, лимит=900):
        """Только строки критериев второй статьи для досье итога: название + пункты с категориями, без примечаний.
        Числа порогов остаются (они в описаниях пунктов), а длинные примечания не тратят входные токены."""
        а = self.с.база.статьи[ид]
        строки = ["Статья %s. %s" % (а.ид, а.название)]
        for п in а.пункты:
            г = п["графы"]
            строки.append("  пункт «%s»: %s | КАТЕГОРИЯ ДЛЯ ПРИЗЫВНИКА (графа I): %s" % (
                п["буква"], п["описание"], г[0] if г else "—"))
            if sum(len(s) for s in строки) >= лимит:
                break
        return "\n".join(строки)[:лимит]

    def _досье_итога(self, статьи_p, лимит_лидера=2400, лимит_второй=900):
        """Досье итога: лидер целиком, вторая — только критерии. Экономит ~1,5 тыс. символов входа без потери порогов."""
        части = []
        for i, (ид, p) in enumerate(статьи_p):
            if i == 0:
                текст = self.с.база.статьи[ид].текст_для_модели(лимит_лидера)
                части.append("### Кандидат: статья %s, вероятность по текущим уликам %.2f\n%s" % (ид, p, текст))
            else:
                текст = self._критерии_статьи(ид, лимит_второй)
                части.append("### Кандидат: статья %s, вероятность по текущим уликам %.2f (кратко: только критерии)\n%s" % (ид, p, текст))
        return "\n\n".join(части)

    def _что_известно(self):
        строки = []
        for у in self.ср.улики:
            if у["тип"] == "упоминание":
                строки.append("- %s (%s)%s%s" % (у["термин"], у["статус"], (": " + у["уточнение"]) if у["уточнение"] else "",
                                                 " [подтверждено врачом]" if у.get("подтверждено") == "врач" else " [со слов человека, врач не подтвердил]" if у["статус"] == "есть" else ""))
            else:
                строки.append("- на вопрос «%s» человек ответил: %s" % (у["вопрос"], у["ответ"]))
        for ст, т in self.ср.значения:
            строки.append("- значение: " + т)
        return "\n".join(строки) or "— пока ничего"

    def _разрешённые_числа(self, ст_ид):
        ok = set()
        for ид in ст_ид:
            ok |= self.с.база.числа_документа(ид)
        ok |= З.нормализованные_числа(" ".join(self.слова_человека))
        # числа, которые человек назвал словами («минус пять с половиной»), разбор уже перевёл в цифры в «уточнении»/«значении»
        ok |= З.нормализованные_числа(" ".join(у.get("уточнение", "") for у in self.ср.улики if у["тип"] == "упоминание"))
        ok |= З.нормализованные_числа(" ".join(т for _, т in self.ср.значения))
        return ok

    # ------------------------------------------------------------------ один ход
    @staticmethod
    def _служебная_реплика(текст):
        """Короткие ответы да/нет, числа, просьбы об итоге или поправки источника («не врач, а я сам») не должны отсекаться воротами области."""
        т = текст.strip()
        if bool(_ИТОГ_ЗАПРОС.search(т)) or bool(_ПОПРАВКА_САМ.search(т)) or bool(re.search(r"\d", т)):
            return True
        if re.match(r"^(?:да|нет|не\s+знаю|не\s+помню|вроде\s+да|вроде\s+нет|конечно|именно|точно|никак\s+нет)\b", т, re.I):
            return True
        return False

    # ------------------------------------------------------------------ один ход
    def ход(self, текст):
        t0 = time.time()
        начало_журнала = К.метка_журнала()
        self.шаг += 1
        тел = {"шаг": self.шаг, "режим": "ядро"}
        self._начать_след("ядро", текст)
        ожидалось = self.ср.ожидается
        # 1. ворота области ПЕРЕД ядром на каждой реплике: если оба значения ниже нуля (например, «как приготовить борщ»), реплика не идёт в разбор и не меняет улики
        cz, cp = self.с.блоки.область(текст)
        тел["ворота"] = {"здоровье": round(cz, 2), "право": round(cp, 2)}
        self._след_ворота(cz, cp)
        начат = self.ср.есть_улики() or ожидалось is not None
        if max(cz, cp) < 0 and (not начат or not self._служебная_реплика(текст)):
            причина = "область:здоровье=%.2f, область:право=%.2f — оба ниже нуля" % (cz, cp)
            self.след.шаг("ядро", "Ядро решило: вне темы (улики не меняются)", причина, действие="вне_темы")
            ответ = self._вне_темы(текст)
            тел.update(действие="вне_темы", причина=причина)
            return self._завершить_ход(ответ, тел, t0, начало_журнала, [], реплика_текущая=текст)
        self.слова_человека.append(текст)
        # 2. разбор реплики. Короткая просьба об итоге без новых фактов разбирается без модели: тем же правилом, которое и так стоит страховкой
        if self._только_просьба_итога(текст):
            разбор = {"упоминания": [], "ответ_на_вопрос": "не_по_вопросу" if ожидалось else "нет_вопроса", "значение": "", "хочет_завершить": True}
            self.след.шаг("ядро", "Разбор без API: это просьба об итоге, новых фактов в ней нет", "правило по словам («что в итоге», «подведи итог»…), не более 6 слов и без цифр", без_api=True)
        else:
            контекст_улик = ""
            действ_упоминания = [з["термин"] for з in self.ср.улики if з["тип"] == "упоминание"]
            if действ_упоминания:
                контекст_улик = "Ранее названные диагнозы/жалобы человека: " + ", ".join(действ_упоминания) + "\n"
            запрос = контекст_улик + "Реплика человека: " + текст
            if ожидалось:
                запрос = "Заданный вопрос: «%s»\n%s" % (ожидалось["текст"], запрос)
            разбор = self._вызов("разбор", СИСТЕМА_РАЗБОРА, [("user", запрос)], схема=СХЕМА_РАЗБОРА, температура=0.0)["данные"]
        тел["разбор"] = разбор
        хочет_итог = bool(разбор["хочет_завершить"]) or bool(_ИТОГ_ЗАПРОС.search(текст))
        # 3. факты → свой блок → ядро
        for у in разбор["упоминания"]:
            фраза = (у["термин"] + " " + (у["уточнение"] or "")).strip()
            p, p0 = self.с.блоки.статьи(фраза)
            запись = self.ср.учесть_упоминание(у["термин"], у["статус"], у["уточнение"], p, p0, _кто(у))
            self._след_упоминание(у, p, p0, запись)
        # Страховка для поправки источника подтверждения («не врач, а я сам так думаю»): если слушатель не вернул упоминание с «сам», отзываем «врач» напрямую в ядре
        if _поправка_источника(текст):
            if self.ср.подтверждено_врачом():
                снятые_врач = self.ср.отменить_подтверждение_врача()
                if снятые_врач:
                    self.след.шаг("ядро", "Ядро учло поправку источника: подтверждение врача снято",
                                  "человек уточнил, что решил сам (%s)" % ", ".join(з["термин"] for з in снятые_врач),
                                  сдвиги=снятые_врач[0].get("сдвиги"), подтверждено="сам")
        if разбор["упоминания"]:
            self._след_сверка(self.ср.сверить_реплику(self.с.блоки.клаузы(текст), self.слова_человека))       # слова человека против разбора модели
        if ожидалось and разбор["ответ_на_вопрос"] in ("да", "нет", "не_знаю"):
            self._след_ответ(ожидалось, self.ср.учесть_ответ(ожидалось, разбор["ответ_на_вопрос"], разбор["значение"]))
        elif ожидалось and разбор["значение"]:
            self._след_ответ(ожидалось, self.ср.учесть_ответ(ожидалось, "не_знаю", разбор["значение"]))
        self.ср.ожидается = None
        # 4. решение ядра
        действие, причина = self.ср.следующий_шаг(хочет_итог)
        тел.update(действие=действие, причина=причина)
        if not self.ср.есть_улики() and cp >= 0 > cz:
            тел["действие"], тел["причина"] = "право", "здоровья в реплике нет, область:право=%.2f" % cp
            self.след.шаг("ядро", "Ядро решило: ответить по правовой теме", тел["причина"], действие="право")
            ответ = self._право(текст, тел)
            return self._завершить_ход(ответ, тел, t0, начало_журнала, [])
        self.след.шаг("ядро", "Ядро решило: %s" % _ДЕЙСТВИЯ.get(действие, действие), причина, действие=действие,
                      рейтинг=[{"статья": ид, "p": round(p, 3)} for ид, p in self.ср.рейтинг(5)])
        разбор_вопросов = []
        реакция_открытого = None        # реакция модели на сказанное: не теряем её, если вместо вопроса пришлось задать открытый
        if действие == "спросить":
            кандидаты = self.ср.кандидаты(порог=0.05, n=4)
            ид_кандидатов = [ид for ид, _ in кандидаты[:3]]
            предложения = self.с.банк.предложения(ид_кандидатов) if (self.с.банк and self.использовать_банк) else None
            if предложения is not None:
                предложения = self._без_известного(предложения)
                реакция_модели = ""
                self.след.шаг("ядро", "Вопросы взяты из банка: вызов API не нужен", "ст. %s: %d готовых вопросов с таблицами; цитаты и числа проверены по тексту статей при построении банка" % (
                    ", ".join(ид_кандидатов), len(предложения)), из_банка=True, вопросов=len(предложения))
            else:
                пр = self._вызов("вопросы", СИСТЕМА_ВОПРОСОВ, [("user", self._запрос_вопросов(кандидаты, текст))],
                                 схема=self._схема_вопросов(кандидаты[:3]), температура=0.3, макс_токенов=1300,
                                 досье=ид_кандидатов)["данные"]
                предложения = [{"вид": q["вид"], "статья": _ид_статьи(q["статья"]), "текст": q["текст"],
                                "таблица": (q["p_да_если_есть"], q["p_да_если_нет"]), "по_критерию": q["по_критерию"]} for q in пр["вопросы"]]
                реакция_модели = пр["реакция"]
            выбран, разбор_вопросов = self.ср.выбрать_вопрос(предложения, {ид: self.с.база.статьи[ид].текст_для_модели(20000) for ид, _ in кандидаты})
            self._след_отбор_вопросов(разбор_вопросов, выбран)
            тел["реакция_модели"] = реакция_модели
            реакция_открытого = (реакция_модели, self._разрешённые_числа([ид for ид, _ in кандидаты]))
            if выбран is None and len(self.ср.задано) < 2 and not хочет_итог:
                действие, причина = "открытый_вопрос", "информации ещё мало (вопросов задано %d): уточняем характер жалобы" % len(self.ср.задано)
                тел.update(действие=действие, причина=причина)
                self.след.шаг("ядро", "Ядро решило: %s" % _ДЕЙСТВИЯ[действие], причина, действие=действие)
            elif выбран is None:
                действие, причина = "завершить", "вопросов с достаточным информационным выигрышем не осталось"
                тел.update(действие=действие, причина=причина)
                self.след.шаг("ядро", "Ядро решило: %s" % _ДЕЙСТВИЯ[действие], причина, действие=действие)
            else:
                self.ср.задано.append((выбран["статья"], выбран["текст"]))
                self.ср.ожидается = выбран
                тел["вопрос"] = {k: выбран[k] for k in ("вид", "статья", "текст", "причина") if k in выбран}
                разрешено = self._разрешённые_числа([ид for ид, _ in кандидаты])
                if реакция_модели.strip():
                    реакция, охрана = self._с_охраной_чисел(реакция_модели, разрешено, "реакция")
                else:                                       # вопрос из банка: текста от модели нет, проверять нечего
                    реакция, охрана = "", {"чисел_с_единицами": 0, "нет_в_источнике": [], "вырождение": False, "перегенерировано": False, "где": "вопрос из банка"}
                ответ = (реакция.strip() + "\n\n" + выбран["текст"].strip()).strip()
                тел["охрана_чисел"] = охрана
                return self._завершить_ход(ответ, тел, t0, начало_журнала, разбор_вопросов)
        if действие == "открытый_вопрос":
            ответ = self._открытый_вопрос(текст)
            if реакция_открытого and реакция_открытого[0].strip():
                реакция, охрана = self._с_охраной_чисел(реакция_открытого[0], реакция_открытого[1], "реакция")
                тел["охрана_чисел"] = охрана
                ответ = (реакция.strip() + "\n\n" + ответ).strip()
            return self._завершить_ход(ответ, тел, t0, начало_журнала, разбор_вопросов)
        # завершение: итог
        ответ, охрана = self._итог(тел)
        self.закончено = True
        тел["охрана_чисел"] = охрана
        return self._завершить_ход(ответ, тел, t0, начало_журнала, разбор_вопросов)

