    # ------------------------------------------------------------------ NNL + API без ограничений: ядро → блоки → API, каждый случай отдельно
    def _случаи(self, текст):
        """(голова, [(номер, фраза)]): после «СЛУЧАИ:» ищем «1.», «2.», … по порядку, переносы строк не нужны (номера могут быть склеены с текстом)."""
        m = re.search(r"СЛУЧАИ\s*:", текст, re.I)
        голова, хвост = (текст[:m.end()], текст[m.end():]) if m else ("", текст)
        отметки, поз, ожид = [], 0, 1
        while True:
            f = re.compile(r"(?<!\d)%d[.)]\s*" % ожид).search(хвост, поз)
            if not f:
                break
            отметки.append((ожид, f.start(), f.end()))
            поз, ожид = f.end(), ожид + 1
        if len(отметки) < 2:
            return "", [("", текст.strip())]
        out = []
        for k, (н, _, конец_) in enumerate(отметки):
            до = отметки[k + 1][1] if k + 1 < len(отметки) else len(хвост)
            out.append((str(н), хвост[конец_:до].strip()))
        return голова, out

    def _единицы(self, текст):
        """(голова, [(номер, [реплики])], вид): случаи «N. …» или диалоги «Диалог N: человек: … человек: …»; без разметки — один случай."""
        m = re.search(r"Диалог\s+1\s*:", текст)
        if m:
            голова = текст[:m.start()].strip()
            части = re.split(r"Диалог\s+(\d+)\s*:", текст[m.start():])
            ед = [(части[k], [x.strip() for x in re.split(r"человек\s*:", части[k + 1]) if x.strip()]) for k in range(1, len(части) - 1, 2)]
            if len(ед) >= 2:
                return голова, ед, "Диалог"
        голова, случаи = self._случаи(текст)
        if len(случаи) >= 2:
            return голова, [(н, [ф]) for н, ф in случаи], "Случай"
        return "", [("", [текст.strip()])], "Случай"

    def _учесть_реплику(self, текст):
        """Шаги 1–3 хода без решения «спросить/завершить»: ворота области → разбор → блок «здоровье» → журнал улик ядра."""
        self.шаг += 1
        cz, cp = self.с.блоки.область(текст)
        self._след_ворота(cz, cp)
        if max(cz, cp) < 0 and not self._служебная_реплика(текст):
            self.след.шаг("ядро", "Ворота области: реплика вне темы, пропущена без изменения улик",
                          "здоровье=%.2f, право=%.2f" % (cz, cp), действие="вне_темы")
            return {"упоминания": [], "ответ_на_вопрос": "нет_вопроса", "значение": "", "хочет_завершить": False, "вне_темы": True}
        self.слова_человека.append(текст)
        if self._только_просьба_итога(текст):
            return {"упоминания": [], "ответ_на_вопрос": "нет_вопроса", "значение": "", "хочет_завершить": True}
        контекст_улик = ""
        действ_упоминания = [з["термин"] for з in self.ср.улики if з["тип"] == "упоминание"]
        if действ_упоминания:
            контекст_улик = "Ранее названные диагнозы/жалобы человека: " + ", ".join(действ_упоминания) + "\n"
        разбор = self._вызов("разбор", СИСТЕМА_РАЗБОРА, [("user", контекст_улик + "Реплика человека: " + текст)], схема=СХЕМА_РАЗБОРА, температура=0.0)["данные"]
        for у in разбор["упоминания"]:
            фраза = (у["термин"] + " " + (у["уточнение"] or "")).strip()
            p, p0 = self.с.блоки.статьи(фраза)
            self.ср.учесть_упоминание(у["термин"], у["статус"], у["уточнение"], p, p0, _кто(у))
        if _поправка_источника(текст):
            if self.ср.подтверждено_врачом():
                self.ср.отменить_подтверждение_врача()
        if разбор["упоминания"]:
            self.ср.сверить_реплику(self.с.блоки.клаузы(текст), self.слова_человека)
        return разбор

    def _досье_ядра(self):
        """Досье для API из состояния ядра: слова, извлечённые факты, вероятности блока, отметка о враче, ворота области, тексты статей по необходимости."""
