def _поправка_источника(текст):
    """Человек поправился: «не врач, а я сам». Снимать подтверждение, только если в реплике не осталось
    положительного слова о враче: явные отрицания («у невролога я не был», «к врачу не ходил») вырезаются."""
    if not _ПОПРАВКА_САМ.search(текст):
        return False
    остаток = re.sub(r"не\s+врач\w*|врач\w*\s+не\s+\w+|врача\s+не\s+было", "", текст, flags=re.I)
    остаток = _ВРАЧА_НЕ_БЫЛО.sub("", остаток)
    return not _ВРАЧ.search(остаток)


