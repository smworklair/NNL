        слова = " ".join(self.слова_человека)
        врач = self.ср.подтверждено_врачом()
        cz, cp = self.с.блоки.область(слова)
        стр = ["Слова человека:\n" + "\n".join("- " + s for s in self.слова_человека),
               "Что извлекло ядро из слов (кто подтвердил: врач/сам):\n" + self._что_известно(),
               "Блок «здоровье», вероятности статей:\n" + "\n".join("- ст. %s «%s»: %.2f" % (ид, self.с.база.статьи[ид].название[:70], p) for ид, p in рейтинг[:4]),
               "Заключение врача в рассказе: " + ("ЕСТЬ" if врач else "НЕТ (только слова человека)"),
               "ВЕРДИКТ ПО КАТЕГОРИИ: " + ("разрешён (врач подтвердил)." if врач else "ЗАПРЕЩЁН (врач ничего не подтвердил): категорию годности не называть."),
               ("Самая вероятная статья по блоку: ст. %s «%s», p=%.2f" % (рейтинг[0][0], self.с.база.статьи[рейтинг[0][0]].название[:60], рейтинг[0][1])) if рейтинг else "Блок не дал вероятной статьи.",
               "Ворота области (блоки): здоровье=%.2f, право=%.2f (ниже нуля — вероятно, вопрос не про здоровье)" % (cz, cp)]
        нужны = [ид for ид in re.findall(r"(?:стать\w+|ст\.)\s*(\d{1,2})", слова) if ид in self.с.база.статьи]
