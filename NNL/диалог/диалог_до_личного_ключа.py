            текст2 = написать(None, False, без_категории=(not разрешён), ошибки_кода=сверка_кода["ошибки"])
            текст2, охрана2 = self._с_охраной_чисел(текст2, разрешено, "итог (повтор)", переписать=None)
            сверка2 = self._проверка_решения_кода(текст2, реш)
