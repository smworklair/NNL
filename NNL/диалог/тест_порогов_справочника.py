# -*- coding: utf-8 -*-
"""Тест калькуляторов порогов справочника (пороги.py): числа читаются из текста статей, правила проверяются на границах.
Запуск: python NNL/диалог/тест_порогов_справочника.py   — без сети и без моделей."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
import знания as З  # noqa: E402
import пороги as П  # noqa: E402

база = З.База()
ошибки = []


def проверить(что, ожидал, получил):
    ок = ожидал == получил
    print(("  ок   " if ок else "  ОШИБКА ") + что + ("" if ок else "  ожидал %r, получил %r" % (ожидал, получил)))
    if not ок:
        ошибки.append(что)


print("пороги, прочитанные из текста:")
проверить("ст. 40: граница шёпота", 3, П._слух_пороги(база.статьи["40"])["граница"])
проверить("ст. 40: пункт б", (1, 2), П._слух_пороги(база.статьи["40"])["б"])
проверить("ст. 40: пункт в", (2, 3), П._слух_пороги(база.статьи["40"])["в"])
проверить("ст. 86: масса и рост", (45, 150), (П._рост_пороги(база.статьи["86"])["масса"], П._рост_пороги(база.статьи["86"])["рост"]))
проверить("ст. 86: срок", 12, П._рост_пороги(база.статьи["86"])["месяцев"])
имт = П._имт_пороги(база.статьи["13"])
проверить("ст. 13: границы ИМТ", (18.5, 18.5, 19.4), (имт["недостаток"], имт["понижено_от"], имт["понижено_до"]))

print("слух (правое, левое → пункт):")
for (п, л), ож in [((0, 0), "а"), ((0, 3), "б"), ((3, 0), "б"), ((0, 3.5), "в"), ((0, 6), "в"), ((1, 2), "б"), ((0.5, 0.5), "б"), ((2, 3), "в"),
                   ((1.5, 2), "в"), ((1, 2.5), "в"), ((2, 2), "в"), ((2.5, 3), None), ((3, 3), None), ((6, 6), None)]:
    проверить("слух %s / %s" % (п, л), ож, П.решить(база, "40", {"правое": п, "левое": л})["пункт"])

print("масса и рост:")
for (м, р, в), ож in [((44, 160, 1), "б"), ((44, 160, 0), "а"), ((60, 149, 1), "б"), ((60, 149, 0), "а"), ((45, 150, 1), None), ((70, 180, 1), None), ((44, 149, 1), "б")]:
    проверить("масса %s рост %s впервые=%s" % (м, р, в), ож, П.решить(база, "86", {"масса": м, "рост": р, "впервые": в})["пункт"])

print("ИМТ (масса, рост → итог; ИМТ округляется до десятых, как в границах текста «18,5» и «19,4»):")
for (м, р), ож in [((50, 175), "Недостаточность питания"), ((58, 175), "Пониженное питание"), ((60, 175), "По питанию оснований нет"), ((56.0, 175), "Недостаточность питания"), ((56.7, 175), "Пониженное питание"), ((56.6, 175), "Пониженное питание"), ((59.4, 175), "Пониженное питание"), ((59.5, 175), "Пониженное питание"), ((59.7, 175), "По питанию оснований нет")]:
    р_ = П.решить(база, "13", {"масса": м, "рост": р})
    проверить("ИМТ масса %s рост %s (ИМТ %s)" % (м, р, р_["метрика"]["значение"]), ож, р_["итог"])

print("нет калькулятора:")
try:
    П.спецификация(база, "43")
    проверить("ст. 43 не поддержана", True, False)
except П.Нельзя:
    проверить("ст. 43 не поддержана", True, True)

print("\nОШИБОК: %d" % len(ошибки))
sys.exit(1 if ошибки else 0)
