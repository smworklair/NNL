# -*- coding: utf-8 -*-
"""Онтология блоков v8 — часть приложения, а не архитектуры NNL.

Блоки v8 (здоровье, право, ответы_мейлру) не объявляют `проекции` в паспорте: какие понятия шины подтверждает их ответ, раньше угадывало ядро по
таблицам «статья → глава» и «тема → акты». Теперь это знание живёт здесь и передаётся в ядро необязательным провайдером:

    ядро = ЯдроПричинности(провайдер=ОнтологияV8(корень_проекта))

Ядро спрашивает провайдера только тогда, когда в паспорте блока для ответа нет объявленной проекции. Новые блоки объявляют проекции сами
(СТАНДАРТ_БЛОКА.md, поле `проекции`) и этого модуля не требуют.

Контракт провайдера: метод `проекция(блок, ответ_id) -> dict[понятие, значение]`.
"""
import os

ЗНАЧЕНИЕ = 16.0

# подстрока в названии акта → понятие шины (порядок важен: первое совпадение побеждает)
АКТЫ = (("53фз", "акт:53фз"), ("пп565", "акт:пп565"), ("пп663", "акт:пп663"), ("пп719", "акт:пп719"), ("кас", "акт:кас"),
        ("коап", "акт:коап"), ("укрф", "акт:укрф"), ("127фз", "акт:127фз"), ("59фз", "акт:59фз"))


class ОнтологияV8:
    def __init__(self, корень):
        self._главы = {}      # id ответа (статья) → глава
        self._акты = {}       # id ответа (тема) → [понятия актов]
        данные = os.path.join(корень, "математичка", "данные")
        путь = os.path.join(данные, "статья_глава.csv")
        if os.path.exists(путь):
            with open(путь, encoding="utf-8") as f:
                f.readline()
                for строка in f:
                    if строка.strip():
                        p = строка.strip().split(";")
                        self._главы[p[0]] = p[1]
        путь = os.path.join(данные, "тема_акты.csv")
        if os.path.exists(путь):
            with open(путь, encoding="utf-8") as f:
                f.readline()
                for строка in f:
                    if строка.strip():
                        p = строка.strip().split(";")
                        акты = []
                        for а in p[1].split("+"):
                            а = а.strip().lower()
                            for подстрока, понятие in АКТЫ:
                                if подстрока in а:
                                    акты.append(понятие)
                                    break
                        self._акты[p[0]] = акты

    def проекция(self, блок, ответ_id):
        проекция = {}
        паспорт = getattr(блок, "паспорт", None) or {}
        if "область" in паспорт:
            проекция["область:%s" % паспорт["область"]] = ЗНАЧЕНИЕ
        сырой = ответ_id.split(":")[-1]
        if сырой in self._главы:
            проекция["глава:%s" % self._главы[сырой]] = ЗНАЧЕНИЕ
            проекция["область:здоровье"] = ЗНАЧЕНИЕ
        elif сырой in self._акты:
            for акт in self._акты[сырой]:
                проекция[акт] = ЗНАЧЕНИЕ
            проекция["область:право"] = ЗНАЧЕНИЕ
        return проекция
