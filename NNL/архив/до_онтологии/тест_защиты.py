# -*- coding: utf-8 -*-
"""Тесты механизмов защиты от каскадных ошибок на уровне архитектуры NNL (шина, процессор, ядро, линтер). Каждая проверка может покраснеть.

Что проверяется:
  * шина: конфликт (один источник «да», другой «нет») убирает понятие из срезов и пишется в `конфликты`; результат не зависит от порядка записи;
    согласные источники не складываются; повторная запись источника заменяет прежнюю; запись без источника работает как раньше;
  * процессор: конфликт доходит до результата и до причинной цепочки ядра; без предела влияния результат НЕ отличается от замороженного «до»
    на 120 вопросах настоящих блоков; с пределом сдвиг такта 2 не выходит за предел × max(отрыв такта 1, tau_conf);
  * изоляция такта 1: Lego-индекс игрушечного мира из 10 блоков равен нулю;
  * линтер, проверка вставки: настоящий блок «ответы_мейлру» проходит (0 изменений); блок, подделывающий чужое понятие шины, не проходит; безобидный
    проходит; порог ε работает в обе стороны; после снятия блока всё как до вставки;
  * архитектура не знает предметной области: в процессоре и матплате нет имён блоков и слов предметной области.
Запуск: python NNL/тест_защиты.py   (код возврата 1, если хоть одна проверка не совпала). Сеть не нужна."""
import importlib.util
import itertools
import json
import os
import re
import sys

import numpy as np

КОРЕНЬ_NNL = os.path.dirname(os.path.abspath(__file__))
ПРОЕКТ = os.path.dirname(КОРЕНЬ_NNL)
for _п in (ПРОЕКТ, os.path.join(КОРЕНЬ_NNL, "каскады"), os.path.join(ПРОЕКТ, "система", "замер")):
    if _п not in sys.path:
        sys.path.insert(0, _п)
sys.dont_write_bytecode = True
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

import игрушка as И  # noqa: E402
import линтер as Л  # noqa: E402
from NNL.матплата import Матплата  # noqa: E402
from NNL.процессор import Процессор  # noqa: E402
from NNL.ядро import ЯдроПричинности  # noqa: E402

проверок = прошло = 0


def отметить(условие, название):
    global проверок, прошло
    проверок += 1
    прошло += 1 if условие else 0
    print("проверка %d: %s — %s" % (проверок, название, "совпало" if условие else "НЕ СОВПАЛО"), flush=True)
    return условие


def замороженный(имя):
    путь = os.path.join(КОРЕНЬ_NNL, "каскады", "до", имя + ".py")
    спец = importlib.util.spec_from_file_location(имя + "_до", путь)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


def новая():
    return Матплата(И.Язык(), os.path.join(КОРЕНЬ_NNL, "каскады"))


def main():
    # ------------------------------------------------------------------ шина: конфликты
    м = новая()
    м.записать_на_шину("x", 16.0, источник="а")
    м.записать_на_шину("x", -16.0, источник="б")
    отметить("x" not in м.шина and set(м.конфликты["x"]) == {"а", "б"}, "конфликт: «да» и «нет» к одному понятию — понятия нет на шине, запись о конфликте осталась")
    отметить(all("x" not in k for k in ()) and not any("x" in м.срез_шины(n, такт=2) for n in м.блоки), "конфликтное понятие не попадает в срезы")
    результаты = set()
    for порядок in itertools.permutations([("а", 16.0), ("б", -16.0), ("в", 16.0)]):
        м = новая()
        for источник, v in порядок:
            м.записать_на_шину("x", v, источник=источник)
        результаты.add((tuple(sorted(м.шина.items())), tuple(sorted(м.конфликты))))
    отметить(len(результаты) == 1, "результат не зависит от порядка записи (6 перестановок трёх источников)")
    м = новая()
    м.записать_на_шину("y", 16.0, источник="а")
    м.записать_на_шину("y", 12.0, источник="б")
    м.записать_на_шину("y", 12.0, источник="в")
    отметить(м.шина["y"] == 16.0 and not м.конфликты, "согласные источники не складываются: три голоса дают наибольшее по модулю, а не сумму")
    м.записать_на_шину("y", -16.0, источник="а")
    м.записать_на_шину("y", -16.0, источник="б")
    м.записать_на_шину("y", -16.0, источник="в")
    отметить(м.шина["y"] == -16.0, "повторная запись источника заменяет прежнюю: после перезаписи все трое согласны, конфликта нет")
    м.записать_на_шину("z", 3.0)
    м.записать_на_шину("z", 5.0)
    отметить(м.шина["z"] == 5.0, "запись без источника работает как раньше (последняя заменяет)")
    м.записать_на_шину("слабое", 0.5, источник="а")
    м.записать_на_шину("слабое", -0.5, источник="б")
    отметить("слабое" in м.шина and not м.конфликты.get("слабое"), "слабые значения (меньше порога знака) не считаются конфликтом")
    м.очистить_шину()
    отметить(not м.шина and not м.конфликты, "очистка шины убирает и конфликты")

    # ------------------------------------------------------------------ процессор + ядро: конфликт доходит до результата
    м, каталог = И.новая_матплата(Матплата)
    for имя in ("д1", "д2"):
        И.записать_блок(м, каталог, имя, ["0", "1"], [], {"0": {"факт": -16.0}, "1": {"факт": 16.0}}, np.zeros((0, 2)))
    И.записать_блок(м, каталог, "чт", ["0", "1"], ["факт"], {"0": {"чт:0": 16.0}, "1": {"чт:1": 16.0}}, np.array([[-3.0, 3.0]]))
    пр = Процессор(м, ядро=ЯдроПричинности(None), tau_conf=1.0)
    согласны = пр.выполнить("д1:1:с д2:1:с чт:0:с0")
    спор = пр.выполнить("д1:1:с д2:0:с чт:0:с0")
    обратный = пр.выполнить("д1:0:с д2:1:с чт:0:с0")
    отметить(not согласны["конфликты"] and согласны["шина"].get("факт") == 16.0 and согласны["такт2"]["чт"]["top1"] == "1", "согласные датчики: понятие на шине, читатель его использует")
    отметить("факт" in спор["конфликты"] and "факт" not in спор["шина"] and спор["такт2"]["чт"]["top1"] == "0", "датчики спорят: понятие не записано, читатель остаётся при своём ответе")
    отметить(спор["такт2"]["чт"]["top1"] == обратный["такт2"]["чт"]["top1"] and "факт" in обратный["конфликты"], "тот же спор с обменом датчиков: тот же ответ (прежде решал порядок записи)")
    отметить(спор["финал"]["_причинная_цепочка"]["статус"] == "есть конфликты" and спор["финал"]["_причинная_цепочка"]["конфликты"] == ["факт"], "ядро видит конфликт в причинной цепочке")

    # ------------------------------------------------------------------ без предела влияния результат тот же, что у замороженного «до»
    import общее as О
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    настоящая = Матплата(язык, О.ARCH)
    старая = замороженный("матплата").Матплата(язык, О.ARCH)
    for мп in (настоящая, старая):
        for имя in ("здоровье", "право", "ответы_мейлру"):
            ok, msg = мп.подключить(os.path.join(О.V8, "блоки", "основная_внешние.з1", имя))
            assert ok, msg
    новый = Процессор(настоящая, ядро=ЯдроПричинности(ПРОЕКТ), tau_conf=1.0)
    прежний = замороженный("процессор").Процессор(старая, ядро=замороженный("ядро").ЯдроПричинности(ПРОЕКТ), tau_conf=1.0)
    вопросы = [json.loads(l)["вопрос"] for l in open(os.path.join(ПРОЕКТ, "бенчмарки", "bench", "bench.jsonl"), encoding="utf-8") if l.strip()][:120]
    расхождений = 0
    for q in вопросы:
        a, b = новый.выполнить(q), прежний.выполнить(q)
        for имя in a["такт2"]:
            расхождений += a["такт2"][имя]["top1"] != b["такт2"][имя]["top1"] or any(abs(a["такт2"][имя]["счёты"][k] - b["такт2"][имя]["счёты"][k]) > 1e-12 for k in a["такт2"][имя]["счёты"])
        расхождений += a["шина"] != b["шина"]
    отметить(расхождений == 0, "без предела влияния и без конфликтов результат настоящих блоков тот же, что у замороженного «до» (120 вопросов, счёты и шина)")

    # ------------------------------------------------------------------ предел влияния: инвариант
    мир = И.Мир(10, 9, зерно=2)
    мир.обучить(вопросов=1500, шагов=150)
    игр = И.собрать_матплату(мир, Матплата)
    rng = np.random.default_rng(5)
    тесты = [" ".join(мир.вопрос(rng)[0]) for _ in range(80)]
    нарушений, обрезано, всего = 0, 0, 0
    для_предела = 0.5
    предельный = Процессор(игр, ядро=ЯдроПричинности(None), tau_conf=1.0, предел_влияния=для_предела)
    безпредела = Процессор(игр, ядро=ЯдроПричинности(None), tau_conf=1.0)
    разница_без_предела = 0
    for q in тесты:
        с_пределом, без = предельный.выполнить(q), безпредела.выполнить(q)
        for имя, о2 in с_пределом["такт2"].items():
            о1 = с_пределом["такт1"][имя]
            L = для_предела * max(о1["margin"], 1.0)
            сдвиг = max(abs(о2["счёты"][a] - о1["счёты"][a]) for a in о2["счёты"])
            нарушений += сдвиг > L + 1e-9
            обрезано += bool(о2.get("обрезано"))
            всего += 1
            разница_без_предела += без["такт2"][имя].get("сдвиг_шины", 0.0) > L + 1e-9
    отметить(нарушений == 0, "с пределом влияния %.1f сдвиг счёта на такте 2 не выходит за предел × max(отрыв такта 1, tau) (блок-вопросов: %d)" % (для_предела, всего))
    отметить(обрезано == разница_без_предела and обрезано > 0, "обрезается ровно то, что без предела вышло бы за границу (%d случаев): предел реально работает и не трогает остальное" % обрезано)

    # ------------------------------------------------------------------ изоляция такта 1 в мире из 10 блоков
    искажений = 0
    for q in тесты:
        res = безпредела.выполнить(q)
        токены = игр.язык.перевести(q)["токены"]
        for имя, б in игр.блоки.items():
            соло = б.arch.проход2(б.obj, токены, {})
            искажений += max(соло, key=соло.get) != res["такт1"][имя]["top1"]
    отметить(искажений == 0, "Lego-индекс игрушечного мира из 10 блоков равен 0 после всех изменений (%d вопросов)" % len(тесты))

    # ------------------------------------------------------------------ линтер: проверка вставки
    пр_реальный = Процессор(Матплата(язык, О.ARCH), ядро=ЯдроПричинности(ПРОЕКТ), tau_conf=1.0)
    for имя in ("здоровье", "право"):
        ok, msg = пр_реальный.матплата.подключить(os.path.join(О.V8, "блоки", "основная_внешние.з1", имя))
        assert ok, msg
    р = Л.проверить_вставку(пр_реальный, os.path.join(О.V8, "блоки", "основная_внешние.з1", "ответы_мейлру"), вопросы)
    отметить(р["статус"] == "УСПЕХ" and р["изменилось_ответов_соседей"] == 0 and р["снятие_возвращает_как_было"], "линтер: настоящий блок «ответы_мейлру» вставляется без изменений ответов соседей (%d из %d)" % (р["изменилось_ответов_соседей"], р["всего_ответов_соседей"]))
    отметить(set(пр_реальный.матплата.блоки) == {"здоровье", "право"}, "после проверки вставки блок снят: матплата как была")

    # игрушечный мир: соседи читают «б00:0»; подделка пишет это понятие при любом ответе
    мир2 = И.Мир(6, 5, зерно=4)
    мир2.обучить(вопросов=1500, шагов=150)
    м2 = И.собрать_матплату(мир2, Матплата)
    пр2 = Процессор(м2, ядро=ЯдроПричинности(None), tau_conf=1.0)
    rng2 = np.random.default_rng(8)
    вопросы2 = [" ".join(мир2.вопрос(rng2)[0]) + " подделка:0:с безобидный:0:с" for _ in range(200)]
    каталог = os.path.join(os.path.dirname(os.path.abspath(__file__)), "каскады")
    import tempfile
    временный = tempfile.mkdtemp(prefix="вставка_")
    читатели_б00 = [n for n in м2.блоки if any(k.startswith(мир2.имена[0] + ":") for k in м2.блоки[n].читает)]

    def блок_вставки(имя, проекции):
        # два ответа: у блока с одним ответом отрыв всегда 0, он никогда не «уверен» и ничего не пишет на шину
        м_, _ = И.новая_матплата(Матплата)
        И.записать_блок(м_, временный, имя, ["0", "1"], [], проекции, np.zeros((0, 2)))
        return os.path.join(временный, имя)
    подделка = блок_вставки("подделка", {"0": {"%s:%d" % (мир2.имена[0], y): 16.0 for y in range(3)}, "1": {}})
    безобидный = блок_вставки("безобидный", {"0": {"никто_не_читает": 16.0}, "1": {}})
    р_подделка = Л.проверить_вставку(пр2, подделка, вопросы2, эпсилон=0.01)
    р_безобидный = Л.проверить_вставку(пр2, безобидный, вопросы2, эпсилон=0.01)
    р_мягкий = Л.проверить_вставку(пр2, подделка, вопросы2, эпсилон=0.5)
    отметить(bool(читатели_б00) and р_подделка["статус"] == "ОШИБКА" and р_подделка["доля_изменений"] > 0.01, "линтер: блок, подделывающий чужие понятия шины, не проходит (изменено %.1f %% ответов соседей при допустимых 1 %%)" % (100 * р_подделка["доля_изменений"]))
    отметить(р_безобидный["статус"] == "УСПЕХ" and р_безобидный["доля_изменений"] == 0.0, "линтер: безобидный блок (его понятия никто не читает) проходит с нулём изменений")
    отметить(р_мягкий["статус"] == "УСПЕХ" and р_мягкий["доля_изменений"] == р_подделка["доля_изменений"], "порог ε работает в обе стороны: тот же блок проходит при ε=50 % (доля изменений та же)")
    отметить(р_подделка["снятие_возвращает_как_было"] and р_подделка["такт1_соседей_изменилось"] == 0, "после снятия подделки ответы соседей вернулись; такт 1 соседей не менялся (изоляция сохранена)")

    # ------------------------------------------------------------------ архитектура без предметной области
    исходники = {имя: open(os.path.join(КОРЕНЬ_NNL, имя), encoding="utf-8").read() for имя in ("процессор.py", "матплата.py")}
    запрещено = re.compile(r"if\s+(?:имя|block|блок\w*)\s*==|здоровье|право\b|военкомат|статья|болезн", re.I)
    код_без_комментариев = {k: "\n".join(l for l in v.splitlines() if not l.strip().startswith(("#", '"""')) and "if имя ==" not in l) for k, v in исходники.items()}
    нашли = {k: sorted(set(m.group(0) for m in запрещено.finditer(v))) for k, v in код_без_комментариев.items()}
    отметить(not any(нашли.values()), "в процессоре и матплате нет имён блоков и предметной области %s" % {k: v for k, v in нашли.items() if v})

    print("\nпройдено %d из %d" % (прошло, проверок))
    sys.exit(0 if прошло == проверок else 1)


if __name__ == "__main__":
    main()
