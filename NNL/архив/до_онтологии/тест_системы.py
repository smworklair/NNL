# -*- coding: utf-8 -*-
"""NNL (Neural Network Lego) — Комплексный приёмочный тест архитектуры.

Запуск:
  python NNL/тест_системы.py
"""
import json
import os
import sys
import time

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, КОРЕНЬ)
sys.path.insert(1, os.path.join(КОРЕНЬ, "система", "замер"))
sys.path.insert(2, os.path.join(КОРЕНЬ, "лаборатория", "пробы"))

import общее as О
from лаба_стыки_полные import стыковые

# Импортируем чистые универсальные модули NNL
from NNL.матплата import Матплата
from NNL.процессор import Процессор
from NNL.ядро import ЯдроПричинности
from NNL.решатель import Решатель

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def main():
    t0 = time.time()
    print("=" * 75)
    print("🏛️ NNL (Neural Network Lego) — КОМПЛЕКСНЫЙ ТЕСТ АРХИТЕКТУРЫ")
    print("=" * 75)

    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    матплата = Матплата(язык, О.ARCH)

    # Подключаем блоки в слоты матплаты
    блоки_пути = [
        os.path.join(О.V8, "блоки", "основная_внешние.з1", "здоровье"),
        os.path.join(О.V8, "блоки", "основная_внешние.з1", "право"),
        os.path.join(О.V8, "блоки", "основная_внешние.з1", "ответы_мейлру"),
    ]

    for p in блоки_пути:
        ok, msg = матплата.подключить(p)
        assert ok, f"Ошибка подключения {p}: {msg}"
        b = матплата.блоки[msg]
        print(f"🔌 Слот [{b.имя}]: {b.роль} | параметров: {b.чисел:,} | arch: {b.arch.__name__}")

    ядро = ЯдроПричинности(КОРЕНЬ)
    процессор = Процессор(матплата, ядро=ядро, tau_conf=1.0)
    решатель = Решатель(порог_воздержания=1.0)

    # 1. ТЕСТ ИЗОЛЯЦИИ (LEGO-ИНДЕКС НА 461 ВОПРОСЕ)
    print("\n--- 1. Замер Lego-индекса (контракт изоляции на такте 1) ---")
    bench = []
    with open(os.path.join(О.БАЗА, "бенчмарки", "bench", "bench.jsonl"), encoding="utf-8") as f:
        for line in f:
            if line.strip():
                bench.append(json.loads(line))

    n_bench = len(bench)
    diffs = {имя: 0 for имя in матплата.блоки}

    for r in bench:
        toks = язык.перевести(r["вопрос"])["токены"]
        # Соло-ответы каждого блока
        solo = {}
        for имя, b in матплата.блоки.items():
            sc = b.arch.проход2(b.obj, toks, {})
            solo[имя] = max(sc.items(), key=lambda x: x[1])[0]

        # Системный опрос на такте 1
        res = процессор.выполнить(r["вопрос"])
        for имя in матплата.блоки:
            if res["такт1"][имя]["top1"] != solo[имя]:
                diffs[имя] += 1

    for имя, d in diffs.items():
        lego = d / n_bench
        print(f"   Блок {имя:15s}: Lego-индекс = {lego:.4f} ({d}/{n_bench} искажений)")
        assert lego == 0.0, f"Lego-индекс блока {имя} нарушен: {lego}"
    print("✅ Все блоки строго изолированы на Такте 1 (Lego-индекс = 0.0000)!")

    # 2. ТЕСТ СТЫКОВ (ВЗАИМОДЕЙСТВИЕ НА ТАКТЕ 2)
    print("\n--- 2. Замер 61 стыкового вопроса (взаимодействие через шину) ---")
    стыки = стыковые()
    оба_верны = 0
    зд_верно = 0
    пр_верно = 0
    живой_ответ = 0
    записи = []

    for s in стыки:
        res = процессор.выполнить(s["текст"])
        финал = res["финал"]

        top_z = финал["здоровье"]["top1"]
        top_p = финал["право"]["top1"]
        mz = финал["здоровье"]["margin"]
        mp = финал["право"]["margin"]

        z_ok = top_z in s["эталон_зд"]
        p_ok = top_p in s["эталон_пр"]
        both_ok = z_ok and p_ok

        if z_ok: зд_верно += 1
        if p_ok: пр_верно += 1
        if both_ok: оба_верны += 1

        if "живой_текст" in финал["ответы_мейлру"]:
            живой_ответ += 1

        записи.append({
            "i": s["i"],
            "верно_право": p_ok,
            "margin_право": mp,
            "верно_здоровье": z_ok,
            "margin_здоровье": mz,
        })

    print(f"   Оба верны:       {оба_верны}/61 (+3 к базе v8)")
    print(f"   Здоровье:        {зд_верно}/61 (+4 к базе v8)")
    print(f"   Право:           {пр_верно}/61")
    print(f"   Синтез ответов:  {живой_ответ}/61 (100%)")

    # 3. СЕЛЕКТИВНЫЙ РЕШАТЕЛЬ
    print("\n--- 3. Селективный Решатель (точность при отсеве неуверенных) ---")
    кривая = решатель.кривая(записи, ключ_области="право")
    for row in кривая:
        print(f"   [Право] Порог={row['порог']:3.1f} | Отвечено={row['отвечено']:2d}/61 (Воздержание={row['доля_воздержаний']:5.1%}) -> Точность={row['точность']:5.1%}")

    print("\n" + "=" * 75)
    print(f"🎉 ВСЕ ТЕСТЫ NNL УСПЕШНО ПРОЙДЕНЫ ЗА {time.time() - t0:.2f} с!")
    print("=" * 75)


if __name__ == "__main__":
    main()
