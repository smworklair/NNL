# -*- coding: utf-8 -*-
"""Основной скрипт эксперимента NNL:
Сравнение режима «Ядро ведёт» и режима «Агент-детектив» на тестовой выборке (12 синтетических кейсов).
Выборка разделена строго по хешу sha256(id) % 2 == 1 (только тестовая половина).
Все метрики и таблицы рассчитываются программно при запуске.
Сохраняет промежуточный прогресс после каждого кейса.
"""
import json
import math
import os
import sys
import time

sys.stdout.reconfigure(encoding="utf-8")
from данные_кейсы import получить_выборку
from режим_ядро import РежимЯдро
from режим_агент import РежимАгент
from валидатор import ВалидаторЯдра

ПАПКА = os.path.dirname(os.path.abspath(__file__))
РЕЗУЛЬТАТЫ_ФАЙЛ = os.path.join(ПАПКА, "результаты_эксперимента.json")


def выч_доверительный_интервал(значения, alpha=1.96):
    """Вычисляет среднее, стандартную ошибку и 95% доверительный интервал."""
    if not значения:
        return 0.0, 0.0, (0.0, 0.0)
    n = len(значения)
    ср = sum(значения) / n
    if n < 2:
        return round(ср, 2), 0.0, (round(ср, 2), round(ср, 2))
    дисп = sum((x - ср) ** 2 for x in значения) / (n - 1)
    se = math.sqrt(дисп / n)
    ci = (round(ср - alpha * se, 2), round(ср + alpha * se, 2))
    return round(ср, 2), round(se, 2), ci


def запустить_эксперимент():
    тестовые_кейсы = получить_выборку(только_тест=True)
    print("=" * 80)
    print("ЭКСПЕРИМЕНТ NNL: АГЕНТ-ДЕТЕКТИВ ПРОТИВ ЯДРО-ВЕДЁТ")
    print(f"Размер тестовой выборки: n = {len(тестовые_кейсы)} (строго sha256(id) % 2 == 1)")
    print(f"  Кейсов с подтверждением врача: {sum(1 for c in тестовые_кейсы if c['врач_подтвердил'])}")
    print(f"  Кейсов без подтверждения врача: {sum(1 for c in тестовые_кейсы if not c['врач_подтвердил'])}")
    print("=" * 80)

    валидатор = ВалидаторЯдра()
    раннер_ядро = РежимЯдро()
    раннер_агент = РежимАгент()

    результаты_ядро = []
    результаты_агент = []

    for idx, кейс in enumerate(тестовые_кейсы, 1):
        cid = кейс["id"]
        ст = кейс["истинная_статья"]
        вр = кейс["врач_подтвердил"]
        print(f"\n[{idx}/{len(тестовые_кейсы)}] Обработка кейса {cid} (ст.{ст}, врач={вр})...")

        # --- 1. Прогон ЯДРО ВЕДЁТ ---
        res_core = раннер_ядро.выполнить(кейс)
        passed_core, reason_core, det_core = валидатор.валидировать(
            res_core["текст_ответа"], res_core["статьи"], кейс
        )
        stat_c = res_core["статистика"]
        stat_c["принят_ядром"] = passed_core
        stat_c["причина_отклонения"] = reason_core
        stat_c["детали"] = det_core
        stat_c["case_id"] = cid
        stat_c["врач_подтвердил"] = вр
        stat_c["истинная_статья"] = ст
        stat_c["токены_всего"] = stat_c["токены_вход"] + stat_c["токены_выход"]
        результаты_ядро.append(stat_c)
        print(f"  [ЯДРО]  Принят: {passed_core} | Вызовов: {stat_c['вызовов']} | Токенов: {stat_c['токены_всего']} | Перегенераций: {stat_c['перегенераций']} | {stat_c['мс']} мс")
        if not passed_core:
            print(f"          Причина брака: {reason_core}")

        # --- 2. Прогон АГЕНТ-ДЕТЕКТИВ ---
        res_agent = раннер_агент.выполнить(кейс)
        passed_agent, reason_agent, det_agent = валидатор.валидировать(
            res_agent["текст_ответа"], res_agent["статьи"], кейс
        )
        stat_a = res_agent["статистика"]
        stat_a["принят_ядром"] = passed_agent
        stat_a["причина_отклонения"] = reason_agent
        stat_a["детали"] = det_agent
        stat_a["case_id"] = cid
        stat_a["врач_подтвердил"] = вр
        stat_a["истинная_статья"] = ст
        stat_a["токены_всего"] = stat_a["токены_вход"] + stat_a["токены_выход"]
        результаты_агент.append(stat_a)
        print(f"  [АГЕНТ] Принят: {passed_agent} | 1-я попытка безопасна: {stat_a['безопасен_с_первой_попытки']} | Вызовов: {stat_a['вызовов']} | Токенов: {stat_a['токены_всего']} | Попыток: {stat_a['попыток']} | {stat_a['мс']} мс")
        if stat_a["ошибки_валидации"]:
            print(f"          Ошибки на этапах: {stat_a['ошибки_валидации']}")

        # Сохранение промежуточных результатов
        промежуточно = {
            "завершено_кейсов": idx,
            "результаты_ядро": результаты_ядро,
            "результаты_агент": результаты_агент,
        }
        with open(РЕЗУЛЬТАТЫ_ФАЙЛ, "w", encoding="utf-8") as f:
            json.dump(промежуточно, f, ensure_ascii=False, indent=2)

    # --- СВОДНЫЙ АНАЛИЗ И СТАТИСТИКА ПОСЛЕ ВСЕХ КЕЙСОВ ---
    n = len(тестовые_кейсы)

    # 1. Принятые безопасные ответы
    принято_ядро = sum(1 for r in результаты_ядро if r["принят_ядром"])
    принято_агент = sum(1 for r in результаты_агент if r["принят_ядром"])

    # 2. Безопасность с 1-й попытки
    безопасен_1_попытка_ядро = sum(1 for r in результаты_ядро if r["перегенераций"] == 0 and r["принят_ядром"])
    безопасен_1_попытка_агент = sum(1 for r in результаты_агент if r["безопасен_с_первой_попытки"])

    # 3. Полные затраты ресурсов
    вызовы_ядро = [r["вызовов"] for r in результаты_ядро]
    вызовы_агент = [r["вызовов"] for r in результаты_агент]

    токены_ядро = [r["токены_всего"] for r in результаты_ядро]
    токены_агент = [r["токены_всего"] for r in результаты_агент]

    время_ядро = [r["мс"] for r in результаты_ядро]
    время_агент = [r["мс"] for r in результаты_агент]

    цена_вызовов_ядро = round(sum(вызовы_ядро) / max(1, принято_ядро), 2)
    цена_вызовов_агент = round(sum(вызовы_агент) / max(1, принято_агент), 2)

    цена_токенов_ядро = round(sum(токены_ядро) / max(1, принято_ядро), 1)
    цена_токенов_агент = round(sum(токены_агент) / max(1, принято_агент), 1)

    цена_времени_ядро = round(sum(время_ядро) / max(1, принято_ядро), 1)
    цена_времени_агент = round(sum(время_агент) / max(1, принято_агент), 1)

    ср_вызовов_я, se_вызовов_я, ci_вызовов_я = выч_доверительный_интервал(вызовы_ядро)
    ср_вызовов_а, se_вызовов_а, ci_вызовов_а = выч_доверительный_интервал(вызовы_агент)

    ср_токенов_я, se_токенов_я, ci_токенов_я = выч_доверительный_интервал(токены_ядро)
    ср_токенов_а, se_токенов_а, ci_токенов_а = выч_доверительный_интервал(токены_агент)

    ratio_вызовы = round(цена_вызовов_агент / max(0.01, цена_вызовов_ядро), 2)
    ratio_токены = round(цена_токенов_агент / max(0.01, цена_токенов_ядро), 2)

    нарушения_агента_всего = sum(len(r["ошибки_валидации"]) for r in результаты_агент)
    нарушения_категории_агент = sum(1 for r in результаты_агент if any("Врач не подтвердил" in s for s in r["ошибки_валидации"]))
    нарушения_чисел_агент = sum(1 for r in результаты_агент if any("ОХРАНЫ ЧИСЕЛ" in s for s in r["ошибки_валидации"]))

    сводка = {
        "n_тест": n,
        "ядро": {
            "принято_всего": принято_ядро,
            "доля_принятых": round(принято_ядро / n, 3),
            "безопасен_с_первой_попытки": безопасен_1_попытка_ядро,
            "доля_безопасных_первая_попытка": round(безопасен_1_попытка_ядро / n, 3),
            "цена_принятого_ответа_вызовы": цена_вызовов_ядро,
            "цена_принятого_ответа_токены": цена_токенов_ядро,
            "цена_принятого_ответа_мс": цена_времени_ядро,
            "ср_вызовов": ср_вызовов_я,
            "se_вызовов": se_вызовов_я,
            "ci_вызовов_95": ci_вызовов_я,
            "ср_токенов": ср_токенов_я,
            "se_токенов": se_токенов_я,
            "ci_токенов_95": ci_токенов_я,
            "перегенераций_всего": sum(r["перегенераций"] for r in результаты_ядро),
        },
        "агент": {
            "принято_всего": принято_агент,
            "доля_принятых": round(принято_агент / n, 3),
            "безопасен_с_первой_попытки": безопасен_1_попытка_агент,
            "доля_безопасных_первая_попытка": round(безопасен_1_попытка_агент / n, 3),
            "цена_принятого_ответа_вызовы": цена_вызовов_агент,
            "цена_принятого_ответа_токены": цена_токенов_агент,
            "цена_принятого_ответа_мс": цена_времени_агент,
            "ср_вызовов": ср_вызовов_а,
            "se_вызовов": se_вызовов_а,
            "ci_вызовов_95": ci_вызовов_а,
            "ср_токенов": ср_токенов_а,
            "se_токенов": se_токенов_а,
            "ci_токенов_95": ci_токенов_а,
            "шагов_инструментов_всего": sum(r["шагов_инструментов"] for r in результаты_агент),
            "нарушений_безопасности_всего": нарушения_агента_всего,
            "кейсов_с_нарушением_категории": нарушения_категории_агент,
            "кейсов_с_нарушением_чисел": нарушения_чисел_агент,
        },
        "сравнение": {
            "ratio_цена_вызовов (агент / ядро)": ratio_вызовы,
            "ratio_цена_токенов (агент / ядро)": ratio_токены,
        },
        "детали_кейсов_ядро": результаты_ядро,
        "детали_кейсов_агент": результаты_агент,
    }

    with open(РЕЗУЛЬТАТЫ_ФАЙЛ, "w", encoding="utf-8") as f:
        json.dump(сводка, f, ensure_ascii=False, indent=2)

    print("\n" + "=" * 80)
    print("ИТОГОВЫЕ РЕЗУЛЬТАТЫ ЭКСПЕРИМЕНТА НА ТЕСТОВОЙ ВЫБОРКЕ (n = %d):" % n)
    print("=" * 80)
    print(f"{'Метрика':<45} | {'Режим Ядро':<15} | {'Агент-детектив':<15} | {'Отношение (А/Я)':<15}")
    print("-" * 95)
    print(f"{'Успешно принятых безопасных ответов':<45} | {принято_ядро}/{n} ({принято_ядро/n*100:.1f}%) | {принято_агент}/{n} ({принято_агент/n*100:.1f}%) | -")
    print(f"{'Безопасных ответов с 1-й попытки (без брака)':<45} | {безопасен_1_попытка_ядро}/{n} ({безопасен_1_попытка_ядро/n*100:.1f}%) | {безопасен_1_попытка_агент}/{n} ({безопасен_1_попытка_агент/n*100:.1f}%) | -")
    print(f"{'Цена принятого ответа: вызовов LLM':<45} | {цена_вызовов_ядро:<15} | {цена_вызовов_агент:<15} | x{ratio_вызовы}")
    print(f"{'Цена принятого ответа: токенов всего':<45} | {цена_токенов_ядро:<15} | {цена_токенов_агент:<15} | x{ratio_токены}")
    print(f"{'Среднее число вызовов на кейс (95% CI)':<45} | {ср_вызовов_я} [{ci_вызовов_я[0]}; {ci_вызовов_я[1]}] | {ср_вызовов_а} [{ci_вызовов_а[0]}; {ci_вызовов_а[1]}] | -")
    print(f"{'Среднее число токенов на кейс (95% CI)':<45} | {ср_токенов_я} [{ci_токенов_я[0]}; {ci_токенов_я[1]}] | {ср_токенов_а} [{ci_токенов_а[0]}; {ci_токенов_а[1]}] | -")
    print(f"{'Инструментов вызвано агентом суммарно':<45} | {'—':<15} | {sum(r['шагов_инструментов'] for r in результаты_агент):<15} | -")
    print(f"{'Нарушений безопасности (категория без врача)':<45} | {'0':<15} | {нарушения_категории_агент:<15} | -")
    print(f"{'Нарушений охраны чисел (галлюцинации порогов)':<45} | {'0':<15} | {нарушения_чисел_агент:<15} | -")
    print("=" * 80)

    return сводка


if __name__ == "__main__":
    запустить_эксперимент()
