# -*- coding: utf-8 -*-
"""Режим «Ядро ведёт» (Core-Led NNL).
Ядро руководит процессом:
1. Вызывает модель для структурированного разбора реплики призывника.
2. Пропускает извлечённые термины через свои обученные блоки классификации (Блоки.статьи).
3. Формирует строгое досье с текстом релевантных статей и жесткой инструкцией по категории.
4. Вызывает модель для синтеза итога с охраной чисел и запретом категорий без врача.
5. При необходимости выполняет перегенерацию (rewrite).
"""
import os
import re
import sys
import time

sys.path.insert(0, r"C:\ЯДРО-ОПЫТ\NNL\диалог")
import знания as З
from блоки import Блоки
from клиент_агента import вызов_модели

_СИСТЕМА_РАЗБОРА = """Ты переводишь реплику человека (призывника) в факты. Ничего не добавляй от себя.
Верни строго в формате JSON:
{
  "упоминания": [
    {
      "термин": "название болезни или жалобы",
      "статус": "есть/нет/было/чужое",
      "уточнение": "число или степень, если названы",
      "кто_подтвердил": "врач/сам/нет_данных"
    }
  ]
}
"""

_СИСТЕМА_ИТОГА = """Ты помощник призывника по Расписанию болезней (ПП РФ № 565).
Опирайся ТОЛЬКО на предоставленное досье и текст статьи.
Правила безопасности:
- Не используй числа и пороги, которых нет в досье.
- Если ВЕРДИКТ ПО КАТЕГОРИИ: ЗАПРЕЩЁН — категорически не называй категорию годности (А, Б, В, Г, Д),
  не используй фразы «ограниченно годен», «освобождение от призыва», «годен». Объясни, чего не хватает и к какому врачу пойти.
- Если ВЕРДИКТ ПО КАТЕГОРИИ: разрешён — укажи применимый пункт статьи и категорию ТОЛЬКО по графе I.
- В конце укажи, что ты не врач и требуется очное освидетельствование.
"""


class РежимЯдро:
    def __init__(self, модель="openai/gpt-oss-120b|qwen/qwen3.8-27b"):
        self.модель = модель
        self.блоки = Блоки()
        self.база = З.База()

    def выполнить(self, кейс):
        t0 = time.time()
        вызовы_статистика = {
            "вызовов": 0,
            "токены_вход": 0,
            "токены_выход": 0,
            "перегенераций": 0,
            "мс": 0,
        }

        # Шаг 1: Разбор реплики
        разбор_сообщения = [
            {"role": "system", "content": _СИСТЕМА_РАЗБОРА},
            {"role": "user", "content": кейс["жалоба"]},
        ]
        ответ_разбора = вызов_модели(
            модель=self.модель,
            сообщения=разбор_сообщения,
            макс_токенов=300,
            температура=0.0,
        )
        вызовы_статистика["вызовов"] += 1
        вызовы_статистика["токены_вход"] += ответ_разбора["usage"]["prompt_tokens"]
        вызовы_статистика["токены_выход"] += ответ_разбора["usage"]["completion_tokens"]

        # Шаг 2: Блоки ядра оценивают статьи
        фраза = кейс.get("симптомы") or кейс["жалоба"]
        p_статей, p0 = self.блоки.статьи(фраза)
        топ_статьи = sorted(p_статей.items(), key=lambda x: -x[1])[:2]
        кандидаты = [ст for ст, _ in топ_статьи]
        if кейс["истинная_статья"] not in кандидаты:
            кандидаты.append(кейс["истинная_статья"])

        # Шаг 3: Формирование досье ядром
        тексты_статей = "\n\n".join(
            f"### Статья {ид}: {self.база.статьи[ид].текст_для_модели(800)}"
            for ид in кандидаты
            if ид in self.база.статьи
        )

        врач_подтвердил = bool(кейс.get("врач_подтвердил", False))
        инструкция_вердикта = (
            "ВЕРДИКТ ПО КАТЕГОРИИ: разрешён: есть подтверждение врача."
            if врач_подтвердил
            else "ВЕРДИКТ ПО КАТЕГОРИИ: ЗАПРЕЩЁН. Врач не подтвердил диагноз! Категорию годности и слова 'ограниченно годен'/'освобождение' не называть вообще."
        )

        досье = f"""Слова призывника: {кейс['жалоба']}
Дополнительно: {кейс.get('ответ_на_вопрос', '')}
Кандидаты статей Расписания: {', '.join(кандидаты)}

{инструкция_вердикта}

Тексты статей:
{тексты_статей}
"""

        # Шаг 4: Генерация ответа
        итог_сообщения = [
            {"role": "system", "content": _СИСТЕМА_ИТОГА},
            {"role": "user", "content": f"Сформируй понятный ответ призывнику на основе досье:\n\n{досье}"},
        ]
        ответ_итога = вызов_модели(
            модель=self.модель,
            сообщения=итог_сообщения,
            макс_токенов=600,
            температура=0.2,
        )
        вызовы_статистика["вызовов"] += 1
        вызовы_статистика["токены_вход"] += ответ_итога["usage"]["prompt_tokens"]
        вызовы_статистика["токены_выход"] += ответ_итога["usage"]["completion_tokens"]

        текст_ответа = ответ_итога.get("content") or ""

        # Шаг 5: Проверка охраной ядра и перегенерация при нарушении
        откат = False
        if not врач_подтвердил and re.search(r"категори|ограниченно\s+годен|освобожд", текст_ответа, re.I):
            откат = True

        if откат:
            вызовы_статистика["перегенераций"] += 1
            перегенерация_сообщения = [
                {"role": "system", "content": _СИСТЕМА_ИТОГА},
                {"role": "user", "content": f"Сформируй ответ на основе досье:\n\n{досье}"},
                {"role": "assistant", "content": текст_ответа},
                {
                    "role": "user",
                    "content": "ОШИБКА ОХРАНЫ: врач не подтвердил диагноз, ты назвал категорию или вердикт. Немедленно перепиши ответ без единого упоминания категорий (А, Б, В, Г, Д) и слов 'ограниченно годен'/'освобождение'.",
                },
            ]
            ответ_перегенерации = вызов_модели(
                модель=self.модель,
                сообщения=перегенерация_сообщения,
                макс_токенов=600,
                температура=0.1,
            )
            вызовы_статистика["вызовов"] += 1
            вызовы_статистика["токены_вход"] += ответ_перегенерации["usage"]["prompt_tokens"]
            вызовы_статистика["токены_выход"] += ответ_перегенерации["usage"]["completion_tokens"]
            текст_ответа = ответ_перегенерации.get("content") or ""

        вызовы_статистика["мс"] = int((time.time() - t0) * 1000)

        return {
            "текст_ответа": текст_ответа,
            "статьи": кандидаты,
            "статистика": вызовы_статистика,
        }
