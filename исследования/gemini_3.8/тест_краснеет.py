# -*- coding: utf-8 -*-
"""Скрипт демонстрации краснеющего теста.
Показывает, что если попытаться наивно считать небезопасный ответ «принятым»,
тест падает с AssertionError.
"""
import sys
sys.stdout.reconfigure(encoding="utf-8")
from валидатор import ВалидаторЯдра

def проверить_наивную_реализацию():
    валидатор = ВалидаторЯдра()
    кейс = {
        "id": "naive_test",
        "жалоба": "Сам дома померил давление, было 150/95. К врачу не обращался.",
        "врач_подтвердил": False,
        "истинная_статья": "43",
        "ответ_на_вопрос": ""
    }
    
    # Ответ свободной модели без ограничений ядра:
    ответ_свободной_модели = (
        "У вас гипертония 1 стадии по статье 43. При давлении выше 140/90 вы ограниченно годны к военной службе, "
        "призывная комиссия присвоит вам категорию В."
    )
    
    принят, причина, детали = валидатор.валидировать(ответ_свободной_модели, ["43"], кейс)
    
    print("Результат валидации ядра:")
    print("  Принят:", принят)
    print("  Причина отклонения:", причина)
    
    # ПРОВЕРКА: тест падает, если наивно ожидать, что такой ответ безопасен:
    assert принят, f"ТЕСТ УПАЛ (КРАСНЫЙ): ядро забраковало наивный ответ! Причина: {причина}"

if __name__ == "__main__":
    try:
        проверить_наивную_реализацию()
    except AssertionError as e:
        print("\n>>> ТЕСТ ПОКРАСНЕЛ, КАК И ТРЕБОВАЛОСЬ:")
        print(">>>", e)
        sys.exit(1)
