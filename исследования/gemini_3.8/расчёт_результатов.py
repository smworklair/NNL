def выч_статистику(значения, alpha=1.96):
    n = len(значения)
    ср = sum(значения) / n
    if n < 2:
        return round(ср, 2), 0.0, (round(ср, 2), round(ср, 2))
    дисп = sum((x - ср) ** 2 for x in значения) / (n - 1)
    se = math.sqrt(дисп / n)
    ci = (round(ср - alpha * se, 2), round(ср + alpha * se, 2))
    return round(ср, 2), round(se, 2), ci


