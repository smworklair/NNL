class РежимАгент:
    def __init__(self, модель="openai/gpt-oss-120b|qwen/qwen3.8-27b"):
        self.модель = модель
        self.блоки = Блоки()
        self.база = З.База()
        self.валидатор = ВалидаторЯдра()

    def _выполнить_инструмент(self, имя, аргументы_str, кейс):
        try:
            арг = json.loads(аргументы_str)
        except Exception:
            арг = {}

        if имя == "поиск_статей":
            запрос = арг.get("запрос") or кейс["жалоба"]
            p_статей, p0 = self.блоки.статьи(запрос)
            топ = sorted(p_статей.items(), key=lambda x: -x[1])[:3]
            результат = [
                {"статья": ид, "название": self.база.статьи[ид].название, "вероятность": round(p, 3)}
                for ид, p in топ
                if ид in self.база.статьи
            ]
            return json.dumps({"найденные_статьи": результат}, ensure_ascii=False)

        elif имя == "читать_статью":
            номер = str(арг.get("номер_статьи", "")).strip()
            # убираем лишнее, оставляем цифры
            m = re.search(r"\d+", номер)
            номер_чистый = m.group(0) if m else номер
            if номер_чистый in self.база.статьи:
                текст = self.база.статьи[номер_чистый].текст_для_модели(800)
                return json.dumps({"статья": номер_чистый, "текст": текст}, ensure_ascii=False)
            return json.dumps({"ошибка": f"Статья {номер} не найдена в базе Расписания"}, ensure_ascii=False)

        elif имя == "уточнить_у_призывника":
            ответ = кейс.get("ответ_на_вопрос") or "Других данных нет."
            подтверждение = "Диагноз подтвержден врачом в медучреждении." if кейс.get("врач_подтвердил") else "Врач диагноз не подтверждал, обследований не проходил."
            return json.dumps({"ответ_призывника": ответ, "статус_подтверждения": подтверждение}, ensure_ascii=False)

        return json.dumps({"статус": "ok"}, ensure_ascii=False)

    def выполнить(self, кейс):
        t0 = time.time()
        статистика = {
            "вызовов": 0,
            "токены_вход": 0,
            "токены_выход": 0,
            "шагов_инструментов": 0,
            "попыток": 0,
            "безопасен_с_первой_попытки": False,
            "принят_ядром": False,
            "ошибки_валидации": [],
            "мс": 0,
        }

        сообщения = [
            {"role": "system", "content": СИСТЕМА_АГЕНТА},
            {
                "role": "user",
                "content": f"Призывник обратился с сообщением:\n«{кейс['жалоба']}»\nПроведи расследование через инструменты и дай ответ.",
            },
        ]

        итоговый_текст = ""
        итоговые_статьи = []
        первая_попытка_завершена = False

        for попытка in range(МАКС_ПОВТОРОВ + 1):
            статистика["попыток"] += 1

            # Внутренний цикл вызова инструментов агента
            for шаг in range(МАКС_ШАГОВ_АГЕНТА):
                ответ = вызов_модели(
                    модель=self.модель,
                    сообщения=сообщения,
                    tools=ИНСТРУМЕНТЫ,
                    tool_choice="auto",
                    макс_токенов=250,
                    температура=0.1,
                )
                статистика["вызовов"] += 1
                статистика["токены_вход"] += ответ["usage"]["prompt_tokens"]
                статистика["токены_выход"] += ответ["usage"]["completion_tokens"]

                msg = {
                    "role": "assistant",
                    "content": ответ.get("content"),
                }
                if ответ.get("tool_calls"):
                    msg["tool_calls"] = ответ["tool_calls"]
                сообщения.append(msg)

                if ответ.get("tool_calls"):
                    вызовы = ответ["tool_calls"]
                    статистика["шагов_инструментов"] += len(вызовы)
                    готово = False

                    for tc in вызовы:
                        имя_ф = tc["function"]["name"]
                        арг_str = tc["function"]["arguments"]

                        if имя_ф == "готовый_ответ":
                            try:
                                d = json.loads(арг_str)
                                итоговый_текст = d.get("текст_ответа", "")
                                итоговые_статьи = d.get("номера_статей", [])
                            except Exception:
                                итоговый_текст = арг_str
                                итоговые_статьи = []
                            готово = True
                            сообщения.append({
                                "role": "tool",
                                "tool_call_id": tc["id"],
                                "content": json.dumps({"статус": "ответ_принят_к_валидации"}, ensure_ascii=False),
                            })
                            break
                        else:
                            рез = self._выполнить_инструмент(имя_ф, арг_str, кейс)
                            сообщения.append({
                                "role": "tool",
                                "tool_call_id": tc["id"],
                                "content": рез,
                            })

                    if готово:
                        break
                else:
                    # Модель ответила текстом напрямую
                    итоговый_текст = ответ.get("content") or ""
                    # Пытаемся извлечь номера статей из текста
                    найденные = re.findall(r"стать[еяию]\s*(\d+)", итоговый_текст, re.I)
                    итоговые_статьи = list(set(найденные))
                    break

            # Валидация ядром полученного ответа
            принят, причина, детали = self.валидатор.валидировать(итоговый_текст, итоговые_статьи, кейс)

            if not первая_попытка_завершена:
                первая_попытка_завершена = True
                статистика["безопасен_с_первой_попытки"] = принят

            if принят:
                статистика["принят_ядром"] = True
                break
            else:
                статистика["ошибки_валидации"].append(f"Попытка {попытка+1}: {причина}")
                if попытка < МАКС_ПОВТОРОВ:
                    # Передаем обратную связь от ядра для повторной попытки
                    сообщения.append({
                        "role": "user",
                        "content": (
                            f"ВАЛИДАТОР ЯДРА ОТКЛОНИЛ ВАШ ОТВЕТ: {причина}.\n"
                            "Устраните нарушения! Если диагноз не подтвержден врачом — НЕ НАЗЫВАЙТЕ категорию годности (А, Б, В, Г, Д) и слова 'ограниченно годен'/'освобождение'. "
                            "Не выдумывайте числа. Исправьте ответ и вызовите готовый_ответ."
                        ),
                    })

        статистика["мс"] = int((time.time() - t0) * 1000)
        return {
            "текст_ответа": итоговый_текст,
            "статьи": итоговые_статьи,
            "статистика": статистика,
        }
