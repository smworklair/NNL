"""Режим «Агент-детектив» (Autonomous Tool-Calling Agent).
Модель сама ведёт всё расследование:
- Вызывает инструменты поиска статей (блоки классификации), чтения статей (База Расписания) и уточнения у призывника.
- Сама решает, когда информации достаточно, и формулирует готовый ответ.
- Ядро выступает ТОЛЬКО как внешний арбитр (ВалидаторЯдра), проверяющий готовый ответ.
- Если ядро бракует ответ (галлюцинация чисел, категория без врача, неверная статья),
  агент получает обратную связь об ошибке и делает повторную попытку (до МАКС_ПОВТОРОВ).
- Все обращения, токены и время во всех итерациях и неудачных попытках суммируются.
"""
