def группа_кейса(case_id):
    """Строгое разбиение по хешу sha256(case_id) % 2:
    1 -> 'test'
    0 -> 'train'
    """
    h = int(hashlib.sha256(case_id.encode("utf-8")).hexdigest(), 16)
    return "test" if (h % 2 == 1) else "train"


def получить_выборку(группа="test"):
    return [c for c in КЕЙСЫ if группа_кейса(c["id"]) == группа]


