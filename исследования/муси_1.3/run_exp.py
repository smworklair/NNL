# --- промт системы: копия из NNL/диалог/диалог.py (СИСТЕМА_ИТОГА), сверяется с файлом при запуске ---
СИСТЕМА_БАЗА = """Ты помогаешь призывнику понять картину по Расписанию болезней (ПП РФ № 565) и закону. Ты выявляешь правду, а не поддакиваешь:
если по документу человек, скорее всего, годен — скажи это прямо и объясни, какого значения не хватает.
Тебе дано досье: вероятности по статьям от системы, текст статей, слова человека и, возможно, правовая тема.
Напиши итог живым языком, как грамотный знакомый, без шаблонных заголовков и списков-простыней:
- что вероятно, а что только возможно (словами, без выдуманной точности); чего человек не сказал и что ещё стоит проверить;
- какие критерии документа важны именно здесь и по какую сторону границы попадает его случай (числа и пункты только из досье);
- что делать дальше: какие обследования и документы нужны, к какому врачу идти; правовой шаг — только если в досье есть правовая тема;
- в самом конце, одним-двумя предложениями своими словами: ты не врач и не ставишь диагноз, это опора, чтобы прийти к врачу и начать юридическую
  работу подготовленным. Не в начале и не отдельным шаблонным блоком.
Не называй числа и пороги, которых нет в досье или словах человека.
Не упоминай «систему», алгоритм, вероятности и расчёты: говори от себя, как человек. Если человек не назвал диагноза или значения — не выноси вердикт, скажи, чего не хватает.
Категорию называй ТОЛЬКО из поля «КАТЕГОРИЯ ДЛЯ ПРИЗЫВНИКА (графа I)» нужного пункта; графы II и III не упоминай.
Пиши связным русским текстом без повторов слов.
"""

МОДЕЛИ = ["openai/gpt-oss-20b", "openai/gpt-oss-120b"]
ТЕМПЕРАТУРА = 0.5
МАКС_ТОКЕНОВ = 800

def половина(ид):
    return "тест" if (int(hashlib.sha256(ид.encode("utf-8")).hexdigest(), 16) % 2 == 1) else "настройка"

def статья34_текст():
    база = З.База()
    return база.статьи["34"].текст_для_модели(1400)

def досье(кейс, вариант, статья_текст):
    од = кейс["од"]
    ос = кейс["ос"]
    слова_врач = "Окулист после закапывания капель записал: правый глаз минус %s дптр, левый глаз минус %s дптр. Близорукость." % (од, ос)
    извлечено_врач = "Что извлечено: упоминание близорукость (есть, уточнение минус %s / минус %s дптр) [подтверждено врачом: замер в медучреждении с каплями]." % (од, ос)
    слова_сам = "Померил дома сам, к врачу не ходил. Кажется, близорукость: правый глаз минус %s, левый минус %s. Точно не знаю." % (од, ос)
    извлечено_сам = "Что извлечено: упоминание близорукость (есть, уточнение минус %s / минус %s) [со слов человека, врач не подтвердил]." % (од, ос)
    шапка = "Слова человека:\n- %s\n%s\n" % (слова_врач if вариант in ("база", "шум") else слова_сам,
                                            извлечено_врач if вариант in ("база", "шум") else извлечено_сам)
    вер = "Насколько вероятно, что статья относится к человеку: статья 34: очень вероятно."
    статьи = "Тексты статей-кандидатов:\nСтатья 34.\n%s" % статья_текст
    хвост = ""
    if вариант == "шум":
        хвост = "\nДополнительно (не относится к здоровью): вчера автобус опоздал на десять минут, был дождь. Просьба это игнорировать."
    # ВНИМАНИЕ: строку ВЕРДИКТ ПО КАТЕГОРИИ из Сессия._итог сознательно не добавляю (свой вариант досье).
    # Проверяю зависимость вердикта от самих фактов, а не от явной подсказки ядра.
    return шапка + вер + "\n" + статьи + хвост + "\nДай итог: вероятные статьи, критерии, что проверить, что делать дальше."

def проверить_промт():
    путь = r"C:\ЯДРО-ОПЫТ\NNL\диалог\диалог.py"
    with open(путь, encoding="utf-8") as f:
        текст = f.read()
    # грубая проверка: начало промта должно дословно встречаться в файле проекта
    начало = "Ты помогаешь призывнику понять картину по Расписанию болезней"
    assert начало in текст, "промт проекта не найден"
    assert СИСТЕМА_БАЗА.strip().split("\n")[0] in текст, "первая строка промта не совпадает с проектом"

def план(кейсы):
    задачи = []
    for к in кейсы:
        пол = половина(к["id"])
        повторов = 3 if пол == "тест" else 1
        for модель in МОДЕЛИ:
            for вариант in ("база", "без_основания", "шум"):
                for п in range(повторов):
                    задачи.append((к, модель, вариант, п, пол))
    return задачи

def main():
    проверить_промт()
    система = СИСТЕМА_БАЗА + З.ЛЕГЕНДА_КАТЕГОРИЙ
    # сохраняю точный промт для аудита
    with open(os.path.join(ПАПКА, "промт_итога.txt"), "w", encoding="utf-8") as f:
        f.write(система)
    with open(os.path.join(ПАПКА, "кейсы.json"), encoding="utf-8") as f:
        кейсы = json.load(f)
    статья = статья34_текст()
    задачи = план(кейсы)
    print("кейсов: %d, задач: %d (настройка по 1, тест по 3; моделей: %d)" % (len(кейсы), len(задачи), len(МОДЕЛИ)))
    print("бюджет: задач %d <= 600: %s" % (len(задачи), "да" if len(задачи) <= 600 else "НЕТ, СТОП"))
    if len(задачи) > 600:
        print("СТОП: превышен бюджет 600")
        return
    out = os.path.join(ПАПКА, "сырые_ответы.jsonl")
    # дописываю, чтобы повторный запуск не терял уже полученное; повторы с тем же ключом пропускаю
    сделано = set()
    if os.path.exists(out):
        with open(out, encoding="utf-8") as f:
            for line in f:
                try:
                    r = json.loads(line)
                    сделано.add((r["id"], r["модель"], r["вариант"], r["повтор"]))
                except Exception:
                    pass
    print("уже сделано: %d" % len(сделано))
    fw = open(out, "a", encoding="utf-8")
    вызовов = 0
    for (к, модель, вариант, п, пол) in задачи:
        ключ = (к["id"], модель, вариант, п)
        if ключ in сделано:
            continue
        д = досье(к, "база" if вариант in ("база", "шум") else "без_основания", статья)
        # вариант шум = база + мусор (досье() добавляет хвост)
        if вариант == "шум":
            д = досье(к, "шум", статья)
        try:
            r = К.спросить("groq", модель, система, [("user", д)], температура=ТЕМПЕРАТУРА, макс_токенов=МАКС_ТОКЕНОВ, кэш=False, таймаут=120)
            ответ = r.get("текст", "")
            запись = {"id": к["id"], "од": к["од"], "ос": к["ос"], "истина_пункт": к["истина_пункт"],
                      "истина_категория": к["истина_категория"], "половина": пол, "модель": модель,
                      "вариант": вариант, "повтор": п, "досье": д, "ответ": ответ,
                      "токены_вход": r.get("токены_вход"), "токены_выход": r.get("токены_выход"), "мс": r.get("мс")}
            вызовов += 1
        except Exception as e:
            запись = {"id": к["id"], "од": к["од"], "ос": к["ос"], "истина_пункт": к["истина_пункт"],
                      "истина_категория": к["истина_категория"], "половина": пол, "модель": модель,
                      "вариант": вариант, "повтор": п, "досье": д, "ответ": "", "ошибка": str(e)[:200]}
            вызовов += 1
        fw.write(json.dumps(запись, ensure_ascii=False) + "\n")
        fw.flush()
        # пауза чтобы не упереться в лимит 8000 токенов в минуту на модель
        time.sleep(4.0)
        if вызовов % 20 == 0:
            print("выполнено вызовов в этом запуске: %d" % вызовов, flush=True)
    fw.close()
    print("готово. вызовов в этом запуске: %d" % вызовов)
    try:
        print("счёт клиента:", json.dumps(К.итоги(), ensure_ascii=False))
    except Exception as e:
        print("счёт недоступен: %s" % e)

if __name__ == "__main__":
    main()
