# -*- coding: utf-8 -*-
"""Домен-агностические операции причинно-следственной связи.

Модуль не знает про военкомат, статьи или категории годности.
Он оперирует абстрактными понятиями на шине и общими правилами:

  факт из блока A  --(правило)-->  факт для блока B  --(K2)-->  ответ/факт

Базовые операции:
  * распределение_из_шины  — извлечь p(мост=v) из шины.
  * применить_правило      — преобразовать причину в следствие.
  * k2                       — условный прогон: Σ_v p(мост=v)·p(выход|v).
  * softmax                — нормализация счётов в вероятности.
"""
import math


def softmax(счёты):
    """счёты: {ключ: число} -> {ключ: вероятность}."""
    if not счёты:
        return {}
    m = max(счёты.values())
    e = {k: math.exp(v - m) for k, v in счёты.items()}
    z = sum(e.values())
    return {k: v / z for k, v in e.items()}


def распределение_из_шины(шина, мост, значения=None):
    """Извлекает p(мост=v) для v из значений.

    Если значения не переданы, собирает все ключи шины, начинающиеся с '<мост>:'.
    """
    if значения is None:
        значения = []
        for k in шина:
            if k == мост:
                значения.append("")
            elif k.startswith(мост + ":"):
                значения.append(k.split(":", 1)[1])
        значения = sorted(set(значения))
    сырые = {v: шина.get(мост + ":" + str(v), шина.get(мост, 0.0)) for v in значения}
    return softmax(сырые)


def применить_правило(распределение, правило):
    """Преобразует распределение по причине в распределение по следствию.

    правило может быть:
      * dict: {причина: следствие} — детерминированное;
      * dict: {причина: {следствие: вероятность}} — вероятностное;
      * callable: причина -> следствие или причина -> {следствие: вероятность}.
    """
    if распределение is None:
        распределение = {}
    итог = {}
    for v, p_v in распределение.items():
        if p_v == 0:
            continue
        out = None
        if callable(правило):
            out = правило(v)
        elif isinstance(правило, dict):
            out = правило.get(v)
        if out is None:
            continue
        if isinstance(out, dict):
            for u, p_u in out.items():
                итог[u] = итог.get(u, 0.0) + p_v * p_u
        else:
            итог[out] = итог.get(out, 0.0) + p_v
    return softmax(итог) if итог else {}


def k2(распределение_моста, условные_распределения):
    """p(выход) = Σ_v p(мост=v)·p(выход|v).

    распределение_моста: {v: p}
    условные_распределения: {v: {выход: p}}
    """
    итог = {}
    for v, p_v in распределение_моста.items():
        for y, p_y in условные_распределения.get(v, {}).items():
            итог[y] = итог.get(y, 0.0) + p_v * p_y
    return softmax(итог) if итог else {}


class Цепочка:
    """Цепочка причинно-следственных шагов.

    Каждый шаг — dict:
      * мост:        понятие, по которому строится входное распределение;
      * значения:    список возможных значений (опционально);
      * правило:     правило преобразования (опционально);
      * цель_блок:   имя блока, который даёт условное распределение (опционально);
      * выход:       "ответы" или имя понятия, которое пишет цель_блок.

    Если цель_блок отсутствует, шаг только применяет правило к текущему
    распределению. Если цель_блок присутствует, выполняется K2:
      * при выход="ответы" возвращается распределение по ответам целевого блока;
      * иначе возвращается распределение по указанному понятию, которое блок
        пишет в проход1 на модифицированной шине.
    """

    def __init__(self, шаги):
        self.шаги = шаги

    def шаг(self, шаг, текущее, шина, токены, блоки):
        """Выполняет один шаг цепочки. Возвращает (новое_текущее, ответ_или_None)."""
        мост = шаг["мост"]
        значения = шаг.get("значения")
        правило = шаг.get("правило")
        цель_блок = шаг.get("цель_блок")
        выход = шаг.get("выход", "ответы")

        # первый шаг: текущее ещё не задано — берём из шины
        if текущее is None:
            текущее = распределение_из_шины(шина, мост, значения)

        # применяем правило, если есть
        if правило is not None:
            текущее = применить_правило(текущее, правило)

        if цель_блок is None:
            return текущее, None

        блок = блоки[цель_блок]
        условные = {}
        for v in текущее:
            v_шина = {k: val for k, val in шина.items() if not (k == мост or k.startswith(мост + ":"))}
            ключ_v = мост if мост in шина else мост + ":" + str(v)
            v_шина[ключ_v] = шина.get(ключ_v, 0.0)
            if выход == "ответы":
                s2 = блок.arch.проход2(блок.obj, токены, v_шина)
                условные[v] = softmax(s2)
            else:
                c1 = блок.arch.проход1(блок.obj, токены)
                # выход — понятие; извлекаем счёта по его значиям
                счета_выход = {u.split(":", 1)[1]: c1[u] for u in c1 if u.startswith(выход + ":")}
                if not счета_выход:
                    # может быть выход само по себе без суффикса
                    счета_выход = {u: c1[u] for u in c1 if u == выход}
                условные[v] = softmax(счета_выход)
        итог = k2(текущее, условные)
        return итог, (итог if выход == "ответы" else None)

    def __len__(self):
        return len(self.шаги)
