# -*- coding: utf-8 -*-
"""System 1 / System 2 на 61 стыковом вопросе.

Сравниваем:
  * стратегию "набор" (baseline 20/61)
  * стратегию "системы" с System 2 = K2 по области для одной из областей
"""
import json
import os
import sys

sys.dont_write_bytecode = True

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

from лаба_общее import О, Процессор  # noqa: E402

ВЫХОД = os.path.join(О.БАЗА, "v9", "результаты", "лаба_системы_61.json")


def main():
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    ядро, _ = О.система("основная_внешние", 1, язык=язык)
    проц = Процессор(ядро)

    стык = json.load(open(os.path.join(О.БАЗА, "v9", "результаты", "лаба_стыки_полные.json"), encoding="utf-8"))["вопросы"]

    цепь_право = [
        {"мост": "область", "значения": ["здоровье", "право"],
         "правило": {"здоровье": "здоровье", "право": "право"},
         "цель_блок": "право", "выход": "ответы"}
    ]
    цепь_зд = [
        {"мост": "область", "значения": ["здоровье", "право"],
         "правило": {"здоровье": "здоровье", "право": "право"},
         "цель_блок": "здоровье", "выход": "ответы"}
    ]

    метрики = {
        "набор": {"оба_верны": 0, "зд_верно": 0, "пр_верно": 0, "n": 0},
        "системы": {"оба_верны": 0, "зд_верно": 0, "пр_верно": 0, "n": 0},
    }

    for r in стык:
        текст = r["текст"]
        зд_эт = set(r["эталон_зд"])
        пр_эт = set(r["эталон_пр"])

        # набор
        ответ, запись = проц.спросить(текст, "набор")
        набор = set(x["ключ"] for x in запись.get("набор", []))
        зд_дано = set(x for x in набор if x.startswith("ответ:здоровье:"))
        пр_дано = set(x for x in набор if x.startswith("ответ:право:"))
        метрики["набор"]["оба_верны"] += bool(зд_дано & зд_эт) and bool(пр_дано & пр_эт)
        метрики["набор"]["зд_верно"] += bool(зд_дано & зд_эт)
        метрики["набор"]["пр_верно"] += bool(пр_дано & пр_эт)

        # системы per-area: System 2 применяем отдельно к каждой области
        пер = {"здоровье": цепь_зд, "право": цепь_право}
        ключи_системы = []
        for обл, цепь in пер.items():
            ответ, запись = проц.спросить(текст, "системы", цепь=цепь, порог_уверенности=0.9)
            if isinstance(ответ, dict):
                ключи_системы.append("ответ:%s:%s" % (ответ["область"], ответ["id"]))
        зд_дано_с = set(x for x in ключи_системы if x.startswith("ответ:здоровье:"))
        пр_дано_с = set(x for x in ключи_системы if x.startswith("ответ:право:"))
        метрики["системы"]["зд_верно"] += bool(зд_дано_с & зд_эт)
        метрики["системы"]["пр_верно"] += bool(пр_дано_с & пр_эт)
        метрики["системы"]["оба_верны"] += (bool(зд_дано_с & зд_эт) and bool(пр_дано_с & пр_эт))

    n = len(стык)
    for k in метрики:
        метрики[k]["n"] = n

    out = {"метрики": метрики}
    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    json.dump(out, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps(out, ensure_ascii=False, indent=1))
    print("записано:", ВЫХОД)


if __name__ == "__main__":
    main()
