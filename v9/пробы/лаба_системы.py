# -*- coding: utf-8 -*-
"""System 1 / System 2 в процессоре.

System 1 — быстрая эвристика (набор).
System 2 — рассуждение через причинно-следственную цепочку.
"""
import json
import os
import sys

sys.dont_write_bytecode = True

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

from лаба_общее import О, Процессор  # noqa: E402
from игрушечный_мир import ФейкБлок, ФейкЯдро  # noqa: E402


def _абстрактный_мир():
    # Блок A: категория годности
    блокA = ФейкБлок(
        имя="A",
        пишет={"категория": ["A", "B"]},
        читает={},
        ответы=[],
        правило={"категория": lambda t: t.get("к")}
    )

    # Блок B: отсрочка/не отсрочка
    def _ответ_по_шине(токены, шина):
        слова = токены.get("_слова", [])
        запрос_отсрочка = any("отсрочка" in w for w in слова)
        кат_B = шина.get("категория:B", -1e9) > шина.get("категория:A", -1e9)
        if кат_B and запрос_отсрочка:
            return "ответ:результат:отсрочка"
        return "ответ:результат:не_отсрочка"

    блокB = ФейкБлок(
        имя="B",
        пишет={},
        читает={"категория": ["A", "B"]},
        ответы=["ответ:результат:отсрочка", "ответ:результат:не_отсрочка"],
        правило={"ответ": _ответ_по_шине}
    )

    проц = Процессор(ФейкЯдро([блокA, блокB]))
    правило = {"A": "не_отсрочка", "B": "отсрочка"}
    цепь = [
        {"мост": "категория", "значения": ["A", "B"],
         "правило": правило,
         "цель_блок": "B", "выход": "ответы"}
    ]

    рез = []
    for текст, ожидаемо in [
        ("к:A болезнь:b1", "System 1"),
        ("к:A болезнь:b1 отсрочка?", "System 2 (противоречие)"),
        ("к:B болезнь:b2 отсрочка?", "System 1 или System 2"),
    ]:
        ответ, запись = проц.спросить(текст, "системы", цепь=цепь, порог_уверенности=0.7)
        рез.append({
            "текст": текст,
            "ожидаемо": ожидаемо,
            "система": запись["система"],
            "уверенность_s1": запись["уверенность_s1"],
            "ответ": ответ if isinstance(ответ, str) else "ответ:%s:%s" % (ответ["область"], ответ["id"]),
        })
    return рез


def _v8_демо():
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    ядро, _ = О.система("основная_внешние", 1, язык=язык)
    проц = Процессор(ядро)

    # Цепочка: область → ответы (тождество)
    цепь = [
        {"мост": "область", "значения": ["здоровье", "право"],
         "правило": {"здоровье": "здоровье", "право": "право"},
         "цель_блок": "право", "выход": "ответы"}
    ]

    рез = []
    for текст, ожидаемо in [
        ("Не явился по повестке, что будет?", "System 1"),
        ("У меня категория А, как получить отсрочку?", "System 2"),
        ("Как варить борщ?", "System 2 / не знаю"),
    ]:
        ответ, запись = проц.спросить(текст, "системы", цепь=цепь, порог_уверенности=0.7)
        рез.append({
            "текст": текст,
            "ожидаемо": ожидаемо,
            "система": запись["система"],
            "уверенность_s1": запись["уверенность_s1"],
            "ответ": ответ if isinstance(ответ, str) else "ответ:%s:%s" % (ответ["область"], ответ["id"]),
        })
    return рез


def main():
    рез = {
        "абстрактный_мир": _абстрактный_мир(),
        "v8_демо": _v8_демо(),
    }

    ВЫХОД = os.path.join(О.БАЗА, "v9", "результаты", "лаба_системы.json")
    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    json.dump(рез, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps(рез, ensure_ascii=False, indent=1))
    print("записано:", ВЫХОД)


if __name__ == "__main__":
    main()
