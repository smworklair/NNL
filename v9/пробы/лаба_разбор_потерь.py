# -*- coding: utf-8 -*-
"""Лаба разбора потерь процессора «набор» на 61 стыковом вопросе.

Чистый анализ уже сохранённого замера v9/результаты/лаба_процессор.json —
модель не запускается. Отвечает на три вопроса:

  1. Из чего состоит потеря: блок промолчал (пусто) или дал неверную метку?
  2. Насколько неверная метка «близка» к эталону (тот же акт/семейство)?
  3. Каков потолок любой сборки поверх этих блоков: наблюдаемое «оба верны»
     против ожидаемого при независимости ошибок.

Пишет v9/результаты/лаба_разбор_потерь.json.
"""
import json
import os
import sys

sys.dont_write_bytecode = True

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

from лаба_общее import О  # noqa: E402

ВХОД = os.path.join(О.БАЗА, "v9", "результаты", "лаба_процессор.json")
ВЫХОД = os.path.join(О.БАЗА, "v9", "результаты", "лаба_разбор_потерь.json")


def ид(ключ):
    """'ответ:право:pp565_x' -> 'pp565_x'."""
    ч = ключ.split(":", 2)
    return ч[2] if len(ч) == 3 else ""


def семейство(идент):
    """Первый токен id: 'pp565_medosmotr' -> 'pp565'; '46' -> '46'."""
    return идент.split("_", 1)[0] if идент else ""


def вид_потери(дано, эталон):
    """Классифицирует исход по одной области."""
    if not дано:
        return "промолчал"
    if дано & эталон:
        return "верно"
    return "неверно"


def близость(дано, эталон):
    """Есть ли у неверной метки общее семейство с каким-либо эталоном."""
    sem_дано = {семейство(ид(x)) for x in дано}
    sem_эт = {семейство(ид(x)) for x in эталон}
    пересечение = sem_дано & sem_эт
    if not пересечение:
        return "другое_семейство"
    return "то_же_семейство:" + ",".join(sorted(пересечение))


def main():
    замер = json.load(open(ВХОД, encoding="utf-8"))
    вопросы = замер["вопросы"]
    n = len(вопросы)

    итог = {
        "здоровье": {"верно": 0, "промолчал": 0, "неверно": 0, "неверно_то_же_семейство": 0,
                     "неверно_другое_семейство": 0},
        "право": {"верно": 0, "промолчал": 0, "неверно": 0, "неверно_то_же_семейство": 0,
                  "неверно_другое_семейство": 0},
        "сочетания_потерь": {},
        "потери": [],
    }

    оба_верны = оба_неверны = 0
    for r in вопросы:
        зд_эт, пр_эт = set(r["эталон_зд"]), set(r["эталон_пр"])
        зд_дано, пр_дано = set(r["зд_дано"]), set(r["пр_дано"])

        состояния = {}
        for обл, дано, эт in (("здоровье", зд_дано, зд_эт), ("право", пр_дано, пр_эт)):
            в = вид_потери(дано, эт)
            итог[обл][в] += 1
            if в == "неверно":
                близ = близость(дано, эт)
                итог[обл]["неверно_то_же_семейство" if близ.startswith("то_же") else
                           "неверно_другое_семейство"] += 1
            состояния[обл] = в

        оба_верны += состояния["здоровье"] == "верно" and состояния["право"] == "верно"
        оба_неверны += состояния["здоровье"] != "верно" and состояния["право"] != "верно"

        ключ = "здоровье=%s | право=%s" % (состояния["здоровье"], состояния["право"])
        итог["сочетания_потерь"][ключ] = итог["сочетания_потерь"].get(ключ, 0) + 1

        if not (состояния["здоровье"] == "верно" and состояния["право"] == "верно"):
            итог["потери"].append({
                "i": r["i"], "текст": r["текст"],
                "здоровье": {"состояние": состояния["здоровье"], "дано": sorted(зд_дано),
                             "эталон": sorted(зд_эт),
                             "близость": близость(зд_дано, зд_эт) if состояния["здоровье"] == "неверно" else None},
                "право": {"состояние": состояния["право"], "дано": sorted(пр_дано),
                          "эталон": sorted(пр_эт),
                          "близость": близость(пр_дано, пр_эт) if состояния["право"] == "неверно" else None},
            })

    # Потолок сборки поверх этих блоков: наблюдаемое против независимости ошибок.
    зд_верно = итог["здоровье"]["верно"]
    пр_верно = итог["право"]["верно"]
    ожид_оба = зд_верно * пр_верно / float(n)
    итог["потолок"] = {
        "n": n,
        "оба_верны_наблюдаемо": оба_верны,
        "оба_верны_ожидаемо_при_независимости": round(ожид_оба, 2),
        "оба_неверны_наблюдаемо": оба_неверны,
        "оба_неверны_ожидаемо_при_независимости": round((n - зд_верно) * (n - пр_верно) / float(n), 2),
        "верхняя_граница_любой_сборки_min": min(зд_верно, пр_верно),
        "отклонение_от_независимости": round(оба_верны - ожид_оба, 2),
    }

    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    json.dump(итог, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    for обл in ("здоровье", "право"):
        c = итог[обл]
        print("%-9s верно %2d  промолчал %2d  неверно %2d (то же семейство %d / другое %d)"
              % (обл, c["верно"], c["промолчал"], c["неверно"],
                 c["неверно_то_же_семейство"], c["неверно_другое_семейство"]))
    print("сочетания потерь:")
    for k, v in sorted(итог["сочетания_потерь"].items(), key=lambda x: -x[1]):
        print("  %-45s %d" % (k, v))
    print("потолок:", json.dumps(итог["потолок"], ensure_ascii=False))
    print("записано:", ВЫХОД)


if __name__ == "__main__":
    main()
