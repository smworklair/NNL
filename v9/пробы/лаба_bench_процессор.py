# -*- coding: utf-8 -*-
"""Тест процессора (ядро-2) на общем bench.

Сравнивает на bench.jsonl:
  - v8 один ответ (baseline)
  - процессор "набор" (топ-1 из каждой области)
  - процессор "набор" топ-3 из каждой области

Метрики: top-1 точность, top-3 точность, доля вопросов с верным ответом в наборе.
"""
import json
import os
import sys

sys.dont_write_bytecode = True
from лаба_общее import О, Процессор  # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

ВЫХОД = os.path.join(О.БАЗА, "v9", "результаты", "лаба_bench_процессор.json")


def ключ_ответа(a):
    if a == О.НЕ_ЗНАЮ or a.get("вид") != "ответ":
        return None
    return "ответ:%s:%s" % (a["область"], a["id"])


def main():
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    ядро, _ = О.система("основная_внешние", 1, язык=язык)
    проц = Процессор(ядро)

    bench = []
    with open(os.path.join(О.БАЗА, "bench", "bench.jsonl"), encoding="utf-8") as f:
        for line in f:
            if line.strip():
                bench.append(json.loads(line))

    n = len(bench)
    v8_top1 = 0
    набор_top1 = 0
    набор_в_наборе = 0
    v8_top3 = 0
    набор_top3 = 0

    вопросы = []

    for r in bench:
        текст = r["вопрос"]
        эталон = "ответ:%s:%s" % (r["область"], r["ответ"])

        # v8 один ответ
        ответ_v8, _ = ядро.спросить(текст)
        ключ_v8 = ключ_ответа(ответ_v8)

        # процессор набор
        ответ_пр, запись_пр = проц.спросить(текст, "набор", n=3)
        набор = запись_пр.get("набор", [])
        ключи_набор = [x["ключ"] for x in набор]
        топ1_пр = ключи_набор[0] if ключи_набор else None

        # v8 топ-3
        канд_v8 = ядро.последняя_запись.get("кандидаты", []) if hasattr(ядро, "последняя_запись") else []
        # Процессор не хранит кандидаты v8; нужно отдельно спросить и взять кандидаты.
        # Лучше: запросить v8 и записать кандидаты.
        # Доступ к кандидатам через запись ядра:

        # Переспросим v8 с сохранением записи
        ответ_v8, запись_v8 = ядро.спросить(текст)
        канд_v8 = запись_v8.get("кандидаты", [])
        ключи_v8_top3 = [x["ответ"] for x in канд_v8[:3]]

        v8_верно = ключ_v8 == эталон
        набор_верно = топ1_пр == эталон
        набор_в_наборе_верно = эталон in ключи_набор
        v8_top3_верно = эталон in ключи_v8_top3
        набор_top3_верно = эталон in ключи_набор[:3] if len(ключи_набор) >= 3 else набор_верно

        v8_top1 += v8_верно
        набор_top1 += набор_верно
        набор_в_наборе += набор_в_наборе_верно
        v8_top3 += v8_top3_верно
        набор_top3 += набор_top3_верно

        вопросы.append({
            "qid": r.get("qid"),
            "текст": текст[:120],
            "область": r["область"],
            "эталон": эталон,
            "v8_top1": ключ_v8,
            "набор_top1": топ1_пр,
            "v8_top3": ключи_v8_top3,
            "набор_top3": ключи_набор[:3],
        })

    рез = {
        "n": n,
        "метрики": {
            "v8_top1": "%d/%d" % (v8_top1, n),
            "набор_top1": "%d/%d" % (набор_top1, n),
            "v8_top3": "%d/%d" % (v8_top3, n),
            "набор_top3": "%d/%d" % (набор_top3, n),
            "набор_верный_в_наборе": "%d/%d" % (набор_в_наборе, n),
        },
        "вопросы": вопросы,
    }

    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    json.dump(рез, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps(рез["метрики"], ensure_ascii=False, indent=1))
    print("записано:", ВЫХОД)


if __name__ == "__main__":
    main()
