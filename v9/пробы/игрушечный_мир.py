# -*- coding: utf-8 -*-
"""Базовые классы для игрушечного мира, совместимые с процессором v9."""
import math
import random


class ФейкЯзык:
    """Язык для игрушечного мира. Текст вида 'ключ1:val1 ключ2:val2 ...'."""

    def перевести(self, текст):
        токены = {"_слова": текст.split()}
        for часть in токены["_слова"]:
            if ":" in часть:
                k, v = часть.split(":", 1)
                токены[k] = v
        return {"токены": токены, "метки": {}, "отрицания": []}


class ФейкАрх:
    """Архитектура игрушечного блока."""

    def __init__(self, пишет, читает, ответы, правило):
        self._пишет = пишет
        self._читает = читает
        self._ответы = ответы
        self._правило = правило

    def _scores(self, значения, истина, шум=0.1):
        random.seed(hash(истина))
        с = {v: random.gauss(0, шум) for v in значения}
        if истина in значения:
            с[истина] += 2.0
        m = max(с.values())
        e = {v: math.exp(с[v] - m) for v in с}
        z = sum(e.values())
        return {v: math.log(e[v] / z) for v in с}

    def проход1(self, obj, токены):
        с = {}
        for понятие in self._пишет:
            истина = self._правило.get(понятие, lambda t: "")(токены)
            for v in self._пишет[понятие]:
                с["%s:%s" % (понятие, v)] = self._scores(self._пишет[понятие], истина)[v]
        return с

    def проход2(self, obj, токены, шина):
        # Для блоков, которые дают ответы на основе шины.
        # По умолчанию: если есть правило для 'ответ', используем его,
        # иначе выбираем на основе максимального понятия на шине.
        if "ответ" in self._правило:
            истина = self._правило["ответ"](токены, шина)
            return self._scores(self._ответы, истина, шум=0.2)
        # fallback: случайный выбор
        return self._scores(self._ответы, random.choice(self._ответы) if self._ответы else "", шум=0.3)


class ФейкБлок:
    def __init__(self, имя, пишет, читает, ответы, правило):
        self.имя = имя
        self.пишет = []
        for понятие, значения in пишет.items():
            for v in значения:
                self.пишет.append("%s:%s" % (понятие, v) if v else понятие)
        self.читает = []
        for понятие, значения in читает.items():
            for v in значения:
                self.читает.append("%s:%s" % (понятие, v) if v else понятие)
        self.ответы = ответы
        self.arch = ФейкАрх(пишет, читает, ответы, правило)
        self.obj = self.arch


class ФейкЯдро:
    """Минимальное ядро для игрушечного мира."""

    def __init__(self, блоки):
        self.язык = ФейкЯзык()
        self.блоки = {b.имя: b for b in блоки}
        self.схема = type("Схема", (), {"проходов": 2, "имя": "игрушечная"})()
        self._владелец = {}
        for b in блоки:
            for a in b.ответы:
                self._владелец[a] = b.имя
