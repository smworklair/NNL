# -*- coding: utf-8 -*-
"""Лего-индекс для процессора (ядро-2): проверяем, что вынимание блока не портит ответы соседа.

Системы:
  - полная: здоровье + право
  - только здоровье
  - только право

Метрики:
  - точка в точку: сколько ответов области изменилось после вынимания другого блока.
  - индекс Лего: изменение ответов / число вопросов.
"""
import json
import os
import sys

sys.dont_write_bytecode = True
from лаба_общее import О, Процессор  # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

sys.path.insert(0, О.V8)
from ядро import Ядро, Язык  # noqa: E402

ВЫХОД = os.path.join(О.БАЗА, "v9", "результаты", "лаба_лего_индекс.json")


def соло(кого, язык):
    k = Ядро(язык, О.ARCH, схема=os.path.join(О.V8, "схемы", "основная_внешние.json"))
    ok, msg, _ = k.подключить(os.path.join(О.V8, "блоки", "основная_внешние.з1", кого))
    assert ok, (кого, msg)
    return k


def main():
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    полная, _ = О.система("основная_внешние", 1, язык=язык)
    сз = соло("здоровье", язык)
    сп = соло("право", язык)

    bench = []
    with open(os.path.join(О.БАЗА, "bench", "bench.jsonl"), encoding="utf-8") as f:
        for line in f:
            if line.strip():
                bench.append(json.loads(line))

    проц_полная = Процессор(полная)
    проц_зд = Процессор(сз)
    проц_пр = Процессор(сп)

    n = len(bench)
    изменилось_зд = 0
    изменилось_пр = 0
    вопросы = []

    for r in bench:
        текст = r["вопрос"]
        область = r["область"]

        # Compare area-specific top-1 in full system vs solo system
        _, запись_полная = проц_полная.спросить(текст, "набор")
        _, запись_зд = проц_зд.спросить(текст, "набор")
        _, запись_пр = проц_пр.спросить(текст, "набор")

        def ответ_области(запись, area):
            for x in запись.get("набор", []):
                if x["область"] == area:
                    return x["ключ"]
            return None

        полн_зд = ответ_области(запись_полная, "здоровье")
        соло_зд = ответ_области(запись_зд, "здоровье")
        полн_пр = ответ_области(запись_полная, "право")
        соло_пр = ответ_области(запись_пр, "право")

        if полн_зд != соло_зд:
            изменилось_зд += 1
        if полн_пр != соло_пр:
            изменилось_пр += 1

        вопросы.append({
            "текст": текст[:120],
            "область": область,
            "полная_зд": полн_зд,
            "соло_зд": соло_зд,
            "полная_пр": полн_пр,
            "соло_пр": соло_пр,
        })

    рез = {
        "n": n,
        "изменилось_здоровье_при_вынимании_права": "%d/%d" % (изменилось_зд, n),
        "изменилось_право_при_вынимании_здоровья": "%d/%d" % (изменилось_пр, n),
        "индекс_лего_здоровье": round(изменилось_зд / n, 4),
        "индекс_лего_право": round(изменилось_пр / n, 4),
        "вопросы": вопросы,
    }

    os.makedirs(os.path.dirname(ВЫХОД), exist_ok=True)
    json.dump(рез, open(ВЫХОД, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(json.dumps({k: v for k, v in рез.items() if k != "вопросы"}, ensure_ascii=False, indent=1))
    print("записано:", ВЫХОД)


if __name__ == "__main__":
    main()
