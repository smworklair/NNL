# -*- coding: utf-8 -*-
"""Ядро причинности (Причинный валидатор).

Отвечает за проверку причинных ролей, проекцию фактов и консистентность:
  1. Паспортный причинный протокол: проекция вывода в понятия шины.
  2. Проверка причинных контрактов и вычисление совместной совместимости.
"""
import os


class Ядро:
    def __init__(self, база_путь):
        self.база_путь = база_путь
        self.статья_глава = {}
        self.тема_акты = {}
        self._загрузить_базу()

    def _загрузить_базу(self):
        sg_path = os.path.join(self.база_путь, "математичка", "данные", "статья_глава.csv")
        if os.path.exists(sg_path):
            with open(sg_path, encoding="utf-8") as f:
                f.readline()
                for line in f:
                    if line.strip():
                        p = line.strip().split(";")
                        self.статья_глава[p[0]] = p[1]

        ta_path = os.path.join(self.база_путь, "математичка", "данные", "тема_акты.csv")
        if os.path.exists(ta_path):
            with open(ta_path, encoding="utf-8") as f:
                f.readline()
                for line in f:
                    if line.strip():
                        p = line.strip().split(";")
                        topic = p[0]
                        acts = []
                        for a in p[1].split("+"):
                            a = a.strip()
                            if "53фз" in a: acts.append("акт:53фз")
                            elif "пп565" in a: acts.append("акт:пп565")
                            elif "пп663" in a: acts.append("акт:пп663")
                            elif "пп719" in a: acts.append("акт:пп719")
                            elif "кас" in a: acts.append("акт:кас")
                            elif "коап" in a: acts.append("акт:коап")
                            elif "укрф" in a: acts.append("акт:укрф")
                            elif "127фз" in a: acts.append("акт:127фз")
                            elif "59фз" in a: acts.append("акт:59фз")
                        self.тема_акты[topic] = acts

    def проецировать_на_шину(self, имя_блока, ответ):
        """Проецирует вывод блока в стандартизованные понятия шины согласно паспорту."""
        проекция = {}
        if имя_блока == "здоровье":
            art_id = ответ.replace("ответ:здоровье:", "")
            chap = self.статья_глава.get(art_id)
            # Базовый масштаб чтения в паспорте равен 8.0, масштаб 2.0 дает 16.0
            проекция["область:здоровье"] = 16.0
            if chap:
                проекция[f"глава:{chap}"] = 16.0
        elif имя_блока == "право":
            top_id = ответ.replace("ответ:право:", "")
            acts = self.тема_акты.get(top_id, [])
            проекция["область:право"] = 16.0
            for a in acts:
                проекция[a] = 16.0
        elif имя_блока == "ответы_мейлру":
            проекция["стиль:живой_ответ"] = 16.0
        return проекция

    def проверить_цепочку(self, отклики):
        """Проверяет причинную совместимость и формирует совместное решение."""
        финал = dict(отклики)
        if "здоровье" in отклики and "право" in отклики:
            zd_top = отклики["здоровье"]["top1"].replace("ответ:здоровье:", "")
            pr_top = отклики["право"]["top1"].replace("ответ:право:", "")
            chap = self.статья_глава.get(zd_top, "?")
            acts = self.тема_акты.get(pr_top, [])
            
            цепочка = {
                "статья_расписания": zd_top,
                "глава": chap,
                "правовая_тема": pr_top,
                "акты": acts,
                "статус_причинности": "верифицировано" if acts else "базовый",
            }
            if "ответы_мейлру" in отклики:
                цепочка["стиль_ответа"] = отклики["ответы_мейлру"]["top1"]
                if "живой_текст" in отклики["ответы_мейлру"]:
                    цепочка["живой_текст"] = отклики["ответы_мейлру"]["живой_текст"]
            финал["_причинная_цепочка"] = цепочка
        return финал
