# -*- coding: utf-8 -*-
"""Процессор тактов (Диспетчер тактов).

Координирует проходы блоков через матплату:
  - Архитектура не содержит захардкоженных областей (работает для любого N блоков).
  - Такт 1: прямой параллельный опрос блоков с изоляцией шины.
    Вычисляет локальный отклик и уровень уверенности (маржин Delta = s_{(1)} - s_{(2)}).
  - Такт 2: обратная запись подтверждённых выводов (Delta >= tau_conf) на шину
    в виде фактов вывода `вывод_{роль}:{id}` и категориальных проекций.
    Неуверенные блоки пересчитывают свои ответы по срезу шины такта 2.
"""
import math


class Процессор:
    def __init__(self, матплата, ядро_валидатор=None, tau_conf=1.0):
        self.матплата = матплата
        self.ядро = ядро_валидатор
        self.tau_conf = tau_conf

    def выполнить(self, текст):
        токены = self.матплата.язык.перевести(текст)["токены"]
        self.матплата.очистить_шину()
        
        # ======================================================== ТАКТ 1
        # Изолированный прямой опрос каждого блока (такт=1 -> срез {})
        отклики_т1 = {}
        уверенные_блоки = set()
        
        for имя, блок in self.матплата.блоки.items():
            срез_т1 = self.матплата.срез_шины(имя, такт=1)
            счёты = блок.arch.проход2(блок.obj, токены, срез_т1)
            сортировка = sorted(счёты.items(), key=lambda x: x[1], reverse=True)
            top1_ans, top1_score = сортировка[0]
            top2_score = сортировка[1][1] if len(сортировка) > 1 else top1_score
            margin = top1_score - top2_score
            
            отклики_т1[имя] = {
                "счёты": счёты,
                "top1": top1_ans,
                "score": top1_score,
                "margin": margin,
            }
            if margin >= self.tau_conf:
                уверенные_блоки.add(имя)

        # ======================================================== ТАКТ 2
        # Обратная запись выводов уверенных блоков на шину матплаты
        нужен_такт2 = (len(уверенные_блоки) > 0 and (
            len(уверенные_блоки) < len(self.матплата.блоки) or
            any(len(b.читает) > 0 for b in self.матплата.блоки.values())
        ))
        отклики_т2 = dict(отклики_т1)
        
        if нужен_такт2:
            for имя in уверенные_блоки:
                блок = self.матплата.блоки[имя]
                top1 = отклики_т1[имя]["top1"]
                # Записываем факт подтверждённого вывода на шину
                понятие_вывода = f"вывод_{имя}:{top1}"
                self.матплата.записать_на_шину(понятие_вывода, 1.0)
                
                # Если у ядра есть категориальная проекция (глава, акт и т.д.):
                if self.ядро:
                    проекции = self.ядро.проецировать_на_шину(имя, top1)
                    for k, v in проекции.items():
                        self.матплата.записать_на_шину(k, v)
                        
            # Опрос блоков, читающих шину (или неуверенных блоков) на такте 2
            for имя, блок in self.матплата.блоки.items():
                if имя not in уверенные_блоки or len(блок.читает) > 0:
                    срез_т2 = self.матплата.срез_шины(имя, такт=2)
                    if срез_т2:
                        счёты_т2 = блок.arch.проход2(блок.obj, токены, срез_т2)
                        сортировка = sorted(счёты_т2.items(), key=lambda x: x[1], reverse=True)
                        top1_ans, top1_score = сортировка[0]
                        top2_score = сортировка[1][1] if len(сортировка) > 1 else top1_score
                        margin = top1_score - top2_score
                        отклик = {
                            "счёты": счёты_т2,
                            "top1": top1_ans,
                            "score": top1_score,
                            "margin": margin,
                        }
                        if hasattr(блок.arch, "синтез"):
                            отклик["живой_текст"] = блок.arch.синтез(блок.obj, токены, срез_т2, top1_ans, отклики=отклики_т2)
                        отклики_т2[имя] = отклик

        # ======================================================== ВАЛИДАЦИЯ ЯДРОМ
        отклики_финал = dict(отклики_т2)
        if self.ядро:
            отклики_финал = self.ядро.проверить_цепочку(отклики_т2)

        return {
            "текст": текст,
            "токены": токены,
            "такт1": отклики_т1,
            "такт2": отклики_т2,
            "финал": отклики_финал,
            "уверенные_блоки": list(уверенные_блоки),
        }
