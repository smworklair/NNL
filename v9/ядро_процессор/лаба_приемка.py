# -*- coding: utf-8 -*-
"""Лаба комплексной приёмки 5-уровневой архитектуры:
Матплата -> Блоки -> Процессор -> Ядро -> Решатель.

Проверяет 3 критерия приёмки:
  1. Lego-индекс на 461 вопросах bench.jsonl: строго 0.0000.
  2. 61 стыковой вопрос: «оба верны» > 20 и per-area (здоровье > 37).
  3. Решатель: при доле воздержаний <= 20% точность на отвеченных >= 80%.

Пишет результаты в v9/результаты/лаба_приемка.json.
"""
import json
import os
import sys

СЮДА = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.dirname(os.path.dirname(СЮДА))
sys.path.insert(0, СЮДА)
sys.path.insert(1, os.path.join(КОРЕНЬ, "v8", "замер"))
sys.path.insert(2, os.path.join(КОРЕНЬ, "v9", "пробы"))

import общее as О
from лаба_стыки_полные import стыковые
from матплата import Матплата
from процессор_тактов import Процессор
from ядро_причинности import Ядро
from решатель import Решатель


def main():
    язык = О.Язык(О.ЯЗЫК_ПАПКА)
    матплата = Матплата(язык, О.ARCH)
    ok_z, _ = матплата.подключить(os.path.join(О.V8, "блоки", "основная_внешние.з1", "здоровье"))
    ok_p, _ = матплата.подключить(os.path.join(О.V8, "блоки", "основная_внешние.з1", "право"))
    assert ok_z and ok_p, "Блоки не подключены к матплате"

    ядро_валидатор = Ядро(КОРЕНЬ)
    процессор = Процессор(матплата, ядро_валидатор, tau_conf=1.0)
    решатель = Решатель(порог_воздержания=1.0)

    # ========================================================
    # 1. ЗАМЕР LEGO-ИНДЕКСА
    # ========================================================
    print("--- 1. Замер Lego-индекса на bench.jsonl (461 вопрос) ---")
    bench = []
    with open(os.path.join(О.БАЗА, "bench", "bench.jsonl"), encoding="utf-8") as f:
        for line in f:
            if line.strip():
                bench.append(json.loads(line))

    diff_z, diff_p = 0, 0
    n_bench = len(bench)
    b_zd = матплата.блоки["здоровье"]
    b_pr = матплата.блоки["право"]

    for r in bench:
        toks = язык.перевести(r["вопрос"])["токены"]
        # Соло-прогон (без других блоков)
        s_z_solo = b_zd.arch.проход2(b_zd.obj, toks, {})
        top_z_solo = max(s_z_solo, key=s_z_solo.get)
        s_p_solo = b_pr.arch.проход2(b_pr.obj, toks, {})
        top_p_solo = max(s_p_solo, key=s_p_solo.get)

        # Прогон в матплате на такте 1 (срез шины пуст по контракту изоляции)
        res = процессор.выполнить(r["вопрос"])
        top_z_sys = res["такт1"]["здоровье"]["top1"]
        top_p_sys = res["такт1"]["право"]["top1"]

        if top_z_sys != top_z_solo:
            diff_z += 1
        if top_p_sys != top_p_solo:
            diff_p += 1

    lego_z = round(diff_z / n_bench, 4)
    lego_p = round(diff_p / n_bench, 4)
    print(f"Lego-индекс Здоровье: {lego_z} ({diff_z}/{n_bench})")
    print(f"Lego-индекс Право:    {lego_p} ({diff_p}/{n_bench})")
    assert lego_z == 0.0 and lego_p == 0.0, "Lego-индекс должен быть строго 0.0!"

    # ========================================================
    # 2. ЗАМЕР 61 СТЫКОВОГО ВОПРОСА
    # ========================================================
    print("\n--- 2. Замер 61 стыкового вопроса ---")
    стыки_список = стыковые()
    n_стыков = len(стыки_список)

    записи_стыков = []
    оба_верны_cnt = 0
    зд_верно_cnt = 0
    пр_верно_cnt = 0

    for s in стыки_список:
        res = процессор.выполнить(s["текст"])
        финал = res["финал"]

        top_z = финал["здоровье"]["top1"]
        top_p = финал["право"]["top1"]
        mz = финал["здоровье"]["margin"]
        mp = финал["право"]["margin"]

        z_ok = top_z in s["эталон_зд"]
        p_ok = top_p in s["эталон_пр"]
        both_ok = z_ok and p_ok

        if z_ok: зд_верно_cnt += 1
        if p_ok: пр_верно_cnt += 1
        if both_ok: оба_верны_cnt += 1

        записи_стыков.append({
            "i": s["i"],
            "текст": s["текст"][:100],
            "верно_здоровье": z_ok,
            "верно_право": p_ok,
            "оба_верны": both_ok,
            "margin_здоровье": mz,
            "margin_право": mp,
            "ответ_здоровье": top_z,
            "ответ_право": top_p,
            "эталон_зд": s["эталон_зд"],
            "эталон_пр": s["эталон_пр"],
        })

    print(f"Базовый v8:           оба_верны=20, здоровье=37, право=44")
    print(f"5-уровневая система:  оба_верны={оба_верны_cnt}, здоровье={зд_верно_cnt}, право={пр_верно_cnt}")

    # ========================================================
    # 3. ЗАМЕР РЕШАТЕЛЯ (КРИВАЯ СЕЛЕКТИВНОСТИ)
    # ========================================================
    print("\n--- 3. Кривая селективности Решателя ---")
    кривая_право = решатель.кривая(записи_стыков, область="право")
    кривая_здоровье = решатель.кривая(записи_стыков, область="здоровье")

    for row in кривая_право:
        print(f"[Право] Порог={row['порог']:3.1f} | Отвечено={row['отвечено']:2d}/{n_стыков} (Воздержание={row['доля_воздержаний']:5.1%}) -> Точность={row['точность']:5.1%} ({row['верно']}/{row['отвечено']})")

    отчет = {
        "lego_индекс": {
            "здоровье": lego_z,
            "право": lego_p,
            "статус": "OK" if (lego_z == 0.0 and lego_p == 0.0) else "FAIL"
        },
        "стыки_61": {
            "оба_верны": оба_верны_cnt,
            "здоровье": зд_верно_cnt,
            "право": пр_верно_cnt,
            "выигрыш_оба": оба_верны_cnt - 20,
            "выигрыш_здоровье": зд_верно_cnt - 37,
        },
        "кривая_решателя_право": кривая_право,
        "кривая_решателя_здоровье": кривая_здоровье,
        "вопросы": записи_стыков,
    }

    вых_файл = os.path.join(КОРЕНЬ, "v9", "результаты", "лаба_приемка.json")
    os.makedirs(os.path.dirname(вых_файл), exist_ok=True)
    with open(вых_файл, "w", encoding="utf-8") as f:
        json.dump(отчет, f, ensure_ascii=False, indent=2)

    print(f"\nОтчёт успешно сохранён в: {вых_файл}")


if __name__ == "__main__":
    main()
