# -*- coding: utf-8 -*-
"""Источники фактов диалога (только чтение): Расписание болезней ред. 2026 (ПП-565) и правовые темы.
Критерии, пороги и категории берутся ОТСЮДА (из текста документа), а не из кода: ни одного числа порога в коде нет."""
import json
import os
import re

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
СТАТЬИ = os.path.join(КОРЕНЬ, "внешние", "документы", "pp565", "статьи_2026.json")
СПРАВОЧНИК = os.path.join(КОРЕНЬ, "внешние", "справочник.json")
ТЕМЫ = os.path.join(КОРЕНЬ, "внешние", "lex_topics.json")

_ПУНКТ = re.compile(r"^([а-е])\)\s*(.*)$")
_КАТЕГОРИЯ = re.compile(r"^((А|Б|В|Г|Д|НГ)(-\d)?|-)(\s*\(.*\))?$")
_СКОБКА = re.compile(r"^\(.*\)$")
_ШАПКА = re.compile(r"^(I|II|III) графа$|^Статья расписания болезней|^Наименование болезней|^Категория годности")


ЛЕГЕНДА_КАТЕГОРИЙ = ("Категории годности (ПП РФ № 565): А — годен к военной службе; Б — годен с незначительными ограничениями; "
                    "В — ограниченно годен; Г — временно не годен; Д — не годен. При призыве и первоначальной постановке на воинский учёт "
                    "применяется графа I Расписания болезней.")


class Статья:
    def __init__(self, ид, сырой, название_справочника):
        self.ид = str(ид)
        строки = [l.strip() for l in сырой.split("\n") if l.strip() and l.strip() != "|"]
        строки = [l for l in строки if not _ШАПКА.match(l)]
        self.название = (строки[0].rstrip(":") if строки else название_справочника) or название_справочника
        self.справочное_название = название_справочника
        self.пункты = []            # {буква, описание, графы: [I, II, III]}
        self.примечания = []
        текущий, таблица = None, True
        for l in строки[1:]:
            if таблица and (m := _ПУНКТ.match(l)):
                текущий = {"буква": m.group(1), "описание": [m.group(2)], "графы": []}
                self.пункты.append(текущий)
            elif таблица and _КАТЕГОРИЯ.match(l) and (текущий is None or len(текущий["графы"]) < 3):
                if текущий is None:         # статья без пунктов: категории стоят сразу под названием
                    текущий = {"буква": "—", "описание": ["(статья без деления на пункты)"], "графы": []}
                    self.пункты.append(текущий)
                текущий["графы"].append(l)
            elif таблица and текущий is not None and _СКОБКА.match(l) and текущий["графы"]:
                текущий["графы"][-1] += " " + l
            elif таблица and текущий is not None and not текущий["графы"] and текущий["буква"] != "—":
                текущий["описание"].append(l)
            else:
                таблица = False
                self.примечания.append(l)
        for p in self.пункты:
            p["описание"] = " ".join(p["описание"])
        self.сырой = сырой

    def текст_для_модели(self, предел=6000):
        """Компактный текст статьи: название, пункты с графами I/II/III, примечания (как в документе)."""
        out = ["Статья %s. %s" % (self.ид, self.название)]
        for p in self.пункты:
            г = p["графы"]
            out.append("  пункт «%s»: %s | КАТЕГОРИЯ ДЛЯ ПРИЗЫВНИКА (графа I): %s%s" % (
                p["буква"], p["описание"], г[0] if г else "—", ("  [графы II/III — для военнослужащих, к призывнику не применять: %s]" % " / ".join(г[1:])) if len(г) > 1 else ""))
        pr = [l for l in self.примечания if not l.startswith("(см. текст") and not l.startswith("(в ред.") and "утратил силу" not in l]
        t = "\n".join(out) + "\nПримечания к статье:\n" + "\n".join(pr)
        if any(len(p["графы"]) != 3 for p in self.пункты):      # разбор таблицы неполный: даём исходный текст как есть
            t += "\nИсходный текст статьи (разбор таблицы неполный):\n" + " ".join(l.strip() for l in self.сырой.split("\n") if l.strip() not in ("", "|"))
        return t[:предел]


class База:
    def __init__(self):
        with open(СТАТЬИ, encoding="utf-8") as f:
            сырые = json.load(f)
        with open(СПРАВОЧНИК, encoding="utf-8") as f:
            сп = json.load(f)
        имена = {b["id"]: b["название"] for b in сп["статьи_болезней"]}
        self.статьи = {ид: Статья(ид, т, имена.get(ид, "")) for ид, т in сырые.items()}
        with open(ТЕМЫ, encoding="utf-8") as f:
            self.темы = {t["topic_id"]: {"название": t["title"], "суть": t["answer_hint"]} for t in json.load(f)}

    def числа_документа(self, ид):
        """Все числа, встречающиеся в тексте статьи (нормализованные): модель в итоге может ссылаться только на них."""
        return нормализованные_числа(self.статьи[ид].текст_для_модели(20000))


def норм_число(s):
    s = s.replace(",", ".").replace("−", "-").strip("-")
    try:
        v = float(s)
    except ValueError:
        return s
    return str(int(v)) if v == int(v) else ("%g" % v)


def нормализованные_числа(текст):
    return {норм_число(m) for m in re.findall(r"\d+(?:[.,]\d+)?", текст)}
