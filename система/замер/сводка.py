# -*- coding: utf-8 -*-
"""Сводка по зёрнам 1–3: среднее и разброс (мин–макс) ключевых чисел. Читает результаты/замер.з*.json, пишет сводка.md/json."""
import glob
import json
import os
import re
import statistics
import sys

sys.dont_write_bytecode = True
V8 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(V8, "результаты")
ВАРИАНТЫ = ["основная", "один_проход", "без_выходных", "монолит"]
ИМЕНА = {"основная": "основная (2 прохода, выходные)", "один_проход": "один проход (шина не читается)",
         "без_выходных": "2 прохода, без выходных", "монолит": "монолит (один блок)"}


def frac(s):
    a, b = s.split("/")
    return int(a) / int(b)


def main():
    files = sorted(glob.glob(os.path.join(R, "замер.з*.json")))
    seeds = {}
    for f in files:
        z = int(re.search(r"з(\d+)", os.path.basename(f)).group(1))
        seeds[z] = json.load(open(f, encoding="utf-8"))
    rows = {}
    for v in ВАРИАНТЫ:
        m = {}
        for z, d in seeds.items():
            s = d["системы"].get(v)
            if not s:
                continue
            ot = s["общий_тест"]
            fl = d["флагманский_600"]["всё · основная разметка"]["v8_" + v]
            vals = {"зд_первый": ot["здоровье"]["первый_ответ_верен"], "пр_первый": ot["право"]["первый_ответ_верен"],
                    "зд_при_пороге": ot["здоровье"]["ответ_верен"], "пр_при_пороге": ot["право"]["ответ_верен"],
                    "600_область": fl["область"] / fl["вопросов"], "600_здоровье": fl["зд_ok"] / fl["зд_n"],
                    "600_право": fl["пр_ok"] / fl["пр_n"], "600_вне": fl["вне_ok"] / fl["вне_n"],
                    "600_ответов": fl["ответов"], "600_ошибок_доля": fl["ошибок"] / max(1, fl["ответов"]),
                    "600_верных": fl["зд_ok"] + fl["пр_ok"]}
            for k, x in vals.items():
                m.setdefault(k, []).append(x)
        rows[v] = {k: {"среднее": statistics.mean(x), "мин": min(x), "макс": max(x), "зёрен": len(x)} for k, x in m.items()}
    v6 = {}
    d = seeds[min(seeds)]
    for name in ("v6_В2б", "v6_Д"):
        fl = d["флагманский_600"]["всё · основная разметка"].get(name)
        if fl:
            v6[name] = {"600_область": fl["область"] / fl["вопросов"], "600_здоровье": fl["зд_ok"] / fl["зд_n"], "600_право": fl["пр_ok"] / fl["пр_n"],
                        "600_вне": fl["вне_ok"] / fl["вне_n"], "600_ответов": fl["ответов"], "600_ошибок_доля": fl["ошибок"] / fl["ответов"],
                        "600_верных": fl["зд_ok"] + fl["пр_ok"]}
    json.dump({"v8": rows, "v6": v6, "зёрна": sorted(seeds)}, open(os.path.join(R, "сводка.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    def p(x, pct=True):
        return ("%.1f" % (100 * x)) if pct else ("%.0f" % x)

    def cell(r, k, pct=True):
        x = r[k]
        return "%s (%s–%s)" % (p(x["среднее"], pct), p(x["мин"], pct), p(x["макс"], pct))
    md = ["# Сводка v8 по зёрнам %s: среднее (мин–макс)" % ", ".join(map(str, sorted(seeds))), "",
          "## Общий тест 461 (%)", "", "| система | здоровье: первый ответ | право: первый ответ | здоровье: ответ при пороге 0,5 | право: ответ при пороге 0,5 |",
          "|---|---|---|---|---|"]
    for v in ВАРИАНТЫ:
        r = rows[v]
        md.append("| %s | %s | %s | %s | %s |" % (ИМЕНА[v], cell(r, "зд_первый"), cell(r, "пр_первый"), cell(r, "зд_при_пороге"), cell(r, "пр_при_пороге")))
    md.append("| v6 В2б (из отчёта v6) | — | — | 73,4 | 72,0 |")
    md += ["", "## Флагманский набор 600, основная разметка (%; ответов — штук)", "",
           "| система | область верна | здоровье: статья | право: тема | вне → вне | ответов | верных ответов | уверенных ошибок, % ответов |",
           "|---|---|---|---|---|---|---|---|"]
    for v in ВАРИАНТЫ:
        r = rows[v]
        md.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (ИМЕНА[v], cell(r, "600_область"), cell(r, "600_здоровье"), cell(r, "600_право"),
                                                             cell(r, "600_вне"), cell(r, "600_ответов", False), cell(r, "600_верных", False),
                                                             cell(r, "600_ошибок_доля")))
    for name, r in v6.items():
        md.append("| %s | %s | %s | %s | %s | %d | %d | %s |" % (name.replace("_", " "), p(r["600_область"]), p(r["600_здоровье"]), p(r["600_право"]),
                                                                p(r["600_вне"]), r["600_ответов"], r["600_верных"], p(r["600_ошибок_доля"])))
    open(os.path.join(R, "сводка.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
