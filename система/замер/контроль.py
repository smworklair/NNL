def вопросы():
    Н = О.наборы()
    return [r["вопрос"] for r in Н["общий_тест"]] + [r["текст"] for r in Н["флагманский_600"]], Н


def снятие():
    """Вынул блок — его знание ушло: ответы снятого блока не уходят к соседу, ответы соседа почти не меняются."""
    qs, Н = вопросы()
    res = {}
    for v in ("основная", "без_выходных", "один_проход"):
        res[v] = {}
        for имя in ("здоровье", "право"):
            k, _ = О.система(v, проверять_язык=False)
            res[v][имя] = k.снять_с_замером(имя, qs)
            # вопросы области снятого блока из общего теста: куда ушли
            d = [r["вопрос"] for r in Н["общий_тест"] if r["область"] == имя]
            c = collections.Counter()
            for q in d:
                a, _ = k.спросить(q, подробно=False)
                c["не знаю" if a == НЕ_ЗНАЮ else ("уточнить:" + a["область"] if a["вид"] == "уточнить" else "ответ соседа")] += 1
            res[v][имя]["вопросы_его_области_в_общем_тесте"] = dict(c, всего=len(d))
        print("снятие", v, json.dumps(res[v], ensure_ascii=False), flush=True)
    return res


def шина():
    """Сколько ответов меняет шина (второй проход): те же блоки, схема «2 прохода» против «1 проход»; доли вкладов в счёте."""
    qs, _ = вопросы()
    k, _ = О.система("основная", проверять_язык=False)
    два = []
    прямой, сосед, свой = [], [], []
    for q in qs:
        a, rec = k.спросить(q)
        два.append(О.ид(a) + "|" + О.область(a))
        if rec["кандидаты"]:
            c = rec["кандидаты"][0]
            прямой.append(abs(c["прямой"]))
            for n, x in c["через_шину"].items():
                (свой if n == c["хозяин"] else сосед).append(abs(x))
    k.схема = Схема(dict(k.схема.данные, проходов=1))
    один = [О.ид(a) + "|" + О.область(a) for a in (k.спросить(q, подробно=False)[0] for q in qs)]
    n = len(qs)
    ch = sum(x != y for x, y in zip(два, один))
    avg = lambda xs: round(sum(xs) / max(1, len(xs)), 4)
    r = {"вопросов": n, "ответ_меняется_от_шины": ch, "доля": round(ch / n, 4),
         "средний_модуль_вклада": {"прямое_чтение_хозяина": avg(прямой), "через_шину_от_соседа": avg(сосед)}}
    print("шина", json.dumps(r, ensure_ascii=False), flush=True)
    return r


def сбой():
    """Повар уронил кастрюлю: блок «право» падает на каждом вопросе — ядро отвечает остальным, ответы «здоровья» как без «права»."""
    qs, Н = вопросы()
    k, _ = О.система("основная", проверять_язык=False)
    orig = k.блоки["право"].arch

    class Падающий:
        def __getattr__(self, n):
            return getattr(orig, n)

        def проход1(self, obj, токены):
            raise RuntimeError("кастрюля упала")
    k.блоки["право"].arch = Падающий()
    с_сбоем = []
    сбоев = 0
    for q in qs:
        a, rec = k.спросить(q, подробно=False)
        сбоев += "право" in rec["сбои"]
        с_сбоем.append(a if a == НЕ_ЗНАЮ else (a["вид"], a["область"], a.get("id")))
    k2, _ = О.система("основная", проверять_язык=False)
    k2.снять("право")
    без = [a if a == НЕ_ЗНАЮ else (a["вид"], a["область"], a.get("id")) for a in (k2.спросить(q, подробно=False)[0] for q in qs)]
    r = {"вопросов": len(qs), "сбой_записан_в_журнал": сбоев, "ответов_как_без_блока": sum(x == y for x, y in zip(с_сбоем, без))}
    print("сбой", json.dumps(r, ensure_ascii=False), flush=True)
    return r


def сессии():
    qs, _ = вопросы()
    k, _ = О.система("основная", проверять_язык=False)
    fresh = [str(k.спросить(q, подробно=False)[0]) for q in qs[:300]]
    s1 = k.сессия()
    for q in qs:
        s1.спросить(q)
    n1 = len(s1.журнал)
    s1.закрыть()
    s2 = k.сессия()
    second = [str(s2.спросить(q)[0]) for q in qs[:300]]
    r = {"вопросов_в_первой_сессии": n1, "журнал_после_закрытия": len(s1.журнал),
         "вторая_сессия_совпала_с_новым_ядром": "%d/%d" % (sum(x == y for x, y in zip(fresh, second)), len(fresh))}
    print("сессии", json.dumps(r, ensure_ascii=False), flush=True)
    return r


def отказы():
    """Ядро не подключает чужое: подменённые веса, блок под другие правила языка, изменённый смысл понятия."""
    tmp = tempfile.mkdtemp(prefix="v8_отказ_")
    res = {}
    try:
        src = os.path.join(О.БЛОКИ, "основная.з1", "право")
        bad = os.path.join(tmp, "право_подмена")
        shutil.copytree(src, bad)
        with open(os.path.join(bad, "веса.npz"), "r+b") as f:
            f.seek(4096)
            x = f.read(1)
            f.seek(4096)
            f.write(bytes([x[0] ^ 1]))
        k = Ядро(О.ЯЗЫК_ПАПКА, О.ARCH)
        res["подменён_байт_весов"] = k.подключить(bad)[1]
        lang = os.path.join(tmp, "язык_правки")
        shutil.copytree(О.ЯЗЫК_ПАПКА, lang)
        p = os.path.join(lang, "правила.py")
        s = open(p, encoding="utf-8").read().replace("SCOPE = 4", "SCOPE = 5")
        open(p, "w", encoding="utf-8").write(s)
        k = Ядро(lang, О.ARCH)
        res["правило_языка_изменено(SCOPE 4→5)"] = k.подключить(src)[1]
        lang2 = os.path.join(tmp, "язык_смысл")
        shutil.copytree(О.ЯЗЫК_ПАПКА, lang2)
        p = os.path.join(lang2, "стандарт.json")
        d = json.load(open(p, encoding="utf-8"))
        d["понятия"]["акт:кас"] = d["понятия"]["акт:кас"].replace("обжалование", "обжалование и жалобы")
        json.dump(d, open(p, "w", encoding="utf-8"), ensure_ascii=False)
        k = Ядро(lang2, О.ARCH)
        res["смысл_понятия_изменён(акт:кас)"] = k.подключить(src)[1]
        k = Ядро(lang2, О.ARCH)
        res["тот_же_язык: «здоровье» основной (читает акт:кас)"] = k.подключить(os.path.join(О.БЛОКИ, "основная.з1", "здоровье"))[1]
        k = Ядро(lang2, О.ARCH)
        res["тот_же_язык: «здоровье» одного прохода (акт:кас не читает и не пишет)"] = k.подключить(os.path.join(О.БЛОКИ, "один_проход.з1", "здоровье"))[1]
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print("отказы", json.dumps(res, ensure_ascii=False), flush=True)
    return res


def заморозка():
    """«право» заморожено в схеме: его веса после дообучения «здоровья» те же (sha256), дообучение самого «права» запрещено."""
    p = os.path.join(О.БЛОКИ, "основная.з1")
    r = {}
    for имя in ("право", "здоровье", "здоровье@2"):
        f = os.path.join(p, имя, "паспорт.json")
        if os.path.exists(f):
            ps = json.load(open(f, encoding="utf-8"))
            r[имя] = {"версия": ps["версия"], "sha256": ps["веса"]["sha256"][:12], "файл_совпадает": sha256_file(os.path.join(p, имя, "веса.npz")) == ps["веса"]["sha256"],
                      "родитель": ps.get("родитель")}
    print("заморозка", json.dumps(r, ensure_ascii=False), flush=True)
    return r


def замена_и_дообучение():
    """Замена «здоровья» блоком другого устройства и дообучение «здоровья» (версия 2) при работающем/замороженном «праве».
    Качество — общий тест и флагманский 600 (основная разметка); «право» одно и то же (sha256)."""
    Н = О.наборы()
    M = О.оценка_флагманов()
    items = M.срезы(Н["флагманский_600"])["всё · основная разметка"]
    p = os.path.join(О.БЛОКИ, "основная.з1")
    res = {}
    for name, зд in (("исходная (здоровье v1)", "здоровье"), ("замена (здоровье@замена)", "здоровье@замена"), ("дообучение (здоровье@2)", "здоровье@2")):
        if not os.path.exists(os.path.join(p, зд, "паспорт.json")):
            continue
        k = Ядро(О.ЯЗЫК_ПАПКА, О.ARCH, схема=os.path.join(О.V8, "схемы", "основная.json"))
        ok1 = k.подключить(os.path.join(p, "право"))
        ok2 = k.подключить(os.path.join(p, зд))
        assert ok1[0] and ok2[0], (ok1[1], ok2[1])
        ps = k.блоки["здоровье"].паспорт
        r = {"паспорт": {"версия": ps["версия"], "sha256": ps["веса"]["sha256"][:12], "родитель": ps.get("родитель"),
                         "устройство": {x: ps["настройки"][x] for x in ("размер", "свёртка")}, "чисел": ps["веса"]["чисел"],
                         "учился_вместе_с": ps["обучение"].get("вместе_с"), "заморожены_при_обучении": ps["обучение"]["схема"].get("заморожены")},
             "право_sha256": k.блоки["право"].sha256[:12], "общий_тест": О.общий_тест(k, Н["общий_тест"])}
        ans = {a["ключ"]: a for a in О.ответы_флагманского(k, Н["флагманский_600"])}
        c = M.счёт(items, ans)
        r["флагманский_600"] = {"область_верна": "%d/%d" % (c["область"], c["вопросов"]), "здоровье_статья": "%d/%d" % (c["зд_ok"], c["зд_n"]),
                                "право_тема": "%d/%d" % (c["пр_ok"], c["пр_n"]), "вне→вне": "%d/%d" % (c["вне_ok"], c["вне_n"]),
                                "ответов": c["ответов"], "уверенных_ошибок": c["ошибок"]}
        res[name] = r
        print("замена/дообучение", name, json.dumps(r, ensure_ascii=False), flush=True)
    return res


ПРОВЕРКИ = {"снятие": снятие, "шина": шина, "сбой": сбой, "сессии": сессии, "отказы": отказы, "заморозка": заморозка,
            "замена_и_дообучение": замена_и_дообучение}


def main(names):
    t0 = time.time()
    res = json.load(open(OUT, encoding="utf-8")) if os.path.exists(OUT) else {}
    for n in names:
        res[n] = ПРОВЕРКИ[n]()
        json.dump(res, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("готово за %.0f с" % (time.time() - t0))


if __name__ == "__main__":
    main(sys.argv[1:] or list(ПРОВЕРКИ))
