# -*- coding: utf-8 -*-
"""Обучение системы основная_внешние: как основная.з1, но train расширен внешними живыми.

База: D.собрать(seed=1) — те же 39501 train / 2357 dev, что у основная.з1.
Добавка (только train, dev не меняется — лучший_dev сравним с базой 0.7558):
  - пул3 (cowork_пул3.jsonl + пул3_вопросы.json): живые вопросы Mail.ru, которых v8 не видел
    (v8 учил только пул1+пул2). Спорные пропускаем. Почти-повторы проверки/свежих/
    флагманов/bench выбрасываем тем же правилом Жаккар>=0.5 по 5-граммам.
    Каждый выживший вопрос — 2 раза (оригинал x2, без синтетических опечаток/болтовни:
    это уже живой язык, шуметь поверх него не надо).
  - фразы.jsonl (150): отрицание -> здоровье без статей (учим область, не статью);
    право -> право без тем; армия_прочее -> вне. Каждую — 3 раза (их мало).
Проверка/свежие3/свежие4/флагманы/bench в обучение НЕ идут — только для замера.
Инициализация та же, что у основная.з1 (seed=1): разница весов — только от данных.
Пишет блоки/основная_внешние.з1/{здоровье,право}/ + обучение.jsonl.
Запуск: python обучение/обучить_внешние.py [зерно]
"""
import json
import os
import random
import sys
import time

import numpy as np

sys.dont_write_bytecode = True
V8 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, V8)
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
from обучение import данные as D  # noqa: E402
from обучение import обучить as O  # noqa: E402
from обучение import сеть as С  # noqa: E402

ВАРИАНТ = "основная_внешние"


def main(seed=1):
    t0 = time.time()
    train, dev, сведения = D.собрать(seed=1)
    print("база", сведения, flush=True)

    известные_зд = set(D.ответы_здоровья())
    известные_пр = set(D.ответы_права())

    # --- расширенный фильтр: базовые проверочные + внешние контрольные ---
    вну = os.path.join(D.ВНЕШНИЕ, "проверка_вопросы.json")
    св3 = os.path.join(D.ВНЕШНИЕ, "свежие3_вопросы.json")
    св4 = os.path.join(D.ВНЕШНИЕ, "свежие4_вопросы.json")
    доп = []
    for p in (вну, св3, св4):
        доп += [r["текст"] for r in json.load(open(p, encoding="utf-8"))]
    фильтр = D.Фильтр(D.проверочные_тексты() + доп)

    # --- пул3 ---
    т3 = {r["i"]: r["текст"] for r in json.load(open(os.path.join(D.ВНЕШНИЕ, "пул3_вопросы.json"), encoding="utf-8"))}
    раз3 = D.jl(os.path.join(D.ВНЕШНИЕ, "cowork_пул3.jsonl"))
    взято3, выбр_спорно, выбр_повтор, выбр_неизв = 0, 0, 0, 0
    новые = []
    for r in раз3:
        if r["область"] == "спорно":
            выбр_спорно += 1
            continue
        t = т3[r["i"]]
        if фильтр.близко(t):
            выбр_повтор += 1
            continue
        a = [x for x in r["ответы"] if ("ответ:здоровье:%s" % x) in известные_зд or ("ответ:право:%s" % x) in известные_пр]
        выбр_неизв += len(r["ответы"]) - len(a)
        if r["область"] == "здоровье":
            row = D.строка(t, 1, 0, [x for x in a if ("ответ:здоровье:%s" % x) in известные_зд], (), "внешние:пул3")
        elif r["область"] == "право":
            row = D.строка(t, 0, 1, (), [x for x in a if ("ответ:право:%s" % x) in известные_пр], "внешние:пул3")
        else:
            row = D.строка(t, 0, 0, (), (), "внешние:пул3")
        новые += [row, row]
        взято3 += 1

    # --- фразы (150): учим область + язык отрицаний, без фильтра (они сами в проверочных — оговорка в замере) ---
    фразы = D.jl(os.path.join(D.ВНЕШНИЕ, "фразы.jsonl"))
    взято_ф = 0
    for r in фразы:
        g = r["группа"]
        if g == "отрицание":
            row = D.строка(r["текст"], 1, 0, (), (), "внешние:фразы:отрицание")
        elif g == "право":
            row = D.строка(r["текст"], 0, 1, (), (), "внешние:фразы:право")
        else:
            row = D.строка(r["текст"], 0, 0, (), (), "внешние:фразы:вне")
        новые += [row, row, row]
        взято_ф += 1

    train = train + новые
    print("внешние: пул3 взято=%d спорно=%d почти_повторов=%d неизвестных_id=%d; фраз=%d; train стал %d" % (
        взято3, выбр_спорно, выбр_повтор, выбр_неизв, взято_ф, len(train)), flush=True)

    train = O.перевести(train)
    dev = O.перевести(dev)
    print("перевод %.0f с" % (time.time() - t0), flush=True)

    устр, проходов, p_off = O.устройство("основная")
    блоки = [С.БлокУч(имя, ответы, пишет, читает, корзины=O.НАСТРОЙКИ["корзины"], размер=d, граница=O.НАСТРОЙКИ["граница"],
                      seed=seed * 100 + i, область=обл, роль="блок области «%s»" % обл, свёртка=O.НАСТРОЙКИ["свёртка"],
                      масштаб_чтения=O.НАСТРОЙКИ["масштаб_чтения"])
             for i, (имя, обл, ответы, пишет, читает, d) in enumerate(устр)]
    понятия = list(O.ЯЗЫК.понятия)
    tr = С.Набор(train, блоки, понятия)
    dv = С.Набор(dev, блоки, понятия)
    for r in train + dev:
        r.pop("токены", None)
    cfg = dict(O.ОБУЧЕНИЕ)
    сеть = С.Сеть(блоки, проходов=проходов, смешивание="среднее",
                  градиент_через_шину=cfg["градиент_через_шину"], шум_шины=cfg["шум_шины"])
    out = os.path.join(V8, "блоки", "%s.з%d" % (ВАРИАНТ, seed))
    os.makedirs(out, exist_ok=True)
    журнал = os.path.join(out, "обучение.jsonl")
    if os.path.exists(журнал):
        os.remove(журнал)
    итог = С.обучить(сеть, tr, dv, эпох=cfg["эпох"], терпение=cfg["терпение"], пакет=cfg["пакет"], lr=cfg["lr"], λ=cfg["λ"],
                     p_выходной=p_off, seed=seed, журнал=журнал, имя="%s.з%d" % (ВАРИАНТ, seed))
    сведения2 = dict(сведения, внешние_пул3_взято=взято3, внешние_пул3_спорно=выбр_спорно,
                     внешние_пул3_почти_повторов=выбр_повтор, внешние_фраз=взято_ф, train=len(train))
    схема = {"проходов": проходов, "смешивание": "среднее"}
    for b in блоки:
        info = dict(итог, контроль=O.контроль(dev, b), выходные=p_off, настройки=cfg, вместе_с=[x.имя for x in блоки if x is not b])
        O.сохранить(b, os.path.join(out, b.имя), ВАРИАНТ, seed, info, сведения2, схема)
    print("готово %s.з%d за %.0f с, лучший dev %.4f" % (ВАРИАНТ, seed, time.time() - t0, итог["лучший_dev"]), flush=True)


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 1)
